"""Compile the four-wire derivations and write them as Lean.

    python3 mk_four.py [check]

A port of Examples/Groups/Alt16-RevCir/gen/mk_four.py and mk_rel.py.  The
derivations are compiled by the Agda generator itself, imported from the
Agda folder (four.py, inst.py, gatesc.py and the macro derivations of
search/), which replays every step; this script writes the lemmas it
collects, in the same order and the same parts, as Four/Part*.lean and
Four/Relations.lean.  `check` compiles and replays without writing.
"""
import glob
import io
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
AGDA = os.path.normpath(os.path.join(
    HERE, '..', '..', '..', '..', 'Examples', 'Groups', 'Alt16-RevCir', 'gen'))
sys.path.insert(0, AGDA)

import mk_four as A          # noqa: E402  (the Agda's mk_four.py)
import four as F             # noqa: E402
from four import LIB         # noqa: E402

NL = chr(10)
SUB = '₀₁₂₃₄₅₆₇₈₉'


def sub(k):
    return ''.join(SUB[int(c)] for c in str(k))


def lean_name(name):
    """An Agda name of FourWire or of a lemma, in Lean."""
    return name.replace('⁼', 'E').replace('-', '_')


def step(i, eq):
    if isinstance(eq, F.Bot):
        return 'bo %d "%s" "%s"' % (i, eq.l, eq.r)
    if isinstance(eq, F.Top):
        return 'tp %d "%s" "%s"' % (i, eq.l, eq.r)
    if isinstance(eq, F.HS):
        return 'hs %d "%s" "%s"' % (i, eq.lhs, eq.rhs)
    if isinstance(eq, F.FR):
        return 'fr %d "%s" "%s" "%s" "%s"' % ((i,) + eq.args)
    assert isinstance(eq, F.Named), eq
    return '%s %d %s' % ('rwˢ' if eq.back else 'rw', i, lean_name(eq.name))


HEADER = """/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Four wires: derivations from the rules (1)–(7), part %(k)d of %(n)d

Translation of `Four/Part%(k)d.agda`.

GENERATED by `gen/mk_four.py` (the port of the Agda's `gen/mk_four.py`) from
the macro derivations of the Agda's `gen/search`; do not edit.  Each lemma
is an equation between letter lists (`Letters`) with the steps that derive
it: a three-wire step on the bottom (`bo`) or the top (`tp`) three wires, a
step between words in the NOT gates and swaps (`hs`), a change of frame
(`fr`), or a rule of `FourWire` or an earlier lemma (`rw`, backwards `rwˢ`).
The comment says what a lemma is about, in the notation of `gen/search`:
12>0 is the Toffoli gate with controls 1 2 and target 0, ~1 a white control.
-/
import QCert.Alt16RevCir.%(prev)s

namespace QCert.Alt16RevCir.Four

open Engine FourWire Letters
"""


def emit(lem):
    name, lhs, rhs, steps, comment = lem
    out = ['']
    if comment:
        out.append('-- ' + comment)
    out.append('def %s : Eqn4 := deriveℓ "%s" "%s"' % (lean_name(name), lhs, rhs))
    for k, (i, eq) in enumerate(steps):
        out.append('  %s%s%s' % ('[' if k == 0 else ' ', step(i, eq),
                                 ']' if k + 1 == len(steps) else ','))
    out.append('  (by decide +kernel)')
    return out


def write(per_part=1200):
    parts = [[]]
    n = 0
    for lem in LIB.lemmas:
        if n and n + len(lem[3]) > per_part:
            parts.append([])
            n = 0
        parts[-1].append(lem)
        n += len(lem[3])
    d = os.path.join(ROOT, 'Four')
    os.makedirs(d, exist_ok=True)
    for old in glob.glob(os.path.join(d, 'Part*.lean')):
        os.remove(old)
    for k, lems in enumerate(parts, 1):
        prev = 'Letters' if k == 1 else 'Four.Part%d' % (k - 1)
        text = HEADER % {'k': k, 'n': len(parts), 'prev': prev}
        body = []
        for lem in lems:
            body.extend(emit(lem))
        body.extend(['', 'end QCert.Alt16RevCir.Four'])
        with io.open(os.path.join(d, 'Part%d.lean' % k), 'w', encoding='utf-8',
                     newline=NL) as fh:
            fh.write(text + NL.join(body) + NL)
        print('Part%d: %d lemmas, %d steps' % (k, len(lems), sum(len(l[3]) for l in lems)))
    return len(parts)


REL_HEADER = """/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Four wires: the relations of Syntactics, from the rules (1)–(7)

Translation of `Four/Relations.agda`.

GENERATED by `gen/mk_four.py` (the port of the Agda's `gen/mk_rel.py`); do
not edit.  The lemmas of `Four.Part*` are equations between letter lists;
here they are read as equations between the words of `Syntactics`: the
relations between the cycles (`orderT`, `nearT`, `farT`, `apartT`: 14, 13, 12
and 66 instances, each transported from one of 24 shapes by a symmetry of
the cube), and each gate on its own wires as the circuit of a word in
Lafont's cycles (`gate_XT`, …).  The words are `Translation`'s for `X`,
`CX`, `CCX` and the bottom swap; for the other two swaps they are longer,
and `Equivalence` carries them to `Translation`'s by Lafont's completeness.

The Agda's guards `True (i ≤ᵇ 13)` are the inequalities themselves, and an
index out of range is absurd by `omega`.  That a lemma's letter lists are
the letters of the two words is decided by the kernel (`Eqn.toB`), where the
Agda's `eqn→` takes two `refl`s.  The Agda's `orderᵀ`, `gate-Xᵀ`, … are
`orderT`, `gate_XT`, ….
-/
import QCert.Alt16RevCir.Translation
import QCert.Alt16RevCir.Four.Part%(last)d

namespace QCert.Alt16RevCir.Four.Relations

open QCert QCert.Circuit CircuitProp Engine
"""

TOB = '.toB (by decide +kernel) (by decide +kernel)'


def lafont_word(word):
    lines = []
    cur = ' '
    for k, i in enumerate(word):
        item = ' ω' + sub(i) + (' *' if k + 1 < len(word) else '')
        if len(cur) + len(item) > 98:
            lines.append(cur)
            cur = ' '
        cur += item
    lines.append(cur)
    return lines


def write_rel(inst, gate, last):
    out = [REL_HEADER % {'last': last}]

    def sect(title):
        out.append('/-! ## ' + title + ' -/')
        out.append('')

    def nm(key):
        return lean_name(inst[key].name)

    sect('The cycles have order three')
    out.append('theorem orderT : ∀ i, i ≤ 13 → 4 ⊢ᵀ Ω i * Ω i * Ω i ≈ 1')
    for i in range(14):
        out.append('  | %d, _ => %s%s' % (i, nm(('order', (i,))), TOB))
    out.append('  | _ + 14, _ => by omega')
    out.append('')

    sect('Two cycles one position apart')
    out.append('theorem nearT : ∀ i, i ≤ 12 →')
    out.append('    4 ⊢ᵀ Ω i * Ω (i + 1) * Ω i ≈ Ω (i + 1) * Ω (i + 1)')
    for i in range(13):
        out.append('  | %d, _ => %s%s' % (i, nm(('near', (i, i + 1))), TOB))
    out.append('  | _ + 13, _ => by omega')
    out.append('')

    sect('Two cycles two positions apart')
    out.append('theorem farT : ∀ i, i ≤ 11 →')
    out.append('    4 ⊢ᵀ Ω i * Ω (i + 2) * Ω i ≈ Ω (i + 2) * Ω i * Ω (i + 1)')
    for i in range(12):
        out.append('  | %d, _ => %s%s' % (i, nm(('far', (i, i + 1, i + 2))), TOB))
    out.append('  | _ + 12, _ => by omega')
    out.append('')

    sect('Two cycles three or more positions apart')
    out.append('theorem apartT : ∀ i j, i + 3 ≤ j → j ≤ 13 → 4 ⊢ᵀ Ω j * Ω i ≈ Ω i * Ω j')
    for j in range(14):
        for i in range(0, j - 2):
            out.append('  | %d, %d, _, _ => %s%s' % (i, j, nm(('apart', (i, j))), TOB))
        k = max(j - 2, 0)
        out.append('  | %s, %d, _, _ => by omega' % ('_ + %d' % k if k else '_', j))
    out.append('  | _, _ + 14, _, _ => by omega')
    out.append('')

    sect('The gates as circuits of words in the cycles')
    names = [('X0', 'X', 'X₀'), ('CX0', 'CX', 'CX'), ('CCX0', 'CCX', 'CCX'),
             ('Ex0', 'Ex₀', 'Ex₀'), ('Ex1', 'Ex₁', 'Ex₁'), ('Ex2', 'Ex₂', 'Ex₂')]
    for key, n, circ in names:
        lem, word = gate[key]
        out.append('def w%s : Alternating.Circ 16 :=' % n)
        out.extend(lafont_word(word))
        out.append('')
        out.append('theorem gate_%sT : 4 ⊢ᵀ %s ≈ FreeMonoid.lift g w%s :=' % (n, circ, n))
        out.append('  %s%s' % (lean_name(lem.name), TOB))
        out.append('')
    out.append('end QCert.Alt16RevCir.Four.Relations')
    path = os.path.join(ROOT, 'Four', 'Relations.lean')
    with io.open(path, 'w', encoding='utf-8', newline=NL) as fh:
        fh.write(NL.join(out) + NL)
    print('Relations: %d instances, %d gates' % (len(inst), len(gate)))


def main():
    A.rule7()
    A.pair_orbits()
    A.relators()
    print('lemmas: %d, steps: %d' % (len(LIB.lemmas), LIB.steps()))
    import inst
    A.INST.update(inst.all_instances(A.RELATORS))
    print('with the %d instances: lemmas: %d, steps: %d' % (
        len(A.INST), len(LIB.lemmas), LIB.steps()))
    import gatesc
    A.GATE.update(gatesc.gate_lemmas())
    print('with the gates: lemmas: %d, steps: %d' % (len(LIB.lemmas), LIB.steps()))
    names = [lean_name(l[0]) for l in LIB.lemmas]
    assert len(set(names)) == len(names)
    if 'check' not in sys.argv[1:]:
        last = write()
        write_rel(A.INST, A.GATE, last)


if __name__ == '__main__':
    main()
