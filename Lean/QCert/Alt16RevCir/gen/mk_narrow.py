"""Write Width2/Derivations.lean and Width3/Derivations.lean from the
derivations that the Agda's narrow.py found (narrow2.json, narrow3.json).

    python3 mk_narrow.py 2
    python3 mk_narrow.py 3

A port of Examples/Groups/Alt16-RevCir/gen/mk_narrow.py: the same input,
read from the Agda folder, the same lemmas in the same order, written as
Lean.  Every chain is replayed here as the engine will run it (by the
Agda generator's `replay`) before anything is written.
"""
