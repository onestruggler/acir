HEADER = """/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# The derivations, from the rules on {K} wires, that the Reidemeister–Schreier step from Symmetric's presentation needs

Translation of `Width{K}/Derivations.agda`.

GENERATED by `gen/mk_narrow.py` (the port of the Agda's `gen/mk_narrow.py`)
from the Agda's `gen/narrow{K}.json`, which its `gen/narrow.py` finds by a
proof-producing Knuth–Bendix completion of the rules.  `Θ d` is the edge
Toffoli of the states `d` and `d + 1` along the Gray code, the circuit of
their transposition.  The equations `order0`, …, `braid0`, … and `far0_2`,
… are the Coxeter relations between the `Θ d`, and `gate_…` says which word
in the `Θ d` a gate on its own wires is.  Each is a run of the engine: every
step rewrites by an axiom `ax_…` (a rule of `Theory`, a law of the swap or a
structural rule, at this width) or by a rule `R…` of the completion, itself
derived from earlier ones.  `order`, `braid` and `far` collect them by
index.

The letters are the alphabet `L{K}` of `Engine` (the Agda defines them here,
as generators).  The Agda's guards `T (2 + d ≤ᵇ N)` are the inequalities
themselves, and an index out of range is absurd by `omega`.
-/
import QCert.Alt16RevCir.Theory
import QCert.Alt16RevCir.Engine

namespace QCert.Alt16RevCir.Width{K}.Derivations

open QCert QCert.Circuit CircuitProp Engine
"""


def lean_name(name):
    return name.replace('^', '_up').replace('-', '_')


def lst(word):
    return '[' + ', '.join('.' + LETTER[x] for x in word) + ']'


def wrap(prefix, items, sep, close, width=98):
    """prefix item sep item ... close, broken at width."""
    lines, cur = [], prefix
    for i, it in enumerate(items):
        piece = it + (sep if i + 1 < len(items) else close)
        if len(cur) + len(piece) > width and cur.strip():
            lines.append(cur.rstrip())
            cur = '   ' + piece
        else:
            cur += piece
    lines.append(cur.rstrip())
    return '\n'.join(lines)


def steps(chain):
    out = []
    for _, (rule, pos, fwd) in chain[1:]:
        e = 'R%d' % rule if fwd else '(symE R%d)' % rule
        out.append('Step.rw %d %s' % (pos, e))
    return out


def lstw(prefix, word):
    """A letter list after prefix, broken at the width."""
    if not word:
        return prefix + '[]'
    return wrap(prefix + '[', ['.' + LETTER[x] for x in word], ', ', ']')


def derive(name, l, r, chain):
    body = [lstw('def %s : Eqn TRel LK := derive ' % name, l),
            lstw('  ', r)]
    st = steps(chain)
    if st:
        body.append(wrap('  [', st, ', ', ']'))
    else:
        body.append('  []')
    body.append('  (by decide +kernel)')
    return '\n'.join(body)


def main():
    k = int(sys.argv[1])
    data = json.load(open(os.path.join(AGDA, 'narrow%d.json' % k)))
    rules = {x['id']: x for x in data['rules']}
    axioms = {name: (l, r) for name, l, r in data['axioms']}
    theta = data['theta']
    n = len(theta)

    def sides(i):
        return rules[i]['lhs'], rules[i]['rhs']

    out = [HEADER.replace('{K}', str(k))]

    # axioms
    out.append('/-! ## The rules at this width -/\n')
    used = sorted({x['axiom'][0] for x in data['rules'] if x['axiom']},
                  key=lambda nm: [a for a, _, _ in data['axioms']].index(nm))
    for name in used:
        l, r = axioms[name]
        an = 'ax_' + lean_name(name)
        out.append('%s\n%s\n  (%s)\n  rfl rfl\n' % (
            lstw('def %s : Eqn TRel LK := eqnW ' % an, l), lstw('  ', r), AXIOM[k][name]))

    # rules of the completion
    out.append('/-! ## The rules of the completion that the derivations use -/\n')
    for i in sorted(rules):
        x = rules[i]
        if x['axiom']:
            name, fwd = x['axiom']
            l, r = axioms[name]
            if not fwd:
                l, r = r, l
            assert (l, r) == (x['lhs'], x['rhs']), i
            an = 'ax_' + lean_name(name)
            out.append('def R%d : Eqn TRel LK := %s\n' % (i, an if fwd else 'symE ' + an))
        else:
            ch = x['chain']
            assert ch[0][0] == x['lhs']
            assert replay(ch, sides) == x['rhs'], i
            assert all(st[0] < i for _, st in ch[1:]), i
            out.append(derive('R%d' % i, x['lhs'], x['rhs'], ch) + '\n')

    # the edge Toffolis
    out.append('/-! ## The edge Toffolis along the Gray code -/\n')
    out.append('def θ : ℕ → List LK')
    for d, w in enumerate(theta):
        out.append('  | %d => %s' % (d, lst(w)))
    out.append('  | _ => []\n')
    out.append('def Θ (d : ℕ) : Circ K := word (θ d)\n')

    # targets
    out.append('/-! ## The Coxeter relations and the gates -/\n')
    for t in data['targets']:
        ch = t['chain']
        assert ch is not None, t['name']
        assert ch[0][0] == t['lhs'] and replay(ch, sides) == t['rhs']
        out.append(derive(lean_name(t['name']), t['lhs'], t['rhs'], ch) + '\n')

    # dispatch
    N = n + 1
    out.append('/-! ## By index -/\n')
    out.append('theorem order : ∀ d, 2 + d ≤ %d → K ⊢ᵀ Θ d * Θ d ≈ 1' % N)
    for d in range(n):
        out.append('  | %d, _ => order%d.to rfl rfl' % (d, d))
    out.append('  | _ + %d, _ => by omega\n' % n)
    out.append('theorem braid : ∀ d, 3 + d ≤ %d →' % N)
    out.append('    K ⊢ᵀ Θ d * Θ (d + 1) * Θ d ≈ Θ (d + 1) * Θ d * Θ (d + 1)')
    for d in range(n - 1):
        out.append('  | %d, _ => braid%d.to rfl rfl' % (d, d))
    out.append('  | _ + %d, _ => by omega\n' % (n - 1))
    out.append('theorem far : ∀ d e, 2 + d ≤ e → 2 + e ≤ %d → K ⊢ᵀ Θ e * Θ d ≈ Θ d * Θ e' % N)
    m = max(n - 2, 0)
    for d in range(m):
        for e in range(n):
            if e >= d + 2:
                out.append('  | %d, %d, _, _ => far%d_%d.to rfl rfl' % (d, e, d, e))
            else:
                out.append('  | %d, %d, _, _ => by omega' % (d, e))
        out.append('  | %d, _ + %d, _, _ => by omega' % (d, n))
    out.append('  | _ + %d, _, _, _ => by omega' % m)

    text = '\n'.join(out).replace('LK', 'L%d' % k).replace('Circ K', 'Circ %d' % k) \
        .replace('K ⊢ᵀ', '%d ⊢ᵀ' % k) + '\n\nend QCert.Alt16RevCir.Width%d.Derivations\n' % k
    path = os.path.join(ROOT, 'Width%d' % k)
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, 'Derivations.lean'), 'w',
              encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote Width%d/Derivations.lean: %d axioms, %d rules, %d targets, '
          '%d lines' % (k, len(used), len(rules), len(data['targets']),
                        text.count('\n')))


if __name__ == '__main__':
    main()
