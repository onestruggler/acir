"""Turn completion traces into Lean derivations.

Port of the Agda's tools/export_kb.py: the same saved search results
(`kb-certificates.json`, or with --permutation `permutation-certificates.json`,
read from the Agda's `tools/`), each completion lemma `KBnnnn` and each goal
a namespace of lemmas `pN : w ≈ v` closed by `proved`.  It writes Proofs/B000.lean
(the 22 certificates the Agda keeps) or PermProofs/B000.lean, ..., in the
Agda's chunks.
"""
import json
import sys
import common as c

PERM = '--permutation' in sys.argv
SPACE = 'PermProofs' if PERM else 'Proofs'
data = json.loads((c.TOOLS / ('permutation-certificates.json' if PERM else 'kb-certificates.json')).read_text())
rules = data['rules']; certs = data['certificates']
tietze = json.loads((c.TOOLS / 'tietze-parsed.json').read_text())


def word(xs):
    return c.word(xs)


class Build:
    def __init__(self):
        self.s = ''; self.n = 0

    def lemma(self, l, r, p):
        n = 'p' + str(self.n); self.n += 1
        self.s += f'theorem {n} : {word(l)} ≈ {word(r)} :=\n  {p}\n\n'
        return n

    def step(self, w, i, pos):
        a, b = rules[i]; assert w[pos:pos + len(a)] == a, (w, i, pos)
        v = w[:pos] + b + w[pos + len(a):]
        e = f'by_assoc_and (under ({word(w[:pos])}) ({word(w[pos + len(a):])}) KB{i:04d}.proved) rfl rfl'
        return v, self.lemma(w, v, e)

    def path(self, w, path):
        start = w; es = []
        for i, pos in path:
            w, e = self.step(w, i, pos); es.append(e)
        p = 'refl'
        for e in reversed(es):
            p = f'trans {e} ({p})'
        return w, self.lemma(start, w, p)

    def cert(self, cc):
        if 'tietze' in cc:
            n = cc['tietze']; l, r, _ = tietze['raw'][n]
            return l, r, self.lemma(l, r, f'Tietze.{n}.proved')
        if 'pauli' in cc:
            return ['X0', 'X1'], ['X1', 'X0'], self.lemma(['X0', 'X1'], ['X1', 'X0'], 'Proofs.X0X1.proved')
        if 'axiom' in cc:
            n = cc['axiom']; a, b = c.RELATIONS[n]
            l, r = c.ag.expand(a), c.ag.expand(b)
            return l, r, self.lemma(l, r, f"by_assoc_and (axiom' .r{n:03d}) rfl rfl")
        if 'sym' in cc:
            a, b, e = self.cert(cc['sym']); return b, a, self.lemma(b, a, 'sym ' + e)
        if 'overlap' in cc:
            w, i, pi, j, pj = cc['overlap']; a, ea = self.step(w, i, pi); b, eb = self.step(w, j, pj)
            return a, b, self.lemma(a, b, f'trans (sym {ea}) {eb}')
        l, r, c0, pl, pr = cc['reduce']; a, b, e = self.cert(c0); assert (a, b) == (l, r), (a, b, l, r)
        a, ea = self.path(l, pl); b, eb = self.path(r, pr)
        return a, b, self.lemma(a, b, f'trans (sym {ea}) (trans {e} {eb})')


def kb(i):
    b = Build(); l, r, e = b.cert(certs[i]); assert [l, r] == rules[i]
    return f'namespace KB{i:04d}\n\n' + b.s + f'theorem proved : {word(l)} ≈ {word(r)} :=\n  {e}\n\nend KB{i:04d}\n\n'


def goal(name):
    paths = data['solved'][name]
    a, b = data['goals'][name]; build = Build()
    na, pa = build.path(a, paths[0]); nb, pb = build.path(b, paths[1]); assert na == nb
    return (f'namespace {name}\n\n' + build.s +
            f'theorem proved : {word(a)} ≈ {word(b)} :=\n  trans {pa} (sym {pb})\n\nend {name}\n\n')


DOC = {
    'Proofs': '''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: completion lemmas

Translation of `Proofs/{chunk}.agda`.  Generated by `gen/export_kb.py` from
the saved Knuth–Bendix completion of the Agda's `tools/kb.py`
(`kb-certificates.json`): each lemma `KBnnnn` is a rule of the completion,
from an axiom or a critical pair of earlier rules, and `X0X1` the goal it
was run for; the 22 certificates the Agda keeps.''',
    'PermProofs': '''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: permutation certificates, part {k}

Translation of `PermProofs/{chunk}.agda`.  Generated by `gen/export_kb.py
--permutation` from the saved completion of the permutation fragment
(`permutation-certificates.json` of the Agda's `tools/`): each lemma
`KBnnnn` is a rule of the completion, from an axiom, an authors' derivation
(`Tietze`) or a critical pair of earlier rules, and each goal (the Coxeter
relations of the circuits `X_[i,i+1]`, the gates as Coxeter words) is two
rewrite paths to one normal form.''',
}

chunks = c.agda_chunks(SPACE)
emitted = 0
for k, (chunk, names) in enumerate(chunks):
    imports = ['Kit']
    if PERM:
        imports += ['Proofs.B000'] + [f'Tietze.{ch}' for ch, _ in c.agda_chunks('Tietze')]
    imports += [f'{SPACE}.{ch}' for ch, _ in chunks[:k]]
    body = ''
    for n in names:
        body += kb(int(n[2:])) if n.startswith('KB') else goal(n)
        emitted += 1
    # The words reach some forty letters, and comparing a step's two
    # bracketings of one takes Lean's unifier deeper than its default limit.
    text = (c.header(DOC[SPACE].format(k=k, chunk=chunk), imports) + 'set_option maxRecDepth 100000\n\n'
            + f'namespace {SPACE}\n\n' + body)
    text += f'end {SPACE}\n\nend {c.NS}\n'
    c.write(f'{SPACE}/{chunk}.lean', text)
print('Exported', emitted, 'certificates in', len(chunks), 'chunks of', SPACE)
