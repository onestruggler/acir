"""Write GatePermutations.lean: each classical gate of Figure 4 as a Coxeter
word, from the permutation certificates of PermProofs.

Port of the Agda's tools/generate_base_frames.py."""
import common as c
import generate_frames as af

g = c.ag
CLASS = {x for x in g.GATES if x.startswith(('X', 'CX', 'CCX', 'SWAP'))}


def classical(word):
    out = ()
    for x in word.split():
        if len(x) == 3 and x[0] == 't' and int(x[2]) == int(x[1]) + 1:
            out += (int(x[1]),)
        elif x in g.DEFS:
            out += classical(g.DEFS[x])
        else:
            assert x in CLASS, x
            m = g.matrix(x)[1]; p = tuple(next(i for i in range(8) if m[i][j]) for j in range(8))
            out += af.decomposition(p)
    return out


def pw(w):
    return '[' + ', '.join(str(i) for i in w) + ']'


chunks = [ch for ch, names in c.agda_chunks('PermProofs') if any(n.startswith('decode') for n in names)]
s = c.header('''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: the gates as permutations

Translation of `GatePermutations.agda`, generated by
`gen/generate_base_frames.py`: each classical gate of Figure 4 is the circuit
of a Coxeter word, by a certificate of `PermProofs` (`decodeX0`, …), and so
is each `X_[i,i+1]`, by definition.''', ['FrameWords'] + [f'PermProofs.{ch}' for ch in chunks])
s += 'set_option maxRecDepth 100000\n\n'
for x in sorted(CLASS):
    s += f'theorem gate{x} : {x} ≈ p {pw(classical(x))} :=\n  by_assoc_and PermProofs.decode{x}.proved rfl rfl\n\n'
for i in range(7):
    x = 't' + str(i) + str(i + 1)
    s += f'theorem gate{x} : {x} ≈ p [{i}] := by_assoc_and refl rfl rfl\n\n'
s += f'end {c.NS}\n'
c.write('GatePermutations.lean', s)
