"""Write FrameWords.lean: the 106 decoded generators as permutation frames.

Port of the Agda's tools/generate_frames.py (whose frames and Coxeter words
it imports).  Each generator is a centre (m0 for the one-level ones, NK for
the four-level ones) conjugated by a Coxeter word, or a Coxeter word alone
(the two-level ones).  The Coxeter words are also written as tables (fM,
fX, fK and fK'), so that the decoding dM, dX, dK is one uniform expression
in them: TwoLevel relates a decoded generator to a frame at symbolic
indices through the tables, by one evaluated check.
"""
import common as c
import generate_frames as af


def pw(w):
    return '[' + ', '.join(str(i) for i in w) + ']'


def cp(w):
    return f'p {pw(w)}'


s = c.header('''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: frame words

Translation of `FrameWords.agda`, generated by `gen/generate_frames.py`: the
106 generators of Li, Ross and Selinger at `n = 8`, decoded as circuits.
Each is a centre (`m0` for `(-1)_[a]`, `NK` for `K_[a,b,c,d]`) conjugated by
a Coxeter word, or a Coxeter word alone (`X_[a,b]`).  The Coxeter words are
also tables (`fM`, `fX`, `fK`, `fK'`), so that the decoding (`dM`, `dX`,
`dK`) is uniform in them.  States are natural numbers (the Agda's `Fin 8`).''',
             ['Frames', 'QCert.LiRossSelinger.Syntax'])
for atom in af.atoms:
    expr = cp(af.transposition(*atom[1:])) if atom[0] == 'X' else \
        f'{cp(af.afr(atom))} * {af.center(atom)} * {cp(tuple(reversed(af.afr(atom))))}'
    s += f'def {af.name(atom)} : Word Gen := {expr}\n'
s += '\n/-! ## The Coxeter words of the generators as tables -/\n\n'
for kind, arity, tables in [('M', 1, [('fM', lambda a: af.afr(a))]),
                            ('X', 2, [('fX', lambda a: af.transposition(*a[1:]))]),
                            ('K', 4, [('fK', lambda a: af.afr(a)), ("fK'", lambda a: tuple(reversed(af.afr(a))))])]:
    for t, word in tables:
        s += f'def {t} : ' + ' → '.join(['ℕ'] * arity) + ' → PWord\n'
        for atom in af.atoms:
            if atom[0] == kind:
                s += '  | ' + ', '.join(str(i) for i in atom[1:]) + f' => {pw(word(atom))}\n'
        s += '  | ' + ', '.join('_' for _ in range(arity)) + ' => []\n\n'
for atom in af.atoms:
    if atom[0] == 'M':
        assert af.afr(atom) == tuple(reversed(af.afr(atom))), atom
s += '''/-- The decoding of `(-1)_[a]`. -/
def dM (a : ℕ) : Word Gen := p (fM a) * m0 * p (fM a)

/-- The decoding of `X_[a,b]`. -/
def dX (a b : ℕ) : Word Gen := p (fX a b)

/-- The decoding of `K_[a,b,c,d]`. -/
def dK (a b c d : ℕ) : Word Gen := p (fK a b c d) * NK * p (fK' a b c d)

/-- The decoding of the generators of Li, Ross and Selinger at `n = 8`. -/
def decode : LiRossSelinger.Gen 8 → Word Gen
  | .neg a => dM a.val
  | .x a b _ => dX a.val b.val
  | .k a b c d _ _ _ => dK a.val b.val c.val d.val

end QCert.ToffoliHadamardTietze
'''
c.write('FrameWords.lean', s)
print('Frame words:', len(af.atoms))
