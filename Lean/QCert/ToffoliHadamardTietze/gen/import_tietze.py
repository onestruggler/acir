"""Read the authors' TIETZE2 traces and replay every literal rewrite in Lean.

Port of the Agda's tools/import_tietze.py: the same traces (`dyadic.rels`
and the six `*.derivs` files of meamy/tietze), checked the same way, each
derivation a namespace of steps `stepN : w ≈ v` closed by `proved`.  It
writes Tietze/B000.lean, ... (the Agda's chunks) and CircuitLemmas.lean.
"""
import re
import common as c

HERE = c.TOOLS
ren = {'CCX0': 'CCX12', 'CCX1': 'CCX02', 'CCX2': 'CCX01'}


def parse_word(s):
    if s == 'ε':
        return ()
    return tuple(ren.get(x, x) for x in s.split('.'))


base = {}
for line in (HERE / 'dyadic.rels').read_text().splitlines():
    line = line.split('--')[0].strip()
    m = re.fullmatch(r'(\S+)\s+([\w.]+)\s*=\s*([\w.ε]+)', line)
    if m:
        base[m[1]] = (parse_word(m[2]), parse_word(m[3]))
raw = {}
for fn in ['bifunct', 'symmetry', 'orders', 'commutators', 'cadd', 'cflip']:
    blocks = re.split(r'^@name\s+', (HERE / (fn + '.derivs')).read_text(), flags=re.M)[1:]
    for block in blocks:
        name, _, rest = block.partition('\n')
        lines = [line.split('--')[0].strip() for line in rest.splitlines()]
        lines = [l for l in lines if l and not l.startswith('@')]
        left = parse_word(lines[0]); right = parse_word(lines[-1]); steps = []
        for line in lines[1:-1]:
            m = re.fullmatch(r'(?:!apply\s+)?(\S+)\s+([←→])\s+(\d+)', line)
            if m:
                steps.append((m[1], m[2], int(m[3])))
            elif re.fullmatch(r'[\w.ε]+', line):
                pass
            else:
                raise ValueError((name, line))
        raw[name.strip()] = (left, right, steps)
known = dict(base); known.update({k: (l, r) for k, (l, r, _) in raw.items()})
for name, (l, r, steps) in raw.items():
    w = l
    for ref, d, pos in steps:
        a, b = known[ref]
        if d == '←':
            a, b = b, a
        assert w[pos:pos + len(a)] == a, (name, ref, pos)
        w = w[:pos] + b + w[pos + len(a):]
    assert w == r, (name, w, r)

paper = {}
for n, (l, r) in list(c.RELATIONS.items())[:46]:
    paper[(tuple(l.split()), tuple(r.split()))] = n
matches = {name: paper.get(pair) for name, pair in base.items()}


def aword(xs):
    return c.word(' '.join('X0 Z0 X0 Z0' if x == 'M' else x for x in xs))


def cert(name):
    l, r, steps = raw[name]
    s = f'namespace {name}\n\n'
    w = l
    for i, (ref, d, pos) in enumerate(steps):
        a, b = known[ref]
        p = (f'{ref}.proved' if ref in raw else 'Proofs.X0X1.proved' if ref == 'bifunct_X_a'
             else f'@refl ({aword(a)})' if ref == 'expand_M' else f"axiom' .r{matches[ref]:03d}")
        if d == '←':
            a, b = b, a; p = f'sym ({p})'
        v = w[:pos] + b + w[pos + len(a):]
        s += f'theorem step{i} : {aword(w)} ≈ {aword(v)} :=\n'
        s += f'  by_assoc_and (under ({aword(w[:pos])}) ({aword(w[pos + len(a):])}) ({p})) rfl rfl\n\n'
        w = v
    p = 'refl'
    for i in reversed(range(len(steps))):
        p = f'trans step{i} ({p})'
    s += f'theorem proved : {aword(l)} ≈ {aword(r)} :=\n  {p}\n\nend {name}\n\n'
    return s


DOC = '''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: the authors' derivations, part {k}

Translation of `Tietze/{chunk}.agda`.  Generated by `gen/import_tietze.py`
from the authors' TIETZE2 traces (`dyadic.rels` and the `.derivs` files of
meamy/tietze, read from the Agda's `tools/`): each derivation replays its
rewrites one step at a time, every step an axiom or an earlier derivation
inside a prefix and a suffix.'''

chunks = c.agda_chunks('Tietze')
done = set()
for k, (chunk, names) in enumerate(chunks):
    imports = ['Kit'] + ['Proofs.B000'] + [f'Tietze.{ch}' for ch, _ in chunks[:k]]
    body = ''.join(cert(n) for n in names)
    done.update(names)
    text = c.header(DOC.format(k=k, chunk=chunk), imports) + 'namespace Tietze\n\n' + body
    text += f'end Tietze\n\nend {c.NS}\n'
    c.write(f'Tietze/{chunk}.lean', text)
assert done == set(raw), set(raw) ^ done

s = c.header('''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: the circuit lemmas

Translation of `CircuitLemmas.agda`: the 218 derivations replayed from the
authors' TIETZE2 files (`Tietze/`), imported together.  Generated by
`gen/import_tietze.py`.''', [f'Tietze.{ch}' for ch, _ in chunks])
c.write('CircuitLemmas.lean', s + f'end {c.NS}\n')
print('Exported', len(raw), 'Lean derivation certificates in', len(chunks), 'chunks')
