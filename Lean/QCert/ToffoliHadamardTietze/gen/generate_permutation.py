"""Write Permutation.lean: the circuits X_[k,k+1] satisfy the Coxeter relations.

Port of the Agda's tools/generate_permutation.py.  The Agda reads Coxeter
words as circuits of the repository's presentation of S8 and transfers its
completeness; the Lean library has no presentation of S8, and its Coxeter
words are CoxeterFrames' lists (translated, with its foundation proved, in
QCert.ToffoliHadamardRS), whose completeness takes the Coxeter relations
(`cox`).  Each relation is a certificate of PermProofs.
"""
import common as c

chunks = [ch for ch, names in c.agda_chunks('PermProofs')
          if any(n.startswith(('invol', 'braid', 'comm')) for n in names)]
s = c.header('''# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-Tietze`: permutations

Translation of `Permutation.agda`, generated by `gen/generate_permutation.py`.
The circuits `adjacent k` of Section 5.6, `X_[k,k+1]`, satisfy the Coxeter
relations of `S₈` (`cox`: each relation one certificate of `PermProofs`), so
two Coxeter words with the same permutation of the basis states are equal
circuits (`permutation_complete`).

**Deviation.**  The Agda reads Coxeter words as circuits of the repository's
presentation of `S₈` (`decode`) and transfers that presentation's
completeness along the Coxeter relations (`axiom-decode`, `decode-cong`).  The
Lean library has no presentation of `S₈`; Coxeter words are the lists of
`CoxeterFrames` (the translation of the Agda's shared
`Symmetric/CoxeterFrames`, in `QCert.ToffoliHadamardRS`), whose completeness
takes the Coxeter relations as its hypothesis.''',
             [f'PermProofs.{ch}' for ch in chunks] + ['QCert.ToffoliHadamardRS.CoxeterFrames',
                                                      'Mathlib.Tactic.IntervalCases'],
             'open QCert.ToffoliHadamardRS.CoxeterFrames')
s += '/-- `X_[k,k+1]`, the circuits of Section 5.6; `ε` from `k = 7` on. -/\ndef adjacent : ℕ → Word Gen\n'
for i in range(7):
    s += f'  | {i} => t{i}{i + 1}\n'
s += '  | _ => 1\n\n'
s += 'theorem involution : ∀ k, adjacent k * adjacent k ≈ 1\n'
for i in range(7):
    s += f'  | {i} => by_assoc_and PermProofs.invol{i}.proved rfl rfl\n'
s += '  | _ + 7 => by_assoc_and (@refl 1) rfl rfl\n\n'
s += ('theorem braid : ∀ k, k ≤ 5 →\n'
      '    adjacent k * adjacent (k + 1) * adjacent k ≈ adjacent (k + 1) * adjacent k * adjacent (k + 1)\n')
for i in range(6):
    s += f'  | {i}, _ => by_assoc_and PermProofs.braid{i}.proved rfl rfl\n'
s += '  | _ + 6, h => absurd h (by omega)\n\n'
s += ('theorem apart (i j : ℕ) (h₁ : 2 + i ≤ j) (h₂ : j ≤ 6) :\n'
      '    adjacent i * adjacent j ≈ adjacent j * adjacent i := by\n'
      '  have : i ≤ 4 := by omega\n'
      '  interval_cases i <;> interval_cases j <;> try omega\n')
for i in range(5):
    for j in range(i + 2, 7):
        s += f'  · exact by_assoc_and PermProofs.comm{i}{j}.proved rfl rfl\n'
s += '''
/-- The Coxeter relations for the circuits `adjacent k`. -/
theorem cox : Coxeter adjacent Rel where
  order i _ := involution i
  braid i h := braid i h
  far i j h₁ h₂ := apart i j h₁ h₂

/-- Two Coxeter words of `S₈` with the same permutation are equal circuits. -/
theorem permutation_complete {p q : CW} (hp : Valid 7 p) (hq : Valid 7 q)
    (e : ∀ x, x < 8 → act p x = act q x) : Pc adjacent p ≈ Pc adjacent q :=
  Pc_complete cox hp hq e

end QCert.ToffoliHadamardTietze
'''
c.write('Permutation.lean', s)
