def lean(w):
    """An Agda word as a Lean word (left-nested products)."""
    w = w.replace(' • ', ' * ')
    return '1' if w == 'ε' else w


def par(w):
    w = lean(w)
    return w if (' ' not in w) else '(' + w + ')'


def write(name, text):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


