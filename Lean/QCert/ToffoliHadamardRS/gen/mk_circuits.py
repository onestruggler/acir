# ------------------------------------------------------------------ the isomorphisms
def ikappa(L, lvl):
    r, rhs = defrule[L]
    toks = rhs.split(' • ')
    parts = ['ικ_' + t if t in defrule else '(Derivable.refl _)' for t in toks]
    ax = '(Derivable.of (R%dplus.fig4 R0.%s))' % (lvl, r)
    if all(p == '(Derivable.refl _)' for p in parts):
        return ax
    acc = parts[0]
    for p in parts[1:]:
        acc = '(%s.mul %s)' % (acc, p)
    return '%s.trans\n    (by simp only [κ, Circuits.%s, map_mul]; exact %s)' % (ax, L, acc)


