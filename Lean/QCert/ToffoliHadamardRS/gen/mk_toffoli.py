"""Write the generated Lean modules Toffoli/Base.lean, Toffoli/Lemmas.lean and
Toffoli/Coxeter.lean from the derivation search database of the Agda
development (Examples/Groups/CCX+H-3qubit-RS/gen/derivations.json).

This is the Lean counterpart of the Agda generator `gen/mk_all.py`: the same
lemmas, in the same order, with the same steps; only the syntax differs.  The
Agda generator's modules (`rels`, `targets`, `model`, `rounds`) are imported
from the Agda folder, so that both developments are written from one
database.

    Toffoli/Base.lean     Figure 4 as engine equations, every gate an involution
    Toffoli/Lemmas.lean   the searched lemmas (relator rotations allowed)
    Toffoli/Coxeter.lean  the Coxeter relations for the circuits T d, by
                          substituting the short forms U d, at level 0, and
                          the structure of Perm at level 1

Run from this directory: python3 mk_toffoli.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AGDA_GEN = os.path.normpath(os.path.join(
    HERE, '..', '..', '..', '..', 'Examples', 'Groups', 'CCX+H-3qubit-RS', 'gen'))
sys.path.insert(0, AGDA_GEN)

import json  # noqa: E402
from rels import R0, T  # noqa: E402
from targets import U, boot as BOOTT  # noqa: E402
from model import W  # noqa: E402
from rounds import load_db  # noqa: E402

OUT = os.path.join(HERE, '..', 'Toffoli')
NS = 'QCert.ToffoliHadamardRS.Toffoli'

_j = json.load(open(os.path.join(AGDA_GEN, 'derivations.json')))
order = _j['order']
db = load_db()
AX = set(R0)
BOOT = [t[0] for t in BOOTT]
assert order[:len(BOOT)] == BOOT
SKIP = lambda n: n.startswith('ordT') or n.startswith('brT') or n.startswith('farT')
REST = [n for n in order[len(BOOT):] if not SKIP(n)]
TK = ['X0', 'X1', 'X2', 'Z0', 'Z1', 'Z2', 'CX01', 'CX02', 'CX10', 'CX12', 'CX20', 'CX21',
      'CZ01', 'CZ02', 'CZ12', 'CCX01', 'CCX02', 'CCX12', 'K01', 'K12', 'SW01', 'SW02', 'SW12']
SQ = {'X0': 'e_r21', 'CX01': 'e_r22', 'K12': 'e_r23', 'CCX12': 'e_r24', 'K01': 'e_r25'}
for g in TK:
    SQ.setdefault(g, g.lower() + 'sq')

LETTER = {
    'X0': 'X₀', 'X1': 'X₁', 'X2': 'X₂', 'Z0': 'Z₀', 'Z1': 'Z₁', 'Z2': 'Z₂',
    'CX01': 'CX₀₁', 'CX02': 'CX₀₂', 'CX10': 'CX₁₀', 'CX12': 'CX₁₂', 'CX20': 'CX₂₀', 'CX21': 'CX₂₁',
    'CZ01': 'CZ₀₁', 'CZ02': 'CZ₀₂', 'CZ12': 'CZ₁₂',
    'CCX01': 'CCX₀₁', 'CCX02': 'CCX₀₂', 'CCX12': 'CCX₁₂', 'K01': 'K₀₁', 'K12': 'K₁₂',
    'SW01': 'SW₀₁', 'SW02': 'SW₀₂', 'SW12': 'SW₁₂', 'NK': 'NK', 'CCZ': 'CCZ', 'H2': 'H₂',
}


def lean_name(n):
    if n in AX:
        return 'e_' + n
    return n.replace('-', '_')


def llist(w):
    return '[' + ', '.join(LETTER[l] for l in w) + ']'


def eq_term(name, o):
    if isinstance(name, tuple):
        _, base, k, m = name
        t = 'rot %d %d %s' % (k, m, lean_name(base))
        return '(%s).symm' % t if o == -1 else '(%s)' % t
    t = lean_name(name)
    return '%s.symm' % t if o == -1 else t


def derivation(name, u, v, steps, doc=None):
    n = lean_name(name)
    lines = []
    if doc:
        lines.append('/-- %s -/' % doc)
    lines += ['def %s : Eqn0 := d0' % n,
              '  ' + llist(u),
              '  ' + llist(v)]
    if not steps:
        lines.append('  []')
    else:
        parts = ['rw %d %s' % (i, eq_term(nm, o)) for (i, nm, o) in steps]
        out = '  [' + parts[0]
        for p in parts[1:]:
            if len(out.split('\n')[-1]) + len(p) + 2 > 96:
                out += ',\n    ' + p
            else:
                out += ', ' + p
        lines.append(out + ']')
    lines.append('  (by decide +kernel)')
    return '\n'.join(lines)


HEAD = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-RS`: %s

Translation of `Toffoli/%s.agda`.  %s

Generated by `gen/mk_toffoli.py` from the derivation search database of the
Agda development (`gen/derivations.json` there); every step was found by
search, and each equation is checked here by running the engine, one
`decide +kernel` per equation.
-/
'''


def write(name, text):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


# ---------------------------------------------------------------- Base
base = [HEAD % ('Figure 4 as equations', 'Base',
                'Toffoli-K circuits (level 0): the relations of Figure 4 as\nengine equations, and every gate an involution.'),
        '''import QCert.ToffoliHadamardRS.Syntactics
import QCert.ToffoliHadamardRS.Engine

namespace %s

open Gate Engine

/-- Figure 4 at level 0, the theory of the derivations here. -/
abbrev Γ0 : WRel GD := R0

/-- An equation at level 0. -/
abbrev Eqn0 : Type := Eqn Γ0

/-- A derivation at level 0: `derive` with its alphabet fixed. -/
abbrev d0 (l r : List GD) (ss : List (Step Γ0)) (h : check ss l r = true) : Eqn0 :=
  derive l r ss h

noncomputable section

/-! ## Figure 4 -/
''' % NS]
for k in R0:
    base.append('def e_%s : Eqn0 := ax R0.%s' % (k, k))
base.append('\n/-! ## Every gate is an involution -/\n')
for n in BOOT:
    u, v, p = db[n]
    base.append(derivation(n, u, v, p) + '\n')
base.append('theorem invol : ∀ x : GD, Derivable Γ0 (FreeMonoid.of x * FreeMonoid.of x) 1')
for g in TK:
    base.append('  | %s => %s.toDer rfl rfl' % (LETTER[g], SQ[g]))
base.append('''
/-- The Agda's `rot⁼` at level 0. -/
abbrev rot (k m : ℕ) (e : Eqn0) : Eqn0 := Engine.rot invol k m e

/-- The Agda's `rev⁼` at level 0. -/
abbrev rev (e : Eqn0) : Eqn0 := Engine.rev invol e

end

end %s
''' % NS)
write('Base.lean', '\n'.join(base))

# ---------------------------------------------------------------- Lemmas
lem = [HEAD % ('the level-0 lemmas', 'Lemmas',
               'Toffoli-K circuits (level 0): commutations, the conjugation\ntables of the swaps and the X gates, short forms `U d` of the circuits\n`T d` of Figure 7 and their Coxeter relations, and the identities that\nlead from the `T d` to every gate.'),
       '''import QCert.ToffoliHadamardRS.Toffoli.Base

namespace %s

open Gate Engine

noncomputable section
''' % NS]
for n in REST:
    u, v, p = db[n]
    lem.append(derivation(n, u, v, p) + '\n')
lem.append('end\n\nend %s\n' % NS)
write('Lemmas.lean', '\n'.join(lem))

# ---------------------------------------------------------------- Coxeter
Uw = {i: W(s) for i, s in U.items()}
Tlem = {i: 'T%d' % i for i in range(6)}     # T(i) -> U(i); T 6 is U 6


def subst_steps(blocks, rel, out_blocks):
    steps = []
    pos = 0
    for i in blocks:
        if i in Tlem:
            steps.append((pos, Tlem[i], 1))
        pos += len(Uw[i])
    if rel is not None:
        steps.append((0, rel, 1))
    pos = 0
    for i in out_blocks:
        if i in Tlem:
            steps.append((pos, Tlem[i], -1))
        pos += len(T(i))
    return steps


def Tw(blocks):
    w = ()
    for i in blocks:
        w = w + T(i)
    return w


cox = []
names = {}
for i in range(7):
    n = 'ordT%d' % i
    names[('ord', i)] = n
    cox.append((n, Tw([i, i]), (), subst_steps([i, i], 'Usq%d' % i, [])))
for i in range(6):
    n = 'brT%d' % i
    names[('br', i)] = n
    cox.append((n, Tw([i, i + 1, i]), Tw([i + 1, i, i + 1]),
                subst_steps([i, i + 1, i], 'br%d' % i, [i + 1, i, i + 1])))
for i in range(7):
    for j in range(i + 2, 7):
        n = 'farT%d%d' % (i, j)
        names[('far', i, j)] = n
        cox.append((n, Tw([i, j]), Tw([j, i]), subst_steps([i, j], 'far%d%d' % (i, j), [j, i])))

lemmas = {n: (db[n][0], db[n][1]) for n in REST}
for (n, u, v, steps) in cox:
    w = u
    for (pos, nm, o) in steps:
        l, r = lemmas[nm]
        p, q = (l, r) if o == 1 else (r, l)
        assert w[pos:pos + len(p)] == p, (n, w, pos, nm)
        w = w[:pos] + q + w[pos + len(p):]
    assert w == v, n

cx = [HEAD % ('the Coxeter relations', 'Coxeter',
              'The Coxeter relations for the circuits `T d` of Figure 7, from\ntheir short forms `U d`, at level 0, and as the structure `Coxeter` of\n`Perm` at levels 0 and 1.'),
      '''import QCert.ToffoliHadamardRS.Toffoli.Lemmas
import QCert.ToffoliHadamardRS.Perm
import QCert.ToffoliHadamardRS.Lift

namespace %s

open Gate Engine

noncomputable section

/-! ## At level 0 -/
''' % NS]
for (n, u, v, steps) in cox:
    cx.append(derivation(n, u, v, steps) + '\n')


def gen_fields(level, wrap):
    out = []
    sfx = str(level)
    G = 'Γ0' if level == 0 else 'R1plus'
    lv = '(k := %d)' % level
    out.append('theorem order%s : ∀ i, i ≤ 6 → Derivable %s (T %s i * T i) 1' % (sfx, G, lv))
    for i in range(7):
        out.append('  | %d, _ => %s' % (i, wrap('%s.toDer rfl rfl' % names[('ord', i)])))
    out.append('  | _ + 7, h => absurd h (by omega)')
    out.append('')
    out.append('theorem braid%s : ∀ i, i ≤ 5 → Derivable %s (T %s i * T (i + 1) * T i) (T (i + 1) * T i * T (i + 1))'
               % (sfx, G, lv))
    for i in range(6):
        out.append('  | %d, _ => %s' % (i, wrap('%s.toDer rfl rfl' % names[('br', i)])))
    out.append('  | _ + 6, h => absurd h (by omega)')
    out.append('')
    out.append('theorem far%s : ∀ i j, 2 + i ≤ j → j ≤ 6 → Derivable %s (T %s i * T j) (T j * T i)'
               % (sfx, G, lv))
    for i in range(7):
        for j in range(7):
            if j >= i + 2:
                out.append('  | %d, %d, _, _ => %s' % (i, j, wrap('%s.toDer rfl rfl' % names[('far', i, j)])))
            else:
                out.append('  | %d, %d, h, _ => absurd h (by omega)' % (i, j))
        out.append('  | %d, _ + 7, _, h => absurd h (by omega)' % i)
    out.append('  | _ + 7, _, h, h\' => absurd (h.trans h\') (by omega)')
    return out


cx.append('/-! ## The structures -/\n')
cx += gen_fields(0, lambda t: t)
cx.append('''
/-- The Coxeter relations for the circuits `T d`, at level 0. -/
theorem coxeter0 : Coxeter Γ0 := ⟨order0, braid0, far0⟩
''')
cx += gen_fields(1, lambda t: 'lift01 (%s)' % t)
cx.append('''
/-- The Coxeter relations for the circuits `T d`, at level 1. -/
theorem coxeter1 : Coxeter R1plus := ⟨order1, braid1, far1⟩

end

end %s
''' % NS)
write('Coxeter.lean', '\n'.join(cx))
print('base', len(BOOT), 'lemmas', len(REST), 'cox', len(cox))
