"""Write the Lean modules Push.lean (Lemma 6.1) and PushMatrices.lean.

The Lean counterpart of the Agda generator `gen/mk_push.py` of
`Examples/Groups/CCX+H-3qubit-RS`, whose modules (`model`, `rels`,
`hconj`) it imports: the same conjugates `H₂ g H₂`, found by the same
breadth-first search over matrices, and the same derivations along the
definitions of Figure 4.  Products are written left-nested, as Lean's `*`
associates.

Run from this directory: python3 mk_push.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AGDA_GEN = os.path.normpath(os.path.join(
    HERE, '..', '..', '..', '..', 'Examples', 'Groups', 'CCX+H-3qubit-RS', 'gen'))
sys.path.insert(0, AGDA_GEN)

from model import W  # noqa: E402
from rels import R0  # noqa: E402
from hconj import hconj, GATES, table, key  # noqa: E402

OUT = os.path.join(HERE, '..')
WORD = {g: g for g in GATES}
WORD['CCZ'] = 'CCZw'
WORD['NK'] = 'NKw'
CONS = {'X0': 'X₀', 'X1': 'X₁', 'X2': 'X₂', 'Z0': 'Z₀', 'Z1': 'Z₁', 'Z2': 'Z₂',
        'CX01': 'CX₀₁', 'CX02': 'CX₀₂', 'CX10': 'CX₁₀', 'CX12': 'CX₁₂', 'CX20': 'CX₂₀', 'CX21': 'CX₂₁',
        'CZ01': 'CZ₀₁', 'CZ02': 'CZ₀₂', 'CZ12': 'CZ₁₂', 'CCX01': 'CCX₀₁', 'CCX02': 'CCX₀₂',
        'CCX12': 'CCX₁₂', 'K01': 'K₀₁', 'K12': 'K₁₂', 'SW01': 'SW₀₁', 'SW02': 'SW₀₂', 'SW12': 'SW₁₂',
        'NK': 'NK', 'CCZ': 'CCZ'}
BASE = {'X0': ('X0', 'r102'), 'CX01': ('CX01', 'r103'), 'CCX12': ('K01 K12 CCZ K12 K01', 'r104'),
        'CCZ': ('CCX01', 'r105'), 'K12': ('K12', 'r106'), 'NK': ('NK', 'r107')}
DEFS = ['X1', 'CX20', 'CX21', 'CX12', 'SW12', 'CX02', 'SW02', 'K01', 'CX10', 'SW01', 'CCX02', 'X2',
        'CZ01', 'Z0', 'Z2', 'Z1', 'CCX01', 'CZ02', 'CZ12']
AXOF = {}
for r, (l, rhs) in R0.items():
    if len(l) == 1 and l[0] in DEFS and l[0] not in AXOF:
        AXOF[l[0]] = (r, rhs)
assert all(g in AXOF for g in DEFS), [g for g in DEFS if g not in AXOF]

T = table(3)
C = {}
for g, (w, _) in BASE.items():
    C[g] = W(w)
for g in DEFS:
    C[g] = T[key(hconj(GATES[g]))]
for g in C:
    assert key(hconj(GATES[g])) == key(__import__('model').mat(C[g])), g


def wexp(w):
    """A word as a left-nested product."""
    if len(w) == 0:
        return '1'
    return ' * '.join(WORD[x] for x in w)


def par(e):
    return e if ' ' not in e else '(' + e + ')'


def pname(g):
    return 'p' + g


def chkname(g):
    return 'h' + g


def lprod(es):
    """Left-nested product of word expressions, each kept whole."""
    return ' * '.join(par(e) for e in es)


HDR = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Amy, Ross, Wesley (2024), after the Agda `CCX+H-3qubit-RS`: %s

Translation of `%s.agda`.  %s

Generated by `gen/mk_push.py`.
-/
'''

pm = [HDR % ('the values behind Push', 'PushMatrices',
             'For each gate defined in Figure 4, the conjugates\nby `H₂` of the letters of its definition multiply to the conjugate chosen\nfor the gate.  Checked by computing them.'),
      '''import QCert.ToffoliHadamardRS.Decide
import QCert.ToffoliHadamardRS.Syntactics

namespace QCert.ToffoliHadamardRS

/-- The value at level 1. -/
noncomputable abbrev sem₁ (w : Word G₁) : O8 := semO w
''']
for g in DEFS:
    r, d = AXOF[g]
    lhs = lprod([wexp(C[x]) for x in d])
    pm.append('theorem %s : sem₁ (%s) = sem₁ (%s) :=\n  semO_eq_of_check (by decide +kernel)\n'
              % (chkname(g), lhs, wexp(C[g])))
pm.append('end QCert.ToffoliHadamardRS\n')
with open(os.path.join(OUT, 'PushMatrices.lean'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(pm))

pu = [HDR % ('Lemma 6.1', 'Push',
             'Lemma 6.1 of Amy, Ross and Wesley: `H₂` passes every\ncircuit over `Σ₁`, `H₂ w ≈ w′ H₂` modulo `R₂⁺`.  For the gates of Figure 8\nby its relations; for every other gate along its definition in Figure 4,\nthe result then replaced by a shorter circuit with the same value (`R₁⁺`\nbeing complete, `PresentationO8`).'),
      '''import QCert.ToffoliHadamardRS.PresentationO8
import QCert.ToffoliHadamardRS.PushMatrices

namespace QCert.ToffoliHadamardRS

open Gate

/-- `H₂` turns `u` into `u′`. -/
def Pushes (u u' : Word G₁) : Prop := Derivable R2plus (H2 * upW u) (upW u' * H2)

theorem push_mul {u u' v v' : Word G₁} (p : Pushes u u') (q : Pushes v v') :
    Pushes (u * v) (u' * v') := by
  unfold Pushes at *
  rw [map_mul, map_mul, ← mul_assoc]
  refine (p.mul (Derivable.refl _)).trans ?_
  rw [mul_assoc, mul_assoc]
  exact (Derivable.refl _).mul q

theorem push_one : Pushes 1 1 := by
  unfold Pushes; simp only [map_one, mul_one, one_mul]; exact Derivable.refl _

/-- A definition of Figure 4, pushed along, and shortened. -/
theorem push_def {g w u u' : Word G₁} (hd : R0 g w) (p : Pushes w u) (h : semO u = semO u') :
    Pushes g u' :=
  ((Derivable.refl _).mul (lift12 (Derivable.of (R1plus.fig4 hd)))).trans
    (p.trans ((lift12 (complete1 h)).mul (Derivable.refl _)))

/-! ## Figure 8 -/
''']
for g, (w, r) in BASE.items():
    pu.append('theorem %s : Pushes %s (%s) := Derivable.of (R2plus.fig8 Fig8.%s)\n'
              % (pname(g), WORD[g], wexp(C[g]), r))
pu.append('/-! ## Figure 4 -/\n')


def pexp(d):
    t = pname(d[0])
    for x in d[1:]:
        t = '(push_mul %s %s)' % (t, pname(x))
    return t


for g in DEFS:
    r, d = AXOF[g]
    pu.append('theorem %s : Pushes %s (%s) :=\n  push_def R0.%s %s %s\n'
              % (pname(g), WORD[g], wexp(C[g]), r, pexp(d), chkname(g)))

pu.append('''/-! ## Every circuit -/

/-- The conjugate of a gate. -/
def conj : G₁ → Word G₁''')
for g in C:
    pu.append('  | .%s => %s' % (CONS[g], wexp(C[g])))
pu.append('''
theorem push : ∀ g : G₁, Pushes (FreeMonoid.of g) (conj g)''')
for g in C:
    pu.append('  | .%s => %s' % (CONS[g], pname(g)))
pu.append('''
/-- The conjugate of a circuit. -/
abbrev conjW : Word G₁ →* Word G₁ := FreeMonoid.lift conj

theorem pushW (w : Word G₁) : Pushes w (conjW w) := by
  induction w using FreeMonoid.inductionOn' with
  | one => rw [map_one]; exact push_one
  | mul_of g w ih => rw [map_mul, FreeMonoid.lift_eval_of]; exact push_mul (push g) ih

end QCert.ToffoliHadamardRS
''')
with open(os.path.join(OUT, 'Push.lean'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(pu))
print('ok', len(DEFS))
