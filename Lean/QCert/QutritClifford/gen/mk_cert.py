"""Writes Cert1Data.lean and Cert2Data.lean: the coset certificates of
cert.py (widths 1 and 2) for Coset.lean, with the stabiliser facts of the
width-2 certificate taken from the two-wire library (Lib2)."""
import cert
import emit
import facts2

HDR = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

%s

Generated by `gen/mk_cert.py`; do not edit.
-/
import QCert.QutritClifford.Coset

namespace QCert.QutritClifford

'''

LT = {('H', 0): '.H 0', ('S', 0): '.S 0', ('H', 1): '.H 1', ('S', 1): '.S 1',
      ('CZ', 0): '.C 0'}


def lst(xs):
    return '[' + ', '.join(xs) + ']'


def rows(rs, f, per=12):
    out = []
    for r in rs:
        out.append(lst([f(x) for x in r]))
    lines = []
    for i in range(0, len(out), per):
        lines.append('    ' + ', '.join(out[i:i + per]))
    return '[\n' + ',\n'.join(lines) + ']'


def flat(xs, per=8):
    lines = []
    for i in range(0, len(xs), per):
        lines.append('    ' + ', '.join(xs[i:i + per]))
    return '[\n' + ',\n'.join(lines) + ']'


def ded_code(how):
    if how[0] == 'tree':
        return '(0, 0, 0, 0, 0)'
    if how[0] == 'sub':
        return '(1, 0, 0, 0, 0)'
    _, e, d, side, j = how
    return '(2, %d, %d, %d, %d)' % (e, d, side, j)


def write(C, name, doc, k):
    nl = len(C.letters)
    size = C.T.size
    rep = [str(emit.enc(C.rep[c])) for c in range(size)]
    dl = [C.dl[c] for c in range(size)]
    ordr = [[C.order[(c, i)] for i in range(nl)] for c in range(size)]
    ded = [[C.ded[(c, i)] for i in range(nl)] for c in range(size)]
    eqs = []
    for (l, r, at) in C.eqs:
        eqs.append('(%d, %d, %d)' % (emit.enc(l), emit.enc(r), 0 if at is None else at + 1))
    src = HDR % doc
    src += 'def %s : Cert where\n' % name
    src += '  k := %d\n' % k
    src += '  letters := %s\n' % lst([LT[x] for x in C.letters])
    src += '  loc := %s\n' % lst([LT[x] for x in C.T.N[0:0]] + [LT[x] for x in loc_of(C)])
    src += '  rep := %s\n' % flat(rep)
    src += '  dl := %s\n' % rows(dl, str, per=16)
    src += '  ord := %s\n' % rows(ordr, str, per=16)
    src += '  ded := %s\n' % rows(ded, ded_code, per=4)
    src += '  eqs := %s\n\n' % flat(eqs, per=4)
    src += 'end QCert.QutritClifford\n'
    return src


LOCS = {}


def loc_of(C):
    return LOCS[id(C)]


def main():
    C1 = cert.width1()
    LOCS[id(C1)] = []
    E, Pa, out = facts2.build_stab()
    facts2.d27_facts(E, Pa, out)
    stab = [(c, m, mu) for c, v in out.items() for (m, mu) in v]
    C2 = cert.width2(stab)
    LOCS[id(C2)] = [('H', 0), ('S', 0), ('H', 1), ('S', 1)]
    # every stabiliser fact is an entry of the two-wire table
    for (c, m, mu) in stab:
        L, R = C2.rep[c] + m, mu + C2.rep[c]
        assert any(l == L and r == R for (l, r) in E.table), (c, m)
    d1 = '''# The coset certificate on one wire

The projective one-qutrit Clifford group as 216 cosets of the trivial
subgroup, with the table of the action of `H` and `S` and a deduction of
every entry from (C2)-(C5) (`gen/cert.py`).'''
    d2 = '''# The coset certificate on two wires

The 90 cosets of the local subgroup (one-wire gates on each wire) in the
projective two-qutrit Clifford group, with the table of the action of `H`,
`S` on each wire and `CZ`, and a deduction of every entry from (C2)-(C14),
the commutation of one-wire gates on different wires and the stabiliser
facts of the two-wire library (`gen/cert.py`).'''
    open('../Cert1Data.lean', 'w', encoding='utf-8', newline='\n').write(write(C1, 'cert1', d1, 1))
    open('../Cert2Data.lean', 'w', encoding='utf-8', newline='\n').write(write(C2, 'cert2', d2, 2))
    print('cert1', C1.T.size, 'cert2', C2.T.size, 'eqs', len(C1.eqs), len(C2.eqs))
    print('cert2 eqs at:', [at for (_, _, at) in C2.eqs])


if __name__ == '__main__':
    main()
