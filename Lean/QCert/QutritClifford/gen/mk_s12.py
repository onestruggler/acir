"""Writes S12Data.lean: for every letter x on two wires and every non-trivial
point y on two wires, a list of K1 tokens k with
  sigma(y) ; x = k ; sigma(x . y)
up to a phase (time order), the stage-1 Schreier condition on two wires."""
import cliff
import qc
import sections as sec
import lib3

LET = [('H', 0), ('S', 0), ('H', 1), ('S', 1), ('CZ', 0)]
TOK = {'S0': '.S0', 'X0': '.X0', 'Z0': '.Z0', 'C0': '.C0',
       'H1': '.top (.H 1)', 'S1': '.top (.S 1)'}
PTS = [(a, b) for a in range(3) for b in range(3)]


def main():
    rows = []
    for x in LET:
        for p in PTS:
            for q in PTS:
                if p == (0, 0) and q == (0, 0):
                    rows.append('[]')
                    continue
                a, b = (p[0], q[0]), (p[1], q[1])
                P = qc.act([x], (0, a, b))
                a2, b2 = P[1], P[2]
                w = sec.sigma(a, b) + [x] + cliff.inv(sec.sigma(a2, b2))
                k = lib3.kword(w, ['S0', 'X0', 'Z0', 'C0', 'H1', 'S1'], 2)
                assert cliff.key(lib3.evalK(k) + sec.sigma(a2, b2), 2) == \
                    cliff.key(sec.sigma(a, b) + [x], 2)
                rows.append('[' + ', '.join(TOK[t] for t in k) + ']')
    src = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# The stage-1 Schreier condition on two wires: the K-words

For the letter `x` of index `i` (`H₀ S₀ H₁ S₁ CZ`) and the point
`[p, q]` on two wires, entry `81 i + 9 (3 p.1 + p.2) + (3 q.1 + q.2)` is a
list of tokens `k` of the stabiliser of `Z₀` with
`sigma [p, q] ⨾ x = k ⨾ sigma (x·[p, q])` up to a phase.

Generated by `gen/mk_s12.py`; do not edit.
-/
import QCert.QutritClifford.Facts3Data

namespace QCert.QutritClifford

set_option maxRecDepth 100000 in
/-- The K-words of the stage-1 condition on two wires. -/
def k12 : List (List Tok) := [
'''
    src += ',\n'.join('  ' + r for r in rows) + ']\n\nend QCert.QutritClifford\n'
    open('../S12Data.lean', 'w', encoding='utf-8', newline='\n').write(src)
    print(len(rows), 'rows')


if __name__ == '__main__':
    main()
