"""Lean files for a stored lemma library, checked lemma by lemma.

write_lib(name, E, k, base, fo, sound_hyp, chunk) writes
  <Name>Data.lean   the data (words as base-9 numbers),
  <Name>_<j>.lean   chunks of `chunk` lemmas, theorem <name>_<i> each
                    stating that the first base + i + 1 entries hold,
the last chunk ending with <name>_all.
"""
import emit

HDR = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

%s

Generated by `gen/%s`; do not edit.
-/
import %s

namespace QCert.QutritClifford

'''


def write_lib(name, Name, E, k, base, fo, sound, hyp, doc, script, chunk=40, outdir='..'):
    nb = E.nbase
    lem = E.lemmas
    data = HDR % (doc + '\n\nThe data.', script, 'QCert.QutritClifford.Local')
    data += 'def %sD : List (ℕ × ℕ × List (ℕ × ℕ × ℕ × ℕ × ℕ)) := [\n' % name
    data += emit.lib_lines(lem) + ']\n\n'
    data += '/-- The table: the base rules and the lemmas. -/\n'
    data += 'def %sT : Tbl := libTbl %s (decLib %sD)\n\n' % (name, base, name)
    data += 'theorem %s_0 %s : ValidUpTo %d %sT %d := validUpTo_base %s %sD\n\n' % (
        name, hyp, k, name, nb, base + '_valid', name)
    data += 'end QCert.QutritClifford\n'
    files = {'%sData.lean' % Name: data}
    prev_mod = 'QCert.QutritClifford.%sData' % Name
    i = 0
    part = 0
    hc = hyp.split(':')[0].strip('( ') if hyp else ''
    while i < len(lem):
        src = HDR % (doc + '\n\nLemmas %d to %d.' % (i, min(i + chunk, len(lem)) - 1), script, prev_mod)
        for j in range(i, min(i + chunk, len(lem))):
            src += '-- %s\ntheorem %s_%d %s : ValidUpTo %d %sT %d :=\n  validUpTo_step %s (%s %s) (%s_%d %s) (i := %d) (by decide +kernel)\n\n' % (
                lem[j][0], name, j + 1, hyp, k, name, nb + j + 1, fo, sound, hc, name, j, hc, j)
        src += 'end QCert.QutritClifford\n'
        fname = '%s_%d.lean' % (Name, part)
        files[fname] = src
        prev_mod = 'QCert.QutritClifford.%s_%d' % (Name, part)
        i += chunk
        part += 1
    for f, s in files.items():
        open('%s/%s' % (outdir, f), 'w', encoding='utf-8', newline='\n').write(s)
    return list(files), prev_mod
