"""Writes Lib3Data.lean, Lib3Chk*.lean and Lib3.lean (the three-wire
library: the lemmas of lib3.py and the local facts of facts3.py), and
Facts3Data.lean (for every fact, its index in the table and its K-word)."""
import sys
import facts3
import mk_lib

CHUNK = int(sys.argv[1]) if len(sys.argv) > 1 else 12

TOK = {'S0': '.S0', 'X0': '.X0', 'Z0': '.Z0', 'C0': '.C0',
       'H1': '.top (.H 1)', 'S1': '.top (.S 1)', 'H2': '.top (.H 2)', 'S2': '.top (.S 2)',
       'C1': '.top (.C 1)'}

PTS = [(a, b) for a in range(3) for b in range(3)]


def pidx(p):
    return 3 * p[0] + p[1]


def main():
    F = facts3.main()
    E = F.E
    doc = '''# The three-wire lemma library

The lemmas of `gen/lib3.py` and the local facts of the generic step
(`gen/facts3.py`) over (C15)-(C18) with free two-wire segments.'''
    files = mk_lib.write_lib('lib3', 'Lib3', E, 3, 'base3', 'fo3', 'fo3_sound', '(hc : Complete 2)',
                             doc, 'mk_lib3.py', chunk=CHUNK)
    # the facts: family -> list of (key, index, k)
    fams = {}
    for (fam, params, lhs, k, rhs) in F.facts:
        name = '%s%s' % (fam, params)
        fams.setdefault(fam, []).append((params, E.names[name], k))
    out = []
    out.append('''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# The local facts of the generic step: indices and K-words

For every fact of `gen/facts3.py`, the index of its lemma in the
three-wire table `lib3T` and its K-word (a list of tokens), by family and
parameters.  Points of one wire `(a, b)` are numbered `3a + b`.

Generated by `gen/mk_lib3.py`; do not edit.
-/
import QCert.QutritClifford.Run

namespace QCert.QutritClifford

/-- Tokens of K-words: `S`, `X`, `Z` and `CZ` at the bottom, or a letter. -/
inductive Tok
  | S0
  | X0
  | Z0
  | C0
  | top (x : Lt)
  deriving DecidableEq

''')
    for fam, items in fams.items():
        out.append('/-- (%s) -/\ndef f%s : List (Nat × List Tok) := [\n' % (fam, fam))
        rows = []
        for (params, idx, k) in items:
            rows.append('  (%d, [%s])' % (idx, ', '.join(TOK[t] for t in k)))
        out.append(',\n'.join(rows) + ']\n\n')
        # parameter order, for checking
        out.append('-- %s parameters: %s\n\n' % (fam, ' '.join(str(p).replace(' ', '') for (p, _, _) in items)))
    out.append('end QCert.QutritClifford\n')
    open('../Facts3Data.lean', 'w', encoding='utf-8', newline='\n').write(''.join(out))
    print(files)
    print({f: len(v) for f, v in fams.items()})


if __name__ == '__main__':
    main()
