"""Writes NFTables.lean: the case tables of the block normal form (the states
of half b at Gray position p, Four's numbering of the sixteen states by
halves, the reversal of the eight positions).

Port of the Agda's gen/mk_nftables.py, writing Lean instead of Agda (the
Agda's script writes its module when imported, so the few lines of data it
computes are repeated here: the Gray code and Four's numbering).  Where the
Agda writes a table of `refl` proofs over `Fin`s and `Bool`s, the Lean module
states it as one `decide`; the table over the sixteen states (`st_eta`),
which `decide` cannot enumerate, is written case by case as in the Agda.

Run with WSL's python3 from this folder: `python3 mk_nftables.py`.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'NFTables.lean'
GRAY = [0b000, 0b001, 0b011, 0b010, 0b110, 0b111, 0b101, 0b100]


def B(b):
    return 'true' if b else 'false'


def bits3(s):
    return [(s >> k) & 1 for k in range(3)]


def vec(bs):
    return ' ∷ '.join(B(b) for b in bs) + ' ∷ .nil'


# Four's numbering: index i < 8 is the lower state at Gray position i;
# index 8 + j is the upper state at Gray position 7 - j.
def four(i):
    if i < 8:
        return bits3(GRAY[i]) + [0]
    return bits3(GRAY[15 - i]) + [1]


def idx(b, p):
    return p if not b else 15 - p


HDR = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Tables for the block normal form

Translation of `NFTables.agda`.  The state of half `b` (wire 3) at Gray
position `p` of the lower wires (`st`), `Four`'s numbering of the sixteen
states (lower half first in Gray order, upper half in reflected Gray order:
`idx`), and the reversal of the eight positions (`rev8`), with their
case-by-case laws.

Generated by `gen/mk_nftables.py` (the port of the Agda's).

Names.  The Agda's `enc′`, `isHi′`, `pos4′`, `enc′-idx` are `enc'`, `isHi'`,
`pos4'`, `enc'_idx`; hyphens are underscores.

**Deviation from the Agda.**  Each table of `refl` proofs over `Fin`s and
`Bool`s is one `decide`; `st_eta`, over the states, is written case by case
as in the Agda.  `rev8` is an `Equiv.Perm (Fin 8)` (the Agda's
`Permutation′ 8`), and `hi_lift` reads the Agda's eight `suc`s as
`Fin.natAdd 8`, the form of `Coxeter.liftN_natAdd`; `isHi_lt` reads
`toℕ i <ᵇ 8` as `Nat.blt i.1 8`.
-/
import QCert.XCXCCX4bit.CSem
import QCert.XCXCCX4bit.Width3

namespace QCert.XCXCCX4bit.NFTables

open CSem (enc8 pos)

/-- Wire 3 of a state. -/
def w3 : Bits 4 → Bool
  | _ ∷ _ ∷ _ ∷ b ∷ .nil => b

/-- The state of half `b` at Gray position `p`. -/
def st (b : Bool) (p : Fin 8) : Bits 4 := Width3.enc p ++ (b ∷ .nil)

theorem w3_st : ∀ (b : Bool) (p : Fin 8), w3 (st b p) = b := by decide

theorem pos_st : ∀ (b : Bool) (p : Fin 8), pos (st b p) = p := by decide
'''


def main():
    o = [HDR]
    o.append('theorem st_eta : ∀ x : Bits 4, st (w3 x) (pos x) = x')
    for s in range(16):
        bs = [(s >> k) & 1 for k in range(4)]
        o.append('  | %s => rfl' % vec(bs))
    o.append('')
    o.append('theorem enc8_st : ∀ p : Fin 8, enc8 p = st true p := by decide')
    o.append('')
    o.append('/-- `Four`\'s index of the state of half `b` at position `p`. -/')
    o.append('def idx : Bool → Fin 8 → Fin 16')
    for b in (0, 1):
        for p in range(8):
            o.append('  | %s, %d => %d' % (B(b), p, idx(b, p)))
    o.append('  | _, ⟨k + 8, h⟩ => absurd h (by omega)')
    o.append('')
    o.append('/-- `Four`\'s numbering, as a table (equal to `Four.enc`, checked there). -/')
    o.append("def enc' : Fin 16 → Bits 4")
    for i in range(16):
        o.append('  | %d => %s' % (i, vec(four(i))))
    o.append('  | ⟨k + 16, h⟩ => absurd h (by omega)')
    o.append('')
    o.append("theorem enc'_idx : ∀ (b : Bool) (p : Fin 8), enc' (idx b p) = st b p := by decide")
    o.append('')
    o.append("def isHi' (i : Fin 16) : Bool := w3 (enc' i)")
    o.append('')
    o.append("def pos4' (i : Fin 16) : Fin 8 := pos (enc' i)")
    o.append('')
    o.append("theorem idx_eta : ∀ i : Fin 16, idx (isHi' i) (pos4' i) = i := by decide")
    o.append('')
    o.append("theorem isHi_lt : ∀ i : Fin 16, isHi' i = !Nat.blt i.1 8 := by decide")
    o.append('')
    o.append('/-- The reversal of the eight positions. -/')
    o.append('def rv : Fin 8 → Fin 8')
    for p in range(8):
        o.append('  | %d => %d' % (p, 7 - p))
    o.append('  | ⟨k + 8, h⟩ => absurd h (by omega)')
    o.append('')
    o.append('theorem rv_rv : ∀ p : Fin 8, rv (rv p) = p := by decide')
    o.append('')
    o.append('def rev8 : Equiv.Perm (Fin 8) := ⟨rv, rv, rv_rv, rv_rv⟩')
    o.append('')
    o.append('/-- The upper index of a position: eight above its reversal. -/')
    o.append('theorem hi_lift : ∀ y : Fin 8, idx true y = Fin.natAdd 8 (rev8 y) := by decide')
    o.append('')
    o.append('end QCert.XCXCCX4bit.NFTables')
    OUT.write_text('\n'.join(o) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
