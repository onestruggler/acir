"""Writes Width2.lean: Proposition B.2, completeness on two wires.

Port of the Agda's gen/width2.py: it runs the same search (width2.py's
lemma calls, over appA.py and derive.py, which importing it runs), checks
that the derivations it finds are those of the Agda's Width2.agda, and
writes them, with the rest of the module, as Lean.
"""
import common as c

HDR = c.COPYRIGHT + r'''# Proposition B.2: the theory is complete on two wires, and G₂ ≅ S₄

Translation of `Width2.agda`.  The states, in the paper's order 00, 01, 11,
10 (its `x₁x₂`, `x₁` on our wire 1), are numbered by `enc`; the
transposition of consecutive states is a circuit `T d`: `T 0` the CNOT with a
white control (X on wire 1 around CX), `T 1` the CNOT from wire 0 to wire 1
(`CXd`) and `T 2` the CNOT `CX`.  Their Coxeter relations follow from
(1)–(3) and Appendix A (`T0 T2 = y = T2 T0` by (2); `T1 T2 T1 = σ = T2 T1 T2`
by (3); the braid of `T0` and `T1` is that of `T1` and `T2` conjugated by X
on wire 1, which passes `T1`), every gate is a word in them (X on wire 0 is
`T2 T0` by (2), the swap `T2 T1 T2` by (3)), and `ByCoxeter` concludes.

The lemmas are derived at width 2 and padded (`Engine.Eqn.pad`, see
`Lib/Engine`); the Agda's `T0²⁼` is `T0sqE`, and so on.  `T_act` is decided
for each letter of `S₄` over the four states, where the Agda has one `refl`
per letter and state.

Generated by `gen/mk_width2.py` (the port of the Agda's `gen/width2.py`,
running its search).
-/
import QCert.XCXCCX4bit.Involutions
import QCert.XCXCCX4bit.ByCoxeter

namespace QCert.XCXCCX4bit.Width2

open QCert QCert.Circuit CircuitProp IndepProp Engine
open Coxeter (SG tr)
open Coxeter.Circuits (Pc)

variable {n : ℕ}

/-! ## The relations, on the bottom two wires of any circuit -/

'''

TAIL = r'''
/-! ## An equation between letter lists, as one between any two words with
those letters -/

/-- The Agda's `via`: the words being lists, both side conditions are
`rfl`. -/
theorem via {n : ℕ} (e : Eqn n) {w v : Circ n} (e₁ : FreeMonoid.ofList e.lhs = w)
    (e₂ : FreeMonoid.ofList e.rhs = v) : n ⊢ w ≈ v :=
  e₁ ▸ e₂ ▸ e.prf

/-! ## The transpositions of consecutive states -/

def T : ℕ → Circ 2
  | 0 => shift X * CX * shift X
  | 1 => CXd
  | 2 => CX
  | _ => 1

theorem cox : Coxeter.Circuits.Coxeter 4 T (VRel SRel 2) where
  order
    | 0, _ => via T0sqE rfl rfl
    | 1, _ => via T1sqE rfl rfl
    | 2, _ => via CXsqE rfl rfl
    | _ + 3, _ => by omega
  braid
    | 0, _ => via braid01E rfl rfl
    | 1, _ => via braid12E rfl rfl
    | _ + 2, _ => by omega
  far
    | 0, 0, _, _ => by omega
    | 0, 1, _, _ => by omega
    | 0, 2, _, _ => via far02E rfl rfl
    | 0, _ + 3, _, _ => by omega
    | _ + 1, _, _, _ => by omega

/-! ## The numbering of the states, and the action of the `T d` -/

def enc : Fin 4 → Bits 2
  | ⟨0, _⟩ => false ∷ false ∷ .nil
  | ⟨1, _⟩ => true ∷ false ∷ .nil
  | ⟨2, _⟩ => true ∷ true ∷ .nil
  | ⟨3, _⟩ => false ∷ true ∷ .nil
  | ⟨_ + 4, h⟩ => absurd h (by omega)

def dec : Bits 2 → Fin 4
  | false ∷ false ∷ .nil => 0
  | true ∷ false ∷ .nil => 1
  | true ∷ true ∷ .nil => 2
  | false ∷ true ∷ .nil => 3

theorem dec_enc : ∀ i, dec (enc i) = i := by decide

'''

TAIL2 = r'''
/-! ## Every gate as a word in the `T d` -/

private def s : ℕ → Word (SG 4)
  | 0 => FreeMonoid.of ⟨0, by decide⟩
  | 1 => FreeMonoid.of ⟨1, by decide⟩
  | _ => FreeMonoid.of ⟨2, by decide⟩

def tw : Gn 2 → Word (SG 4)
  | .gate0 (.gate g) => nomatch g
  | .gate1 (.gate .X_gate) => s 2 * s 0
  | .gate2 (.gate .CX_gate) => s 2
  | .gate2 .swap => s 2 * s 1 * s 2
  | .up (.gate0 (.gate g)) => nomatch g
  | .up (.gate1 (.gate .X_gate)) => s 2 * s 0 * s 1 * s 2 * s 0 * s 1
  | .up (.up (.gate0 (.gate g))) => nomatch g

theorem tw_ok : ∀ g : Gn 2, 2 ⊢ FreeMonoid.of g ≈ Pc T 0 (tw g)
  | .gate0 (.gate g) => nomatch g
  | .gate1 (.gate .X_gate) => via (symE r2E) rfl rfl
  | .gate2 (.gate .CX_gate) => Derivable.refl _
  | .gate2 .swap => via (symE r3E) rfl rfl
  | .up (.gate0 (.gate g)) => nomatch g
  | .up (.gate1 (.gate .X_gate)) => via xTE rfl rfl
  | .up (.up (.gate0 (.gate g))) => nomatch g

/-! ## Completeness on two wires -/

def translate : Circ 2 →* Word (SG 4) := ByCoxeter.Via.translate tw

theorem translate_ok (u : Circ 2) : 2 ⊢ u ≈ Pc T 0 (translate u) :=
  ByCoxeter.Via.translate_ok T tw tw_ok u

theorem complete₂ {u v : Circ 2} (e : sem u ≐ sem v) : 2 ⊢ u ≈ v :=
  ByCoxeter.Via.complete 2 4 T enc cox dec dec_enc T_act tw tw_ok e

end QCert.XCXCCX4bit.Width2
'''


def tact(N):
    """`T_act`, decided for each letter of `S_N` over the `N` states."""
    L = []
    for d in range(N - 1):
        L.append('private theorem T_act%d : ∀ i : Fin %d,' % (d, N))
        L.append('    sem (T %d) (enc i) = enc (Coxeter.perm (FreeMonoid.of (⟨%d, by decide⟩ : SG %d)) i) := by'
                 % (d, d, N))
        L.append('  decide +kernel')
        L.append('')
    L.append('theorem T_act : ∀ (g : SG %d) (i : Fin %d),' % (N, N))
    L.append('    sem (T (tr 0 g)) (enc i) = enc (Coxeter.perm (FreeMonoid.of g) i)')
    for d in range(N - 1):
        L.append('  | ⟨%d, _⟩, i => T_act%d i' % (d, d))
    L.append('  | ⟨_ + %d, h⟩, _ => absurd h (by omega)' % (N - 1))
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    import width2  # runs the search
    found = c.agda_blocks('\n'.join(width2.out))
    agda = c.agda_blocks((c.AGDA / 'Width2.agda').read_text(encoding='utf-8'))
    assert [c.parse_lemma(b) for b in agda] == [c.parse_lemma(b) for b in found], \
        'the search no longer finds the derivations of Width2.agda'
    txt = HDR + '\n'.join(c.lemma(b) for b in found) + TAIL + tact(4) + TAIL2
    c.write('Width2.lean', txt)
