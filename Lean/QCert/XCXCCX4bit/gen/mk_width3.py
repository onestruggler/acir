MID = r'''
/-! ## An equation between letter lists, as one between any two words with
those letters -/

/-- The Agda's `via`: the words being lists, both side conditions are
`rfl`. -/
theorem via {n : ℕ} (e : Eqn n) {w v : Circ n} (e₁ : FreeMonoid.ofList e.lhs = w)
    (e₂ : FreeMonoid.ofList e.rhs = v) : n ⊢ w ≈ v :=
  e₁ ▸ e₂ ▸ e.prf

/-! ## The transpositions of consecutive states -/

def T : ℕ → Circ 3
'''


def coxeter_record():
    L = ['theorem cox : Coxeter.Circuits.Coxeter 8 T (VRel SRel 3) where', '  order']
    for i in range(7):
        L.append('    | %d, _ => via T%dsqE rfl rfl' % (i, i))
    L.append('    | _ + 7, _ => by omega')
    L.append('  braid')
    for i in range(6):
        L.append('    | %d, _ => via braid%dE rfl rfl' % (i, i))
    L.append('    | _ + 6, _ => by omega')
    L.append('  far')
    for i in range(7):
        for j in range(7):
            if j >= i + 2:
                L.append('    | %d, %d, _, _ => via far%d%dE rfl rfl' % (i, j, i, j))
            else:
                L.append('    | %d, %d, _, _ => by omega' % (i, j))
    L.append('    | _ + 7, _, _, _ => by omega')
    L.append('    | _, _ + 7, _, _ => by omega')
    return '\n'.join(L) + '\n'


def bits(g):
    return ' ∷ '.join('true' if (g >> w) & 1 else 'false' for w in (0, 1, 2)) + ' ∷ .nil'


def numbering():
    L = ['/-! ## The numbering of the states, and the action of the `T d` -/', '',
         'def enc : Fin 8 → Bits 3']
    for i, g in enumerate(GRAY):
        L.append('  | ⟨%d, _⟩ => %s' % (i, bits(g)))
    L.append('  | ⟨_ + 8, h⟩ => absurd h (by omega)')
    L += ['', 'def dec : Bits 3 → Fin 8']
    for i, g in enumerate(GRAY):
        L.append('  | %s => %d' % (bits(g).replace(' ∷ .nil', ' ∷ .nil'), i))
    L += ['', 'theorem dec_enc : ∀ i, dec (enc i) = i := by decide', '']
    N = 8
    for d in range(N - 1):
        L.append('private theorem T_act%d : ∀ i : Fin %d,' % (d, N))
        L.append('    sem (T %d) (enc i) = enc (Coxeter.perm (FreeMonoid.of (⟨%d, by decide⟩ : SG %d)) i) := by'
                 % (d, d, N))
        L.append('  decide +kernel')
        L.append('')
    L.append('theorem T_act : ∀ (g : SG %d) (i : Fin %d),' % (N, N))
    L.append('    sem (T (tr 0 g)) (enc i) = enc (Coxeter.perm (FreeMonoid.of g) i)')
    for d in range(N - 1):
        L.append('  | ⟨%d, _⟩, i => T_act%d i' % (d, d))
    L.append('  | ⟨_ + %d, h⟩, _ => absurd h (by omega)' % (N - 1))
    return '\n'.join(L) + '\n'


TAIL = r'''
/-! ## Every gate as a word in the `T d` -/

private def s : ℕ → Word (SG 8)
  | 0 => FreeMonoid.of ⟨0, by decide⟩
  | 1 => FreeMonoid.of ⟨1, by decide⟩
  | 2 => FreeMonoid.of ⟨2, by decide⟩
  | 3 => FreeMonoid.of ⟨3, by decide⟩
  | 4 => FreeMonoid.of ⟨4, by decide⟩
  | 5 => FreeMonoid.of ⟨5, by decide⟩
  | _ => FreeMonoid.of ⟨6, by decide⟩

def tw_X0 : Word (SG 8) := s 4 * s 2 * s 6 * s 0
def tw_CX0 : Word (SG 8) := s 2 * s 4
def tw_SW0 : Word (SG 8) := s 2 * s 4 * s 1 * s 5 * s 2 * s 4
def tw_X1 : Word (SG 8) := tw_SW0 * tw_X0 * tw_SW0
def tw_CX1 : Word (SG 8) := tw_SW0 * (s 4 * s 6) * tw_SW0
def tw_SW1 : Word (SG 8) := tw_CX1 * (s 3 * tw_X0 * s 3 * tw_X0) * tw_CX1
def tw_X2 : Word (SG 8) := tw_SW1 * tw_X1 * tw_SW1

theorem ok_X0 : 3 ⊢ X ≈ Pc T 0 tw_X0 := via X0bE rfl rfl

theorem ok_CX0 : 3 ⊢ CX ≈ Pc T 0 tw_CX0 := via (symE WcE) rfl rfl

theorem ok_SW0 : 3 ⊢ σ ≈ Pc T 0 tw_SW0 := via genSW0E rfl rfl

theorem ok_X1 : 3 ⊢ shift X ≈ Pc T 0 tw_X1 := by
  refine (via genX1E (v := σ * X * σ) rfl rfl).trans ?_
  rw [tw_X1, map_mul, map_mul]
  exact (ok_SW0.mul ok_X0).mul ok_SW0

theorem ok_CX1 : 3 ⊢ shift CX ≈ Pc T 0 tw_CX1 := by
  refine (via genCX1E (v := σ * (T 4 * T 6) * σ) rfl rfl).trans ?_
  rw [tw_CX1, map_mul, map_mul]
  exact (ok_SW0.mul (Derivable.refl _)).mul ok_SW0

theorem ok_CXd1 : 3 ⊢ shift σ * shift CX * shift σ ≈ Pc T 0 (s 3 * tw_X0 * s 3 * tw_X0) := by
  refine (via genCXd1E (v := T 3 * X * T 3 * X) rfl rfl).trans ?_
  rw [map_mul, map_mul, map_mul]
  exact (((Derivable.refl _).mul ok_X0).mul (Derivable.refl _)).mul ok_X0

theorem ok_SW1 : 3 ⊢ shift σ ≈ Pc T 0 tw_SW1 := by
  refine (via (symE (liftE r3E)) (v := shift CX * (shift σ * shift CX * shift σ) * shift CX)
    rfl rfl).trans ?_
  rw [tw_SW1, map_mul, map_mul]
  exact (ok_CX1.mul ok_CXd1).mul ok_CX1

theorem ok_X2 : 3 ⊢ shift (shift X) ≈ Pc T 0 tw_X2 := by
  refine (via genX2E (v := shift σ * shift X * shift σ) rfl rfl).trans ?_
  rw [tw_X2, map_mul, map_mul]
  exact (ok_SW1.mul ok_X1).mul ok_SW1

def tw : Gn 3 → Word (SG 8)
  | .gate0 (.gate g) => nomatch g
  | .gate1 (.gate .X_gate) => tw_X0
  | .gate2 (.gate .CX_gate) => tw_CX0
  | .gate2 .swap => tw_SW0
  | .gate3 (.gate .CCX_gate) => s 4
  | .up (.gate0 (.gate g)) => nomatch g
  | .up (.gate1 (.gate .X_gate)) => tw_X1
  | .up (.gate2 (.gate .CX_gate)) => tw_CX1
  | .up (.gate2 .swap) => tw_SW1
  | .up (.up (.gate0 (.gate g))) => nomatch g
  | .up (.up (.gate1 (.gate .X_gate))) => tw_X2
  | .up (.up (.up (.gate0 (.gate g)))) => nomatch g

theorem tw_ok : ∀ g : Gn 3, 3 ⊢ FreeMonoid.of g ≈ Pc T 0 (tw g)
  | .gate0 (.gate g) => nomatch g
  | .gate1 (.gate .X_gate) => ok_X0
  | .gate2 (.gate .CX_gate) => ok_CX0
  | .gate2 .swap => ok_SW0
  | .gate3 (.gate .CCX_gate) => Derivable.refl _
  | .up (.gate0 (.gate g)) => nomatch g
  | .up (.gate1 (.gate .X_gate)) => ok_X1
  | .up (.gate2 (.gate .CX_gate)) => ok_CX1
  | .up (.gate2 .swap) => ok_SW1
  | .up (.up (.gate0 (.gate g))) => nomatch g
  | .up (.up (.gate1 (.gate .X_gate))) => ok_X2
  | .up (.up (.up (.gate0 (.gate g)))) => nomatch g

/-! ## Completeness on three wires -/

def translate : Circ 3 →* Word (SG 8) := ByCoxeter.Via.translate tw

theorem translate_ok (u : Circ 3) : 3 ⊢ u ≈ Pc T 0 (translate u) :=
  ByCoxeter.Via.translate_ok T tw tw_ok u

theorem complete₃ {u v : Circ 3} (e : sem u ≐ sem v) : 3 ⊢ u ≈ v :=
  ByCoxeter.Via.complete 3 8 T enc cox dec dec_enc T_act tw tw_ok e

end QCert.XCXCCX4bit.Width3
'''

