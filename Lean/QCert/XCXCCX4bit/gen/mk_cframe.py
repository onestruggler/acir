"""Writes CFrame.lean: the frame lemma for G = CX30 at every Coxeter word.

Port of the Agda's gen/mk_cframe.py, writing Lean instead of Agda.  A Coxeter
word r whose permutation of the Gray positions commutes with
mu0 = (0 1)(2 3)(4 5)(6 7) is, as a permutation, a flip inside some pairs
followed by a permutation of the pairs (decided by its values on the even
positions); the 24 pair permutations have fixed Coxeter words (pairW, found
by the Agda generator's breadth-first search `pair_words`, imported), each
checked once against G by CBase.wcore, and the flips are Width3's T 0, T 2,
T 4, T 6.  The rest of the module is fixed text: the header below, and the
tail in cframe_tail.txt (this folder's, the Lean counterpart of the Agda's).

Where the Agda generator writes tables of `refl` proofs (the flips' and the
pair words' actions on the eight positions, the action of a letter), the
Lean module states each table as one `decide +kernel`; the Agda's table of
the fast letter action (`swp`, `act-letter`) is the lemma `swN_eq` of the
tail.  Like the Agda's, this script is untrusted: Lean checks what it
writes.

Run with WSL's python3 from this folder: `python3 mk_cframe.py`.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parent                       # Lean/QCert/XCXCCX4bit
REPO = LEAN.parents[2]                   # the repository root
AGEN = REPO / 'Examples' / 'Groups' / 'XCXCCX-4bit' / 'gen'
OUT = LEAN / 'CFrame.lean'

sys.path.insert(0, str(AGEN))
import mk_cframe as ag  # noqa: E402  (the Agda generator, for pair_words)


def letter(d):
    return 'sg %d' % d


def cw(w):
    if not w:
        return '1'
    return 'FreeMonoid.ofList [' + ', '.join(letter(d) for d in w) + ']'


def main():
    PW = ag.pair_words()
    assert len(PW) == 24
    o = [HDR]
    o.append('/-- A Coxeter word for each permutation of the four pairs, given by the')
    o.append('images of the pairs 0, 1, 2, 3 (`ε` for anything else). -/')
    o.append('def pairW : Fin 4 → Fin 4 → Fin 4 → Fin 4 → CW 8')
    for s, w in sorted(PW.items()):
        o.append('  | %s => %s' % (', '.join(str(v) for v in s), cw(w)))
    o.append('  | _, _, _, _ => 1')
    o.append('')
    o.append(TAIL.rstrip('\n'))
    OUT.write_text('\n'.join(o) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT)


HDR = r'''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# The frame lemma for G = CX₃₀, at every Coxeter word

Translation of `CFrame.agda`.  A Coxeter word `r` of `S₈` whose permutation
commutes with the matching `μ₀ = (0 1)(2 3)(4 5)(6 7)` of the Gray positions
(`InC r`) gives a circuit that commutes with `G` (`W_core`).  Write a
position as `2 v + e` (`mk v e`, a pair `v` and a side `e`).  Such a
permutation sends `2 v + e` to `2 σ v + (e xor β v)`, where `σ v` and `β v`
are read off its value at `2 v` (the centraliser condition gives the odd
positions); `σ` is injective because the permutation is (`valid4`).  So `r`
has the same permutation as `pairW σ * flipsW β` (`perm_complete`), whose
circuit is a pair permutation (one of 24 fixed Coxeter words, each checked
against `G` once by `CBase.wcore`) after flips inside the pairs (`Width3`'s
`T 0`, `T 2`, `T 4`, `T 6`, `CBase.flip_comm₀` …).  Hence two frames of `G`
with the same matching are equal (`W'`, the matchings compared on the eight
positions by `eqMatch`).

Generated by `gen/mk_cframe.py` (the port of the Agda's: the 24 pair words,
from its breadth-first search), with the fixed text of `gen/cframe_tail.txt`.

Names.  The Agda's `_==₄_`, `_==₈_` are `eq4`, `eq8`; `match` (a Lean
keyword) is `matchW`; `W′` is `W'`; `W-core` is `W_core`; the Agda's
anonymous module over `(r : CW) (h : InC r)` is the section `Core`, whose
definitions take `r` and theorems `r` and `h`, explicitly.

**Deviation from the Agda.**  `mk`, `half`, `low` compute (`2 v + e`, `x / 2`,
`x % 2`) where the Agda's are tables, and each of the Agda's tables of `refl`
proofs (`flips-act`, `pair-act`, and the 24 checks of `pair-comm`) is one
`decide`.  The fast action `actF` acts on the values of the positions,
letter by letter with `Nat.beq` tests (`swN`, `actL`), where the Agda's
acts on `Fin 8` through a table of the transpositions (`swp`, with
`act-letter`); `swN_eq` and `actL_val` make it `act` (`actF_ok`).  `eq8`
compares the values of the positions.
-/
import QCert.XCXCCX4bit.CBase

namespace QCert.XCXCCX4bit.CFrame

open QCert QCert.Circuit CircuitProp IndepProp
open PFrames CBase
open Coxeter (act_mul act_inv)

/-- The generators of `S₈` (the Agda's `Sym.gate₂ Sym.σ-gate Sym.↥ …`). -/
abbrev sg (d : ℕ) (q : 2 + d ≤ 8 := by decide) : SG 8 := ⟨d, q⟩

/-! ## Positions as pairs -/

/-- The position `2 v + e`: the pair `v`, the side `e`. -/
def mk (v : Fin 4) (e : Bool) : Fin 8 :=
  ⟨2 * v.1 + (bif e then 1 else 0), by have := v.2; cases e <;> simp <;> omega⟩

/-- The pair of a position. -/
def half (x : Fin 8) : Fin 4 := ⟨x.1 / 2, by omega⟩

/-- The side of a position. -/
def low (x : Fin 8) : Bool := Nat.beq (x.1 % 2) 1

theorem mk_hl : ∀ x : Fin 8, mk (half x) (low x) = x := by decide

theorem half_mk : ∀ (v : Fin 4) (e : Bool), half (mk v e) = v := by decide

theorem low_mk : ∀ (v : Fin 4) (e : Bool), low (mk v e) = e := by decide

/-- The matching that flips wire 0. -/
def μ₀ (x : Fin 8) : Fin 8 := mk (half x) (!low x)

theorem μ₀_mk : ∀ v : Fin 4, μ₀ (mk v false) = mk v true := by decide

/-- Commuting with `μ₀`. -/
def InC (r : CW 8) : Prop := ∀ x, act r (μ₀ x) = μ₀ (act r x)

/-! ## Equality of positions and pair indices -/

/-- Equality of pair indices, decided (the Agda's `_==₄_`). -/
def eq4 (a b : Fin 4) : Bool := Nat.beq a.1 b.1

theorem eq4_sound : ∀ a b : Fin 4, eq4 a b = true → a = b := by decide

/-- Four pair indices that are pairwise distinct. -/
def valid4 (a b c d : Fin 4) : Bool :=
  !eq4 a b && (!eq4 a c && (!eq4 b c && (!eq4 a d && (!eq4 b d && !eq4 c d))))

def sel4 (a b c d : Fin 4) : Fin 4 → Fin 4
  | 0 => a
  | 1 => b
  | 2 => c
  | 3 => d
  | ⟨k + 4, h⟩ => absurd h (by omega)

def sel4b (a b c d : Bool) : Fin 4 → Bool
  | 0 => a
  | 1 => b
  | 2 => c
  | 3 => d
  | ⟨k + 4, h⟩ => absurd h (by omega)

/-! ## Flips inside the pairs: `s₀`, `s₂`, `s₄`, `s₆` -/

def fw : Bool → SG 8 → CW 8
  | true, g => FreeMonoid.of g
  | false, _ => 1

def flips4 (b₀ b₁ b₂ b₃ : Bool) : CW 8 :=
  fw b₀ (sg 0) * fw b₁ (sg 2) * fw b₂ (sg 4) * fw b₃ (sg 6)

private theorem cf (b : Bool) (k : ℕ) (g : SG 8) (e : Pc 0 (FreeMonoid.of g) = T₄ k)
    (h : Comm (T₄ k) G) : Comm (Pc 0 (fw b g)) G := by
  cases b
  · exact comm_ε
  · show Comm (Pc 0 (FreeMonoid.of g)) G
    rw [e]; exact h

theorem flips_comm (b₀ b₁ b₂ b₃ : Bool) : Comm (Pc 0 (flips4 b₀ b₁ b₂ b₃)) G := by
  rw [flips4, map_mul, map_mul, map_mul]
  exact comm_mul (comm_mul (comm_mul (cf b₀ 0 _ rfl flip_comm₀) (cf b₁ 2 _ rfl flip_comm₂))
    (cf b₂ 4 _ rfl flip_comm₄)) (cf b₃ 6 _ rfl flip_comm₆)

theorem flips_act : ∀ (b₀ b₁ b₂ b₃ : Bool) (x : Fin 8),
    act (flips4 b₀ b₁ b₂ b₃) x = mk (half x) (low x ^^ sel4b b₀ b₁ b₂ b₃ (half x)) := by
  decide +kernel

/-! ## Permutations of the pairs -/
'''

TAIL = (HERE / 'cframe_tail.txt').read_text(encoding='utf-8')


if __name__ == '__main__':
    main()
