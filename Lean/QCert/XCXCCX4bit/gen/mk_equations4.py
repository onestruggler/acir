"""Writes Equations4.lean: the four-wire equations of pg_results.json as
PlacedEngine derivations.

Port of the Agda's gen/mk_equations4.py, writing Lean instead of Agda.  It
reads the same saved search results (the Agda's gen/pg_results.json, found
by gen/pg_search.py) and imports the Agda's generator for its replay of a
search result as engine steps (`steps_of`) and for the names and comments of
the equations (`NAMES`); the Agda's generator writes nothing when imported.
Each step becomes

  perm lin                     Step.perm [lin]
  narrow (triple, i, j, new)   Step.narrow i (j - i) [new]
  rule7 (perm p, fwd, i)       Step.rw i (r7at p0 p1 p2 p3)
  rule7 (perm p, bwd, i)       Step.rw i (symE (r7at p0 p1 p2 p3))

and a derivation is `derive [lhs] [rhs] [steps] (by decide +kernel)`.
Letters: ["X", t], ["CX", c, t], ["CCX", a, b, t] with a > b, read as
PG.Xₚ t, PG.CXₚ c t, PG.CCXₚ b a t (PlacedEngine's controls are
increasing).  Like the Agda's, this generator is untrusted: Lean checks what
it writes.

Run with WSL's python3 from this folder: `python3 mk_equations4.py`.
"""
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parent                       # Lean/QCert/XCXCCX4bit
REPO = LEAN.parents[2]                   # the repository root
AGEN = REPO / 'Examples' / 'Groups' / 'XCXCCX-4bit' / 'gen'
OUT = LEAN / 'Equations4.lean'

sys.path.insert(0, str(AGEN))
import mk_equations4 as ag  # noqa: E402  (the Agda generator, for steps_of and NAMES)

ORDER = ['E2', 'E4', 'E8', 'E5', 'E6a', 'E6e', 'E6d', 'E6b', 'E6c', 'E7', 'E3', 'E1']


def lean_name(a):
    """The Agda's `E2⁼`, `eq8⁼` as `E2E`, `eq8E`."""
    assert a.endswith('⁼'), a
    return a[:-1] + 'E'


def letter(j):
    k = j[0]
    if k == 'X':
        return 'PG.Xₚ %d' % j[1]
    if k == 'CX':
        return 'PG.CXₚ %d %d' % (j[1], j[2])
    if k == 'CCX':
        a, b, t = j[1], j[2], j[3]
        return 'PG.CCXₚ %d %d %d' % (min(a, b), max(a, b), t)
    raise ValueError(j)


def lean_list(w, indent):
    """A list of letters, wrapped at 100 columns, continuation lines
    indented to `indent` + 1."""
    if not w:
        return '[]'
    items = [letter(j) for j in w]
    out, line = [], '['
    for k, it in enumerate(items):
        piece = it + (', ' if k + 1 < len(items) else ']')
        if indent + 1 + len(line) + len(piece) + 1 > 100 and line.strip("["):
            out.append(line.rstrip())
            line = ''
        line += piece
    out.append(line)
    return ('\n' + ' ' * (indent + 1)).join(out)


def emit_step(s, indent):
    if s[0] == 'perm':
        return 'Step.perm ' + lean_list(s[1], indent + len('Step.perm '))
    if s[0] == 'narrow':
        _, i, k, new = s
        lead = 'Step.narrow %d %d ' % (i, k)
        return lead + lean_list(new, indent + len(lead))
    _, p, d, i = s
    r = 'r7at %d %d %d %d' % tuple(p)
    if d == 'fwd':
        return 'Step.rw %d (%s)' % (i, r)
    return 'Step.rw %d (symE (%s))' % (i, r)


def emit(name, comment, t):
    st = ag.steps_of(t)
    lines = ['/-- ' + '\n'.join(comment) + ' -/']
    lines.append('def ' + name + ' : Eqnp := derive')
    lines.append('  ' + lean_list(t['lhs'], 2))
    lines.append('  ' + lean_list(t['rhs'], 2))
    for k, s in enumerate(st):
        lead = '  [' if k == 0 else '   '
        sep = ',' if k + 1 < len(st) else ']'
        lines.append(lead + emit_step(s, 3) + sep)
    if not st:
        lines.append('  []')
    lines.append('  (by decide +kernel)')
    return '\n'.join(lines)


HDR = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Equations on four wires, among them the paper's equation (8)

Translation of `Equations4.agda`.  Each is a derivation of `PlacedEngine`
whose steps are rule (7) under a relabelling of the wires and three-wire
steps justified by completeness on three wires, found by the Agda's
`gen/pg_search.py` (`gen/pg_results.json`) and written out by
`gen/mk_equations4.py` (the port of the Agda's, from the same saved search
results).  A letter `CCX_{a,b→t}` is the Toffoli with controls `a, b` and
target `t`; a bar marks a control that is negated (`X` on both sides of it).
Wire 0 is the bottom wire, and words are in diagram order.

The Agda's `E2⁼`, …, `eq8⁼` are `E2E`, …, `eq8E`.  Each derivation is one
Boolean (`PlacedEngine.check`), decided by `decide +kernel`.

Generated by `gen/mk_equations4.py`.
-/
import QCert.XCXCCX4bit.PlacedEngine

namespace QCert.XCXCCX4bit.Equations4

open Placed PlacedEngine'''

FTR = '''
end QCert.XCXCCX4bit.Equations4
'''


def main():
    d = json.load(open(AGEN / 'pg_results.json', encoding='utf-8'))
    tg = {t['name']: t for t in d['targets']}
    parts = [HDR]
    for n in ORDER:
        nm, cm = ag.NAMES[n]
        parts.append(emit(lean_name(nm), cm, tg[n]))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n\n'.join(parts) + '\n' + FTR)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
