"""Writes Involutions.lean: Appendix A, the gates are involutions.

Port of the Agda's gen/mk_involutions.py: it runs the same search (the
Agda's appA.py, over derive.py), checks that the derivations it finds are
those of the Agda's Involutions.agda, and writes them as Lean.
"""
import common as c

HDR = c.COPYRIGHT + r'''# Appendix A: the gates are involutions

Translation of `Involutions.agda`: the two derivations of the paper's
Appendix A, in diagram order (the paper writes composition order, so each of
its products is read backwards here).  They take place in the PROP, where
gates have no formal inverses, and cancel a circuit only after exhibiting an
inverse for it as an equation (`awyE`, `xvbE`, `LmdE`, `LdE`).

The CNOT, on two wires: `x` = X on wire 1, `y` = X on wire 0, `a` = CX,
`b` = σ CX σ (the paper's `CX_{2→1}`), `w = x a x` and `v = y b y`; (2) reads
`a w = y` and (3) `a b a = σ`.  The lemmas follow the paper's (i)–(vi), and
`CXsqE` is `a a = a (b a a b) a = (a b a)(a b a) = σ σ = ε`.

The Toffoli gate, on three wires: `x` = X on wire 2, `c` = CCX,
`e = σ c σ` (`CCX_{13→2}`), `W = x c x`, `m = x e x`, `q` = CX, `p = σ CX σ`
and `d = p c p`; (4) reads `c W = q` and (6) `d = e c e`.  The lemmas follow
the paper's (i)–(viii), and `CCXsqE` is `c c = σ e e σ = σ x m m x σ = ε`.

Every lemma is an equation on the bottom wires of a circuit of any width:
derived at the width it is drawn on and padded (`Engine.Eqn.pad`, see
`Lib/Engine`).  The Agda's names `xaxa⁼`, `CX²⁼`, `em=me⁼` are `xaxaE`,
`CXsqE`, `em_eq_meE`.

Generated by `gen/mk_involutions.py` (the port of the Agda's
`gen/mk_involutions.py`, running its search `appA.py`, `derive.py`).
-/
import QCert.XCXCCX4bit.Kit

namespace QCert.XCXCCX4bit

open QCert QCert.Circuit CircuitProp IndepProp Engine

variable {n : ℕ}

/-! ## The CNOT -/

'''

MID = r'''
/-! ## The Toffoli gate -/

'''

TAIL = '''
end QCert.XCXCCX4bit
'''

if __name__ == '__main__':
    import appA  # runs the search
    cnot = c.agda_blocks('\n'.join(appA.cnot))
    toffoli = c.agda_blocks('\n'.join(appA.toffoli))
    # the search finds the derivations of the Agda's Involutions.agda
    agda = c.agda_blocks((c.AGDA / 'Involutions.agda').read_text(encoding='utf-8'))
    assert [c.parse_lemma(b) for b in agda] == [c.parse_lemma(b) for b in cnot + toffoli], \
        'the search no longer finds the derivations of Involutions.agda'
    cn = [c.lemma(t) for t in cnot]
    tf = [c.lemma(t) for t in toffoli]
    txt = HDR + '\n'.join(cn) + MID + '\n'.join(tf) + TAIL
    c.write('Involutions.lean', txt)
