"""Writes KData.lean: a Coxeter word for each letter on the lower three
wires, whose circuit (Pc) has the letter's function on the Gray positions.

Port of the Agda's gen/mk_kdata.py, writing Lean instead of Agda.  It imports
the Agda generator for its list of letters (`LOWER`, each with its function
on the states) and the Agda's gen/clabels.py for the Gray numbering and the
breadth-first search for Coxeter words (`word_of`).  Pc v realises the
inverse of act v, so v is the word of the inverse of the letter's
permutation (each letter is an involution).  Like the Agda's, it is
untrusted: KFaithful checks each word.

Run with WSL's python3 from this folder: `python3 mk_kdata.py`.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parent                       # Lean/QCert/XCXCCX4bit
REPO = LEAN.parents[2]                   # the repository root
AGEN = REPO / 'Examples' / 'Groups' / 'XCXCCX-4bit' / 'gen'
OUT = LEAN / 'KData.lean'

sys.path.insert(0, str(AGEN))
from clabels import GRAY, POS, word_of, inverse  # noqa: E402
import mk_kdata as ag  # noqa: E402  (the Agda generator, for LOWER)

DIGIT = {'₀': '0', '₁': '1', '₂': '2', '₃': '3'}


def pattern(name):
    """The Agda letter `Xᵖ ₀`, `CXᵖ ₀ ₁`, `CCXᵖ ₀ ₁ ₂` as a Lean pattern."""
    head, *ws = name.split()
    ws = [DIGIT[w] for w in ws]
    ctor = {'Xᵖ': '.Xₚ', 'CXᵖ': '.CXₚ', 'CCXᵖ': '.CCXₚ'}[head]
    return ' '.join([ctor] + ws + ([] if head == 'Xᵖ' else ['_']))


def cw(w):
    if not w:
        return '1'
    return 'FreeMonoid.ofList [' + ', '.join('s' + '₀₁₂₃₄₅₆'[d] for d in w) + ']'


def wrap(lead, w):
    """`lead` followed by the word, wrapped at 100 columns."""
    if not w:
        return lead + '1'
    first = lead + 'FreeMonoid.ofList ['
    out, line = [], first
    items = ['s' + '₀₁₂₃₄₅₆'[d] for d in w]
    for k, it in enumerate(items):
        piece = it + (', ' if k + 1 < len(items) else ']')
        if len(line) + len(piece) > 100 and line.strip():
            out.append(line.rstrip())
            line = ' ' * 6
        line += piece
    out.append(line)
    return '\n'.join(out)


HDR = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Coxeter words for the letters of the lower wires

Translation of `KData.agda`.  For each of the twelve letters on wires 0, 1,
2, a word of `S₈`'s Coxeter generators whose circuit (`PFrames.Pc`) has the
letter's function on the eight Gray positions of the lower states; any
other letter gets `ε`.  `KFaithful` checks each of them.

Generated by `gen/mk_kdata.py` (the port of the Agda's).  A word is
`FreeMonoid.ofList` of its letters (the Agda's `[ s₀ ]ʷ • [ s₂ ]ʷ • …`).
-/
import QCert.XCXCCX4bit.CLabels

namespace QCert.XCXCCX4bit.KData

open Placed (PG)
open PFrames (CW)
open CLabels (s₀ s₁ s₂ s₃ s₄ s₅ s₆)

def rg : PG → CW 8'''


def main():
    o = [HDR]
    for n, f in ag.LOWER:
        fwd = tuple(POS[f(GRAY[i])] for i in range(8))
        assert inverse(fwd) == fwd
        w = word_of(inverse(fwd))
        o.append(wrap('  | %s => ' % pattern(n), w))
    o.append('  | _ => 1')
    o.append('')
    o.append('end QCert.XCXCCX4bit.KData')
    OUT.write_text('\n'.join(o) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
