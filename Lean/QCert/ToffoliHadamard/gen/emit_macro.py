def lname(x):
    return f".T {x}" if x < 7 else (".N" if x == NL else ".K")

def lw(w):
    return "[" + ", ".join(lname(x) for x in w) + "]"

PB = 33554432
def pack_plain(steps):
    c = 0
    for t, (i, k, d) in enumerate(steps):
        assert i < 2 ** 11 and k < 4096
        c += (2 * (4096 * i + k) + (1 if d else 0)) * PB ** t
    return c

def entry(l, r, st):
    return f"  ⟨{lw(l)}, {lw(r)}, false, {len(st)}, {pack_plain(st)}⟩"

