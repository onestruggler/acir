# ---- the standard instance of (6a)
class MA:
    def __init__(self, w):
        self.w = tuple(w); self.steps = []
    def do(self, st):
        self.w = replay_plain(TABLE, self.w, [st]); self.steps.append(st)
    def find(self, pat, start=0):
        pat = tuple(pat)
        for i in range(start, len(self.w) - len(pat) + 1):
            if self.w[i:i + len(pat)] == pat:
                return i
        raise ValueError(pat)

def ax_id(name):
    return next(i for i, (nm, _, _) in enumerate(BASE) if nm == name)

def pal_cancel(A, pos, pal):
    """cancel pal pal at pos (pal a palindrome of T letters)"""
    n = len(pal)
    for t in range(n):
        c = pos + n - 1 - t
        x = A.w[c]
        assert A.w[c + 1] == x
        A.do((c, ax_id(("sq", x)), True))

