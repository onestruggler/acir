# Generate QCert/HadamardPi/Switch.lean: switch words on a window of four odd entries of one
# class, their derivations (checked by `derive_of`) and the goodness of every state.
import sys
from deriv import *
from good4 import good
from words import words, D02, D13
from emit import lean_good
from f1 import f1_chain

OUT = sys.argv[1]
F1A = (H(0, 1), H(2, 3), H(0, 2), H(1, 3)) * 2
F1B = (H(0, 2), H(1, 3), H(0, 1), H(2, 3)) * 2
P = (H(0, 1), H(2, 3))

def pname(A): return f"{A[0]}{A[1]}"

out = []
w = out.append
w("""/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Switching between two matched pairs of a window of four entries

Generated by `gen/gen_switch.py` (run `python gen_switch.py ../Switch.lean` in
`gen/`); do not edit by hand.

On a window `0 < 1 < 2 < 3` of four odd numerators of one class, for every
pair `A` of the window and each parity of the pattern (`Good.lean`), a word
`D` with `D H_A ≈ H_[0,1]` whose every state, from `H_A s` on, is good
(`switch4`).  The words are built from two base words, for `A = (0,2)` and
`A = (1,3)` at even parity, which pass through the pairings
`P = (01)(23)` and `Q = (02)(13)` and use (f1), `H_P H_Q ≈ H_Q H_P`
(Proposition A.11 of the paper, derived here from (d3) by its proof); the
others conjugate a base word by `X_[2,3]` (relabelling the window) or by a
sign `(-1)_[j]` off `A` and `[0,1]` (which changes the parity of the
pattern).
-/
import QCert.HadamardPi.Good

namespace QCert.HadamardPi

open FreeMonoid

-- the generated proofs share one `simp` call, whose lemmas are not all needed everywhere
set_option linter.unusedSimpArgs false

/-! ### (f1) on four indices -/
""")
eng0 = Engine(4)
for name, ix in [("f1₀", (0, 1, 2, 3)), ("f1₁", (0, 2, 1, 3))]:
    ch = f1_chain(*ix)
    st = eng0.chain(ch, maxd=6)
    check_steps(st, ch[0], ch[-1], eng0)
    w(f"""/-- (f1) `(H_[a,b] H_[c,d] H_[a,c] H_[b,d])² ≈ ε` at `{ix}`, by the paper's proof. -/
theorem {name} : Derivable Fig6 (ofList {lean_word(ch[0])}) (ofList ([] : List (Gen 4))) :=
  derive_of {lean_steps(st)} (by decide +kernel)
""")

lemmas = [("f1₀", F1A, ()), ("f1₁", F1B, ())]
W = words()
order = [((0, 1), 0), ((0, 1), 1), ((2, 3), 0), ((2, 3), 1), ((0, 2), 0), ((1, 3), 0),
         ((0, 3), 0), ((1, 2), 0), ((0, 2), 1), ((1, 3), 1), ((0, 3), 1), ((1, 2), 1)]
w("\n/-! ### The derivations -/\n")
for (A, par) in order:
    D = W[(A, par)]
    src = tuple(D) + (H(*A),)
    tgt = (H(0, 1),)
    eng = Engine(4, lemmas)
    if (A, par) in [((0, 2), 0), ((1, 3), 0)]:
        ch = [src, parse("H23 H02 H13 H01 H23 H02 H13"),
              (H(2, 3),) + P + parse("H01 H23 H02 H13 H01 H23 H02 H13"),
              parse("H23 H01 H23"), parse("H01")]
        st = eng.chain(ch, maxd=6)
    else:
        st = eng.search(src, tgt, maxd=8)
        assert st is not None, (A, par)
    check_steps(st, src, tgt, eng)
    name = f"der{pname(A)}_{par}"
    w(f"""theorem {name} : Derivable Fig6 (ofList {lean_word(src)}) (ofList [hL (m := 4) 0 1]) :=
  derive_of {lean_steps(st)} (by decide +kernel)
""")
    lemmas.append((name, src, tgt))

w("\n/-! ### Every state is good -/\n")
for (A, par) in order:
    D = W[(A, par)]
    full = D + [H(*A)]
    for k in range(len(D) + 1):
        w(lean_good(f"good{pname(A)}_{par}_{k}", full[k:], par))

w("""
/-! ### The switch -/

/-- A switch word from the pair `(j₁, j₂)` to `(0, 1)` at the parity `par`. -/
structure Switch (par : ℤ) (j₁ j₂ : Fin 4) (h : j₁ < j₂) where
  /-- The word, in written order. -/
  D : List (Gen 4)
  der : Derivable Fig6 (ofList (D ++ [.H j₁ j₂ h])) (ofList [hL 0 1])
  good : ∀ k ≤ D.length, Good4 par (D.drop k ++ [.H j₁ j₂ h])
""")
for (A, par) in order:
    D = W[(A, par)]
    L = len(D)
    cases = "\n".join(f"    | {k}, _ => good{pname(A)}_{par}_{k}" for k in range(L + 1))
    w(f"""def sw{pname(A)}_{par} : Switch {par} {A[0]} {A[1]} (by decide) where
  D := {lean_word(D)}
  der := der{pname(A)}_{par}
  good := fun k hk => match k, hk with
{cases}
    | _ + {L + 1}, hk => absurd hk (by simp only [List.length_cons, List.length_nil]; omega)
""")

alts = []
for A in [(0, 1), (2, 3), (0, 2), (1, 3), (0, 3), (1, 2)]:
    alts.append(f"(rcases hpar with rfl | rfl; exacts [⟨sw{pname(A)}_0⟩, ⟨sw{pname(A)}_1⟩])")
w(f"""
/-- A switch word for every pair of the window and both parities. -/
theorem switch4 (j₁ j₂ : Fin 4) (h : j₁ < j₂) (par : ℤ) (hpar : par = 0 ∨ par = 1) :
    Nonempty (Switch par j₁ j₂ h) := by
  fin_cases j₁ <;> fin_cases j₂ <;> (try exact absurd h (by decide)) <;>
    first
""")
for a in alts:
    w(f"    | {a}\n")
w("\nend QCert.HadamardPi\n")
open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out))
print("written", OUT)
