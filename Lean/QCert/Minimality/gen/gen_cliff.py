DOCS = {
  'Z2': '(Z²): `Z Z = id`.', 'X2': '(X²): `X X = id`.', 'XSX': '(XSX): `X S X = ω₈² S†`.',
  'eulerH': '(eulerH): the Euler decomposition of `H`.', 'CX2': '(CX²): `CNOT CNOT = id`.',
  'C': '(C): `S` on the control commutes with the CNOT.', 'phasegadget': '(phasegadget).',
  'CNOTHH': '(CNOTHH): the CNOT reversed by Hadamards.', 'czrev': '(czrev): the decoded `CZ` is symmetric.',
  'XcommutCNOT': '(XcommutCNOT): `X` on the target commutes with the CNOT.', 'wCNOT': '(wCNOT).',
  'zCNOT': '(zCNOT).', 'I': '(I) in the form of Selinger\'s figure.',
  '3CNOTtargetcommut': '(3CNOTtargetcommut).', '3CNOTcontrolcommut': '(3CNOTcontrolcommut).',
  'lem:dswap-unfolding': 'The swap unfolded (Appendix A).'}
def doc(name):
    if name in DOCS: return DOCS[name] + ' Appendix A.'
    if name.startswith('lem:C'): return 'The decoding of (%s), Appendix A.' % name[4:].replace('-dec-eq', '')
    return name

def de(g, res):
    out = ['''
/-- Appendix F.1 and Lemma 19: decoding the encoding of a circuit derives the
circuit. -/
theorem DE {n : ℕ} (w : Circuit Gate n) : Derivable (Lift Th n) (D.map n (E.map n w)) w := by
  refine E.derivable_comp D (fun c => ?_) (fun c => ?_) (fun c => ?_) (fun c => nomatch c) w
  · cases c; exact derive hsc [] [] (by decide +kernel)
  · cases c
    · exact derive hsc [] [] (by decide +kernel)
    · exact derive hsc [] [] (by decide +kernel)
  · cases c''']
    for nm in ['DECX', 'DEswap']:
        n, l, r, eqs, steps = res[nm]
        out.append('    · exact %s' % g.proof(eqs, steps, 8))
    return '\n'.join(out)

