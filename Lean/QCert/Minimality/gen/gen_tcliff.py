DOCS = {}
def doc(name):
    if name.startswith('lem:t-'):
        return 'The decoding of (%s), Appendix D.' % name[6:].replace('-dec-eq', '').replace('-unfolding', ' unfolded')
    if name.startswith('t-'):
        return '(%s), Appendix D.' % name[2:]
    return name

BS_CASES = []
for A in ['H₀', 'H₁', 'S₀', 'S₁', 'T₀', 'T₁', 'CZ']:
    BS_CASES.append(('c1 .%s _' % A, 'dec c1 .%s' % A))
for A in 'HST':
    for B in 'HST':
        BS_CASES.append(('c2 .%s .%s' % (A, B), 'dec c2 .%s .%s' % (A, B)))
BS_CASES.append(('c3', 'dec c3'))
for c in ['c4', 'c5', 'c6']:
    for i in (0, 1): BS_CASES.append(('%s %d' % (c, i), 'dec %s %d' % (c, i)))
for c in ['c7', 'c8', 'c9', 'c10', 'c11', 'c12', 'c13']: BS_CASES.append((c, 'dec ' + c))
for c in ['c14', 'c15']:
    for i in (0, 1): BS_CASES.append(('%s %d' % (c, i), 'dec %s %d' % (c, i)))
for c in ['c16', 'c17', 'c18', 'c19', 'c20']: BS_CASES.append((c, 'dec ' + c))

def tail(g, res):
    def P(nm, ind):
        n, l, r, eqs, steps = res[nm]
        return g.proof(eqs, steps, ind)
    out = ['''  | _, _, .c1 .ω h => absurd rfl h

/-- Appendix F.4 on two wires: decoding the encoding of a generator derives
it. -/
theorem BS.DE_gen : ∀ g : Gen Gate 2, Derivable (Lift Th 2) (BS.D (BS.e g)) (FreeMonoid.of g)''']
    for pat, nm in [('.gate0 .ω', 'DE w0'), ('.gate1 .H', 'DE H0'), ('.gate1 .T', 'DE T0'),
                    ('.gate2 .CX', 'DE CX'), ('.gate2 .swap', 'DE SW'), ('.up (.gate0 .ω)', 'DE w1'),
                    ('.up (.gate1 .H)', 'DE H1'), ('.up (.gate1 .T)', 'DE T1'),
                    ('.up (.up (.gate0 .ω))', 'DE w2')]:
        out.append('  | %s =>\n    %s' % (pat, P(nm, 6)))
    T3 = [('r5', 'j k l hjk hlj hlk'), ('r6', 'j k l hjk hlj hlk'),
          ('r7', 'j k l t hjk hlt hlj hlk htj htk'), ('r8', 'j k l t hjk hlt hlj hlk htj htk'),
          ('r9', 'j k l t hjk hlt hlj hlk htj htk'), ('r12', 'j k l hjk hkl'),
          ('r13', 'j k l hlj hjk'), ('r14', 'j k l hjk hkl'), ('r15', 'j k l hlj hjk'),
          ('r20', 'j k l t hjk hkl hlt')]
    T2 = ['r2', 'r3', 'r4', 'r10', 'r11', 'r16', 'r17', 'r18', 'r19']
    out.append(NL.join(['', "/-- The decoding of every relation of Greylyn's presentation in dimension `2`",
        'is derivable on one wire. -/',
        'theorem GL.rel_derivable₁ : ∀ {a b : Word (QCert.Greylyn.Gen 2)}, QCert.Greylyn.Rel 2 a b →',
        '    Derivable (Lift Th 1) (GL.D₁ a) (GL.D₁ b) := by', '  intro a b r', '  cases r with']))
    out.append(fin_arm(g, res, 'r1', 'j', ['j'], 2, {(0,): 'G1 r1 0', (1,): 'G1 r1 1'}))
    for rel in T2:
        valid = {(0, 1): 'G1 ' + rel} if rel != 'r4' else {(0, 1): 'G1 r4 01', (1, 0): 'G1 r4 10'}
        out.append(fin_arm(g, res, rel, 'j k h', ['j', 'k'], 2, valid))
    for rel, vs in T3:
        out.append(absurd_arm(rel, vs))
    out.append(NL.join(['', '/-- Decoding the encoding of a generator on one wire derives it. -/',
        'theorem GL.DE₁_gen : ∀ g : Gen Gate 1, Derivable (Lift Th 1) (GL.D₁ (GL.e₁ g)) (FreeMonoid.of g)',
        '  | .gate0 .ω =>', '      ' + P('G1DE w0', 6),
        '  | .gate1 .H => Derivable.refl _', '  | .gate1 .T => Derivable.refl _',
        '  | .up (.gate0 .ω) =>', '      ' + P('G1DE w1', 6), '',
        "/-- The decoding of every relation of Greylyn's presentation in dimension `1`",
        'is derivable with no wire: only `ω_[0]⁸ = ε` has instances. -/',
        'theorem GL.rel_derivable₀ : ∀ {a b : Word (QCert.Greylyn.Gen 1)}, QCert.Greylyn.Rel 1 a b →',
        '    Derivable (Lift Th 0) (GL.D₀ a) (GL.D₀ b) := by', '  intro a b r', '  cases r with']))
    out.append(fin_arm(g, res, 'r1', 'j', ['j'], 1, {(0,): 'G0 r1'}))
    for rel in T2:
        out.append(absurd_arm(rel, 'j k h'))
    for rel, vs in T3:
        out.append(absurd_arm(rel, vs))
    out.append(NL.join(['', '/-- Decoding the encoding of the scalar derives it. -/',
        'theorem GL.DE₀_gen : ∀ g : Gen Gate 0, Derivable (Lift Th 0) (GL.D₀ (GL.e₀ g)) (FreeMonoid.of g)',
        '  | .gate0 .ω => Derivable.refl _']))
    return '\n'.join(out)

