def kb():
    """The base equations as lemmas, the completion, and its rules and targets as results."""
    for nm, l, r in KBR.BASE:
        ok = D.derive('KB0 ' + nm, 2, [list(reversed(l)), list(reversed(r))], [BASE_LABS[nm]], quiet=True)
        assert ok, nm
    kbs = KB(KBR.LET, KBR.BASE)
    assert kbs.run(targets=list(KB_TARGETS.values()), maxrules=20000, report=500)
    proofs = {nm: kbs.proof_of(l, r) for nm, (l, r) in KB_TARGETS.items()}
    need = KBR.needed(kbs, proofs.values())

    def ref(rid, rev):
        """A rule as (lemma name, rev) for the Lean step."""
        pr = kbs.rules[rid][2]
        if pr[0] == 'base':
            return 'KB0 ' + pr[1], rev != pr[2]
        return 'KB r%d' % rid, rev

    def result(lhs, rhs, st):
        names = []
        out = []
        for (p, rid, rev) in st:
            nm, rv = ref(rid, rev)
            if nm not in names: names.append(nm)
            out.append(('rw', p, names.index(nm), rv))
        return (2, list(reversed(lhs)), list(reversed(rhs)), [('lem', nm, 0, 0) for nm in names], out)

    for rid in sorted(need):
        lhs, rhs, pr, _ = kbs.rules[rid]
        if pr[0] == 'base': continue
        nm = 'KB r%d' % rid
        res = result(kbs.dec(lhs), kbs.dec(rhs), pr)
        D.results[nm] = res; D.lemmas[nm] = (2, res[1], res[2]); D.CACHE[nm] = ('kb', res)
    for tn, (l, r) in KB_TARGETS.items():
        nm = 'KBT ' + tn
        res = result(l, r, proofs[tn])
        D.results[nm] = res; D.lemmas[nm] = (2, res[1], res[2]); D.CACHE[nm] = ('kb', res)
    D.save()
    print('kb: %d rules exported' % len([r for r in need if kbs.rules[r][2][0] != 'base']), flush=True)

