def tw(bw):
    return K.time(bw)

def bl(name, *ways, labs=None):
    """A block relation through lines (each an operator-order block word, or a time-order letter
    word given as ('t', word)), every step citing `labs`."""
    ws = [w[1] if isinstance(w, tuple) else tw(w) for w in ways]
    for w in ws[1:]: assert np.allclose(C.mat(2, ws[0]), C.mat(2, w)), (name, w)
    t = time.time()
    ok = D.derive(name, 2, ws, [list(labs or [])] * (len(ws) - 1), quiet=True)
    print('  %s: %s (%.1fs)' % (name, 'ok' if ok else 'FAILED', time.time() - t), flush=True)
    return ok

# ------------------------------------------------------------------ Knuth–Bendix
def op(t): return tuple(reversed(t))

