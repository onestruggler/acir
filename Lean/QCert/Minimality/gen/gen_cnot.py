def permute(cur, target):
    """Adjacent swaps (of apart letters) taking cur to target (operator order)."""
    cur = list(cur); steps = []
    for j in range(len(target)):
        for i in range(j, len(cur)):
            if cur[i] == target[j] and all(apart(fr, cur[t], cur[i]) for t in range(j, i)):
                for t in range(i, j, -1):
                    steps.append(('swap', t - 1))
                    cur[t - 1], cur[t] = cur[t], cur[t - 1]
                break
        else:
            raise Exception('cannot permute at %d' % j)
    assert tuple(cur) == tuple(target)
    return steps

