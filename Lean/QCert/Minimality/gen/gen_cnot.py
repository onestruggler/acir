def CT3(a, b):  # three wires, a > b, as in my Syntax W3
    if (a, b) == (1, 0): return [L('CX', 0), L('T', 0), L('CX', 0)]
    if (a, b) == (2, 1): return [L('CX', 1), L('T', 1), L('CX', 1)]
    if (a, b) == (2, 0): return [L('SW', 0)] + CT3(2, 1) + [L('SW', 0)]
CCT3 = [L('CX', 1), L('CX', 0), L('T', 0), L('CX', 0), L('CX', 1)]

def up4(b, a): return [L('SW', b + j) for j in range(a - 1 - b)]
def conj4(c, p): return p + c + list(reversed(p))
def CT4(a, b): return conj4([L('CX', a - 1), L('T', a - 1), L('CX', a - 1)], up4(b, a))
def CCT4(a, b, c):
    return conj4([L('CX', a - 1), L('CX', a - 2), L('T', a - 2), L('CX', a - 2), L('CX', a - 1)],
                 up4(b, a) + up4(c, a - 1))

