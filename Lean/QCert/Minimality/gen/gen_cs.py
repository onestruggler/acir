def doc(name):
    return name

from tacgen import fin_arm, absurd_arm

THREE = [('r5', 'j k l hkl hjk hjl'), ('r6', 'j k l hkl hjk hjl'),
         ('r7', 'j k l m hjk hlm hjl hjm hkl hkm'), ('r8', 'j k l m hjk hlm hjl hjm hkl hkm'),
         ('r9', 'j k l m hjk hlm hjl hjm hkl hkm'), ('r11', 'j k l hjk hkl'),
         ('r12', 'j k l hjk hkl'), ('r13', 'j k l hjk hkl'), ('r14', 'j k l hjk hkl'),
         ('r19', 'j k l m hjk hlm hjl hkm hkl')]
TWO = [('r2', 'j k hjk'), ('r3', 'j k hjk'), ('r4', 'j k hjk'), ('r10', 'j k hjk'),
       ('r15', 'j k hjk'), ('r16', 'j k hjk'), ('r17', 'j k hjk'), ('r18', 'j k hjk')]

def tail(g, res):
    def P(nm, ind):
        n, l, r, eqs, steps = res[nm]
        return g.proof(eqs, steps, ind)
    out = ['''/-- The decoding of every relation of Bian and Selinger's presentation in
dimension `2` is derivable on one wire. -/
theorem W1.src_derivable : ∀ {a b : Word (QCert.BianSelingerUn.Gen 2)},
    QCert.BianSelingerUn.Rel 2 a b → Derivable (Lift Th 1) (W1.D (ιw a)) (W1.D (ιw b)) := by
  intro a b r
  cases r with''']
    out.append(fin_arm(g, res, 'r1', 'j', ['j'], 2, {(0,): 'U1 r1 0', (1,): 'U1 r1 1'}))
    for rel, vars_ in TWO:
        nm = {'r2': 'U1 r2', 'r3': 'U1 r3', 'r10': 'U1 r10', 'r15': 'U1 r15', 'r16': 'U1 r16',
              'r17': 'U1 r17', 'r18': 'U1 r18'}
        valid = {(0, 1): nm[rel]} if rel != 'r4' else {(0, 1): 'U1 r4 01', (1, 0): 'U1 r4 10'}
        out.append(fin_arm(g, res, rel, vars_, ['j', 'k'], 2, valid))
    for rel, vars_ in THREE:
        out.append(absurd_arm(rel, vars_))
    out.append('''
/-- The decoding of every refined relation in dimension `2` is derivable on
one wire. -/
theorem W1.rel_derivable : ∀ {a b : FreeMonoid (Option (QCert.BianSelingerUn.Gen 2))},
    RRel (QCert.BianSelingerUn.Rel 2) (UN.gi 2) a b → Derivable (Lift Th 1) (W1.D a) (W1.D b) := by
  intro a b r
  cases r with
    | src r => exact W1.src_derivable r
    | comm y =>
      cases y with''')
    out.append(fin_arm(g, res, 'X', 'j k h', ['j', 'k'], 2, {(0, 1): 'U1 comm X'}, ind=6))
    out.append(fin_arm(g, res, 'K', 'j k h', ['j', 'k'], 2, {(0, 1): 'U1 comm K'}, ind=6))
    out.append(fin_arm(g, res, 'i', 'j', ['j'], 2, {(0,): 'U1 comm i0', (1,): 'U1 comm i1'}, ind=6))
    out.append(fin_arm(g, res, 'sq', '', [], 2, {(): 'U1 sq'}))
    out.append('''
/-- Decoding the encoding of a generator on one wire derives it. -/
theorem W1.DE_gen : ∀ g : Gen Gate 1, Derivable (Lift Th 1) (W1.D (W1.e g)) (FreeMonoid.of g)
  | .gate0 .ω => Derivable.refl _
  | .gate1 .H =>
      %s
  | .gate1 .S => Derivable.refl _
  | .up (.gate0 .ω) =>
      %s

/-- The decoding of every relation of Bian and Selinger's presentation in
dimension `1` is derivable with no wire: only `i_[0]⁴ = ε` has instances. -/
theorem W0.src_derivable : ∀ {a b : Word (QCert.BianSelingerUn.Gen 1)},
    QCert.BianSelingerUn.Rel 1 a b → Derivable (Lift Th 0) (W0.D (ιw a)) (W0.D (ιw b)) := by
  intro a b r
  cases r with''' % (P('U1DE H0', 6), P('U1DE w1', 6)))
    out.append(fin_arm(g, res, 'r1', 'j', ['j'], 1, {(0,): 'U0 r1'}))
    for rel, vars_ in TWO + THREE:
        out.append(absurd_arm(rel, vars_))
    out.append('''
/-- The decoding of every refined relation in dimension `1` is derivable with
no wire. -/
theorem W0.rel_derivable : ∀ {a b : FreeMonoid (Option (QCert.BianSelingerUn.Gen 1))},
    RRel (QCert.BianSelingerUn.Rel 1) (UN.gi 1) a b → Derivable (Lift Th 0) (W0.D a) (W0.D b) := by
  intro a b r
  cases r with
    | src r => exact W0.src_derivable r
    | comm y =>
      cases y with
        | X j k h => exfalso; revert h; revert j k; decide
        | K j k h => exfalso; revert h; revert j k; decide
        | i j => exact Derivable.refl _
    | sq => exact Derivable.refl _

/-- Decoding the encoding of the scalar derives it. -/
theorem W0.DE_gen : ∀ g : Gen Gate 0, Derivable (Lift Th 0) (W0.D (W0.e g)) (FreeMonoid.of g)
  | .gate0 .ω => Derivable.refl _''')
    return chr(10).join(out)

