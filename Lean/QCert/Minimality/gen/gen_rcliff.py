DOCS = {'realczrev': '(czrev): the decoded `CZ` is symmetric.',
        'I': '(I) in the form of Selinger\'s figure (Appendix A).',
        '3CNOTtargetcommut': '(3CNOTtargetcommut), Appendix A.',
        '3CNOTcontrolcommut': '(3CNOTcontrolcommut), Appendix A.',
        'lem:dswap-unfolding': 'The swap unfolded (Appendix A).'}
def doc(name):
    if name in DOCS: return DOCS[name]
    if name.startswith('lem:R'): return 'The decoding of (%s), Appendix B.' % name[4:].replace('-dec-eq', '')
    if name.startswith('lem:C'): return 'The decoding of Selinger\'s (%s), Appendix A, replayed in RCliff₂.' % name[4:].replace('-dec-eq', '')
    return name

def de(g, res):
    out = ['''
/-- Appendix F.2 and Lemma 19: decoding the encoding of a circuit derives the
circuit. -/
theorem DE {n : ℕ} (w : Circuit Gate n) : Derivable (Lift Th n) (D.map n (E.map n w)) w := by
  refine E.derivable_comp D (fun c => ?_) (fun c => ?_) (fun c => ?_) (fun c => nomatch c) w
  · cases c; exact derive hsc [] [] (by decide +kernel)
  · cases c
    · exact derive hsc [] [] (by decide +kernel)
    · exact derive hsc [] [] (by decide +kernel)
  · cases c''']
    for nm in ['DECX', 'DEswap']:
        n, l, r, eqs, steps = res[nm]
        out.append('    · exact %s' % g.proof(eqs, steps, 8))
    return '\n'.join(out)

