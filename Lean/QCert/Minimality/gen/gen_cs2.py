def data():
    out = [HDR % '''# CliffCS₂ on two wires: the data of the block decoding

The blocks of the decoding of Bian and Selinger's two-level generators in
dimension `4`, the block relations (`brels`, in operator order), the
canonical words of `S₄` over the transpositions `t0 = (0 1)`, `t1 = (1 2)`,
`t2 = (2 3)` with the rewriting certificates of their multiplication table
(`certTable`), and the stabiliser words of the atoms (`stabTable`).''']
    out.append('''import QCert.CliffordT2.Rewrite

namespace QCert.Minimality.CliffordCS.W2

/-- The blocks: the permutations `t0 = (0 1)`, `t1 = (1 2)` (the swap),
`t2 = (2 3)` (the CNOT), `x0`, `x1` (`X` on wire `0`, `1`) of the basis
indices `s₀ + 2 s₁`, the atoms `cs` (`CS`, the generator `i_[3]`) and `ck`
(the controlled `K`, `K_[2,3]`), and the single gates `ω`, `H₀`, `H₁`, `S₀`,
`S₁`. -/
inductive Blk
  | t0 | t1 | t2 | x0 | x1 | cs | ck | w | h0 | h1 | s0 | s1
  deriving DecidableEq

open Blk
''')
    out.append('/-- The block relations, in operator order (`gen/cs2blk.py`, in this order:\n' +
               wrap(['`%s`' % n for n in A.RN], 0, 80) + '). -/')
    out.append('def brels : List (List Blk × List Blk) := [\n  ' +
               wrap(['(%s, %s)' % (blist(l), blist(r)) for (l, r) in A.RULES], 2) + ']\n')
    out.append('/-- The canonical words of `S₄` (shortest, over `t0`, `t1`, `t2`). -/')
    out.append('def canonL : List (List Blk) := [\n  ' + wrap([blist(c) for c in A.CANON], 2) + ']\n')
    cc = A.canon_certs()
    out.append('/-- For each canonical word `c` and permutation block `b`, rewriting steps from\n'
               '`c ++ [b]` to the canonical word of the same permutation. -/')
    out.append('def certTable : List ((List Blk × Blk) × List (ℕ × ℕ × Bool)) := [')
    items = []
    for c in A.CANON:
        for b in A.PERMB:
            items.append('((%s, %s), %s)' % (blist(c), b, steps(cc[(tuple(c), b)])))
    out.append('  ' + ',\n  '.join(items) + ']\n')
    out.append('/-- For each atom, a word over its stabiliser letters for each permutation they\n'
               'generate (keyed by the images of `0, 1, 2, 3`). -/')
    out.append('def stabTable : Blk → List (List (Fin 4) × List Blk)')
    for at in ['cs', 'ck', 't2']:
        tab = A.STAB[at]
        out.append('  | %s => [%s]' % (at, wrap(['(%s, %s)' % ('[' + ', '.join(map(str, k)) + ']', blist(v))
                                                for k, v in sorted(tab.items())], 4)))
    out.append('  | _ => []\n')
    out.append('end QCert.Minimality.CliffordCS.W2\n')
    write('W2Data.lean', '\n'.join(out))

