def de_part(sc):
    out = []
    out.append("/-- The refinement's `w w = gi`, decoded. -/")
    out.append('theorem std_sq : Derivable BRel (FreeMonoid.ofList [w, w])\n'
               '    (DBs [.i 0, .i 1, .i 2, .i 3]) :=')
    out.append('  derivable_of_runSteps rules _ _\n    %s\n    (by decide +kernel)\n' % steps(sc['sq']))
    out.append(REL_DEC)
    for g, (gs, tgt, lines, names) in A.DE.items():
        L = A.DBs(gs)
        out.append('/-- The decoding of the encoding of `%s`, as blocks. -/' % g)
        out.append('theorem de_%s : Derivable BRel (FreeMonoid.ofList %s)\n    (FreeMonoid.ofList %s) :=' % (
            g, blist(L), blist(tgt)))
        out.append('  derivable_of_runSteps rules _ _\n    %s\n    (by decide +kernel)\n' % steps(sc['DE ' + g]))
    sw = A.dB(('X', 1, 2))
    out.append('/-- The decoding of `X_[1,2]`, the encoding of the swap. -/')
    out.append('theorem de_swap : Derivable BRel (FreeMonoid.ofList %s)\n    (FreeMonoid.ofList [t1]) :=\n'
               '  perm_complete (by decide) (by decide) (by decide)\n' % blist(sw))
    return '\n'.join(out)

def rels():
    sc = A.std_certs()
    out = [HDR % '''# CliffCS₂ on two wires: the decoded relations, at the level of blocks

Every relation of Bian and Selinger's presentation of `U₄(ℤ[½, i])`,
refined by the new scalar, decodes to an equation between words of blocks
that the block relations derive (`rel_dec`): its standard instance by a
rewriting certificate, by `perm_complete` (relations among the `X_[a,b]`)
or by `swap_conj` (one atom passing a permutation), and every other
instance by `transport` along the permutation carrying the standard
indices to its own.  Decoding the encoding of each two-wire generator gives
back its block (`de_*`).''']
    out.append('''import QCert.Minimality.CliffordCS.W2Blocks
import QCert.Minimality.CliffordCS.Transfer

namespace QCert.Minimality.CliffordCS.W2

open Blk
''')
    for (f, args, L, R, l0, r0, std, tv) in FAM:
        hs = [a for a in args.split() if a.startswith('h')]
        vs = tv.split()
        L0, R0 = A.DBs(l0), A.DBs(r0)
        stdname = 'std_' + f
        lean_l0 = llist([std_gen(g) for g in l0]); lean_r0 = llist([std_gen(g) for g in r0])
        out.append('/-- The standard instance of (%s). -/' % f[1:])
        out.append('theorem %s : Derivable BRel (DBs %s)\n    (DBs %s) :=' % (stdname, lean_l0, lean_r0))
        if f in sc:
            out.append('  derivable_of_runSteps rules _ _\n    %s\n    (by decide +kernel)\n' % steps(sc[f]))
        elif f in PERMF:
            out.append("  derivable_congr (a' := FreeMonoid.ofList %s)\n    (b' := FreeMonoid.ofList %s)"
                       " (by decide) (by decide)\n    (perm_complete (by decide) (by decide) (by decide))\n"
                       % (blist(L0), blist(R0)))
        else:
            at, Rw, Ww, R2, flip = SWAPC[f]
            assert A.base_ok(at, A.key(list(reversed(Ww)) + Rw), A.key(R2)), f
            if not flip:
                assert L0 == Rw + [at] + list(reversed(Rw)) + Ww and R0 == Ww + R2 + [at] + list(reversed(R2)), f
            else:
                assert R0 == Rw + [at] + list(reversed(Rw)) + Ww and L0 == Ww + R2 + [at] + list(reversed(R2)), f
            sw = ("(swap_conj (A := %s) (R := %s) (W := %s) (R' := %s) (by decide) (by decide)\n"
                  "      (by decide) (by decide) (by decide))") % (at, blist(Rw), blist(Ww), blist(R2))
            if flip: sw = sw + '.symm'
            out.append('  derivable_congr (by decide) (by decide)\n    %s\n' % sw)
        sig = ' '.join('(%s : Fin 4)' % v for v in vs)
        out.append('/-- (%s), every instance. -/' % f[1:])
        out.append('theorem fam_%s %s %s :\n    Derivable BRel (DBs %s)\n      (DBs %s) :=' % (
            f, sig, ' '.join(hs_types(f, hs)), llist(L), llist(R)))
        P = 'Pw %s [%s]' % ('[' + ', '.join(map(str, std)) + ']', ', '.join(vs))
        rv = ('revert %s; ' % ' '.join(hs) if hs else '') + 'revert %s; decide +kernel' % ' '.join(vs)
        out.append('  transport (%s) (Pw_perm _ _) %s _ %s _\n    (by %s)\n    (by %s)\n    %s\n' % (
            P, lean_l0, lean_r0, rv, rv, stdname))
    out.append(REL_TAIL)
    out.append(de_part(sc))
    out.append('end QCert.Minimality.CliffordCS.W2\n')
    write('W2Rels.lean', '\n'.join(out))

