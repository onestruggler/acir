def blist(w):
    return '[' + ', '.join(w) + ']'

def wrap(items, indent, width=96, sep=','):
    lines, cur = [], ''
    for i, it in enumerate(items):
        piece = it + (sep if i < len(items) - 1 else '')
        if cur and len(cur) + 1 + len(piece) > width - indent:
            lines.append(cur); cur = piece
        else:
            cur = (cur + ' ' + piece) if cur else piece
    lines.append(cur)
    return ('\n' + ' ' * indent).join(lines)

def steps(st, indent=4):
    return '[' + wrap(['(%d, %d, %s)' % (i, k, 'true' if d else 'false') for (i, k, d) in st], indent) + ']'

def write(name, text):
    open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n').write(text)
    print('written', name)

