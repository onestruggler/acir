import re, ast
from leangen import Gen as LGen, fmt_list
import leangen

def ident(name):
    s = name.replace('lem:cs-', '').replace('-dec-eq', 'dec')
    s = s.replace('^', 'u').replace('~', '_').replace('ω', 'w')
    s = re.sub(r'[^A-Za-z0-9_]', '_', s)
    return 'd' + s

def lword(letters):
    lname = {'w': 'w', 'H': 'H', 'S': 'S', 'CS': 'CS', 'SW': 'SW'}
    return '[' + ', '.join('(.%s, %d)' % (lname[g], o) for (g, o) in letters) + ']'

def lemmas():
    leangen.SLIDES = True
    CACHE = ast.literal_eval(open('cs2_cache.txt', encoding='utf-8').read())
    res = {k: v[1] for k, v in CACHE.items()}
    syms = {'invol': 'Sym.invol', 'nat1 .H': '(Sym.nat1 Gate.H)', 'nat1 .S': '(Sym.nat1 Gate.S)',
            'nat2 .CS': '(Sym.nat2 Gate.CS)', 'nat2 .swap': '(Sym.nat2 Gate.swap)'}
    g = LGen(syms, 'Gate.ω', ident)
    tops = ['B2 ' + n for n in A.RN]
    order, seen = [], set()
    def visit(x):
        if x in seen: return
        seen.add(x)
        for e in res[x][3]:
            if e[0] == 'lem': visit(e[1])
        order.append(x)
    for t in tops: visit(t)
    idents = [ident(x) for x in order]
    assert len(set(idents)) == len(idents), 'ident clash'
    out = [HDR % '''# CliffCS₂ on two wires: the block relations, derived from Figure 6

Each block relation of `W2Data.brels`, read as an equation between two-wire
circuits, derived from the rules of Figure 6 (`circ`, in the order of
`brels`).  The derivations were found by the search of `gen/driver.py`
through given lines, citing Appendix E's two-wire lemmas, and, for the five
relations in the group generated by `H₀`, `S₀`, `S₁`, `CS` and `ω` that the
search does not reach (`ck ck = s1³`, (15), (16), `t0` past `ck`, and `KK0`
after conjugating by `X₁`), by a Knuth–Bendix completion with proofs in that
group (`gen/cskb.py`, the rules `dKB_r*` and targets `dKBT_*`); each is
replayed by `derive`.''']
    out.append('''import QCert.Minimality.CliffordCS.W2Data
import QCert.Minimality.CliffordCS.Derivations

namespace QCert.Minimality.CliffordCS.W2

open QCert.Circuit
''')
    big = 300
    for nm in order:
        n, l, r, eqs, st = res[nm]
        assert n == 2, nm
        doc = nm
        if len(st) > big:
            sn = ident(nm) + '_steps'
            out.append(g.steps_def(sn, st, 'The steps of `%s`.' % ident(nm)))
            pf = g.proof_named(eqs, sn, 4)
        else:
            pf = g.proof(eqs, st, 4)
        out.append('''/-- `%s`. -/
def %s : DEqn Th 2 where
  lhs := tw 2 %s
  rhs := tw 2 %s
  proof := %s
''' % (doc, ident(nm), lword(l), lword(r), pf))
    out.append('/-- The derivations of the block relations, in the order of `brels`. -/')
    out.append('def circ : List (DEqn Th 2) := [\n  ' + wrap([ident(t) for t in tops], 2) + ']\n')
    out.append('end QCert.Minimality.CliffordCS.W2\n')
    write('W2Lemmas.lean', '\n'.join(out))
    print(len(order), 'derivations,', sum(len(res[x][4]) for x in order), 'steps')

