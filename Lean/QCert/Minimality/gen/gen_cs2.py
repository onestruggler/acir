def hs_types(f, hs):
    T = {'hjk': 'j < k', 'hkl': 'k < l', 'hlm': 'l < m', 'hjl': 'j < l', 'hkm': 'k < m'}
    N = {'hjk': 'j ≠ k', 'hjl': 'j ≠ l', 'hjm': 'j ≠ m', 'hkl': 'k ≠ l', 'hkm': 'k ≠ m'}
    out = []
    for h in hs:
        if f == 'r4' and h == 'hjk': t = N[h]
        elif f in ('r5', 'r6') and h in ('hjk', 'hjl'): t = N[h]
        elif f in ('r7', 'r8', 'r9') and h in ('hjl', 'hjm', 'hkl', 'hkm'): t = N[h]
        elif f == 'r19' and h == 'hkl': t = N[h]
        else: t = T[h]
        out.append('(%s : %s)' % (h, t))
    return out

REL_TAIL = '''/-- The scalar commutes with the decoding of every generator. -/
theorem w_comm_dB (y : QCert.BianSelingerUn.Gen 4) :
    Derivable BRel (DB (wl * FreeMonoid.of (some y))) (DB (FreeMonoid.of (some y) * wl)) := by
  have h := w_comm (Qof y ++ atomOf y :: (Qof y).reverse)
  have e : FreeMonoid.ofList (Qof y ++ atomOf y :: (Qof y).reverse) = dB (some y) := by
    simp only [dB, conj, FreeMonoid.ofList_append, FreeMonoid.ofList_cons, mul_assoc]
  rw [e] at h
  simpa only [DB, map_mul, FreeMonoid.lift_eval_of] using h
'''

