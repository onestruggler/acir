def doc(name):
    if name.startswith('qt-'): return '(%s), Appendix C.' % name[3:]
    if name.startswith('lem:qt-'): return 'The decoding of (%s), Appendix C.' % name[7:].replace('-dec-eq', '')
    if name == 'dczrev': return 'The decoded `CZ` is symmetric: `H³ CNOT H` on either wire.'
    if name == 'Dsix': return 'The decoded swap of Li et al. (D6) is `-1` times the swap (Appendix G.3, (S)).'
    return name

def de(g, res):
    out = ['''
/-- Appendix F.3 and Lemma 19: decoding the encoding of a circuit derives the
circuit. -/
theorem DE {n : ℕ} (w : Circuit Gate n) : Derivable (Lift Th n) (D.map n (E.map n w)) w := by
  refine E.derivable_comp D (fun c => ?_) (fun c => ?_) (fun c => ?_) (fun c => nomatch c) w
  · cases c; exact derive hsc [] [] (by decide +kernel)
  · cases c''']
    for nm in ['DEH', 'DES']:
        n, l, r, eqs, steps = res[nm]
        out.append('    · exact %s' % g.proof(eqs, steps, 8))
    out.append('  · cases c')
    for nm in ['DECX', 'DEswap']:
        n, l, r, eqs, steps = res[nm]
        out.append('    · exact %s' % g.proof(eqs, steps, 8))
    return '\n'.join(out)

