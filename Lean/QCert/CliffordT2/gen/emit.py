# Write the Lean certificate files from the pickled rules and equation certificates.
import sys, os, pickle
sys.set_int_max_str_digits(0)
sys.path.insert(0, os.path.dirname(__file__))
from ct import AX

HERE = os.path.dirname(os.path.abspath(__file__))
from paths import OUT, WORK
LEAN = os.path.join(OUT, 'Cert')
os.makedirs(LEAN, exist_ok=True)

LET = {'w': '.ω', 'H': '.H₀', 'h': '.H₁', 'S': '.S₀', 's': '.S₁', 'T': '.T₀', 't': '.T₁', 'Z': '.CZ'}
GENL = {'H': 'H₀', 'h': 'H₁', 'S': 'S₀', 's': 'S₁', 'T': 'T₀', 't': 'T₁', 'Z': 'CZ'}
LOC = {'H': 'H', 'S': 'S', 'T': 'T', 'h': 'H', 's': 'S', 't': 'T'}

def lw(w):
    return '[' + ', '.join(LET[c] for c in w) + ']'

def axiom_term(name):
    if name.startswith('c1_'):
        return 'Rel.c1 .%s (by decide)' % GENL[name[3]]
    if name.startswith('c2_'):
        return 'Rel.c2 .%s .%s' % (LOC[name[3]], LOC[name[4]])
    if '_' in name:
        base, i = name.split('_')
        return 'Rel.%s %s' % (base, i)
    return 'Rel.' + name

def pack(steps):
    code = 0
    for (p, k, d) in reversed(steps):
        assert p < 4096 and k < 4096, (p, k)
        code = code * 33554432 + 2 * (4096 * p + k) + (1 if d else 0)
    return code

CH = 2000

def chunks_term(st):
    parts = [st[i:i + CH] for i in range(0, len(st), CH)] or [[]]
    sep = "," + chr(10) + "      "
    return '[' + sep.join('(%d, %d)' % (len(p), pack(p)) for p in parts) + ']'

def local(steps, rules):
    used = sorted(set(k for (_, k, _) in steps))
    remap = {k: i for i, k in enumerate(used)}
    names = [rules[k][2] for k in used]
    return [(p, remap[k], d) for (p, k, d) in steps], names

HEADER = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

%s

Generated by `QCert/CliffordT2/gen/emit.py`.
-/
'''

def emit_rules(fname, title, imports, names_order, rules, proofs, index):
    out = [HEADER % title]
    for imp in imports: out.append('import ' + imp)
    out.append('')
    out.append('namespace QCert.CliffordT2.CR')
    out.append('')
    out.append('open QCert.CliffordT2')
    out.append('')
    for name in names_order:
        k = index[name]
        l, r, _ = rules[k]
        cert = proofs[name]
        if cert is None:
            out.append('def %s : Rule Rel := Rule.ofDerivable _ _ (Derivable.of (%s))' % (name, axiom_term(name)))
        else:
            st, names = local(cert, rules)
            out.append('def %s : Rule Rel :=' % name)
            out.append('  Rule.byChunks gcode_bounds gcode_inj [%s]' % ', '.join(names))
            out.append('    %s' % lw(l))
            out.append('    %s' % lw(r))
            out.append('    %s (by decide +kernel)' % chunks_term(st))
        out.append('')
    out.append('end QCert.CliffordT2.CR')
    open(os.path.join(LEAN, fname), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')

if __name__ == '__main__':
    with open(os.path.join(WORK, 'eqcerts.pkl'), 'rb') as f:
        rules, proofs, index, good = pickle.load(f)
    axn = [n for (_, _, n) in AX]
    names = [r[2] for r in rules]
    cl = [n for n in names if n.startswith('cl')]
    rot = [n for n in names if n.startswith('L')]
    emit_rules('Axioms.lean', '# The relations of Figure 1 as rewriting rules',
               ['QCert.CliffordT2.Cert.Code'], axn, rules, proofs, index)
    emit_rules('Clifford.lean', '# Rewriting rules for Clifford normal forms (stabilizer-chain tables)',
               ['QCert.CliffordT2.Cert.Axioms'], cl, rules, proofs, index)
    emit_rules('Rotations.lean', '# Rewriting rules for Pauli rotations',
               ['QCert.CliffordT2.Cert.Clifford'], rot, rules, proofs, index)
    print(len(axn), len(cl), len(rot), 'equations', sorted(good))
