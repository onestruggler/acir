# Write QCert/CliffordT2/Equations.lean: the 46 equations, with packed
# certificates where available (eqcerts.pkl) and `sorry` otherwise.  Long
# certificates are cut into pieces of CHUNK steps, each a lemma between
# explicit intermediate words.
