HERE = os.path.dirname(os.path.abspath(__file__))
from paths import OUT, WORK
DST = os.path.join(OUT, 'Equations.lean')
CHUNK = 10000
LETL = {'w': '.ω', 'H': '.H₀', 'h': '.H₁', 'S': '.S₀', 's': '.S₁', 'T': '.T₀', 't': '.T₁', 'Z': '.CZ'}

gens = ['ω', 'H₀', 'H₁', 'S₀', 'S₁', 'T₀', 'T₁', 'CZ']
srel = {
 1: ('ω₀ ^ 8', '1'), 2: ('H₀₁ ^ 2', '1'), 3: ('X₀₁ ^ 2', '1'), 4: ('X₁₂ ^ 2', '1'),
 5: ('X₂₃ ^ 2', '1'), 6: ('ω₀ * ω₁', 'ω₁ * ω₀'), 7: ('ω₂ * H₀₁', 'H₀₁ * ω₂'),
 8: ('ω₀ * X₁₂', 'X₁₂ * ω₀'), 9: ('ω₀ * X₂₃', 'X₂₃ * ω₀'), 10: ('H₀₁ * H₂₃', 'H₂₃ * H₀₁'),
 11: ('H₀₁ * X₂₃', 'X₂₃ * H₀₁'), 12: ('X₀₁ * X₂₃', 'X₂₃ * X₀₁'),
 13: ('X₀₁ * X₁₂ * X₀₁', 'X₁₂ * X₀₁ * X₁₂'), 14: ('X₁₂ * X₂₃ * X₁₂', 'X₂₃ * X₁₂ * X₂₃'),
 15: ('ω₀ * ω₁ * X₀₁', 'X₀₁ * ω₀ * ω₁'), 16: ('ω₀ * ω₁ * H₀₁', 'H₀₁ * ω₀ * ω₁'),
 17: ('H₀₁ * X₀₁', 'ω₁ ^ 4 * H₀₁'), 18: ('H₀₁ * ω₀ ^ 2 * H₀₁', 'ω₀ ^ 6 * H₀₁ * ω₀ ^ 3 * ω₁ ^ 5'),
 19: ('H₀₁ * H₂₃ * H₀₂ * H₁₃', 'H₀₂ * H₁₃ * H₀₁ * H₂₃'),
}

def lwd(w):
    return '(FreeMonoid.ofList [' + ', '.join(LETL[c] for c in w) + '])'

def code_term(lhs, rhs, st, rules):
    st2, names = local(st, rules)
    return ('derivable_of_chunks gcode_bounds gcode_inj [%s] %s %s' % (', '.join('CR.' + x for x in names), lhs, rhs)
            + chr(10) + '    ' + chunks_term(st2) + ' (by decide +kernel)')

def pieces_for(n, good, rules):
    st = good[n]
    w = EQN[n][0]
    out = []
    for i in range(0, len(st), CHUNK):
        part = st[i:i + CHUNK]
        w2 = replay(w, rules, part)
        out.append((w, w2, part))
        w = w2
    assert w == EQN[n][1]
    return out

def emit_eq(L, n, stmt_name, stmt_type, doc, good, rules):
    if n not in good:
        L.append('%s\ntheorem %s :\n    %s := by\n  sorry\n' % (doc, stmt_name, stmt_type))
        return
    st = good[n]
    if len(st) <= CHUNK:
        L.append('%s\ntheorem %s :\n    %s :=\n  %s\n' % (doc, stmt_name, stmt_type, code_term('_', '_', st, rules)))
        return
    ps = pieces_for(n, good, rules)
    names = []
    for idx, (a, b, part) in enumerate(ps):
        nm = '%s_part%d' % (stmt_name, idx)
        names.append(nm)
        if idx == 0:
            lhs_t = stmt_type.split('(wordA')[0] if False else None
        L.append('/-- Part %d of the certificate of `%s`. -/\ntheorem %s :\n    Derivable Rel %s %s :=\n  %s\n'
                 % (idx, stmt_name, nm,
                    LHS[n] if idx == 0 else lwd(a),
                    RHS[n] if idx == len(ps) - 1 else lwd(b),
                    code_term('_', '_', part, rules)))
    L.append('%s\ntheorem %s :\n    %s :=\n  %s\n' % (doc, stmt_name, stmt_type,
             names[0] + ''.join('\n    |>.trans ' + x for x in names[1:])))

