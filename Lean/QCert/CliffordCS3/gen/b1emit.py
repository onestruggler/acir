"""Lean emission of the macro data and derivations of `b1gen.B1` (a module `Checks D n`)."""
from b1gen import B1
from leanemit import RuleEmitter, wrap


def fmt_ml(a):
    if a == 'Z':
        return '.Z'
    if a == 'K':
        return '.K'
    return '.T %d' % a[1]


def fmt_word(w):
    return '[' + ', '.join(fmt_ml(a) for a in w) + ']'


def fmt_ag(g):
    if g[0] == 'i':
        return '.i %d' % g[1]
    return '.%s %d %d' % g


# ---------------------------------------------------------------- pathTo (as in Lean)
def arrange(N, s, t):
    free = [p for p in range(N) if p not in s]
    freeT = [p for p in range(N) if p not in t]
    out = []
    for p in range(N):
        if p in s:
            out.append(t[s.index(p)])
        else:
            out.append(freeT[free.index(p)])
    return out


def bpass(a, rest, i):
    if not rest:
        return [a], []
    b = rest[0]
    if b < a:
        l, sw = bpass(a, rest[1:], i + 1)
        return [b] + l, [i] + sw
    l, sw = bpass(b, rest[1:], i + 1)
    return [a] + l, sw


def bubble(k, l):
    out = []
    for _ in range(k):
        if not l:
            break
        l, sw = bpass(l[0], l[1:], 0)
        out += sw
    return out


def path_to(M, s, t):
    N = M.n
    perm = arrange(N, s, t)
    l = [M.gray.index(perm[M.gray[q]]) for q in range(N)]
    return bubble(N, l)


def act_path(B, P, g):
    for d in P:
        g = B.act(d, g)
    return g


def check_std(B, s, t, L, R, Lt, Rt):
    P = path_to(B.M, s, t)
    return [act_path(B, P, g) for g in L] == Lt and [act_path(B, P, g) for g in R] == Rt


def verify(B, n):
    """The family checks, in Python."""
    st = B.std
    z = st['r1']
    for j in range(n):
        assert check_std(B, [z], [j], [('i', z)] * 4, [], [('i', j)] * 4, [])
    for j in range(n):
        for k in range(n):
            if j < k:
                s = st['r3']
                assert check_std(B, list(s), [j, k], [('k',) + s] * 8, [], [('k', j, k)] * 8, [])
            if j != k:
                a, b = st['r4']
                assert check_std(B, [a, b], [j, k], [('i', a), ('i', b)], [('i', b), ('i', a)],
                                 [('i', j), ('i', k)], [('i', k), ('i', j)])
    for j in range(n):
        for k in range(n):
            for l in range(n):
                if k < l and j not in (k, l):
                    a, b, c = st['r6']
                    assert check_std(B, [a, b, c], [j, k, l], [('i', a), ('k', b, c)], [('k', b, c), ('i', a)],
                                     [('i', j), ('k', k, l)], [('k', k, l), ('i', j)])
    import itertools
    for j, k, l, m in itertools.product(range(n), repeat=4):
        if j < k and l < m and len({j, k, l, m}) == 4:
            a, b, c, d = st['r9']
            assert check_std(B, [a, b, c, d], [j, k, l, m], [('k', a, b), ('k', c, d)],
                             [('k', c, d), ('k', a, b)], [('k', j, k), ('k', l, m)], [('k', l, m), ('k', j, k)])
        if j < k and l < m and j < l and k < m and k != l:
            a, b, c, d = st['r19']
            assert check_std(B, [a, b, c, d], [j, k, l, m],
                             [('k', a, b), ('k', c, d), ('k', a, c), ('k', b, d)],
                             [('k', a, c), ('k', b, d), ('k', a, b), ('k', c, d)],
                             [('k', j, k), ('k', l, m), ('k', j, l), ('k', k, m)],
                             [('k', j, l), ('k', k, m), ('k', j, k), ('k', l, m)])
    return True


def emit(B, n, module, namespace, header, std, out_path):
    M, T = B.M, B.T
    targets = list(B.adj.values())
    from emit import needed
    ks = needed(T, targets)
    lines = []
    lines.append('/-\nCopyright (c) 2026 QCert contributors. All rights reserved.\n\n%s\n\nGenerated by `QCert/CliffordCS3/gen/b1emit.py`.\n-/\n' % header)
    lines.append('import QCert.CliffordCS3.Macro.Families\n')
    lines.append('set_option maxRecDepth 100000\n')
    lines.append('namespace %s\n' % namespace)
    lines.append('open QCert.CliffordCS3.Macro\n')
    fz = ['[%s]' % ', '.join(fmt_ml(a) for a in M.vF(p)) for p in range(n)]
    fk = []
    xp = []
    for p in range(n):
        row = []
        rowx = []
        for q in range(n):
            row.append(fmt_word(M.vE(p, q)) if p != q else '[]')
            rowx.append('[%s]' % ', '.join(str(d) for d in B.xp[(p, q)]) if p != q else '[]')
        fk.append('[' + ', '.join(row) + ']')
        xp.append('[' + ', '.join(rowx) + ']')
    axl = ['(%s, %s)' % (fmt_word(l), fmt_word(r)) for (nm, l, r) in B.ax]
    lines.append('/-- The macro data: the Gray path, the frames, the palindromic paths of the\ntranspositions, and the macro axioms. -/')
    lines.append('def D : Data where')
    lines.append('  gray := %s' % str(M.gray))
    lines.append('  fz := [%s]' % wrap(', '.join(fz), 4))
    lines.append('  fk := [%s]' % wrap(', '.join(fk), 4))
    lines.append('  xp := [%s]' % wrap(', '.join(xp), 4))
    lines.append('  ax := [%s]\n' % wrap(', '.join(axl), 4))
    lines.append('/-- The generators by indices. -/')
    lines.append('def S : List AG := [%s]\n' % wrap(', '.join(fmt_ag(g) for g in B.allAG), 4))
    axidx = {e: i for i, e in enumerate([B.axid[nm] for nm, l, r in B.ax])}

    def axiom(k):
        l, r, j = T.eqs[k]
        return 'axRule D (%s, %s) (by decide)' % (fmt_word(l), fmt_word(r))

    def steps(k):
        j = T.eqs[k][2]
        if j[0] == 'ax':
            return None
        return j[1]
    R = RuleEmitter('m', 'Rule (MRel D)', 'mcode_bounds', 'mcode_inj', fmt_ml,
                    lambda k: T.eqs[k][:2], steps, axiom)
    for k in ks:
        lines.append(R.emit(k))
    tab = []
    for (d, g), e in sorted(B.adj.items()):
        tab.append('(%d, %s, %s)' % (d, fmt_ag(g), R.name(e)))
    lines.append('/-- The transport table. -/')
    lines.append('def adjTable : List (Fin 7 × AG × Rule (MRel D)) :=\n  [%s]\n' % wrap(', '.join(tab), 3))
    lines.append('theorem adj_ok : adjOK D %d S adjTable = true := by decide +kernel\n' % (n - 1))
    lines.append('theorem inv_ok : invOK D %d = true := by decide +kernel\n' % (n - 1))
    z = std['r1']
    s3, s4, s6, s9, s15, s19 = std['r3'], std['r4'], std['r6'], std['r9'], std['r15'], std['r19']
    tup = lambda t: '(' + ', '.join(str(x) for x in t) + ')'
    lines.append('/-- The macro alphabet of `U%d` and the family checks. -/' % n)
    lines.append('def C : Checks D %d where' % n)
    lines.append('  S := S')
    lines.append('  hinv := tokInv_of_ok inv_ok')
    lines.append('  hadj := adj_of_ok adj_ok')
    lines.append('  z := %d' % z)
    for f, t in [('s3', s3), ('s4', s4), ('s6', s6), ('s9', s9), ('s15', s15), ('s19', s19)]:
        lines.append('  %s := %s' % (f, tup(t)))
    axfam = {nm: (l, r) for nm, l, r in B.ax}
    for f in ['ax1', 'ax3', 'ax4', 'ax6', 'ax9', 'ax15', 'ax16', 'ax17', 'ax18', 'ax19']:
        l, r = axfam['r' + f[2:]]
        lines.append('  %s := Derivable.of (MRel.ax (e := (%s, %s)) (by decide))'
                     % (f, wrap(fmt_word(l), 6), wrap(fmt_word(r), 6)))
    for f in ['c1', 'c2', 'c3', 'c4', 'c5', 'c6', 'c7', 'c8', 'c9', 'c10', 'c11', 'c12', 'c13', 'c14', 'c15', 'c19']:
        lines.append('  %s := by decide +kernel' % f)
    lines.append('')
    lines.append('/-- Every relation of `U%d(ℤ[1/2, i])` is derivable over the macro alphabet. -/' % n)
    lines.append('theorem b1 : ∀ w w\', BianSelingerUn.Rel %d w w\' → Derivable (MRel D) (encW D w) (encW D w\') :=\n  b1_of C\n' % n)
    lines.append('end %s\n' % namespace)
    open(out_path, 'w').write('\n'.join(lines))
    return len(ks)
