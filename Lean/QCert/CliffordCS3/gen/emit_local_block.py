#!/usr/bin/env python3
"""Replay the finite residual Clifford-group proof DAG on actual gate words."""
from pathlib import Path
import pickle,sys
from three_words import atom,ccZ,transposition,lean_list
from emit_atom import chunks
sys.set_int_max_str_digits(0)
BASE=Path(__file__).resolve().parent
EXP={0:[8],1:ccZ(),2:atom(),3:transposition(3,7)}
TERMS={
 'p4':'Replay.ax (Rel.c5 1)',
 'q2':'Rule.ofDerivable _ _ Monomial.ccZ_square',
 'a3':'Rule.ofDerivable _ _ Swap01.atom_cube',
 'pA':'Rule.ofDerivable _ _ (QuotientGroup.to_derivable (by simpa only [map_mul] using LocalKZ.P_A.eq))',
 'pQ':'Rule.ofDerivable _ _ Monomial.phase_ccZ_commute',
 'triangle':'Rule.ofDerivable _ _ LocalKZ.sign_atom_cube',
 'tdef':'Rule.ofDerivable _ _ LocalKZ.token_as_atoms'}


def emit():
 with Path('/tmp/acir-cs3-local-block.pickle').open('rb') as f:s=pickle.load(f)
 rules=s['rules'];letters=s['letters'];used=set()
 def need(i):
  if i in used:return
  used.add(i);p=rules[i][2]
  if p[0]!='base':
   for _,j,_ in p:need(j)
 for p in s['solved'].values():
  assert p is not None
  for _,j,_ in p:need(j)
 def decode(w):return [letters[i] for i in w]
 def expand(w):return sum((EXP[g] for g in w),[])
 def replay(w,proof):
  deps=sorted(set(j for _,j,_ in proof));indexes={j:i for i,j in enumerate(deps)}
  steps=[];w=list(w)
  for pos,j,rev in proof:
   l,r=map(decode,rules[j][:2])
   if rev:l,r=r,l
   assert w[pos:pos+len(l)]==l
   steps.append((len(expand(w[:pos])),indexes[j],rev))
   w=w[:pos]+r+w[pos+len(l):]
  return deps,steps,w
 out=['''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Kernel-checked residual equations on K, Z and the last transposition

Generated by gen/local_block.py and gen/emit_local_block.py from the
proved order, commutation, and triangle equations of LocalKZ.
-/
import QCert.CliffordCS3.Three.LocalKZ

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace QCert.CliffordCS3.Three.Cert.LocalBlock
''']
 for i in sorted(used):
  l,r,p,_=rules[i]
  if p[0]=='base':
   expr=TERMS[p[1]]
   if p[2]:expr='('+expr+').symm'
   # Let the endpoints constrain the implicit word arguments.
   out.append(f'def r{i} : Rule Rel where\n  lhs := {lean_list(expand(decode(l)))}\n  rhs := {lean_list(expand(decode(r)))}\n  sound := ({expr}).sound\n')
  else:
   deps,steps,end=replay(decode(l),p);assert end==decode(r)
   out.append(f'def r{i} : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list(expand(decode(l)))}\n    {lean_list(expand(decode(r)))}\n    {chunks(steps)} (by decide +kernel)\n')
 for name,l,r in s['targets']:
  deps,steps,end=replay(l,s['solved'][name]);assert end==list(r)
  out.append(f'def {name} : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list(expand(l))}\n    {lean_list(expand(r))}\n    {chunks(steps)} (by decide +kernel)\n')
 out.append('''def table : Bool → List (Rule Rel)
  | false => [T20, Z40, K80, phase0, KZ20, KZ30, KP0, K2P0]
  | true => [T21, Z41, K81, phase1, KZ21, KZ31, KP1, K2P1]

def indices : List ℕ := [6, 39, 40, 41, 44, 45, 46, 47]

def covers : Bool :=
  [false, true].all fun c => indices.all fun i =>
    let e := M8.D.ax[i]!
    let a := (hstar h c (FreeMonoid.ofList e.1)).1
    let b := (hstar h c (FreeMonoid.ofList e.2)).1
    (table c).any fun r => r.lhs == a.toList && r.rhs == b.toList

theorem covers_true : covers = true := by decide +kernel

end QCert.CliffordCS3.Three.Cert.LocalBlock
''')
 path=BASE.parent/'Three/Cert/LocalBlock.lean'
 path.write_text('\n'.join(out),encoding='utf8',newline='\n')
 print('Used',len(used),'rules;',len(path.read_text().splitlines()),'lines')


if __name__=='__main__':emit()
