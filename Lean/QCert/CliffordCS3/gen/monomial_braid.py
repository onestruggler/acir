#!/usr/bin/env python3
"""Emit the finite abstract reduction of a Toffoli braid to disjointness."""
import heapq, importlib.util, sys
from pathlib import Path
BASE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('kb', BASE.parents[1]/'Minimality/gen/cskb.py')
mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
t,w,z=(0,),(1,),(2,);x=t+z+t+z
bases=[('t2',t+t,()),('w2',w+w,()),('z2',z+z,()),('wz',w+z,z+w),
       ('tz4',(t+z)*4,()),('xw3',(x+w)*3,()),('cross',t+w+z+t+z+w,w+z+t+z+w+t)]
kb=mod.KB([0,1,2],bases)
for steps in range(10000):
    if not kb.pending:break
    _,_,a,b,p=heapq.heappop(kb.pending);kb.process(a,b,p)
    if steps%100==99 and kb.provable((t+w)*6,()):break
proof=kb.proof_of((t+w)*6,());assert proof is not None
used=set()
def need(rid):
    if rid in used:return
    used.add(rid);p=kb.rules[rid][2]
    if p[0]!='base':
        for _,j,_ in p:need(j)
for _,j,_ in proof:need(j)
def wl(w):return '['+', '.join(str(x)for x in w)+']'
def pack(steps):
    ans=0
    for p,j,rev in reversed(steps):ans=ans*33554432+2*(4096*p+j)+(0 if rev else 1)
    return ans
out=['''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Reducing the Toffoli braid to opposite-control disjointness

Generated by gen/monomial_braid.py. This is a conditional algebraic lemma:
all seven assumptions must be supplied as derivations of the target theory.
-/
import QCert.CliffordT2.FastRewrite

set_option maxRecDepth 10000

namespace QCert.CliffordCS3.Three.MonomialBraid

abbrev Letter := Fin 3
def word (l : List Letter) : Word Letter := FreeMonoid.ofList l

inductive R : WRel Letter where
''']
for name,a,b in bases:out.append(f'  | {name} : R (word {wl(a)}) (word {wl(b)})')
out.append('''
def code (x : Letter) : Nat := x.val + 1
theorem bounds : forall x, 0 < code x /\\ code x < 16 := by
  intro x; dsimp [code]; omega
theorem inj : Function.Injective code := by
  intro a b h; apply Fin.ext; simp only [code] at h; omega
'''.replace('forall','∀').replace('/\\','∧'))
for rid in sorted(used):
    a,b,p,_=kb.rules[rid]
    if p[0]=='base':
        _,name,rev=p
        lhs,rhs=next((l,r)for n,l,r in bases if n==name)
        e=f'Rule.ofDerivable (word {wl(lhs)}) (word {wl(rhs)}) (Derivable.of R.{name})'
        if rev:e='('+e+').symm'
        out.append(f'def r{rid} : Rule R := {e}')
    else:
        deps=sorted(set(j for _,j,_ in p));ids={j:i for i,j in enumerate(deps)}
        p2=[(a,ids[j],d)for a,j,d in p]
        out.append(f'def r{rid} : Rule R := Rule.byChunks bounds inj\n  [{", ".join("r"+str(j)for j in deps)}] {wl(a)} {wl(b)}\n  [({len(p2)}, {pack(p2)})] (by decide +kernel)')
deps=sorted(set(j for _,j,_ in proof));ids={j:i for i,j in enumerate(deps)}
p2=[(a,ids[j],d)for a,j,d in proof]
out.append(f'theorem abstract_six : Derivable R (word {wl((t+w)*6)}) 1 :=\n  derivable_of_chunks bounds inj [{", ".join("r"+str(j)for j in deps)}]\n    (word {wl((t+w)*6)}) 1 [({len(p2)}, {pack(p2)})] (by decide +kernel)')
out.append('''
section Transfer
variable {A : Type*} {Gamma : WRel A}

def sub (t w z : Word A) : Word Letter →* Word A :=
  FreeMonoid.lift fun a => if a = 0 then t else if a = 1 then w else z

theorem six_of (t w z : Word A)
    (ht : Derivable Gamma (t * t) 1)
    (hw : Derivable Gamma (w * w) 1)
    (hz : Derivable Gamma (z * z) 1)
    (hwz : Derivable Gamma (w * z) (z * w))
    (htz : Derivable Gamma ((t * z) ^ 4) 1)
    (horder : Derivable Gamma ((t * z * t * z * w) ^ 3) 1)
    (hcross : Derivable Gamma (t * w * z * t * z * w) (w * z * t * z * w * t)) :
    Derivable Gamma ((t * w) ^ 6) 1 := by
  have liftR : forall a b, R a b → Derivable Gamma (sub t w z a) (sub t w z b) := by
    intro a b h
    cases h
    all_goals simp only [word, sub, FreeMonoid.lift_ofList, List.map_cons,
      List.map_nil, List.prod_cons, List.prod_nil, mul_one, Fin.reduceEq, if_true, if_false]
    · exact ht
    · exact hw
    · exact hz
    · exact hwz
    · simpa only [pow_succ, pow_zero, one_mul, mul_assoc] using htz
    · simpa only [pow_succ, pow_zero, one_mul, mul_assoc] using horder
    · simpa only [mul_assoc] using hcross
  have h := Derivable.map (sub t w z) liftR abstract_six
  simpa only [word, sub, FreeMonoid.lift_ofList, List.map_cons,
    List.map_nil, List.prod_cons, List.prod_nil, mul_one, Fin.reduceEq, if_true, if_false,
    pow_succ, pow_zero, one_mul, mul_assoc] using h

end Transfer
end QCert.CliffordCS3.Three.MonomialBraid
'''.replace('forall','∀'))
path=BASE.parent/'Three/MonomialBraid.lean';path.write_text('\n\n'.join(out)+'\n',encoding='utf8',newline='\n')
print(path,len(used),'rules')

