#!/usr/bin/env python3
"""Export the proof DAG of the small-alphabet controlled-commutator search."""
from pathlib import Path
import pickle,sys,json
from three_words import LEAN,lean_list
sys.set_int_max_str_digits(0)
BASE=Path(__file__).resolve().parent
MAP=(0,2,7,8)


def pack(steps):
    ans=0
    for pos,rid,rev in reversed(steps):ans=ans*33554432+2*(4096*pos+rid)+(0 if rev else 1)
    return ans


def chunks(steps):
    return '['+', '.join(f'({len(steps[i:i+1000])}, {pack(steps[i:i+1000])})' for i in range(0,len(steps),1000))+']'


def emit(seed=5,extra=False):
    negative=extra=='negative'
    signneg=extra=='signneg'
    directory='/tmp/acir-cs3-atom-signneg' if signneg else '/tmp/acir-cs3-atom-neg' if negative else '/tmp/acir-cs3-atom-extra' if extra else '/tmp/acir-cs3-atom'
    goalnames=['sign_negA','sign_negB'] if signneg else ['comm_negA','comm_negB'] if negative else ['conjugate_sign','triangle'] if extra else ['cube']
    module='SignNegative' if signneg else 'AtomNegative' if negative else 'AtomRelations' if extra else 'AtomCube'
    datafile=BASE/'data'/f'{module}-seed{seed}.json'
    if datafile.exists():
        s=json.loads(datafile.read_text())
        s['rules']={int(k):v for k,v in s['rules'].items()}
    else:
        with Path(f'{directory}/atom{seed}.pickle').open('rb') as f:s=pickle.load(f)
    assert all(name in s['solved'] for name in goalnames)
    letters=s['letters'];rules=s['rules'];bases={n:(l,r) for n,l,r in s['base']}
    def decode(w):return tuple(letters[i] for i in w)
    def globalword(w):return tuple(MAP[g] for g in decode(w))
    used=set()
    def need(rid):
        if rid in used:return
        used.add(rid);proof=rules[rid][2]
        if proof[0]!='base':
            for _,j,_ in proof:need(j)
    for name in goalnames:
        for _,j,_ in s['solved'][name]:need(j)
    if not datafile.exists():
        neededbases={rules[j][2][1] for j in used if rules[j][2][0]=='base'}
        data={'letters':s['letters'],'base':[v for v in s['base'] if v[0] in neededbases],
              'rules':{j:[list(rules[j][0]),list(rules[j][1]),rules[j][2],rules[j][3]] for j in used},
              'solved':{name:s['solved'][name] for name in goalnames},'targets':s['targets']}
        datafile.parent.mkdir(exist_ok=True)
        datafile.write_text(json.dumps(data,separators=(',',':'))+'\n')
    print('USED',len(used),'of',len(rules))
    out=['''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# The cube of a doubly controlled Clifford commutator

Generated by gen/emit_atom.py. Base steps are Figure 2 or independently
proved two-qubit equations; every completion step is replayed by the kernel.
-/
import QCert.CliffordCS3.Rewrite

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace QCert.CliffordCS3.Three.Cert.MODULE
'''.replace('MODULE',module)]
    for rid in sorted(used):
        l,r,proof,_=rules[rid]
        if proof[0]=='base':
            _,name,rev=proof
            if name.startswith('pair'):
                j=0 if name[-1]=='a' else 1
                conv={0:'i',1:'Kl' if j==0 else 'Ku',2:'CS',3:'CS'}
                bl,br=bases[name]
                def local(w):return '['+', '.join('Two.Gen2.'+conv[g] for g in w)+']'
                expr=f'Replay.pairRule {j} {local(bl)} {local(br)} (by decide +kernel)'
            else:expr='Replay.ax Rel.'+name
            if rev:expr='('+expr+').symm'
            out.append(f'def r{rid} : Rule Rel := {expr}\n')
        else:
            dependencies=sorted(set(j for _,j,_ in proof));indexes={j:i for i,j in enumerate(dependencies)}
            steps=[(p,indexes[j],rev) for p,j,rev in proof]
            out.append(f'def r{rid} : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in dependencies)}]\n    {lean_list(globalword(l))}\n    {lean_list(globalword(r))}\n    {chunks(steps)} (by decide +kernel)\n')
    targets={n:(l,r) for n,l,r in s['targets']}
    A=targets['cube'][0][:len(targets['cube'][0])//3]
    out.append('def word : Word Gen := FreeMonoid.ofList '+lean_list([MAP[g] for g in A])+'\n')
    out.append('def phaseSquare : Word Gen := FreeMonoid.ofList '+lean_list([MAP[g] for g in targets['cube'][1]])+'\n')
    if extra:
        R=targets['conjugate_sign'][0][len(A):]
        out.append('def signCore : Word Gen := FreeMonoid.ofList '+lean_list([MAP[g] for g in R])+'\n')
    for name in goalnames:
        proof=s['solved'][name];deps=sorted(set(j for _,j,_ in proof));indexes={j:i for i,j in enumerate(deps)}
        steps=[(p,indexes[j],rev) for p,j,rev in proof];lhs,rhs=targets[name]
        out.append(f'def {name}Rule : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list([MAP[g] for g in lhs])}\n    {lean_list([MAP[g] for g in rhs])}\n    {chunks(steps)} (by decide +kernel)\n')
    if signneg:
        out.append('theorem sign_negA : Derivable Rel (W.CS12 ^ 2 * signCore * (W.K 1 * signCore * (W.I * W.K 1))) ((W.K 1 * signCore * (W.I * W.K 1)) * W.CS12 ^ 2 * signCore) := sign_negARule.sound\n')
        out.append('theorem sign_negB : Derivable Rel (W.CS01 ^ 2 * signCore * (W.K 1 * signCore * (W.I * W.K 1))) ((W.K 1 * signCore * (W.I * W.K 1)) * W.CS01 ^ 2 * signCore) := sign_negBRule.sound\n')
    elif negative:
        out.append('theorem comm_negA : Derivable Rel (word * (W.K 1 * W.CS12 ^ 2 * signCore * (W.I * W.K 1))) ((W.K 1 * W.CS12 ^ 2 * signCore * (W.I * W.K 1)) * word) := comm_negARule.sound\n')
        out.append('theorem comm_negB : Derivable Rel (word * (W.K 1 * W.CS01 ^ 2 * signCore * (W.I * W.K 1))) ((W.K 1 * W.CS01 ^ 2 * signCore * (W.I * W.K 1)) * word) := comm_negBRule.sound\n')
    elif extra:
        out.append('theorem conjugate_sign : Derivable Rel (word * signCore) (W.K 1 * signCore * (W.I * W.K 1) * word) := conjugate_signRule.sound\n')
        out.append('theorem triangle : Derivable Rel ((signCore * word) ^ 3) phaseSquare := by\n  simpa [word, signCore, phaseSquare, pow_succ, pow_zero, FreeMonoid.ofList_append] using triangleRule.sound\n')
    else:
        out.append('theorem cube : Derivable Rel (word ^ 3) phaseSquare := by\n  simpa [word, phaseSquare, pow_succ, pow_zero, FreeMonoid.ofList_append] using cubeRule.sound\n')
    out.append('end QCert.CliffordCS3.Three.Cert.'+module+'\n')
    path=BASE.parent/('Three/Cert/'+module+'.lean');path.write_text('\n'.join(out),encoding='utf8',newline='\n')
    print(path,'lines',len(path.read_text().splitlines()))


if __name__=='__main__':emit(int(sys.argv[1]) if len(sys.argv)>1 else 5,sys.argv[2] if len(sys.argv)>2 else False)
