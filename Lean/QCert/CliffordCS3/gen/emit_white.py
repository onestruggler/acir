#!/usr/bin/env python3
"""Export the double-white control commutation certificate."""
from pathlib import Path
import pickle,json,sys
from three_words import lean_list
from emit_atom import chunks
sys.set_int_max_str_digits(0)
BASE=Path(__file__).resolve().parent
MAP=(0,2,7,8,5)

def emit(seed=4):
 datafile=BASE/'data'/f'AtomWhite-seed{seed}.json'
 if datafile.exists():
  s=json.loads(datafile.read_text());s['rules']={int(k):v for k,v in s['rules'].items()}
 else:
  with Path(f'/tmp/acir-cs3-atom-white/white{seed}.pickle').open('rb') as f:s=pickle.load(f)
 assert 'comm_white' in s['solved']
 rules=s['rules'];letters=s['letters'];bases={n:(l,r) for n,l,r in s['base']};used=set()
 def need(i):
  if i in used:return
  used.add(i);proof=rules[i][2]
  if proof[0]!='base':
   for _,j,_ in proof:need(j)
 for _,j,_ in s['solved']['comm_white']:need(j)
 if not datafile.exists():
  bn={rules[j][2][1] for j in used if rules[j][2][0]=='base'}
  data={'letters':letters,'base':[x for x in s['base'] if x[0] in bn],
        'rules':{j:[list(rules[j][0]),list(rules[j][1]),rules[j][2],rules[j][3]] for j in used},
        'solved':s['solved'],'targets':s['targets']}
  datafile.parent.mkdir(exist_ok=True);datafile.write_text(json.dumps(data,separators=(',',':'))+'\n')
 def globalword(w):return [MAP[letters[i]] for i in w]
 def stepterm(proof):
  dep=sorted(set(j for _,j,_ in proof));remap={j:i for i,j in enumerate(dep)}
  return dep,chunks([(p,remap[j],rev) for p,j,rev in proof])
 out=['''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Commutation with the double-white controlled exchange

Generated by gen/emit_white.py. All base equations have already been
proved from Figure 2, or follow from checked two-qubit completeness.
-/
import QCert.CliffordCS3.Three.Cert.AtomRelations
import QCert.CliffordCS3.Three.Cert.AtomNegative

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace QCert.CliffordCS3.Three.Cert.AtomWhite
''']
 for rid in sorted(used):
  l,r,p,_=rules[rid]
  if p[0]=='base':
   _,name,rev=p
   if name.startswith('pair'):
    j=0 if name[4]=='a' else 1;conv={0:'i',1:'Kl' if j==0 else 'Ku',2:'CS',3:'CS',4:'Sl' if j==0 else 'Su'}
    def local(w):return '['+', '.join('Two.Gen2.'+conv[g] for g in w)+']'
    bl,br=bases[name];expr=f'Replay.pairRule {j} {local(bl)} {local(br)} (by decide +kernel)'
   else:expr=name
   if rev:expr='('+expr+').symm'
   out.append(f'def r{rid} : Rule Rel := {expr}\n')
  else:
   deps,cert=stepterm(p)
   out.append(f'def r{rid} : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list(globalword(l))}\n    {lean_list(globalword(r))}\n    {cert} (by decide +kernel)\n')
 _,lhs,rhs=s['targets'][0];deps,cert=stepterm(s['solved']['comm_white'])
 out.append(f'def comm_whiteRule : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list([MAP[g] for g in lhs])}\n    {lean_list([MAP[g] for g in rhs])}\n    {cert} (by decide +kernel)\n')
 out.append('''theorem comm_white : Derivable Rel
    (AtomRelations.word * (W.K 1 * W.S 1 ^ 2 * W.CS01 ^ 2 * W.CS12 ^ 2 * AtomRelations.signCore * (W.I * W.K 1)))
    ((W.K 1 * W.S 1 ^ 2 * W.CS01 ^ 2 * W.CS12 ^ 2 * AtomRelations.signCore * (W.I * W.K 1)) * AtomRelations.word) :=
  comm_whiteRule.sound

end QCert.CliffordCS3.Three.Cert.AtomWhite
''')
 path=BASE.parent/'Three/Cert/AtomWhite.lean';path.write_text('\n'.join(out),encoding='utf8',newline='\n')
 print('Used',len(used),'rules;',len(path.read_text().splitlines()),'lines')

if __name__=='__main__':emit(int(sys.argv[1]) if len(sys.argv)>1 else 4)
