"""Coset tables with proofs (coset-table verification).

A finite group G is generated by letters (with matrices).  H is a subgroup with a normal form
provider (`Abelian`, or any object with `letters`, `word(e)`, `exps(m)`, `normalize(D, s, e)`,
`mat_of_exps(e)`, `elements`).  For the right cosets H g (representatives `rep(c)`, words built
by breadth-first search) and every letter x, the entry

    rep(c) x  =  h rep(c x)        (h an H normal form)

is proved from relator equations of the proof table by the deductions of a coset
enumeration over the known table.  Every word then normalizes to h rep(c) with a derivation
(`normalize_word`), and two words with the same matrix have the same normal form.
"""
import itertools
import numpy as np
from collections import deque
from table import Deriv
from qc import key


class Abelian:
    """H = prod <a_i> of orders o_i, normal form a_1^e_1 ... a_r^e_r.
    comm[(a, b)] (rank a > rank b) = (eid, d): applying it rewrites 'a b' into 'b a'.
    power[a] = (eid, d): rewrites a^o into the empty word."""

    def __init__(self, letters, orders, mats, comm, power):
        self.letters = list(letters)
        self.orders = list(orders)
        self.pos = {a: i for i, a in enumerate(self.letters)}
        self.mats = mats
        self.comm = comm
        self.power = power
        self.elements = {}
        n = mats[self.letters[0]].shape[0]
        self.n = n
        self.elist = []
        self.identity = tuple([0] * len(self.letters))
        for e in itertools.product(*[range(o) for o in self.orders]):
            m = self.mat_of_exps(e)
            k = key(m)
            assert k not in self.elements, 'H is not free abelian on these letters'
            self.elements[k] = e
            self.elist.append(m)

    def mat_of_exps(self, e):
        m = np.eye(self.n, dtype=complex)
        for a, k in zip(self.letters, e):
            for _ in range(k):
                m = m @ self.mats[a]
        return m

    def word(self, e):
        out = []
        for a, k in zip(self.letters, e):
            out += [a] * k
        return tuple(out)

    def exps(self, m):
        return self.elements.get(key(m))

    def normalize(self, D, start, end):
        """Sort and reduce the segment D.w[start:end] (a word in H's letters); returns its end."""
        while True:
            seg = D.w[start:end]
            moved = False
            for i in range(len(seg) - 1):
                a, b = seg[i], seg[i + 1]
                if self.pos[a] > self.pos[b]:
                    k, d = self.comm[(a, b)]
                    D.step(start + i, k, d)
                    moved = True
                    break
            if moved:
                continue
            for i in range(len(seg)):
                a = seg[i]
                o = self.orders[self.pos[a]]
                if seg[i:i + o] == (a,) * o:
                    k, d = self.power[a]
                    D.step(start + i, k, d)
                    end -= o
                    moved = True
                    break
            if not moved:
                return end


class Inverses:
    """inv[x]: a word; right[x] = (eid, d) rewriting x inv(x) into the empty word;
    left[x] = (eid, d) rewriting inv(x) x into the empty word."""

    def __init__(self, inv, right, left):
        self.inv = inv
        self.right = right
        self.left = left

    def word(self, u):
        out = []
        for x in reversed(u):
            out += list(self.inv[x])
        return tuple(out)

    def insert(self, D, p, u):
        """Insert u inv(u) at position p."""
        for j in range(len(u)):
            k, d = self.right[u[j]]
            D.step(p + j, k, not d)

    def cancel(self, D, p, u):
        """Delete u inv(u) at position p."""
        for j in range(len(u) - 1, -1, -1):
            k, d = self.right[u[j]]
            D.step(p + j, k, d)

    def insert_left(self, D, p, u):
        """Insert inv(u) u at position p."""
        for j in range(len(u) - 1, -1, -1):
            off = sum(len(self.inv[u[t]]) for t in range(j + 1, len(u)))
            k, d = self.left[u[j]]
            D.step(p + off, k, not d)


class CTV:
    def __init__(self, T, letters, mats, H, invs, relators, verbose=False, phases=None, name=''):
        self.T = T
        self.letters = list(letters)
        self.mats = mats
        self.H = H
        self.I = invs
        self.relators = list(relators)
        self.verbose = verbose
        self.phases = phases
        self.name = name
        self.build_table()

    def ckey(self, m):
        prods = self._hst @ m
        a = np.round(prods * (1 << 20))
        re = a.real.astype(np.int64).reshape(len(self._hst), -1)
        im = a.imag.astype(np.int64).reshape(len(self._hst), -1)
        allk = np.concatenate([re, im], axis=1)
        j = np.lexsort(allk.T[::-1])[0]
        return allk[j].tobytes()

    def coset_of(self, m):
        if self._hst is not None:
            return self.cid.get(self.ckey(m))
        for c in range(len(self.reps)):
            if self.H.exps(m @ self.invm[c]) is not None:
                return c
        return None

    def build_table(self):
        H = self.H
        n = self.mats[self.letters[0]].shape[0]
        self.invm = []
        if getattr(H, 'elist', None) is not None and len(H.elist) <= 70000:
            self._hst = np.array(H.elist)            # |H| x n x n
        else:
            self._hst = None
        coset_of = self.coset_of
        e = np.eye(n, dtype=complex)
        self.reps = [()]
        self.repm = [e]
        self.invm = [e]
        self.cid = {self.ckey(e): 0} if self._hst is not None else {}
        self.parent = [None]
        for phase in (self.phases or [self.letters]):
            q = deque(range(len(self.reps)))
            while q:
                c = q.popleft()
                for x in phase:
                    m = self.repm[c] @ self.mats[x]
                    if coset_of(m) is None:
                        k = len(self.reps)
                        if self._hst is not None:
                            self.cid[self.ckey(m)] = k
                        self.reps.append(self.reps[c] + (x,))
                        self.repm.append(m)
                        self.invm.append(np.linalg.inv(m))
                        self.parent.append((c, x))
                        q.append(k)
        N = len(self.reps)
        if self.verbose:
            print(' ', self.name, 'cosets', N, flush=True)
        self.tab = {}
        self.hpart = {}
        for c in range(N):
            for x in self.letters:
                m = self.repm[c] @ self.mats[x]
                c2 = coset_of(m)
                h = m @ self.invm[c2]
                ex = H.exps(h)
                assert ex is not None
                self.tab[(c, x)] = c2
                self.hpart[(c, x)] = ex
        self.proof = {}
        zero = H.identity
        for c2 in range(1, N):
            c, x = self.parent[c2]
            assert self.hpart[(c, x)] == zero
            self.proof[(c, x)] = 'tree'
        for c in range(N):
            for x in self.letters:
                if (c, x) not in self.proof:
                    l, r = self.entry_eq(c, x)
                    if l == r:
                        self.proof[(c, x)] = 'id'

    def entry_eq(self, c, x):
        c2 = self.tab[(c, x)]
        return self.reps[c] + (x,), self.H.word(self.hpart[(c, x)]) + self.reps[c2]

    def trace(self, D, p, c, u):
        """D.w[p:] starts with rep(c) u; rewrite it into h rep(c u) with h normalized.
        Returns (end of h, final coset)."""
        hend = p
        for x in u:
            pr = self.proof[(c, x)]
            if pr != 'tree':
                if pr != 'id':
                    D.step(hend, pr, True)
                hl = len(self.H.word(self.hpart[(c, x)]))
                hend = self.H.normalize(D, p, hend + hl)
            c = self.tab[(c, x)]
        return hend, c

    def path(self, c, u):
        cs = [c]
        for x in u:
            cs.append(self.tab[(cs[-1], x)])
        return cs

    def rotations(self, rid):
        """The rotations of the relator l = r: b = inv(a) r and a = r inv(b) for l = a b, and
        likewise with l and r exchanged, as derived equations."""
        T, I = self.T, self.I
        l, r, _ = T.eqs[rid]
        out = []
        for (u, v, d) in ((l, r, True), (r, l, False)):
            for k in range(1, len(u)):
                a, b = u[:k], u[k:]
                if any(x not in I.inv for x in a + b):
                    continue
                # b -> inv(a) a b -> inv(a) v
                D = Deriv(T, b)
                I.insert_left(D, 0, a)
                D.step(len(I.word(a)), rid, d)
                out.append(T.derived(b, D.w, D.steps))
                # a -> a b inv(b) -> v inv(b)
                D = Deriv(T, a)
                I.insert(D, len(a), b)
                D.step(0, rid, d)
                out.append(T.derived(a, D.w, D.steps))
        return out

    def deduce_all(self, maxrounds=1000, rotate=True):
        T = self.T
        N = len(self.reps)
        total = N * len(self.letters)
        rotated = False
        for rnd in range(maxrounds):
            progress = False
            for c in range(N):
                for rid in self.relators:
                    l, r, _ = T.eqs[rid]
                    for (a, b, d) in ((l, r, True), (r, l, False)):
                        while self.try_deduce(c, a, b, rid, d):
                            progress = True
            if self.verbose:
                print('   round', rnd, 'proved', len(self.proof), '/', total, flush=True)
            if len(self.proof) == total:
                return True
            if not progress:
                if rotate and not rotated:
                    rotated = True
                    new = []
                    seen = set()
                    for rid in self.relators:
                        for e in self.rotations(rid):
                            k = T.eqs[e][:2]
                            if k not in seen:
                                seen.add(k)
                                new.append(e)
                    if self.verbose:
                        print('   rotations', len(new), flush=True)
                    self.relators = self.relators + new
                    continue
                return False
        return False

    def missing(self):
        return [(c, x) for c in range(len(self.reps)) for x in self.letters if (c, x) not in self.proof]

    def try_deduce(self, c, a, b, rid, d):
        ca = self.path(c, a)
        cb = self.path(c, b)
        missing = [k for k in range(len(a)) if (ca[k], a[k]) not in self.proof]
        if len(missing) != 1:
            return False
        if any((cb[k], b[k]) not in self.proof for k in range(len(b))):
            return False
        k = missing[0]
        ck1, x = ca[k], a[k]
        lhs, rhs = self.entry_eq(ck1, x)
        H = self.H
        I = self.I
        D = Deriv(self.T, lhs)
        # rep(ck1) x  ->  H1^-1 H1 rep(ck1) x  ->  H1^-1 rep(c) a[:k] x
        D1 = Deriv(self.T, self.reps[c] + tuple(a[:k]))
        h1end, cc = self.trace(D1, 0, c, a[:k])
        assert cc == ck1
        H1 = D1.w[:h1end]
        I.insert_left(D, 0, H1)
        off = len(I.word(H1))
        D.rsteps_at(D1.steps, off)
        # append suffix inv(suffix), apply the relator
        suf = tuple(a[k + 1:])
        I.insert(D, len(D.w), suf)
        D.step(off + len(self.reps[c]), rid, d)
        # rep(c) b -> H2 rep(c_end)
        D2 = Deriv(self.T, self.reps[c] + tuple(b))
        h2end, cr = self.trace(D2, 0, c, b)
        D.steps_at(D2.steps, off)
        Hr = D2.w[:h2end]
        ck = self.tab[(ck1, x)]
        # rep(ck) suf -> H3 rep(c_end)
        D3 = Deriv(self.T, self.reps[ck] + suf)
        h3end, ce = self.trace(D3, 0, ck, suf)
        assert ce == cr
        H3 = D3.w[:h3end]
        p = off + len(Hr)
        I.insert_left(D, p, H3)
        D.rsteps_at(D3.steps, p + len(I.word(H3)))
        q = p + len(I.word(H3)) + len(self.reps[ck])
        I.cancel(D, q, suf)
        H.normalize(D, 0, p + len(I.word(H3)))
        assert D.w == rhs, (D.w, rhs)
        eid = self.T.derived(lhs, rhs, D.steps)
        self.proof[(ck1, x)] = eid
        return True

    def normalize_word(self, w, D=None, p=0):
        """Rewrite w (at position p of D) into h rep(c); returns (D, coset, end of h)."""
        if D is None:
            D = Deriv(self.T, w)
        hend, c = self.trace(D, p, 0, tuple(w))
        return D, c, hend

    def prove(self, u, v, name=None):
        """u = v (same element): a derivation through the common normal form."""
        Du, cu, _ = self.normalize_word(u)
        Dv, cv, _ = self.normalize_word(v)
        assert cu == cv and Du.w == Dv.w, ('different normal forms', Du.w, Dv.w)
        steps = Du.steps + [(p, k, not dd) for (p, k, dd) in reversed(Dv.steps)]
        return self.T.derived(u, v, steps, name)


def word_of(G, m):
    """The normal form word h rep(c) of the element with matrix m (None if m is not in G)."""
    for c in range(len(G.reps)):
        h = m @ G.invm[c]
        ex = G.H.exps(h)
        if ex is not None:
            return G.H.word(ex) + G.reps[c]
    return None
