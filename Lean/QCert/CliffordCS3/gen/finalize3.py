"""Assemble the checked action and round-trip tables and their Lean interface."""
import pickle
import sys
from pathlib import Path
from threeemit import ROOT, CACHE, FMT
from b1emit import fmt_word
from macro import macro_axioms
import b2q1


def main():
    sys.setrecursionlimit(1000000)
    with CACHE.with_name('phase-c-roundtrips.pkl').open('rb') as f:
        P,CT,faces,done,missing,aa=pickle.load(f)
    assert not missing and len(aa)==9
    with CACHE.with_name('emitted-current.pkl').open('rb') as f:
        names,pi=pickle.load(f)
    def word(w): return '['+', '.join(FMT[z] for z in P.A.expand(w))+']'
    src=['/- Generated by QCert/CliffordCS3/gen/finalize3.py. -/',
         'import QCert.CliffordCS3.Cert.Part%03d'%pi]
    pair_count = len(list((ROOT/'Cert').glob('Pair*.lean')))
    src += ['import QCert.CliffordCS3.Cert.Pair%03d' % j for j in range(max(0, pair_count-4), pair_count)]
    src += ['namespace QCert.CliffordCS3.Cert', 'open Macro']
    rows=[]
    for nm,l,r in macro_axioms(b2q1.M8,b2q1.STD):
        for c in ('I','J'):
            e=done[nm,c]
            if e in names: term=names[e]
            else:
                u,_=b2q1.hstarM(c,l); v,_=b2q1.hstarM(c,r)
                assert P.A.expand(u)==P.A.expand(v)
                term='Rule.ofDerivable (FreeMonoid.ofList %s) (FreeMonoid.ofList %s) (Derivable.refl _)'%(word(u),word(v))
            rows.append('(%s, %s, %s, %s)'%('false' if c=='I' else 'true',fmt_word(l),fmt_word(r),term))
    src.append('def b2Table : List (Bool × List ML × List ML × Rule Rel) :=\n  [ '+',\n    '.join(rows)+' ]')
    rows=['(%s, %s)'%(FMT[x],names[e]) for x,e in aa.items()]
    src.append('def aTable : List (Gen × Rule Rel) :=\n  [ '+',\n    '.join(rows)+' ]')
    src.append('end QCert.CliffordCS3.Cert\n')
    (ROOT/'Cert/Targets.lean').write_text('\n\n'.join(src),encoding='utf-8',newline='\n')
    action=['/-- The identity coset (`false`) and the coset of the phase on state 7 (`true`). -/',
            'def action : Bool → ML → Word Gen × Bool']
    for c in ('I','J'):
        for z in ['Z','K']+[('t',i) for i in range(7)]:
            w,d=b2q1.letter_action(c,z)
            pat='.'+z if isinstance(z,str) else '.T '+str(z[1])
            action.append('  | %s, %s => (FreeMonoid.ofList %s, %s)'%('false' if c=='I' else 'true',pat,word(w),'false' if d=='I' else 'true'))
    template=(Path(__file__).parent/'cosets_template.lean').read_text(encoding='utf-8')
    (ROOT/'Cosets.lean').write_text(template.replace('-- ACTION','\n'.join(action)),encoding='utf-8',newline='\n')
    print('action and all 107 obligations assembled')


if __name__=='__main__': main()
