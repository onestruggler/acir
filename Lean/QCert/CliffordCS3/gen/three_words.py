#!/usr/bin/env python3
"""Independent three-qubit coset words, checked over Gaussian dyadics.

Only the gate matrices and Figure 2's conventions are used. The numerical
checks here help construct certificates; they are not Lean proof terms.
"""
from pathlib import Path

GATES = ('i', 'K0', 'K1', 'K2', 'S0', 'S1', 'S2', 'CS01', 'CS12')
LEAN = ('i', 'K₀', 'K₁', 'K₂', 'S₀', 'S₁', 'S₂', 'CS₀₁', 'CS₁₂')
GRAY = (5, 1, 0, 4, 6, 2, 3, 7)


def inverse(w):
    result = []
    for g in reversed(w):
        result.extend([0, g] if 1 <= g <= 3 else [g] * 3)
    return result


def mul(*words):
    """Concatenate and perform only adjacent power cancellations."""
    result = []
    for w in words:
        result.extend(w)
    return result


def K(q):
    return [1 + q]


def S(q):
    return [4 + q]


def X(q):
    return K(q) + S(q) * 2 + K(q) + [0]


def CX(c, t):
    assert abs(c - t) == 1
    cs = 7 + min(c, t)
    return K(t) + [cs, cs] + K(t) + [0]


def SW(c, t):
    return CX(c, t) + CX(t, c) + CX(c, t)


def CS(a, b, power=1):
    a, b = sorted([a, b])
    if b - a == 1:
        return [7 + a] * power
    p = SW(0, 1)
    return p + [8] * power + p


def ccZ():
    # CS02^-1 CX01 CS12 CX01 CS12^-1 has phase (-1)^(q0*q1*q2).
    return CS(0, 2, 3) + CX(0, 1) + CS(1, 2) + CX(0, 1) + CS(1, 2, 3)


def ccX(target):
    # K differs from H only by a central scalar, which cancels in conjugation.
    return K(target) + ccZ() + inverse(K(target))


def transposition(a, b):
    mask = a ^ b
    assert mask and not (mask & (mask - 1))
    target = 2 - (mask.bit_length() - 1)
    white = [q for q in range(3) if q != target and not (a & (1 << (2-q)))]
    frame = sum((X(q) for q in white), [])
    return frame + ccX(target) + sum((X(q) for q in reversed(white)), [])


def atom():
    # K*S^-1 = [K*S*K^-1,S^-1]. Distribute the two commutator controls.
    a = K(0) + CS(0, 1) + inverse(K(0))
    ai = K(0) + CS(0, 1, 3) + inverse(K(0))
    return a + CS(0, 2, 3) + ai + CS(0, 2)


def identity(n=8):
    return tuple(tuple((int(i == j), 0) for j in range(n)) for i in range(n))


def normalize(m, exponent):
    while exponent and all((a % 2 == 0 and b % 2 == 0) for row in m for a,b in row):
        m = tuple(tuple((a//2,b//2) for a,b in row) for row in m)
        exponent -= 1
    return m, exponent


def eval_word(w):
    """Exact matrix, integer real/imaginary coefficients divided by 2^e."""
    m = identity()
    exponent = 0
    for g in reversed(w):
        if 1 <= g <= 3:
            bit = 1 << (3-g)
            out = list(m)
            for i in range(8):
                if i & bit:
                    continue
                a,b = m[i],m[i|bit]
                out[i] = tuple((x+u+y+v, y+v-x-u) for (x,y),(u,v) in zip(a,b))
                out[i|bit] = tuple((x-u+y-v, y-v-x+u) for (x,y),(u,v) in zip(a,b))
            exponent += 1
            m,exponent = normalize(tuple(out),exponent)
        else:
            def phase(i):
                if g == 0:return True
                if 4 <= g <= 6:return bool(i & (1 << (6-g)))
                if g == 7:return (i & 6) == 6
                if g == 8:return (i & 3) == 3
                raise ValueError(g)
            m = tuple(tuple((-b,a) for a,b in row) if phase(i) else row for i,row in enumerate(m))
    return m, exponent


def transpose_matrix(a,b):
    m=[list(row) for row in identity()]
    m[a],m[b]=m[b],m[a]
    return tuple(tuple(row) for row in m),0


def phase_matrix(point,power):
    m=[list(row) for row in identity()]
    m[point][point]=((1,0),(0,1),(-1,0),(0,-1))[power%4]
    return tuple(tuple(row) for row in m),0


def atom_matrix():
    m=[[(2*int(i==j),0) for j in range(8)] for i in range(8)]
    m[3][3]=(1,-1);m[3][7]=(-1,-1)
    m[7][3]=(1,-1);m[7][7]=(1,1)
    return tuple(tuple(row) for row in m),1


def check_words():
    assert eval_word(ccZ()) == phase_matrix(7,2), 'CCZ'
    for a,b in zip(GRAY,GRAY[1:]):
        assert eval_word(transposition(a,b)) == transpose_matrix(a,b), ('T',a,b)
    assert eval_word(atom()) == atom_matrix(), 'A'


def lean_list(w):
    terms=['Gen.'+LEAN[g] for g in w]
    lines=[]
    for k in range(0,len(terms),12):lines.append(', '.join(terms[k:k+12]))
    return '[' + ',\n      '.join(lines) + ']'


def emit():
    check_words()
    target=Path(__file__).resolve().parents[1]/'Three/Cert/Words.lean'
    target.parent.mkdir(parents=True,exist_ok=True)
    header='''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Three-qubit coset representatives: explicit gate words

Generated by `gen/three_words.py` from controlled commutators and Toffoli
circuits, independently of any Agda formalization. These are definitions;
the certificates and their Lean checks establish their required equations.
-/
import QCert.CliffordCS3.Syntax

namespace QCert.CliffordCS3.Three.Cert

def tokenL : Fin 7 → List Gen
'''
    body=''.join(f'  | {k} => {lean_list(transposition(a,b))}\n' for k,(a,b) in enumerate(zip(GRAY,GRAY[1:])))
    body+='\ndef atomL : List Gen :=\n  '+lean_list(atom())+'\n'
    body+='\ndef ccZL : List Gen :=\n  '+lean_list(ccZ())+'\n'
    body+='\ndef token (d : Fin 7) : Word Gen := FreeMonoid.ofList (tokenL d)\n'
    body+='\ndef atom : Word Gen := FreeMonoid.ofList atomL\n'
    body+='\ndef ccZ : Word Gen := FreeMonoid.ofList ccZL\n'
    body+='\nend QCert.CliffordCS3.Three.Cert\n'
    target.write_text(header+body,encoding='utf-8',newline='\n')
    print(target)
    print('tokens lengths',[len(transposition(a,b)) for a,b in zip(GRAY,GRAY[1:])])
    print('A length',len(atom()),'CCZ length',len(ccZ()))


if __name__=='__main__':emit()
