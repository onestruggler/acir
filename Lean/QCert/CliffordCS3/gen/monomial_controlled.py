#!/usr/bin/env python3
"""Export controlled-gate identities from the independent four-letter completion."""
from pathlib import Path
import pickle,sys
from three_words import lean_list
sys.set_int_max_str_digits(0)
BASE=Path(__file__).resolve().parent
MAP=(0,2,7,8)
k=(1,);ki=(0,1);d=(2,);b=(3,);a=k+d*2+k+(0,)
R=a+b+a+b*3;V=b+k+b+k+b;Vi=b*3+ki+b*3+ki+b*3
targets=[('core_opposite_commute',R+k+R+d*2+ki,k+R+d*2+ki+R),
         ('conjugate_core',V+R+Vi,k+R+ki),
         ('commute_opposite_core',V+R+d*2,R+d*2+V)]
s=pickle.load(Path(sys.argv[1] if len(sys.argv)>1 else '/tmp/acir-cs3-atom-extra/atom5.pickle').open('rb'))
import importlib.util
spec=importlib.util.spec_from_file_location('kb',BASE.parents[1]/'Minimality/gen/cskb.py')
mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
kb=mod.KB(s['letters'],[]);kb.rules=s['rules'];kb.index={l:i for i,(l,r,p,a)in enumerate(kb.rules)if a};kb.lens={len(l)for l in kb.index}
proofs={n:kb.proof_of(l,r)for n,l,r in targets};assert all(p is not None for p in proofs.values())
rules=s['rules'];letters=s['letters'];bases={n:(l,r)for n,l,r in s['base']}
def globalword(w):return tuple(MAP[letters[g]]for g in w)
def pack(st):
 ans=0
 for p,j,rev in reversed(st):ans=ans*33554432+2*(4096*p+j)+(0 if rev else 1)
 return ans
used=set()
def need(i):
 if i in used:return
 used.add(i);p=rules[i][2]
 if p[0]!='base':
  for _,j,_ in p:need(j)
for pr in proofs.values():
 for _,j,_ in pr:need(j)
out=['''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Controlled gates and opposite controls

Generated by gen/monomial_controlled.py. Every initial equation is a
Figure 2 relation or follows from the completed two-qubit presentation.
-/
import QCert.CliffordCS3.Rewrite

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace QCert.CliffordCS3.Three.MonomialControlled
''']
for rid in sorted(used):
 l,r,p,_=rules[rid]
 if p[0]=='base':
  _,name,rev=p
  if name.startswith('pair'):
   j=0 if name[-1]=='a' else 1
   conv={0:'i',1:'Kl'if j==0 else'Ku',2:'CS',3:'CS'}
   bl,br=bases[name]
   def loc(w):return '['+', '.join('Two.Gen2.'+conv[g]for g in w)+']'
   expr=f'Replay.pairRule {j} {loc(bl)} {loc(br)} (by decide +kernel)'
  else:expr='Replay.ax Rel.'+name
  if rev:expr='('+expr+').symm'
  out.append(f'def r{rid} : Rule Rel := {expr}')
 else:
  deps=sorted(set(j for _,j,_ in p));ix={j:i for i,j in enumerate(deps)}
  st=[(a,ix[j],rev)for a,j,rev in p]
  out.append(f'def r{rid} : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j)for j in deps)}]\n    {lean_list(globalword(l))}\n    {lean_list(globalword(r))}\n    [({len(st)}, {pack(st)})] (by decide +kernel)')
for n,w in [('core',R),('control',V),('controlInv',Vi)]:
 out.append(f'def {n} : Word Gen := FreeMonoid.ofList '+lean_list([MAP[g]for g in w]))
for name,l,r in targets:
 p=proofs[name];deps=sorted(set(j for _,j,_ in p));ix={j:i for i,j in enumerate(deps)}
 st=[(a,ix[j],rev)for a,j,rev in p]
 out.append(f'def {name}Rule : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j)for j in deps)}]\n    {lean_list([MAP[g]for g in l])}\n    {lean_list([MAP[g]for g in r])}\n    [({len(st)}, {pack(st)})] (by decide +kernel)')
out.append('''
theorem core_opposite_commute : Derivable Rel
    (core * (W.K 1 * core * W.CS01 ^ 2 * (W.I * W.K 1)))
    ((W.K 1 * core * W.CS01 ^ 2 * (W.I * W.K 1)) * core) := by
  simpa only [core, pow_succ, pow_zero, one_mul, W.CS01, W.g,
    FreeMonoid.ofList_append] using core_opposite_commuteRule.sound

theorem conjugate_core : Derivable Rel (control * core * controlInv)
    (W.K 1 * core * (W.I * W.K 1)) :=
  conjugate_coreRule.sound

theorem commute_opposite_core : Derivable Rel (control * (core * W.CS01 ^ 2))
    ((core * W.CS01 ^ 2) * control) := by
  simpa only [control, core, pow_succ, pow_zero, one_mul, W.CS01, W.g,
    FreeMonoid.ofList_append] using commute_opposite_coreRule.sound

end QCert.CliffordCS3.Three.MonomialControlled
''')
path=BASE.parent/'Three/MonomialControlled.lean'
path.write_text('\n\n'.join(out)+'\n',encoding='utf8',newline='\n')
print(path,'rules',len(used),'proof lengths',{n:len(p)for n,p in proofs.items()})

