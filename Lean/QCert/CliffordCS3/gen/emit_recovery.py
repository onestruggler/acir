#!/usr/bin/env python3
"""Export and retain the proof DAG for the atom recovery identity."""
import json
import pickle
import sys
from pathlib import Path
from emit_atom import chunks
from three_words import lean_list

sys.set_int_max_str_digits(0)
BASE = Path(__file__).resolve().parent
MAP = (0, 2, 7, 8, 5)


def emit(seed=0):
    datafile = BASE / 'data' / f'AtomRecovery-seed{seed}.json'
    if datafile.exists():
        state = json.loads(datafile.read_text())
        state['rules'] = {int(k): v for k, v in state['rules'].items()}
    else:
        state = pickle.loads(Path(f'/tmp/acir-cs3-recovery-search/recovery{seed}.pickle').read_bytes())
    rules, letters = state['rules'], state['letters']
    bases = {n: (l, r) for n, l, r in state['base']}
    used = set()
    def need(i):
        if i in used:
            return
        used.add(i)
        proof = rules[i][2]
        if proof[0] != 'base':
            for _, j, _ in proof:
                need(j)
    for _, j, _ in state['solved']['remove_control']:
        need(j)
    if not datafile.exists():
        bn = {rules[j][2][1] for j in used if rules[j][2][0] == 'base'}
        data = dict(letters=letters, base=[x for x in state['base'] if x[0] in bn],
                    rules={j: [list(rules[j][0]), list(rules[j][1]), rules[j][2], rules[j][3]] for j in used},
                    solved=state['solved'], targets=state['targets'])
        datafile.write_text(json.dumps(data, separators=(',', ':')) + '\n')
    def globalword(w):
        return [MAP[letters[i]] for i in w]
    def replay(proof):
        deps = sorted({j for _, j, _ in proof})
        remap = {j: i for i, j in enumerate(deps)}
        return deps, chunks([(p, remap[j], rev) for p, j, rev in proof])
    out = ['''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Removing a control of the Clifford commutator

Generated by gen/emit_recovery.py. Every step is a proved Figure 2
equation or a kernel-checked two-qubit equation.
-/
import QCert.CliffordCS3.Three.Cert.AtomRelations
import QCert.CliffordCS3.Three.Cert.AtomNegative
import QCert.CliffordCS3.Three.Cert.SignNegative

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace QCert.CliffordCS3.Three.Cert.AtomRecovery
''']
    for rid in sorted(used):
        l, r, proof, _ = rules[rid]
        if proof[0] == 'base':
            _, name, reverse = proof
            if name.startswith('pair'):
                j = 0 if name[4] == 'a' else 1
                conv = {0: 'i', 1: 'Kl' if j == 0 else 'Ku', 2: 'CS', 3: 'CS', 4: 'Sl' if j == 0 else 'Su'}
                def local(w):
                    return '[' + ', '.join('Two.Gen2.' + conv[g] for g in w) + ']'
                bl, br = bases[name]
                expr = f'Replay.pairRule {j} {local(bl)} {local(br)} (by decide +kernel)'
            else:
                expr = name
            if reverse:
                expr = '(' + expr + ').symm'
            out.append(f'def r{rid} : Rule Rel := {expr}\n')
        else:
            deps, cert = replay(proof)
            out.append(f'def r{rid} : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list(globalword(l))}\n    {lean_list(globalword(r))}\n    {cert} (by decide +kernel)\n')
    _, lhs, rhs = state['targets'][0]
    deps, cert = replay(state['solved']['remove_control'])
    out.append(f'def remove_controlRule : Rule Rel :=\n  Replay.byChunks [{", ".join("r"+str(j) for j in deps)}]\n    {lean_list([MAP[g] for g in lhs])}\n    {lean_list([MAP[g] for g in rhs])}\n    {cert} (by decide +kernel)\n')
    out.append('end QCert.CliffordCS3.Three.Cert.AtomRecovery\n')
    target = BASE.parent / 'Three/Cert/AtomRecovery.lean'
    target.write_text('\n'.join(out), encoding='utf8', newline='\n')
    print('Used', len(used), 'rules;', len(target.read_text().splitlines()), 'lines')


if __name__ == '__main__':
    emit(int(sys.argv[1]) if len(sys.argv) > 1 else 0)
