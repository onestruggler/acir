"""Phase A emission: the two-qubit derivations (B2 and hypothesis (a)) as rules of `Rel2`,
in modules `Two/Cert/PartNN.lean`, and the table `Two/Cert/Targets.lean`."""
import os
from pathlib import Path
import b2two
from emit import needed, expanded, exp_steps
from leanemit import RuleEmitter, wrap
from b1emit import fmt_word as fmt_mlword

LEAN = Path(__file__).resolve().parent.parent / 'Two' / 'Cert'
AXNAME = {'c1': 'Rel2.c1', 'c2u': 'Rel2.c2u', 'c2l': 'Rel2.c2l', 'c3u': 'Rel2.c3u', 'c3l': 'Rel2.c3l',
          'c4u': 'Rel2.c4u', 'c4l': 'Rel2.c4l', 'c5': 'Rel2.c5', 'c6': 'Rel2.c6', 'c7': 'Rel2.c7',
          'c8': 'Rel2.c8', 'c9': 'Rel2.c9', 'c10': 'Rel2.c10', 'c11': 'Rel2.c11',
          'comm_Ku_Kl': 'Rel2.comm_KuKl', 'comm_Ku_Sl': 'Rel2.comm_KuSl',
          'comm_Su_Kl': 'Rel2.comm_SuKl', 'comm_Su_Sl': 'Rel2.comm_SuSl'}


def ax_term(nm):
    if nm.startswith('comm_i_'):
        return 'Rule.ofDerivable _ _ (Derivable.of (Rel2.comm_i .%s (by decide)))' % nm[7:]
    return 'Rule.ofDerivable _ _ (Derivable.of %s)' % AXNAME[nm]


def fmt2(a):
    return '.' + a


HEADER = """/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Two qubits: derivations, part %d

Rules of `Rel2` (equations between words on a pair of qubits with their
derivations), replayed by the kernel (`QCert.CliffordT2.FastRewrite`).

Generated by `QCert/CliffordCS3/gen/twoemit.py`.
-/
"""


def main(per=300):
    W = b2two.build()
    B = b2two.prove_b2(W)
    Aa = b2two.prove_a(W)
    A, T = W.A, W.T
    targets = [e for (_, _, e) in B.values()] + [e for (_, _, e) in Aa.values()]
    ks = needed(T, targets)
    # drop equations that expand to trivial ones
    live = []
    for k in ks:
        l, r, j = T.eqs[k]
        if j[0] == 'def':
            continue
        el, er = expanded(A, k)
        if el == er and j[0] == 'der':
            continue
        live.append(k)

    def steps(k):
        j = T.eqs[k][2]
        if j[0] == 'ax':
            return None
        return exp_steps(A, k)

    def axiom(k):
        return ax_term(T.eqs[k][2][1])

    R = RuleEmitter('r', 'Rule Rel2', 'gcode2_bounds', 'gcode2_inj', fmt2,
                    lambda k: expanded(A, k), steps, axiom)
    os.makedirs(LEAN, exist_ok=True)
    parts = [live[i:i + per] for i in range(0, len(live), per)]
    for pi, part in enumerate(parts):
        src = [HEADER % pi]
        if pi == 0:
            src.append('import QCert.CliffordCS3.Two.Code\n')
        else:
            src.append('import QCert.CliffordCS3.Two.Cert.Part%02d\n' % (pi - 1))
        src.append('namespace QCert.CliffordCS3.Two.Cert\n')
        src.append('open QCert.CliffordCS3.Two\n')
        for k in part:
            src.append(R.emit(k))
        src.append('end QCert.CliffordCS3.Two.Cert\n')
        open(os.path.join(LEAN, 'Part%02d.lean' % pi), 'w').write('\n'.join(src))
    # targets: B2 per macro axiom, (a) per generator
    from b2two import M4, STD4
    from macro import macro_axioms
    ax = macro_axioms(M4, STD4)
    src = ["""/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Two qubits: the decoded macro axioms and hypothesis (a)

Generated by `QCert/CliffordCS3/gen/twoemit.py`.
-/
"""]
    src.append('import QCert.CliffordCS3.Two.Cert.Part%02d\n' % (len(parts) - 1))
    src.append('namespace QCert.CliffordCS3.Two.Cert\n')
    src.append('open QCert.CliffordCS3.Two QCert.CliffordCS3.Macro\n')
    rows = []
    for nm, l, r in ax:
        dl, dr, e = B[nm]
        el, er = A.expand(dl), A.expand(dr)
        if el == er:
            term = 'Rule.ofDerivable (FreeMonoid.ofList %s) (FreeMonoid.ofList %s) (Derivable.refl _)' % (
                R.word(el), R.word(er))
        else:
            term = R.name(e)
            l2, r2 = expanded(A, e)
            assert (l2, r2) == (el, er), nm
        rows.append('(%s, %s, %s)' % (fmt_mlword(l), fmt_mlword(r), term))
    src.append('/-- The decoded macro axioms. -/')
    src.append('def b2Table : List (List ML × List ML × Rule Rel2) :=\n  [%s]\n' % wrap(', '.join(rows), 3))
    rows = []
    for x, (w, xx, e) in Aa.items():
        ew = A.expand(w)
        if e is None or ew == (x,):
            assert ew == (x,)
            rows.append('(.%s, Rule.ofDerivable (FreeMonoid.ofList %s) (FreeMonoid.ofList %s) (Derivable.refl _))'
                        % (x, R.word(ew), R.word(ew)))
            continue
        l2, r2 = expanded(A, e)
        assert r2 == (x,) and l2 == ew
        rows.append('(.%s, %s)' % (x, R.name(e)))
    src.append('/-- Hypothesis (a): the decoded encoding of the translation of each generator. -/')
    src.append('def aTable : List (Gen2 × Rule Rel2) :=\n  [%s]\n' % wrap(', '.join(rows), 3))
    src.append('end QCert.CliffordCS3.Two.Cert\n')
    open(os.path.join(LEAN, 'Targets.lean'), 'w').write('\n'.join(src))
    print('parts', len(parts), 'rules', len(live))


if __name__ == '__main__':
    main()
