"""Write Tables.lean: the rewrite rules of Figures 3-7 (equations 3.3-3.101
of the supplement) as push tables.

Each equation says that a dirty gate immediately before one or two boxes of
a normal form equals boxes followed by dirty gates.  A table gives, for the
indices of the boxes, the new indices and the dirty gates after them (as
`Dg`s, in the equation's frame), with the equation of `Rules*.lean` as its
proof and a check, by `decide`, that the gates after it are allowed there
(Section 6's labels).

    python tables.py            # writes ../Tables.lean
    python tables.py --check    # compares instead
"""
import os
import sys

from supp import HERE, frame_size, parse_supp

LEAN = os.path.dirname(HERE)

# table name: (first and last equation, box kinds on the left, the
# statement's template, the allowed-check)
#
# Templates: {I} {J} are the input indices (`i.val + 1` ...), {I2} {J2}
# the output ones.
TABLES = [
    ('tAH', 3, 5, 'H at the wire of `A_i`', 'i', 'Fin 3',
     '[.H 0] ++ bA ({i}.val + 1) 0', [('bA ({o}.val + 1) 0', 'Fin 3')], 'okB 0', 1),
    ('tAS', 6, 8, 'S at the wire of `A_i`', 'i', 'Fin 3',
     '[.S 0] ++ bA ({i}.val + 1) 0', [('bA ({o}.val + 1) 0', 'Fin 3')], 'okB 0', 1),
    ('tBH', 24, 27, 'H on the upper wire of `B_j`', 'j', 'Fin 4',
     '[.H 1] ++ bB ({i}.val + 1) 0', [('bB ({o}.val + 1) 0', 'Fin 4')], 'okB 1', 2),
    ('tBS1', 28, 31, 'S on the upper wire of `B_j`', 'j', 'Fin 4',
     '[.S 1] ++ bB ({i}.val + 1) 0', [('bB ({o}.val + 1) 0', 'Fin 4')], 'okB 1', 2),
    ('tBS0', 32, 35, 'S on the lower wire of `B_j`', 'j', 'Fin 4',
     '[.S 0] ++ bB ({i}.val + 1) 0', [('bB ({o}.val + 1) 0', 'Fin 4')], 'okB 1', 2),
    ('tBX', 36, 39, 'X on the lower wire of `B_j`', 'j', 'Fin 4',
     'bX 0 ++ bB ({i}.val + 1) 0', [('bB ({o}.val + 1) 0', 'Fin 4')], 'okB 1', 2),
    ('tBZ', 40, 43, 'CZ below `B_j`, on its lower wire', 'j', 'Fin 4',
     '[.CZ 0] ++ bB ({i}.val + 1) 1', [('bB ({o}.val + 1) 1', 'Fin 4')], 'okB 2', 3),
    ('tCX', 44, 45, 'X at the wire of `C_k`', 'k', 'Fin 2',
     'bX 0 ++ bC ({i}.val + 1) 0', [('bC ({o}.val + 1) 0', 'Fin 2')], 'okD true 0', 1),
    ('tCS', 46, 47, 'S at the wire of `C_k`', 'k', 'Fin 2',
     '[.S 0] ++ bC ({i}.val + 1) 0', [('bC ({o}.val + 1) 0', 'Fin 2')], 'okD true 0', 1),
    ('tCZ', 48, 49, 'CZ below `C_k`, on its wire', 'k', 'Fin 2',
     '[.CZ 0] ++ bC ({i}.val + 1) 1', [('bC ({o}.val + 1) 1', 'Fin 2')], 'okD true 1', 2),
    ('tDH', 66, 69, 'H on the lower wire of `D_l`', 'l', 'Fin 4',
     '[.H 0] ++ bD ({i}.val + 1) 0', [('bD ({o}.val + 1) 0', 'Fin 4')], 'okD false 0', 2),
    ('tDS0', 70, 73, 'S on the lower wire of `D_l`', 'l', 'Fin 4',
     '[.S 0] ++ bD ({i}.val + 1) 0', [('bD ({o}.val + 1) 0', 'Fin 4')], 'okD false 0', 2),
    ('tDS1', 74, 77, 'S on the upper wire of `D_l`', 'l', 'Fin 4',
     '[.S 1] ++ bD ({i}.val + 1) 0', [('bD ({o}.val + 1) 0', 'Fin 4')], 'okD false 0', 2),
    ('tDZ', 78, 81, 'CZ on the wires of `D_l`', 'l', 'Fin 4',
     '[.CZ 0] ++ bD ({i}.val + 1) 0', [('bD ({o}.val + 1) 0', 'Fin 4')], 'okD false 0', 2),
]

# two-box tables: CZ before two boxes
TABLES2 = [
    ('tBB', 50, 65, 'CZ on the wires of the second of `B_j B_j\'`, before the first', 'B',
     '[.CZ 1] ++ bB ({i}.val + 1) 0 ++ bB ({i2}.val + 1) 1',
     'bB ({o}.val + 1) 0 ++ bB ({o2}.val + 1) 1', 'okB 2', 3),
    ('tDD', 86, 101, 'CZ on the wires of the second of `D_l D_l\'`, before the first', 'D',
     '[.CZ 0] ++ bD ({i}.val + 1) 1 ++ bD ({i2}.val + 1) 0',
     'bD ({o}.val + 1) 1 ++ bD ({o2}.val + 1) 0', 'okD false 0', 3),
]

HEAD = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Clifford circuits (Selinger): the push tables

The rewrite rules of Figures 3–7 of Selinger's paper (equations 3.3–3.101 of
the supplement, proved in `Rules1`–`Rules5`) as tables: a dirty gate
immediately before one or two boxes of a normal form equals boxes followed by
dirty gates, which are allowed where they stand (the labels of Section 6,
`okB`, `okD`).  Everything is in the equation's own frame (wire `0` at the
bottom); `Push` moves it into place.  Generated by `gen/tables.py`.
-/
import QCert.SelingerClifford.Dirty
import QCert.SelingerClifford.Rules1
import QCert.SelingerClifford.Rules2
import QCert.SelingerClifford.Rules3
import QCert.SelingerClifford.Rules4
import QCert.SelingerClifford.Rules5

namespace QCert.SelingerClifford

'''


def dg(tok, k):
    name, args = tok
    if name in ('H', 'S', 'X'):
        return f'.{name} {k - 1 - args[0]}'
    if name == 'ZZ':
        return f'.CZ {k - 2 - min(args)}'
    raise ValueError(tok)


def split(eq):
    """(dirty token, left boxes, right boxes, right dirty tokens, phase)."""
    (lt, lp), (rt, rp) = eq['stmt']
    assert lp == 0
    d, lboxes = lt[0], lt[1:]
    assert d[0] not in 'ABCDE' and all(t[0] in 'ABCDE' for t in lboxes)
    n = 0
    while n < len(rt) and rt[n][0] in 'ABCDE':
        n += 1
    rboxes, rdirty = rt[:n], rt[n:]
    assert all(t[0] not in 'ABCDE' for t in rdirty)
    return d, lboxes, rboxes, rdirty, rp


def out_list(rdirty, ph, k):
    return '[' + ', '.join([dg(t, k) for t in rdirty] + ['.om'] * (ph % 8)) + ']'


def gen():
    eqs = {e['name']: e for e in parse_supp()}
    s = HEAD
    # one-box tables
    for name, a, b, doc, var, ty, lhs, rhs, ok, k in TABLES:
        rows = []
        for x in range(a, b + 1):
            eq = eqs[f'3.{x}']
            assert frame_size(eq) == k, (x, frame_size(eq), k)
            d, lb, rb, rd, ph = split(eq)
            assert len(lb) == 1 and len(rb) == 1 and rb[0][0] == lb[0][0], x
            rows.append((lb[0][1][0] - 1, rb[0][1][0] - 1, out_list(rd, ph, k), x))
        rows.sort()
        assert [r[0] for r in rows] == list(range(len(rows)))
        bx, _ = rhs[0]
        s += f'/-- {doc}: equations 3.{a}–3.{b}. -/\n'
        s += f'theorem {name} : ∀ {var} : {ty}, ∃ ({var}\' : {ty}) (out : List Dg),\n'
        s += f'    Holds {k} ({lhs.format(i=var)})\n'
        s += f'      ({bx.format(o=var + chr(39))} ++ dw out) ∧ OkL ({ok}) {k} out\n'
        for i, o, out, x in rows:
            s += f'  | {i} => ⟨{o}, {out}, rule_3_{x}, by decide⟩\n'
        s += '\n'
    # two-box tables
    for name, a, b, doc, kind, lhs, rhs, ok, k in TABLES2:
        rows = []
        for x in range(a, b + 1):
            eq = eqs[f'3.{x}']
            assert frame_size(eq) == k, x
            d, lb, rb, rd, ph = split(eq)
            assert [t[0] for t in lb] == [kind, kind] == [t[0] for t in rb], x
            rows.append(((lb[0][1][0] - 1, lb[1][1][0] - 1),
                         (rb[0][1][0] - 1, rb[1][1][0] - 1), out_list(rd, ph, k), x))
        rows.sort()
        assert [r[0] for r in rows] == [(p, q) for p in range(4) for q in range(4)]
        s += f'/-- {doc}: equations 3.{a}–3.{b}. -/\n'
        s += 'theorem ' + name + ' : ∀ a b : Fin 4, ∃ (a\' b\' : Fin 4) (out : List Dg),\n'
        s += f'    Holds {k} ({lhs.format(i="a", i2="b")})\n'
        s += f'      ({rhs.format(o=chr(97) + chr(39), o2="b" + chr(39))} ++ dw out) ∧ OkL ({ok}) {k} out\n'
        for (i, i2), (o, o2), out, x in rows:
            s += f'  | {i}, {i2} => ⟨{o}, {o2}, {out}, rule_3_{x}, by decide⟩\n'
        s += '\n'
    # the A box with a CZ: equations 3.9-3.23
    s += A_TABLES(eqs)
    # the E box: equations 3.82-3.85
    rows = []
    for x in range(82, 86):
        d, lb, rb, rd, ph = split(eqs[f'3.{x}'])
        assert not rd and ph % 8 == 0
        rows.append((lb[0][1][0] - 1, rb[0][1][0] - 1, x))
    rows.sort()
    s += '/-- S at the wire of `E_h`: equations 3.82–3.85. -/\n'
    s += 'theorem tES : ∀ h : Fin 4, ∃ h\' : Fin 4,\n'
    s += '    Holds 1 ([.S 0] ++ bE (h.val + 1) 0) (bE (h\'.val + 1) 0)\n'
    for i, o, x in rows:
        s += f'  | {i} => ⟨{o}, rule_3_{x}⟩\n'
    s += '\nend QCert.SelingerClifford\n'
    return s


def A_TABLES(eqs):
    s = ''
    # 3.9-3.11: CZ with A_i on its upper wire
    rows = []
    for x in range(9, 12):
        eq = eqs[f'3.{x}']
        assert frame_size(eq) == 2
        d, lb, rb, rd, ph = split(eq)
        i = lb[0][1][0] - 1
        out = out_list(rd, ph, 2)
        if len(rb) == 1:
            assert rb[0][0] == 'A' and rb[0][1][1] == 0
            rows.append((i, f'Or.inl ⟨{rb[0][1][0] - 1}, {out}, rule_3_{x}, by decide⟩'))
        else:
            assert [t[0] for t in rb] == ['A', 'B'] and rb[0][1][1] == 1
            rows.append((i, f'Or.inr ⟨{rb[0][1][0] - 1}, {rb[1][1][0] - 1}, {out}, '
                            f'rule_3_{x}, by decide⟩'))
    rows.sort()
    s += '''/-- CZ with `A_i` on its upper wire: equations 3.9–3.11.  Either `A_i`
stays, or the ladder grows down by one wire (`A_{i'}` below `B_j`). -/
theorem tAZ : ∀ i : Fin 3,
    (∃ (i' : Fin 3) (out : List Dg),
      Holds 2 ([.CZ 0] ++ bA (i.val + 1) 1) (bA (i'.val + 1) 1 ++ dw out) ∧
        OkL (okB 1) 2 out) ∨
    (∃ (i' : Fin 3) (j : Fin 4) (out : List Dg),
      Holds 2 ([.CZ 0] ++ bA (i.val + 1) 1) (bA (i'.val + 1) 0 ++ bB (j.val + 1) 0 ++ dw out) ∧
        OkL (okB 1) 2 out)
'''
    for i, t in rows:
        s += f'  | {i} => {t}\n'
    s += '\n'
    # 3.12-3.23: CZ on the wires of A_i B_j
    rows = []
    for x in range(12, 24):
        eq = eqs[f'3.{x}']
        assert frame_size(eq) == 2
        d, lb, rb, rd, ph = split(eq)
        assert [t[0] for t in lb] == ['A', 'B'] and lb[0][1][1] == 1
        i, j = lb[0][1][0] - 1, lb[1][1][0] - 1
        out = out_list(rd, ph, 2)
        if len(rb) == 2:
            assert [t[0] for t in rb] == ['A', 'B'] and rb[0][1][1] == 1
            rows.append(((i, j), f'Or.inl ⟨{rb[0][1][0] - 1}, {rb[1][1][0] - 1}, {out}, '
                                 f'rule_3_{x}, by decide⟩'))
        else:
            assert rb[0][0] == 'A' and rb[0][1][1] == 0
            rows.append(((i, j), f'Or.inr ⟨{rb[0][1][0] - 1}, {out}, rule_3_{x}, by decide⟩'))
    rows.sort()
    s += '''/-- CZ on the wires of `A_i B_j`, before both: equations 3.12–3.23.  Either
the two boxes stay, or the ladder shrinks by one wire (`A_{i'}` on the upper
wire). -/
theorem tAB : ∀ (i : Fin 3) (j : Fin 4),
    (∃ (i' : Fin 3) (j' : Fin 4) (out : List Dg),
      Holds 2 ([.CZ 0] ++ bA (i.val + 1) 0 ++ bB (j.val + 1) 0)
        (bA (i'.val + 1) 0 ++ bB (j'.val + 1) 0 ++ dw out) ∧ OkL (okB 1) 2 out) ∨
    (∃ (i' : Fin 3) (out : List Dg),
      Holds 2 ([.CZ 0] ++ bA (i.val + 1) 0 ++ bB (j.val + 1) 0)
        (bA (i'.val + 1) 1 ++ dw out) ∧ OkL (okB 1) 2 out)
'''
    for (i, j), t in rows:
        s += f'  | {i}, {j} => {t}\n'
    s += '\n'
    return s


if __name__ == '__main__':
    text = gen()
    path = os.path.join(LEAN, 'Tables.lean')
    if '--check' in sys.argv:
        old = open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else None
        print('Tables.lean:', 'same' if old == text else 'DIFFERS')
        sys.exit(0 if old == text else 1)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', path)
