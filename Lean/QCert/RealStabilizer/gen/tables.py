"""Write Tables.lean: the typed relations of Appendix B as push tables.

Each relation says that a dirty gate immediately before one or two boxes of
a normal form equals boxes followed by dirty gates (Definition 5.1).  A
table gives, for the indices of the boxes (and the type of the wire the
first one takes), the new indices and the dirty gates after them (as
`Dg`s, in the relation's frame), with the relation of `Relations*.lean` as
its proof and a check, by `decide`, that the gates after it are allowed
there (the labels of Definition 5.3, `okB`, `okD` in `Dirty.lean`) and that
the boxes keep the type of the wire above them (Definition 4.6).

The gates after the boxes are those of the relation, with `X` and `CXZ`
kept as one dirty gate where the next rule needs them so (`X` on the
current wire of a `B`-ladder, `CXZ` below a double current wire) and
written as their letters (`H Z H`, `H CZ H CZ`) elsewhere.  Every row is
also checked here: the letters are those of the relation, the relation
holds numerically, and the labels and types are as the Lean check says.

    python3 tables.py            # writes ../Tables.lean
    python3 tables.py --check    # compares instead
"""
import os
import sys

import paper
import relations

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)

TA = {1: False, 2: False, 3: True}


def tB(t, j):
    return (not t) if j == 3 else t


def bty(p):
    """A `B` box by its paper index: the type it takes and `j`."""
    return (p >= 5, (p - 1) % 4)


# the labels, as in Dirty.lean -------------------------------------------------

def okB(t, c, g):
    k = g[0]
    if k == 'neg':
        return True
    w = g[1]
    return {'H': w != c or t, 'Z': True, 'X': w == c,
            'CZ': w != c and (w + 1 != c or not t), 'CXZ': w + 1 == c and t}[k]


def okD(top, c, g):
    k = g[0]
    if k == 'neg':
        return True
    w = g[1]
    return {'H': w != c, 'Z': True, 'X': False, 'CXZ': False,
            'CZ': w != c and (top or w + 1 != c)}[k]


def hi(g):
    return 0 if g[0] == 'neg' else g[1] + (1 if g[0] in ('H', 'Z', 'X') else 2)


def word(g):
    """The letters of a dirty gate, as `Dg.word`."""
    if g[0] == 'neg':
        return [('m',)]
    k, w = g
    if k in ('H', 'Z'):
        return [(k, w)]
    if k == 'X':
        return [('H', w), ('Z', w), ('H', w)]
    if k == 'CZ':
        return [('C', w)]
    return [('H', w + 1), ('C', w), ('H', w + 1), ('C', w)]


def dirty(rd, neg, cur=None, double=False):
    """The gates after the boxes as dirty gates; `cur` the current wire of
    the ladder after them (or None), `double` its type."""
    out = []
    for g in rd:
        if g[0] in ('H', 'Z'):
            out.append(g)
        elif g[0] == 'CZ':
            out.append(('CZ', min(g[1], g[2])))
        elif g[0] == 'X':
            if g[1] == cur:
                out.append(('X', g[1]))
            else:
                out += [('H', g[1]), ('Z', g[1]), ('H', g[1])]
        elif g[0] == 'CXZ':
            t, c = g[1], g[2]
            if t == c + 1 and t == cur and double:
                out.append(('CXZ', c))
            else:
                lo = min(t, c)
                out += [('H', t), ('CZ', lo), ('H', t), ('CZ', lo)]
        else:
            raise ValueError(g)
    if neg:
        out.append(('neg',))
    return out


def lean_dg(g):
    if g[0] == 'neg':
        return '.neg'
    return '.%s %d' % g


def lean_out(out):
    return '[' + ', '.join(lean_dg(g) for g in out) + ']'


# the relations --------------------------------------------------------------

def split(rec):
    num, fig, supp, (lg, ln), (rg, rn), note = rec
    assert not ln, num
    nb = 0
    while nb < len(rg) and rg[nb][0] == 'box':
        nb += 1
    return lg, rg[:nb], rg[nb:], rn


def check(rec, out, ok, k):
    """The row's letters are the relation's, it holds, and its gates are
    allowed."""
    num, fig, supp, (lg, ln), (rg, rn), note = rec
    _, rb, _, _ = split(rec)
    R = paper.expand(rb) + sum((word(g) for g in out), [])
    assert R == paper.expand(rg) + ([('m',)] if rn else []), num
    assert paper.same(paper.expand(lg), R, k), num
    for g in out:
        assert ok(g) and hi(g) <= k, (num, g)


HEAD = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# Real stabilizer circuits: the push tables

The typed relations of Appendix B (`rel1`–`rel139`, `Relations*.lean`) as
tables: a dirty gate immediately before one or two boxes of a normal form
equals boxes followed by dirty gates, which are allowed where they stand
(the labels of Definition 5.3, `okB`, `okD`), and the boxes keep the type of
the wire above them.  Everything is in the relation's own frame (wire `0`
at the bottom); `Push` moves it into place.  Generated by `gen/tables.py`.
-/
import QCert.RealStabilizer.Dirty
import QCert.RealStabilizer.Relations1

namespace QCert.RealStabilizer

set_option maxRecDepth 8000

'''


def gen(recs):
    R = {r[0]: r for r in recs}
    s = HEAD

    # the A box ---------------------------------------------------------------
    for name, ns, d, doc in (('tAZ', range(1, 4), 'Z', '`Z` at the wire of `A_i`'),
                             ('tAH', range(4, 7), 'H', '`H` at the wire of `A_i`')):
        rows = []
        for n in ns:
            lg, rb, rd, rn = split(R[n])
            i, (b,) = lg[1][2], rb
            i2 = b[2]
            assert TA[i2] == TA[i]
            out = dirty(rd, rn, 0, TA[i2])
            check(R[n], out, lambda g: okB(TA[i2], 0, g), 1)
            rows.append((i - 1, '⟨%d, %s, rel%d, by decide⟩' % (i2 - 1, lean_out(out), n)))
        s += '/-- %s: relations %d–%d. -/\n' % (doc, ns[0], ns[-1])
        s += ('theorem %s : ∀ i : Fin 3, ∃ (i\' : Fin 3) (out : List Dg),\n'
              '    Holds 1 ([.%s 0] ++ bA (i.val + 1) 0) (bA (i\'.val + 1) 0 ++ dw out) ∧\n'
              '      tA i\' = tA i ∧ OkL (okB (tA i\') 0) 1 out\n' % (name, d))
        for i, t in sorted(rows):
            s += '  | %d => %s\n' % (i, t)
        s += '\n'
    # CZ with A on its upper wire
    rows = []
    for n in range(7, 10):
        lg, rb, rd, rn = split(R[n])
        i = lg[1][2]
        if len(rb) == 1:
            i2 = rb[0][2]
            assert rb[0][3] == (1,) and TA[i2] == TA[i]
            out = dirty(rd, rn, 1, TA[i2])
            check(R[n], out, lambda g: okB(TA[i2], 1, g), 2)
            rows.append((i - 1, 'Or.inl ⟨%d, %s, rel%d, by decide⟩' % (i2 - 1, lean_out(out), n)))
        else:
            i2, p = rb[0][2], rb[1][2]
            t0, j = bty(p)
            assert rb[0][3] == (0,) and t0 == TA[i2] and tB(t0, j) == TA[i]
            out = dirty(rd, rn, 1, tB(t0, j))
            check(R[n], out, lambda g: okB(tB(t0, j), 1, g), 2)
            rows.append((i - 1, 'Or.inr ⟨%d, %d, %s, rel%d, by decide⟩'
                         % (i2 - 1, j, lean_out(out), n)))
    s += '''/-- `CZ` with `A_i` on its upper wire: relations 7–9.  Either `A_i` stays,
or the ladder grows down by one wire (`A_{i'}` below a `B` gate). -/
theorem tACZ : ∀ i : Fin 3,
    (∃ (i' : Fin 3) (out : List Dg),
      Holds 2 ([Lt.CZ 0] ++ bA (i.val + 1) 1) (bA (i'.val + 1) 1 ++ dw out) ∧
        tA i' = tA i ∧ OkL (okB (tA i') 1) 2 out) ∨
    (∃ (i' : Fin 3) (j : Fin 4) (out : List Dg),
      Holds 2 ([Lt.CZ 0] ++ bA (i.val + 1) 1)
        (bA (i'.val + 1) 0 ++ bB (bIdx (tA i') j) 0 ++ dw out) ∧
        tB (tA i') j = tA i ∧ OkL (okB (tB (tA i') j) 1) 2 out)
'''
    for i, t in sorted(rows):
        s += '  | %d => %s\n' % (i, t)
    s += '\n'
    # CZ on the wires of A B
    rows = []
    for n in range(10, 22):
        lg, rb, rd, rn = split(R[n])
        i, p = lg[1][2], lg[2][2]
        t0, j = bty(p)
        assert t0 == TA[i]
        tin = tB(t0, j)
        if len(rb) == 2:
            i2, p2 = rb[0][2], rb[1][2]
            t1, j2 = bty(p2)
            assert t1 == TA[i2] and tB(t1, j2) == tin
            out = dirty(rd, rn, 1, tin)
            check(R[n], out, lambda g: okB(tin, 1, g), 2)
            rows.append(((i - 1, j), 'Or.inl ⟨%d, %d, %s, rel%d, by decide⟩'
                         % (i2 - 1, j2, lean_out(out), n)))
        else:
            i2 = rb[0][2]
            assert rb[0][3] == (1,) and TA[i2] == tin
            out = dirty(rd, rn, 1, tin)
            check(R[n], out, lambda g: okB(tin, 1, g), 2)
            rows.append(((i - 1, j), 'Or.inr ⟨%d, %s, rel%d, by decide⟩'
                         % (i2 - 1, lean_out(out), n)))
    s += '''/-- `CZ` on the wires of `A_i B`, before both: relations 10–21.  Either the
two boxes stay, or the ladder shrinks by one wire (`A_{i'}` on the upper
wire). -/
theorem tAB : ∀ (i : Fin 3) (j : Fin 4),
    (∃ (i' : Fin 3) (j' : Fin 4) (out : List Dg),
      Holds 2 ([Lt.CZ 0] ++ bA (i.val + 1) 0 ++ bB (bIdx (tA i) j) 0)
        (bA (i'.val + 1) 0 ++ bB (bIdx (tA i') j') 0 ++ dw out) ∧
        tB (tA i') j' = tB (tA i) j ∧ OkL (okB (tB (tA i') j') 1) 2 out) ∨
    (∃ (i' : Fin 3) (out : List Dg),
      Holds 2 ([Lt.CZ 0] ++ bA (i.val + 1) 0 ++ bB (bIdx (tA i) j) 0)
        (bA (i'.val + 1) 1 ++ dw out) ∧ tA i' = tB (tA i) j ∧ OkL (okB (tA i') 1) 2 out)
'''
    for (i, j), t in sorted(rows):
        s += '  | %d, %d => %s\n' % (i, j, t)
    s += '\n'

    # one B box at (0, 1) ----------------------------------------------------------
    for name, ns, lhs, doc, fixed in (
            ('tBH0', range(22, 26), '[Lt.H 0]', '`H` on the lower wire of a `B` gate, which is double',
             True),
            ('tBX', range(26, 34), 'bX 0', '`X` on the lower wire of a `B` gate', None),
            ('tBH1', range(34, 42), '[Lt.H 1]', '`H` on the upper wire of a `B` gate', None),
            ('tBZ1', range(42, 50), '[Lt.Z 1]', '`Z` on the upper wire of a `B` gate', None),
            ('tBZ0', range(50, 58), '[Lt.Z 0]', '`Z` on the lower wire of a `B` gate', None)):
        rows = []
        for n in ns:
            lg, rb, rd, rn = split(R[n])
            t, j = bty(lg[-1][2])
            (b,) = rb
            t2, j2 = bty(b[2])
            assert t2 == t and tB(t, j2) == tB(t, j) and (fixed is None or t == fixed)
            out = dirty(rd, rn, 1, tB(t, j2))
            check(R[n], out, lambda g: okB(tB(t, j2), 1, g), 2)
            rows.append(((t, j), '⟨%d, %s, rel%d, by decide⟩' % (j2, lean_out(out), n)))
        s += '/-- %s: relations %d–%d. -/\n' % (doc, ns[0], ns[-1])
        if fixed is None:
            s += ('theorem %s : ∀ (t : Ty) (j : Fin 4), ∃ (j\' : Fin 4) (out : List Dg),\n'
                  '    Holds 2 (%s ++ bB (bIdx t j) 0) (bB (bIdx t j\') 0 ++ dw out) ∧\n'
                  '      tB t j\' = tB t j ∧ OkL (okB (tB t j\') 1) 2 out\n' % (name, lhs))
            for (t, j), r in sorted(rows):
                s += '  | %s, %d => %s\n' % ('true' if t else 'false', j, r)
        else:
            tt = 'true' if fixed else 'false'
            s += ('theorem %s : ∀ j : Fin 4, ∃ (j\' : Fin 4) (out : List Dg),\n'
                  '    Holds 2 (%s ++ bB (bIdx %s j) 0) (bB (bIdx %s j\') 0 ++ dw out) ∧\n'
                  '      tB %s j\' = tB %s j ∧ OkL (okB (tB %s j\') 1) 2 out\n'
                  % (name, lhs, tt, tt, tt, tt, tt))
            for (t, j), r in sorted(rows):
                s += '  | %d => %s\n' % (j, r)
        s += '\n'
    # a gate below the first B box: CZ (simple) or CXZ (double) at (0, 1)
    for name, ns, lhs, doc, fixed in (
            ('tBCZ', range(64, 68), '[Lt.CZ 0]', '`CZ` below a `B` gate, its upper wire on the '
             'simple lower wire of the gate', False),
            ('tBCXZ', range(68, 72), '[Lt.H 1, Lt.CZ 0, Lt.H 1, Lt.CZ 0]', '`CXZ` below a `B` gate, its '
             '`XZ` on the double lower wire of the gate', True)):
        rows = []
        for n in ns:
            lg, rb, rd, rn = split(R[n])
            t, j = bty(lg[-1][2])
            (b,) = rb
            t2, j2 = bty(b[2])
            assert t == fixed and t2 == t and tB(t, j2) == tB(t, j) and b[3] == (1, 2)
            out = dirty(rd, rn, 2, tB(t, j2))
            check(R[n], out, lambda g: okB(tB(t, j2), 2, g), 3)
            rows.append((j, '⟨%d, %s, rel%d, by decide⟩' % (j2, lean_out(out), n)))
        tt = 'true' if fixed else 'false'
        s += '/-- %s: relations %d–%d. -/\n' % (doc, ns[0], ns[-1])
        s += ('theorem %s : ∀ j : Fin 4, ∃ (j\' : Fin 4) (out : List Dg),\n'
              '    Holds 3 (%s ++ bB (bIdx %s j) 1) (bB (bIdx %s j\') 1 ++ dw out) ∧\n'
              '      tB %s j\' = tB %s j ∧ OkL (okB (tB %s j\') 2) 3 out\n'
              % (name, lhs, tt, tt, tt, tt, tt))
        for j, r in sorted(rows):
            s += '  | %d => %s\n' % (j, r)
        s += '\n'
    # CZ on the wires of the second of two B boxes
    rows = []
    for n in range(72, 104):
        lg, rb, rd, rn = split(R[n])
        t, a = bty(lg[1][2])
        tb_, b = bty(lg[2][2])
        t2, a2 = bty(rb[0][2])
        tb2, b2 = bty(rb[1][2])
        assert tb_ == tB(t, a) and t2 == t and tb2 == tB(t, a2)
        tout = tB(tB(t, a2), b2)
        assert tout == tB(tB(t, a), b)
        out = dirty(rd, rn, 2, tout)
        check(R[n], out, lambda g: okB(tout, 2, g), 3)
        rows.append(((t, a, b), '⟨%d, %d, %s, rel%d, by decide⟩' % (a2, b2, lean_out(out), n)))
    s += '''/-- `CZ` on the wires of the second of two `B` gates, before the first:
relations 72–103. -/
theorem tBB : ∀ (t : Ty) (a b : Fin 4), ∃ (a' b' : Fin 4) (out : List Dg),
    Holds 3 ([Lt.CZ 1] ++ bB (bIdx t a) 0 ++ bB (bIdx (tB t a) b) 1)
      (bB (bIdx t a') 0 ++ bB (bIdx (tB t a') b') 1 ++ dw out) ∧
      tB (tB t a') b' = tB (tB t a) b ∧ OkL (okB (tB (tB t a') b') 2) 3 out
'''
    for (t, a, b), r in sorted(rows):
        s += '  | %s, %d, %d => %s\n' % ('true' if t else 'false', a, b, r)
    s += '\n'

    # the C box ------------------------------------------------------------------
    for name, ns, lhs, frame, doc in (
            ('tCZ', (58, 61), '[Lt.Z 0] ++ bC (k.val + 1) 0', 1, '`Z` at the wire of `C_k`'),
            ('tCX', (59, 62), 'bX 0 ++ bC (k.val + 1) 0', 1, '`X` at the wire of `C_k`'),
            ('tCCZ', (60, 63), '[Lt.CZ 0] ++ bC (k.val + 1) 1', 2, '`CZ` below `C_k`, on its wire')):
        rows = []
        cw = frame - 1
        for n in ns:
            lg, rb, rd, rn = split(R[n])
            (b,) = rb
            out = dirty(rd, rn)
            check(R[n], out, lambda g: okD(True, cw, g), frame)
            rows.append((lg[-1][2] - 1, '⟨%d, %s, rel%d, by decide⟩' % (b[2] - 1, lean_out(out), n)))
        s += '/-- %s: relations %d, %d. -/\n' % (doc, ns[0], ns[1])
        s += ('theorem %s : ∀ k : Fin 2, ∃ (k\' : Fin 2) (out : List Dg),\n'
              '    Holds %d (%s) (bC (k\'.val + 1) %d ++ dw out) ∧ OkL (okD true %d) %d out\n'
              % (name, frame, lhs, cw, cw, frame))
        for k, r in sorted(rows):
            s += '  | %d => %s\n' % (k, r)
        s += '\n'

    # the D and E boxes ----------------------------------------------------------------
    for name, ns, lhs, doc in (
            ('tDZ1', range(104, 108), '[Lt.Z 1]', '`Z` on the upper wire of `D_l`'),
            ('tDZ0', range(108, 112), '[Lt.Z 0]', '`Z` on the lower wire of `D_l`'),
            ('tDH', range(112, 116), '[Lt.H 0]', '`H` on the lower wire of `D_l`'),
            ('tDCZ', range(116, 120), '[Lt.CZ 0]', '`CZ` on the wires of `D_l`')):
        rows = []
        for n in ns:
            lg, rb, rd, rn = split(R[n])
            (b,) = rb
            out = dirty(rd, rn)
            check(R[n], out, lambda g: okD(False, 0, g), 2)
            rows.append((lg[-1][2] - 1, '⟨%d, %s, rel%d, by decide⟩' % (b[2] - 1, lean_out(out), n)))
        s += '/-- %s: relations %d–%d. -/\n' % (doc, ns[0], ns[-1])
        s += ('theorem %s : ∀ l : Fin 4, ∃ (l\' : Fin 4) (out : List Dg),\n'
              '    Holds 2 (%s ++ bD (l.val + 1) 0) (bD (l\'.val + 1) 0 ++ dw out) ∧\n'
              '      OkL (okD false 0) 2 out\n' % (name, lhs))
        for l, r in sorted(rows):
            s += '  | %d => %s\n' % (l, r)
        s += '\n'
    rows = []
    for n in range(122, 138):
        lg, rb, rd, rn = split(R[n])
        out = dirty(rd, rn)
        check(R[n], out, lambda g: okD(False, 0, g), 3)
        rows.append(((lg[1][2] - 1, lg[2][2] - 1),
                     '⟨%d, %d, %s, rel%d, by decide⟩' % (rb[0][2] - 1, rb[1][2] - 1, lean_out(out), n)))
    s += '''/-- `CZ` on the wires of the second of two `D` gates, before the first:
relations 122–137. -/
theorem tDD : ∀ a b : Fin 4, ∃ (a' b' : Fin 4) (out : List Dg),
    Holds 3 ([Lt.CZ 0] ++ bD (a.val + 1) 1 ++ bD (b.val + 1) 0)
      (bD (a'.val + 1) 1 ++ bD (b'.val + 1) 0 ++ dw out) ∧ OkL (okD false 0) 3 out
'''
    for (a, b), r in sorted(rows):
        s += '  | %d, %d => %s\n' % (a, b, r)
    s += '\n'
    rows = []
    for n in (120, 121):
        lg, rb, rd, rn = split(R[n])
        assert not rd and not rn
        rows.append((lg[-1][2] - 1, '⟨%d, rel%d⟩' % (rb[0][2] - 1, n)))
    s += '''/-- `Z` at the wire of `E_h`: relations 120, 121. -/
theorem tEZ : ∀ h : Fin 2, ∃ h' : Fin 2,
    Holds 1 ([Lt.Z 0] ++ bE (h.val + 1) 0) (bE (h'.val + 1) 0)
'''
    for h, r in sorted(rows):
        s += '  | %d => %s\n' % (h, r)
    s += '\nend QCert.RealStabilizer\n'
    return s


def main():
    recs = relations.records()
    relations.check(recs)
    text = gen(recs)
    path = os.path.join(OUT, 'Tables.lean')
    if '--check' in sys.argv:
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        print('Tables.lean:', 'same' if old == text else 'DIFFERS')
        return 0 if old == text else 1
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', path)
    return 0


if __name__ == '__main__':
    sys.exit(main())
