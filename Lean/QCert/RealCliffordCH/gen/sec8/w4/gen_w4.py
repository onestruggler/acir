def fold_proof(a, b):
    return 'Net.der_of_eq (by set_option maxRecDepth 100000 in rfl)'


def finish(S, L, R, allsteps, n):
    T, fixed = [], []
    for s in allsteps:
        if s[0] == 'rw':
            e = S.table[s[2]]
            if e not in T:
                T.append(e)
            s = ('rw', s[1], T.index(e), s[3])
        fixed.append(s)
    eng = tok.Engine(M, T)
    w, bad = eng.run(L, fixed)
    assert w == list(R), (n, bad, w)
    return Eq(n, L, R, fixed, T)


def prove161(d, known):
    """(161) by (150) and Lemma B.4: SW23 conjugates the eight-gate form A of the box into
    A' (CZ(2,0) and CZ(3,0) exchanged); the paper's chain gives W16 = 1 with
    W16 = A rev(A') up to two commuting CZs; so A' = W16 A' = A rev(A') A' = A."""
    L, R, chains = chain_words(d, 161, {})
    l150, r150 = known['150']
    A = list(r150)
    S = solve.Solver(N, (), [])
    k150 = S.table_index(l150, r150)
    eng = tok.Engine(M, S.table)
    steps = [('rw', 1, k150, False)]
    cur = eng.run(L, steps)[0]
    st, cur = S.distribute(cur, 0, [2], len(A))
    steps += st
    C02, C03 = A[1], A[3]
    Ap = [C03 if t == C02 else C02 if t == C03 else t for t in A]
    S.start()
    st = S.solve(cur, Ap)
    steps += st
    ws = chains[1][2:]
    W16 = ws[0]
    fwd = solve_chain(S, ws)                      # W16 -> []
    steps += solve.reverse_steps(M, S.table, W16, fwd)   # [] -> W16, in front of A'
    target = A + list(reversed(Ap))
    S.start()
    steps += S.solve(W16, target)
    n = len(A)
    for k in range(len(Ap)):
        i = n + len(Ap) - 1 - k
        t = Ap[k]
        q = S.window([t, t], [])
        assert q is not None, t
        steps.append(('sem', i, 2, (), q))
    steps.append(('rw', 0, k150, True))
    return finish(S, L, R, steps, 161)


def endpoint(d, n, side, env=None):
    """A run carrying the statement's side ('l' or 'r') written as SmallDefs letters (`s`
    tokens) to its token word; returns (letters, tokens, steps, table)."""
    env = env or {}
    st = d['statements'][str(n)]
    D = st[0] if side == 'l' else st[-1]
    S = solve.Solver(N)
    letters, toks, steps = [], [], []
    for g0 in D['gates']:
        g = dec(g0)
        Lg = [('s',) + tuple(l) for l in model.word(N, [g], env)]
        Tg = conv.gate_tokens(N, g, env)
        pos = len(toks)
        if Lg == Tg:
            sub = []
        elif len(Tg) == 1 and Tg[0][0] == 'g' and len(tok.wires(Tg[0])) == N:
            k, Lt = S.fold_entry(Tg[0])
            if Lt != Lg:
                raise solve.Fail(f'endpoint: letters of {g} differ from the token')
            sub = [('rw', 0, k, False)]
        else:
            S.start()
            sub = S.solve(Lg, Tg)
        steps += solve.shift(sub, pos)
        letters += Lg
        toks += Tg
    eng = tok.Engine(M, S.table)
    cur = list(letters)
    for s in steps:
        cur = eng.apply_step(cur, s)
        assert cur is not None, (n, side, s)
    assert cur == toks, (n, side)
    return letters, toks, steps, S.table


def tinv(t):
    """The inverse token (or None)."""
    if t[0] == 's':
        return t
    if t[0] == 'g':
        _, Kd, tg, cs = t
        return ('g', {'zx': 'xz', 'xz': 'zx'}.get(Kd, Kd), tg, cs)
    _, m, w, ps = t
    if tok.weq(N, [t, t], []):
        return t
    w2 = tuple(reversed(w))
    t2 = ('p', m, w2, ps)
    return t2 if tok.weq(N, [t, t2], []) else None


def winv(w):
    out = [tinv(t) for t in reversed(w)]
    return None if None in out else out


def pair_steps(S, at, w):
    """Insert w + winv(w) at position `at`, outermost pair first, each a semantic window."""
    steps = []
    for k, t in enumerate(w):
        ti = tinv(t)
        q = S.window([], [t, ti])
        if q is None:
            raise solve.Fail('pair')
        steps.append(('sem', at + k, 0, (t, ti), q))
    return steps


def derive(name, l, r, known):
    """Derived forms of an equation l = r: its inverse, and when it is a commutation
    x y = y x, the commutations of x^-1 with y and of y^-1 with x.  Each comes with a run
    using l = r once; returns a list of (name, Eq)."""
    out = []
    S = solve.Solver(N, (), [])
    k = S.table_index(l, r)
    il, ir = winv(l), winv(r)
    if il is not None and ir is not None and (il, ir) != (list(l), list(r)):
        try:
            # inv(l) -> inv(l) r inv(r) -> inv(l) l inv(r) -> inv(r)
            st = pair_steps(S, len(il), list(r))
            st.append(('rw', len(il), k, True))
            cur = il + list(l) + ir
            # cancel inv(l) l: innermost pair at len(il) - 1
            for j in range(len(il)):
                i = len(il) - 1 - j
                t = cur[i]
                q = S.window([cur[i], cur[i + 1]], [])
                if q is None:
                    raise solve.Fail('cancel')
                st.append(('sem', i, 2, (), q))
                cur = cur[:i] + cur[i + 2:]
            out.append((name + 'i', finish(S, il, ir, st, name + 'i')))
        except (solve.Fail, AssertionError):
            pass
    for c in range(1, len(l)):
        x, y = list(l[:c]), list(l[c:])
        if list(r) != y + x:
            continue
        for (u, v, nm) in ((x, y, 'a'), (y, x, 'b')):
            iu = winv(u)
            if iu is None:
                continue
            # v iu -> iu u v iu -> iu v u iu -> iu v
            try:
                S2 = solve.Solver(N, (), [])
                k2 = S2.table_index(l, r)
                st = pair_steps(S2, 0, iu)      # iu u in front (iu u = 1)
                cur = iu + winv(iu) + v + iu
                assert winv(iu) == u
                kk = k2
                if nm == 'a':
                    st.append(('rw', len(iu), kk, False))     # u v -> v u
                else:
                    st.append(('rw', len(iu), kk, True))      # v u -> u v (here u = y, v = x)
                cur = iu + v + u + iu
                # cancel u iu at the end
                for j in range(len(u)):
                    i = len(iu) + len(v) + len(u) - 1 - j
                    q = S2.window([cur[i], cur[i + 1]], [])
                    if q is None:
                        raise solve.Fail('cancel')
                    st.append(('sem', i, 2, (), q))
                    cur = cur[:i] + cur[i + 2:]
                out.append((name + 'c' + nm, finish(S2, v + iu, iu + v, st, name + 'c' + nm)))
            except (solve.Fail, AssertionError):
                pass
        break
    return out


def small_form(t):
    """A placed word on two adjacent increasing wires (or one wire) as a letter, if it is one."""
    if t[0] == 'p' and len(t[2]) == 1:
        (k, j), = t[2]
        ps = t[3]
        if j == 0 and (len(ps) == 1 or (len(ps) == 2 and ps[1] == ps[0] + 1)):
            return ('s', k, ps[0])
    return t


def conj_target(t, j):
    if t[0] == 's':
        k, i = t[1], t[2]
        if k in 'HZ':
            t = tok.P(1, [(k, 0)], [i])
        elif k == 'S':
            return None
        else:
            t = tok.P(2, [(k, 0)], [i, i + 1])
    t2 = tok.relabel(t, j)
    if t2[0] == 'g' and not tok.swp_ok(N, j, t, t2):
        return t                       # both controls: a symmetry of the gadget, if known
    return small_form(t2)


def distribute_j(S, w, j):
    """Steps from [S j] + w + [S j] to w conjugated token by token."""
    sj = ('s', 'S', j)
    steps = []
    n = len(w)
    for k in range(n - 1):
        q = S.window([], [sj, sj])
        steps.append(('sem', 2 + 3 * k, 0, (sj, sj), q))
    out = []
    for k in range(n - 1, -1, -1):
        t = w[k]
        t2 = conj_target(t, j)
        if t2 is None:
            raise solve.Fail('conj swap')
        S.start(1500)
        sub = S.solve([sj, t, sj], [t2])
        steps += solve.shift(sub, 3 * k)
        out.insert(0, t2)
    return steps, out


def conj_eq(name, l, r, j, known):
    S = solve.Solver(N, (), [(k, a, b) for k, (a, b) in known.items()])
    k = S.table_index(l, r)
    sj = ('s', 'S', j)
    sl, l2 = distribute_j(S, list(l), j)
    sr, r2 = distribute_j(S, list(r), j)
    if (l2, r2) == (list(l), list(r)):
        return None
    w0 = [sj] + list(l) + [sj]
    steps = solve.reverse_steps(M, S.table, w0, sl) + [('rw', 1, k, False)] + sr
    return finish(S, l2, r2, steps, name)


def entry_proof(e, known):
    a, b = e
    for name, (l, r) in known.items():
        if (tuple(a), tuple(b)) == (tuple(l), tuple(r)):
            return f't{name} ih'
    if len(b) == 1 and b[0][0] == 'g' and all(x[0] == 's' for x in a):
        return fold_proof(a, b)
    return None


def generate(d, eqs, known, title, imp):
    body = []
    done = []
    pending = []
    for n in eqs:
        try:
            if n == 161:
                e = prove161(d, known)
            else:
                e = prove(d, n, eqs=[(k, l, r) for k, (l, r) in known.items()])
        except (solve.Fail, AssertionError, KeyError, IndexError) as ex:
            print(f'({n}) FAILED: {type(ex).__name__} {str(ex)[:200]}', flush=True)
            continue
        proofs = [entry_proof(t, known) for t in e.table]
        if None in proofs:
            print(f'({n}) FAILED: table entry without proof')
            continue
        body.append(lean_run(str(n), e, proofs))
        known[str(n)] = (e.L, e.R)
        for j in range(N - 1):
            pending.append((f'{n}s{j}', e.L, e.R, j))
        conj = []
        still = []
        for (cn, cl, cr, j) in pending:
            try:
                ce = conj_eq(cn, cl, cr, j, known)
            except (solve.Fail, AssertionError):
                still.append((cn, cl, cr, j))
                continue
            if ce is not None:
                conj.append((cn, ce))
        pending[:] = still
        for dn, de in derive(str(n), e.L, e.R, known) + conj:
            dp = [entry_proof(t, known) for t in de.table]
            if None in dp:
                continue
            body.append(lean_run(dn, de, dp))
            known[dn] = (de.L, de.R)
        if n in EXPORT:
            try:
                body.append(lean_endpoint(n, d, known))
            except (solve.Fail, AssertionError) as ex:
                print(f'({n}) endpoint FAILED: {str(ex)[:200]}', flush=True)
        done.append(n)
        print(f'({n}): {len(e.steps)} steps, table {len(e.table)}', flush=True)
    text = HEADER.replace('{title}', title).replace('{imp}', imp)
    text += NL.join(body) + NL + 'end QCert.RealCliffordCH.Sec8.D.W4' + NL
    return text, done


