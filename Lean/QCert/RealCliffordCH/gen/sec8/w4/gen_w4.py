def diag_tokens(D, env):
    return conv.word(N, [dec(g) for g in D['gates']], env)


def chain_words(d, n, env):
    """The token words of the chains of equation n, oriented from the statement's lhs."""
    st = d['statements'][str(n)]
    L, R = diag_tokens(st[0], env), diag_tokens(st[-1], env)
    out = []
    for ch in d['proofs'].get(str(n), []):
        ws = [diag_tokens(D, env) for D in ch['diags']]
        out.append(ws)
    return L, R, out


class Eq:
    def __init__(self, n, L, R, steps, table):
        self.n, self.L, self.R, self.steps, self.table = n, L, R, steps, table


def solve_chain(S, ws):
    steps = []
    cur = ws[0]
    for i in range(len(ws) - 1):
        S.start()
        try:
            st = S.solve(cur, ws[i + 1])
        except solve.Fail as e:
            raise solve.Fail(f'step {i}: {e}')
        ok, bad = S.verify(cur, ws[i + 1], st)
        assert ok, (i, bad)
        steps += st
        cur = ws[i + 1]
    return steps


def full_chain(chains, L, R):
    """The chains joined end to end (a statement with three sides has two), oriented from
    the statement's left side when the first chain starts at its right side."""
    cs = [c for c in chains if c]
    if not cs:
        return [list(L), list(R)]       # no chain: "follows directly from ..."
    ws = list(cs[0])
    for c in cs[1:]:
        if c[0] == ws[-1]:
            ws += c[1:]
        else:
            break
    if (ws[0] == list(R) or ws[-1] == list(L)) and not (ws[0] == list(L)):
        ws = list(reversed(ws))
    return ws


def prove(d, n, env=None, chain=0, start=0, eqs=()):
    env = env or {}
    L, R, chains = chain_words(d, n, env)
    S = solve.Solver(N, (), eqs)
    ws = full_chain(chains, L, R) if chain == 0 and start == 0 else chains[chain][start:]
    S.start()
    pre = S.solve(L, ws[0]) if ws[0] != L else []
    steps = solve_chain(S, ws)
    S.start()
    post = S.solve(ws[-1], R) if ws[-1] != R else []
    allsteps = pre + steps + post
    # keep only the table entries used, in order of first use
    T, fixed = [], []
    for s in allsteps:
        if s[0] == 'rw':
            e = S.table[s[2]]
            if e not in T:
                T.append(e)
            s = ('rw', s[1], T.index(e), s[3])
        fixed.append(s)
    eng = tok.Engine(M, T)
    w, bad = eng.run(L, fixed)
    assert w == R, (n, bad)
    return Eq(n, L, R, fixed, T)


def lean_run(name, e, entry_proofs):
    out = []
    out.append(f'def L{name} : List Tk := {tok.lean_word(e.L)}\n')
    out.append(f'def R{name} : List Tk := {tok.lean_word(e.R)}\n')
    tbl = '[' + ',\n  '.join(f'({tok.lean_word(a)}, {tok.lean_word(b)})' for a, b in e.table) + ']'
    out.append(f'def T{name} : Tbl := {tbl}\n')
    steps = ',\n    '.join(tok.lean_step(s) for s in e.steps)
    out.append(f'theorem run{name} : check 3 T{name} L{name} R{name}\n    [{steps}] = true := by\n  decide +kernel\n')
    proofs = ' (\n    '.join(entry_proofs) if entry_proofs else ''
    allD = 'AllD.nil 4'
    for p in reversed(entry_proofs):
        allD = f'AllD.cons ({p}) ({allD})'
    out.append(f'theorem t{name} (ih : IH 4) : Derivable (theory 4) (wcT 4 L{name}) (wcT 4 R{name}) :=\n'
               f'  check_sound ih ({allD}) run{name}\n')
    return '\n'.join(out)


