"""Engine runs for the equations of Appendix D.3 at width 4 (package (ii)).

    python gen_w4.py D3.json OUT.lean EQ [EQ ...]

For each equation, the paper's chain (parsed by chains.py) is turned into tokens of
Sec8/D/WEng.lean (conv.py), each step into engine steps (solve.py), the whole run checked
by the Python model of the engine (tok.Engine), and written as Lean: the statement as
token words `LNNN`, `RNNN` (the first and last diagram of its row), the table, the run
(`decide +kernel`), and `tNNN : Derivable (theory 4) (wcT 4 LNNN) (wcT 4 RNNN)`.
Earlier equations enter the table through their `tNNN`; a four-wire gadget enters it
through its letters (`fold`, by `rfl`).
"""
