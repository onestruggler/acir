def lean_endpoint(n, d, known):
    """The exported statement eNNN : Derivable (theory 4) lNNN rNNN from tNNN."""
    out = []
    ent = []
    for side in ('l', 'r'):
        letters, toks, steps, table = endpoint(d, n, side)
        e = finish_simple(table, letters, toks, steps)
        nm = f'{side.upper()}C{n}'
        lw = '[' + ', '.join(f'L.{t[1]} {t[2]}' for t in letters) + ']'
        out.append(f'def S{nm} : List Tk := ({lw} : List L).map Tk.s' + NL)
        tbl = '[' + (',' + NL + '  ').join(f'({tok.lean_word(x)}, {tok.lean_word(y)})' for x, y in e[0]) + ']'
        out.append(f'def T{nm} : Tbl := {tbl}' + NL)
        st = (',' + NL + '    ').join(tok.lean_step(s) for s in e[1])
        tgt = f'{side.upper()}{n}'
        out.append(f'theorem run{nm} : check 3 T{nm} S{nm} {tgt}' + NL + f'    [{st}] = true := by' + NL
                   + '  decide +kernel' + NL)
        proofs = [entry_proof(t, known) for t in e[0]]
        assert None not in proofs
        allD = 'AllD.nil 4'
        for p in reversed(proofs):
            allD = f'AllD.cons ({p}) ({allD})'
        ent.append((nm, allD))
    (ln, la), (rn, ra) = ent
    out.append(NL.join([
        f'theorem e{n} (ih : IH 4) : Derivable (theory 4) l{n} r{n} := by',
        f'  have hl : l{n} = wcT 4 S{ln} := circW_eq_wcT 4 _',
        f'  have hr : r{n} = wcT 4 S{rn} := circW_eq_wcT 4 _',
        '  rw [hl, hr]',
        f'  exact (check_sound ih ({la}) run{ln}).trans',
        f'    ((t{n} ih).trans (check_sound ih ({ra}) run{rn}).symm)', '']))
    return NL.join(out)


def finish_simple(table, w, v, steps):
    T, fixed = [], []
    for s in steps:
        if s[0] == 'rw':
            e = table[s[2]]
            if e not in T:
                T.append(e)
            s = ('rw', s[1], T.index(e), s[3])
        fixed.append(s)
    eng = tok.Engine(M, T)
    r, bad = eng.run(w, fixed)
    assert r == list(v), bad
    return T, fixed


