"""Write the decided rotation-against-rotation steps of (337), (338), (339)
with one semantic window per declaration and `Elab.async` off.

The kernel keeps a declaration's caches until the declaration is checked, so
a declaration deciding several windows holds all of them at once; one window
of 22 letters on four wires costs about 0.7 GB.  Each window is its own
declaration here, and the statements the drafts use (`chkRR337r`,
`chkRR338r`, `chkRR339`) are assembled from them by cases.
"""
import itertools, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[3] / "Sec8/D/N13"

def b(v): return "true" if v else "false"
def tag(vs): return "".join("t" if v else "f" for v in vs)

def gen(fname, title, imp, name, lhs_list, rhs_list, conj_l, conj_r, length):
    """`lhs_list(b1, b3)`: the first list (a function `rots2 b1 true b3`),
    `rhs_list(c3)`: the second; the window is `[r] ++ conj_l ++ [r'] ++ conj_r`."""
    out = [f'''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

# {title}

One semantic window per declaration, `Elab.async` off (memory: the kernel
keeps a declaration's caches until it is checked); generated by
`gen/sec8/n13/split_rr.py`.
-/
import {imp}

set_option Elab.async false

namespace QCert.RealCliffordCH.Sec8.D.N13

open Circuit Eng SE Net N8
''']
    def stmt(r, r2):
        return (f"check 4 [] ([{r}] ++ {conj_l} ++ [{r2}] ++ {conj_r}) "
                f"({conj_l} ++ [{r2}] ++ {conj_r} ++ [{r}])\n"
                f"      [.sem 0 {length} ({conj_l} ++ [{r2}] ++ {conj_r} ++ [{r}]) 4] = true")
    cases = list(itertools.product((False, True), repeat=3))
    for (b1, b3, c3) in cases:
        L, Ln = lhs_list(b(b1), b(b3))
        R, Rn = rhs_list(b(c3))
        ws = []
        for i, r in enumerate(Ln):
            for j, r2 in enumerate(Rn):
                w = f"{name}_{tag((b1, b3, c3))}_{i + 1}{j + 1}"
                ws.append(w)
                out.append(f"theorem {w} :\n    {stmt(r, r2)} := by\n  decide +kernel\n")
        out.append(f"theorem {name}_{tag((b1, b3, c3))} :\n"
                   f"    ∀ r ∈ {L}, ∀ r' ∈ {R},\n      {stmt('r', 'r' + chr(39))} := by\n"
                   f"  intro r hr r' hr'\n"
                   f"  simp only [rots2, srots2, List.mem_cons, List.mem_nil_iff, or_false] at hr hr'\n"
                   f"  rcases hr with rfl | rfl <;> rcases hr' with rfl | rfl\n"
                   f"  exacts [{', '.join(ws)}]\n")
    L, _ = lhs_list("b1", "b3")
    R, _ = rhs_list("c3")
    out.append(f"theorem {name} (b1 b3 c3 : Bool) :\n    ∀ r ∈ {L}, ∀ r' ∈ {R},\n"
               f"      {stmt('r', 'r' + chr(39))} := by\n"
               f"  cases b1 <;> cases b3 <;> cases c3\n"
               f"  exacts [{', '.join(name + '_' + tag(c) for c in cases)}]\n")
    out.append("end QCert.RealCliffordCH.Sec8.D.N13\n")
    (ROOT / fname).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote", fname)

def rots2(b1, b2, b3):
    return f"rots2 {b1} {b2} {b3}", [f"P1 {b1} {b2} {b3}", f"P2 {b1} {b2} {b3}"]

def srots2(b1, b2, b3):
    return f"srots2 {b1} {b2} {b3}", [f"SR1 {b1} {b2} {b3}", f"SR2 {b1} {b2} {b3}"]

which = sys.argv[1:] or ["337", "338", "339"]
if "337" in which:
    gen("E337r1.lean", "Two rotations of (337)", "QCert.RealCliffordCH.Sec8.D.N13.E337c",
        "chkRR337r", lambda b1, b3: rots2(b1, "true", b3), lambda c3: rots2("true", "false", c3),
        "N13.ppL", "N13.ppL", 22)
if "338" in which:
    gen("E337r2.lean", "Two rotations of (338)", "QCert.RealCliffordCH.Sec8.D.N13.E337c",
        "chkRR338r", lambda b1, b3: rots2(b1, "true", b3), lambda c3: srots2("true", "false", c3),
        "N13.ppL", "N13.ppL", 22)
if "339" in which:
    gen("E339r1.lean", "Two rotations of (339)", "QCert.RealCliffordCH.Sec8.D.N13.E339a",
        "chkRR339", lambda b1, b3: rots2(b1, "true", b3), lambda c3: rots2("false", c3, "true"),
        "mL'", "mL", 34)
