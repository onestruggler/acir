"""Write `Sec8/D/N13/E322.lean` with every decided run in its own declaration.

The kernel keeps the caches of one declaration until the declaration is
checked, so a declaration deciding many runs holds all of them at once
(the earlier `E322`, one declaration for 32 runs of a 22-letter semantic
window, took about 11 GB).  Here each Boolean case is one declaration, and
`Elab.async` is off so that the declarations are checked one at a time.
"""
import itertools, pathlib

OUT = pathlib.Path(__file__).resolve().parents[3] / "Sec8/D/N13/E322.lean"

def b(v): return "true" if v else "false"
def tag(vs): return "".join("t" if v else "f" for v in vs)

HEAD = '''/-
Copyright (c) 2026 QCert contributors. All rights reserved.

The conjugated local rotations of (322), (323) commute with a box whose
control on wire 2 has the opposite colour. Expanding the box on wire 4
leaves four-wire rotations handled by (267), (268), and an inner box.
The inner box is idle on wire 4, so its commutation follows directly from
the smaller-width completeness hypothesis.

Memory: every decided run is its own declaration and `Elab.async` is off,
so the kernel checks one run at a time (generated by
`gen/sec8/n13/split_e322.py`).  One run of a 22-letter semantic window on
four wires costs about 0.7 GB in the kernel; the earlier version, one
declaration for all 32 runs, needed about 11 GB.
-/
import QCert.RealCliffordCH.Sec8.D.N13.E322a

set_option Elab.async false

namespace QCert.RealCliffordCH.Sec8.D.N13
open Circuit Eng SE Net N8

def W322 (one a α β : Bool) : List Lt := if one then W1 a α β else W0 a α β
def B322 (γ : Bool) : Lt := .g .box [0] [(1, γ), (2, false), (4, true)] true
def I322 (γ : Bool) : Lt := .g .box [0] [(1, γ), (2, false)] true
def P322 (γ : Bool) : List Lt :=
  [Qa true γ, Qb γ true, I322 γ, Qb (!γ) true, Qa false γ,
    Qb γ true, I322 γ, Qb (!γ) true]

def T322 (one a α β γ : Bool) : SE.Tbl :=
  [([B322 γ], P322 γ),
   (W322 one a α β ++ [Qa true γ], [Qa true γ] ++ W322 one a α β),
   (W322 one a α β ++ [Qb γ true], [Qb γ true] ++ W322 one a α β),
   (W322 one a α β ++ [I322 γ], [I322 γ] ++ W322 one a α β),
   (W322 one a α β ++ [Qb (!γ) true], [Qb (!γ) true] ++ W322 one a α β),
   (W322 one a α β ++ [Qa false γ], [Qa false γ] ++ W322 one a α β)]

def run322 : List St :=
  [.rw 21 0 false, .rw 0 1 false, .rw 1 2 false, .rw 2 3 false,
   .rw 3 4 false, .rw 4 5 false, .rw 5 2 false, .rw 6 3 false,
   .rw 7 4 false, .rw 0 0 true]
'''

def exp_stmt(g):
    return f"check 4 [] [B322 {g}] (P322 {g}) [.sem 0 1 (P322 {g}) 3] = true"

def inner_stmt(one, a, al, be, g):
    w = f"W322 {one} {a} {al} {be}"
    return (f"check 4 [] ({w} ++ [I322 {g}]) ([I322 {g}] ++ {w})\n"
            f"      [.sem 0 22 ([I322 {g}] ++ {w}) 4] = true")

def run_stmt(one, a, al, be, g):
    w = f"W322 {one} {a} {al} {be}"
    return (f"check 4 (T322 {one} {a} {al} {be} {g}) ({w} ++ [B322 {g}])\n"
            f"      ([B322 {g}] ++ {w}) run322 = true")

out = [HEAD]
out.append("/-! ## The expansion of the box on wire `4` -/\n")
for g in (False, True):
    out.append(f"theorem chk_exp322_{tag([g])} : {exp_stmt(b(g))} := by\n  decide +kernel\n")
out.append("theorem chk_exp322 : ∀ γ : Bool,\n    " + exp_stmt("γ") + " := by\n"
           "  intro γ; cases γ\n  · exact chk_exp322_f\n  · exact chk_exp322_t\n")

cases5 = list(itertools.product((False, True), repeat=5))
for name, stmt in (("chk_inner322", inner_stmt), ("chk322", run_stmt)):
    sec = "the inner box, idle on wire `4`" if name == "chk_inner322" else "the run"
    out.append(f"/-! ## {sec[0].upper() + sec[1:]}, one Boolean case at a time -/\n")
    for vs in cases5:
        out.append(f"theorem {name}_{tag(vs)} :\n    {stmt(*map(b, vs))} := by\n  decide +kernel\n")
    out.append(f"theorem {name} : ∀ one a α β γ : Bool,\n    {stmt('one', 'a', 'α', 'β', 'γ')} := by\n"
               "  intro one a α β γ\n"
               "  cases one <;> cases a <;> cases α <;> cases β <;> cases γ\n"
               "  exacts [" + ",\n    ".join(f"{name}_{tag(vs)}" for vs in cases5) + "]\n")

out.append('''theorem T322_ok (m : ℕ) (ih : IH (m + 5)) (one a α β γ : Bool) :
    AllD 5 m (T322 one a α β γ) := by
  intro e he
  simp only [T322, List.mem_cons, List.mem_nil_iff, or_false] at he
  rcases he with rfl | rfl | rfl | rfl | rfl | rfl
  · exact check_sound (frame 4) ih (allD_nil 5 m) (chk_exp322 γ)
  · cases one
    · exact e268 m ih a α true β γ
    · exact e267s m ih a α true β γ
  · cases one
    · exact e267 m ih a α γ β true
    · exact e268s m ih a α γ β true
  · exact check_sound (frame 4) ih (allD_nil 5 m) (chk_inner322 one a α β γ)
  · cases one
    · exact e267 m ih a α (!γ) β true
    · exact e268s m ih a α (!γ) β true
  · cases one
    · exact e268 m ih a α false β γ
    · exact e267s m ih a α false β γ

theorem r322 (m : ℕ) (ih : IH (m + 5)) (one a α β γ : Bool) :
    Derivable (theory (m + 5)) (wc 5 (m + 5) (W322 one a α β ++ [B322 γ]))
      (wc 5 (m + 5) ([B322 γ] ++ W322 one a α β)) :=
  check_sound (frame 4) ih (T322_ok m ih one a α β γ) (chk322 one a α β γ)

end QCert.RealCliffordCH.Sec8.D.N13
''')
OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
print("wrote", OUT)
