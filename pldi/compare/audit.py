def main():
    per = split()
    shared = {t: show('shared: ' + t, audit(spec)) for t, spec in SHARED}
    for row, spec in ROWS.items():
        per[row]['audit'] = show(row, audit(spec))
    own = sum(d['audit'] for d in per.values())
    tot = {k: sum(d[k] for d in per.values()) for k in ('files', 'code', 'written', 'generated', 'ported')}
    sh = sum(shared.values())
    print(f"{'row':18}{'files':>6}{'code':>8}{'written':>9}{'generated':>10}{'ported':>8}{'audit':>7}")
    for r, d in per.items():
        print(f"{r:18}{d['files']:6}{d['code']:8}{d['written']:9}{d['generated']:10}{d['ported']:8}{d['audit']:7}")
    print(f"{'sixteen rows':18}{tot['files']:6}{tot['code']:8}{tot['written']:9}{tot['generated']:10}{tot['ported']:8}{own:7}")
    print(f"shared {sh}; audit set {own + sh}, {100 * (own + sh) / tot['code']:.1f}% of {tot['code']}")
    if len(sys.argv) > 2:
        json.dump(dict(rows=per, shared=shared, total=dict(tot, audit_rows=own, audit_shared=sh,
                                                           audit=own + sh)),
                  open(sys.argv[2], 'w'), indent=1)

main()
