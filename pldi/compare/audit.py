"""The audit set of each row of Table 1, and the split of its code lines.

The audit set of a row is what a reader must read to know what the row's
main theorem says: the statement (its MainTheorem module) and the
definitions the statement mentions -- the relations, the gates or
generators, the target group, the semantics down to the value of each
generator.  It was chosen by reading (the dictionaries SHARED and ROWS
below); this script only counts.  An entry is (path, 'ALL') or
(path, [names or (first, last) line ranges]); a name selects the
declaration block of that name.  Where a module was not cut down it is
counted whole, so the counts lean high.  The qudit Clifford row is the
least precise: the modules that define its model are counted whole, and
the generic constructions that the definition of its target group goes
through (cocycles, central extensions, cyclic groups) are not counted.

The second part classifies every tracked Agda file of a row as written,
generated or ported, by loc.py's rule (`kind`, copied here), and sums
loc.py's code lines (`count`, copied here).

Usage, from this folder:  python3 audit.py ../.. audit.json
"""
