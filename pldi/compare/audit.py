def read(path):
    return open(os.path.join(ROOT, path), encoding='utf-8', errors='replace').read()

def kind(path, text):
    lines = text.split('\n')
    head = '\n'.join(lines[:40])
    longb = sum(len(l) for l in lines if len(l) > 200)
    if WRITTEN_PATHS.search(path):
        return 'written'
    if PORT.search(head):
        return 'ported'
    if GEN.search(head) or longb > 0.4 * max(1, len(text)) or GEN_PATHS.search(path):
        return 'generated'
    return 'written'

def count(text):
    lines = text.split('\n')
    if lines and lines[-1] == '':
        lines.pop()
    depth = 0; code = 0
    for ln in lines:
        s = ln.strip()
        if not s and depth == 0:
            continue
        has_code = False; i = 0
        while i < len(s):
            if depth > 0:
                if s.startswith('{-', i): depth += 1; i += 2
                elif s.startswith('-}', i): depth -= 1; i += 2
                else: i += 1
                continue
            if s.startswith('--', i): break
            if s.startswith('{-', i): depth += 1; i += 2; continue
            if not s[i].isspace(): has_code = True
            i += 1
        if has_code: code += 1
    return code

def split():
    per = {}
    for row, paths in AGDA.items():
        c = collections.Counter(); n = 0
        for f in TRACKED:
            if f.endswith('.agda') and any(f.startswith(p + '/') for p in paths):
                text = read(f)
                c[kind(f, text)] += count(text); n += 1
        per[row] = dict(files=n, code=sum(c.values()),
                        **{k: c[k] for k in ('written', 'generated', 'ported')})
    return per

# ------------------------------------------------------- declaration blocks

def ind(l):
    return len(l) - len(l.lstrip())

def find(lines, name):
    pats = [name + ' :', 'data ' + name + ' ', 'record ' + name + ' ', 'pattern ' + name + ' ',
            'module ' + name + ' ', 'data ' + name + ':', 'syntax ' + name + ' ']
    for i, l in enumerate(lines):
        s = l.strip()
        if any(s.startswith(p) or s == p.strip() for p in pats):
            return i
    return None

def block(lines, name):
    """The declaration of `name`: from its signature line to the line before
    the next blank line that is followed by a line indented no deeper."""
    i = find(lines, name)
    if i is None:
        return None
    k = ind(lines[i]); j = i + 1; last = i
    while j < len(lines):
        if lines[j].strip() == '':
            m = j
            while m < len(lines) and lines[m].strip() == '': m += 1
            if m >= len(lines) or ind(lines[m]) <= k: break
            j = m; continue
        last = j; j += 1
    return i + 1, last + 1

def audit(spec):
    out = []
    for path, names in spec:
        lines = read(path).replace('\r\n', '\n').split('\n')
        full = count('\n'.join(lines))
        if names == 'ALL':
            out.append((path, full, full, 'all')); continue
        covered = set()
        for nm in names:
            r = nm if isinstance(nm, tuple) else block(lines, nm)
            if r is None:
                sys.exit(f'{path}: no declaration of {nm}')
            covered.update(range(r[0], r[1] + 1))
        rs = []; cur = None
        for i in sorted(covered):
            if cur and i == cur[1] + 1: cur[1] = i
            else:
                cur = [i, i]; rs.append(cur)
        n = sum(count('\n'.join(lines[a - 1:b])) for a, b in rs)
        out.append((path, n, full, ','.join(f'{a}-{b}' for a, b in rs)))
    return out

def show(title, rows):
    print('##', title)
    t = 0
    for p, n, full, r in rows:
        print(f'{n:6d} / {full:6d}  {p}  [{r}]'); t += n
    print(f'{t:6d}  total\n')
    return t

