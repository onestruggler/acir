"""Write figures/compare.tex, the pgfplots figure comparing the Agda and
Lean formalizations: (a) code lines and (b) check times, from
figdata.json, and (c) execution times, from exec.json (runbench.py).

Usage: python mkfig.py OUT.tex
"""
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'figdata.json')))
rows = d['rows']  # (i, key, label, agda code, lean code, at, lt, af, lf)
N = len(rows)

def k(x):
    return f'{x / 1000:.2f}'.rstrip('0').rstrip('.')

def coords(col, sel=None):
    return ' '.join(f'({k(r[col])},{r[0]})' for r in rows if sel is None or sel(r))

labels = ','.join('{' + r[2] + '}' for r in rows)
timed = [r for r in rows if r[5] is not None]
# Direct labels on the qudit Clifford row, where Agda is right of Lean.
LAB = next(r for r in rows if r[1] == 'QuditClifford')

out = r"""%% Generated by pldi/compare/mkfig.py from the measurements of
%% pldi/compare/ (code lines: loc.py, and th4.py for the Toffoli--Hadamard
%% row; check times: Table 1).
\begin{tikzpicture}
\begin{groupplot}[
  group style={group size=2 by 1, horizontal sep=18pt,
               yticklabels at=edge left},
  width=0.40\linewidth, height=9.2cm, scale only axis=false,
  y dir=reverse, ymin=-0.7, ymax=%(ymax)s,
  ytick={0,...,%(last)d}, yticklabels={%(labels)s},
  y tick label style={font=\scriptsize},
  x tick label style={font=\scriptsize},
  xlabel style={font=\footnotesize},
  title style={font=\footnotesize\bfseries, yshift=-2pt},
  tick align=outside, tick pos=lower,
  axis line style={cmpAxis}, major tick style={cmpAxis},
  xmajorgrids, grid style={cmpGrid},
  clip=false,
]
%% (a) Proof development: code lines.
\nextgroupplot[
  title={(a) Proof development},
  xbar, bar width=3.1pt,
  xmin=0, xmax=150, xtick={0,25,...,125},
  xlabel={Code lines (thousands)},
  legend to name=cmpLegend, legend columns=2,
  legend style={font=\scriptsize, draw=none, column sep=6pt},
  legend image code/.code={\draw[#1] (0pt,-2.5pt) rectangle (9pt,2.5pt);},
]
\addplot[bar shift=1.9pt, fill=cmpAgda, draw=cmpAgda] coordinates {%(ac)s};
\addlegendentry{Agda}
\addplot[bar shift=-1.9pt, fill=cmpLean, draw=cmpLean] coordinates {%(lc)s};
\addlegendentry{Lean}
\draw[cmpAxis, densely dotted] (axis cs:0,%(sep)s) -- (axis cs:150,%(sep)s);
%% (b) Verification time: check time per row, log scale.
\nextgroupplot[
  title={(b) Verification time},
  xmode=log, xmin=10, xmax=20000, log basis x=10,
  xlabel={Check time (s), log scale},
]
%(links)s
\addplot[only marks, mark=*, mark size=1.9pt, color=cmpAgda]
  coordinates {%(at)s};
\addplot[only marks, mark=square*, mark size=1.7pt, color=cmpLean]
  coordinates {%(lt)s};
\node[font=\scriptsize, text=black!75, anchor=west, xshift=3pt]
  at (axis cs:%(a0)s,%(lab)s) {Agda};
\node[font=\scriptsize, text=black!75, anchor=east, xshift=-3pt]
  at (axis cs:%(l0)s,%(lab)s) {Lean};
\end{groupplot}
\node[anchor=north] at ($(group c1r1.south east)!0.5!(group c2r1.south west) + (0,-28pt)$)
  {\pgfplotslegendfromname{cmpLegend}};
\end{tikzpicture}
""" % dict(
    ymax=f'{N - 1 + 0.7}', last=N - 1, labels=labels,
    ac=coords(3), lc=coords(4),
    sep=f'{N - 1.5}',
    links='\n'.join(
        f'\\addplot[cmpLink, forget plot] coordinates {{({r[5]},{r[0]}) ({r[6]},{r[0]})}};'
        for r in timed),
    at=' '.join(f'({r[5]},{r[0]})' for r in timed),
    lt=' '.join(f'({r[6]},{r[0]})' for r in timed),
    a0=LAB[5], l0=LAB[6], lab=LAB[0],
)

# (c) Execution time: milliseconds per decision against the number of
# wires, log scale; a direct label at the end of each line.
ex = json.load(open(os.path.join(here, 'exec.json')))
series = {s: sorted((r['n'], r['ms_per_decision']) for r in ex['results'] if r['system'] == s)
          for s in ('agda', 'lean')}
nmin = min(n for s in series.values() for n, _ in s)
nmax = max(n for s in series.values() for n, _ in s)

def pts(s):
    return ' '.join(f'({n},{t:g})' for n, t in series[s])

out += r"""
\par\medskip
\begin{tikzpicture}
\begin{axis}[
  title={(c) Execution time},
  title style={font=\footnotesize\bfseries, yshift=-2pt},
  width=0.62\linewidth, height=5.2cm,
  xmin=%(x0)s, xmax=%(x1)s, xtick={%(nmin)d,...,%(nmax)d},
  ymode=log, log basis y=10, ymin=1, ymax=100000,
  xlabel={Qubits}, ylabel={Time per decision (ms), log scale},
  xlabel style={font=\footnotesize}, ylabel style={font=\footnotesize},
  tick label style={font=\scriptsize},
  tick align=outside, tick pos=lower,
  axis line style={cmpAxis}, major tick style={cmpAxis},
  ymajorgrids, grid style={cmpGrid}, clip=false,
]
\addplot[color=cmpAgda, line width=1pt, mark=*, mark size=1.9pt]
  coordinates {%(ag)s};
\addplot[color=cmpLean, line width=1pt, mark=square*, mark size=1.7pt]
  coordinates {%(le)s};
\node[font=\scriptsize, text=black!75, anchor=west, xshift=4pt]
  at (axis cs:%(an)s,%(at)g) {Agda};
\node[font=\scriptsize, text=black!75, anchor=west, xshift=4pt]
  at (axis cs:%(ln)s,%(lt)g) {Lean};
\end{axis}
\end{tikzpicture}
""" % dict(x0=nmin - 0.3, x1=nmax + 0.3, nmin=nmin, nmax=nmax,
           ag=pts('agda'), le=pts('lean'),
           an=series['agda'][-1][0], at=series['agda'][-1][1],
           ln=series['lean'][-1][0], lt=series['lean'][-1][1])
open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write(out)
print('wrote', sys.argv[1])
