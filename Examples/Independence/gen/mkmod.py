"""Write an Agda module from the derivations of a spec file:

    python3 mkmod.py appendixA Examples.Independence.Clifford.AppendixA \
        'Appendix A of the paper: auxiliary derivations for Cliff₂' \
        ../Clifford/AppendixA.agda [imported modules ...]

The spec sets up its fragment (cliff.py, rcliff.py, ...), which names
the Agda modules the derivations open (frag.MODULES)."""
import sys, importlib
spec, module, title, path = sys.argv[1:5]
imports = sys.argv[5:]
mod = importlib.import_module(spec)
from frag import OUT, emit, MODULES
head = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- %s
--
-- Generated by Examples/Independence/gen (python3 mkmod.py %s ...):
-- each derivation is a chain of the paper's, its steps found by a
-- breadth-first search over single rewrites up to commuting letters
-- (circ.py), and checked here by the engine (%s).
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module %s where

open import Data.List.Base using ([] ; _∷_)
open import Data.Nat.Base using (ℕ)
open import Relation.Binary.PropositionalEquality using (refl)

open import Notations using (₁₊ ; ₂₊ ; ₃₊)

open import %s using (_↥)
open import %s
%s
private
  variable
    n : ℕ
''' % (title, spec, MODULES['kitname'], module, MODULES['syntax'], MODULES['kit'],
       ''.join('open import %s\n' % m for m in imports))
with open(path, 'w', encoding='utf-8') as f:
    f.write(head)
    for d in OUT:
        f.write('\n' + emit(d) + '\n')
print(len(OUT), 'derivations')
