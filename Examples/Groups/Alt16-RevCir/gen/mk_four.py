"""Compile the four-wire derivations and write them as Agda.

    python capped.py 1500 600 mk_four.py [check]

Order: rule (7) in the spelling of placed gates; a representative of
every other orbit of pair lemmas (search/boot.json); the relators of
search/macro_*.json.  `check` compiles and replays without writing.
"""
import glob
import io
import json
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import four as F           # noqa: E402
from four import M, P, Proof, LIB, HS, Bot, spw  # noqa: E402

SEARCH = os.path.join(HERE, 'search')


def rule7():
    """(T c)^2 -> Q for T = 23>1, c = 1>0, Q = 23>0: rule (7)."""
    T = M.gate(1, (2, 1), (3, 1))
    c = M.gate(0, (1, 1))
    Q = M.gate(0, (2, 1), (3, 1))
    assert (F.sp(T), F.sp(c), F.sp(Q)) == ('stuTuts', 'c', 'tuTut')
    pr = Proof('stuTuts')
    pr.rw(3, F.NAT)
    pr.rw(0, HS('stuuts', ''))
    ut = LIB.add('R', pr, 'U', 'CCX one wire up in its frame')
    pr = Proof(spw([T, c, T, c]))
    pr.rw(0, ut)
    pr.rw(2, ut)
    pr.rw(0, F.R7)
    pr.rw(3, Bot('cc', ''))
    pr.rw(1, ut.sym())
    pr.rw(0, HS('sstu', 'tu'))
    pr.rw(3, HS('utss', 'ut'))
    eq = LIB.add('R', pr, F.sp(Q), 'rule (7): (23>1 1>0)^2 = 23>0')
    F.add_base(T, c, eq)


def pair_orbits():
    boot = json.load(open(os.path.join(SEARCH, 'boot.json')))
    for name, d in boot['derived'].items():
        g, h = d['key']
        rel = d['relator']
        pr = F.compile_macro(rel, d['steps'])
        releq = LIB.add('Q', pr, '', 'relator of the pair ' + name)
        l, r = F.pair_word(g, h)
        assert rel == l + r
        if r:
            pr = Proof(spw(l))
            pr.rw(len(pr.cur), F.inv(r[0]).sym())
            pr.rw(0, releq)
            eq = LIB.add('P', pr, spw(r), 'pair ' + name)
        else:
            eq = releq
        F.add_base(g, h, eq)
        print('pair %-20s macro steps %3d   lemmas %4d  steps %6d' % (
            name, len(d['steps']), len(LIB.lemmas), LIB.steps()), flush=True)


RELATORS = {}
INST = {}
GATE = {}


def relators():
    for f in sorted(glob.glob(os.path.join(SEARCH, 'macro_*.json'))):
        d = json.load(open(f))
        if not d.get('found'):
            continue
        nm = d['name']
        pr = F.compile_macro(d['relator'], d['steps'])
        RELATORS[nm] = (d, LIB.add('Z', pr, '', 'relator ' + nm))
        print('%-18s macro steps %3d   lemmas %4d  steps %6d' % (
            nm, len(d['steps']), len(LIB.lemmas), LIB.steps()), flush=True)


HEADER = """------------------------------------------------------------------------
-- Presentations of groups
--
-- Four wires: derivations from the rules (1)–(7), part %(k)d of %(n)d
--
-- GENERATED by gen/mk_four.py from the macro derivations of gen/search;
-- do not edit.  Each lemma is an equation between letter lists
-- (Letters) with the steps that derive it: a three-wire step on the
-- bottom (bo) or the top (to) three wires, a step between words in the
-- NOT gates and swaps (hs), a change of frame (fr), or a rule of
-- FourWire or an earlier lemma (rw, backwards rwˢ).  The comment says
-- what a lemma is about, in the notation of gen/search: 12>0 is the
-- Toffoli gate with controls 1 2 and target 0, ~1 a white control.
------------------------------------------------------------------------

{-# OPTIONS --cubical-compatible --safe #-}

module Examples.Groups.Alt16-RevCir.Four.Part%(k)d where

open import Data.List.Base using ([] ; _∷_)
open import Relation.Binary.PropositionalEquality using (refl)

open import Examples.Groups.Alt16-RevCir.FourWire
  using ( Eqn ; rw ; r7⁼ ; nat-ccx⁼
        ; comm-x3-x0 ; comm-cx2-x0 ; comm-ex2-x0 ; comm-ccx1-x0
        ; comm-x3-cx0 ; comm-cx2-cx0 ; comm-ex2-cx0
        ; comm-x3-ex0 ; comm-cx2-ex0 ; comm-ex2-ex0 ; comm-x3-ccx0 )
open import Examples.Groups.Alt16-RevCir.Letters
  using (bo ; to ; hs ; fr ; rwˢ ; deriveℓ)
%(prev)s"""


NL = chr(10)


def emit(lem):
    name, lhs, rhs, steps, comment = lem
    out = ['']
    if comment:
        out.append('-- ' + comment)
    out.append('%s : Eqn 4' % name)
    out.append('%s = deriveℓ "%s" "%s"' % (name, lhs, rhs))
    for k, (i, eq) in enumerate(steps):
        out.append('  %s %s' % ('(' if k == 0 else '∷', eq.agda(i)))
    out.append('  ∷ [])')
    out.append('  refl')
    return out


def write(per_part=1200):
    parts = [[]]
    n = 0
    for lem in LIB.lemmas:
        if n and n + len(lem[3]) > per_part:
            parts.append([])
            n = 0
        parts[-1].append(lem)
        n += len(lem[3])
    d = os.path.join(HERE, '..', 'Four')
    os.makedirs(d, exist_ok=True)
    for old in glob.glob(os.path.join(d, 'Part*.agda')):
        os.remove(old)
    for k, lems in enumerate(parts, 1):
        prev = '' if k == 1 else (
            'open import Examples.Groups.Alt16-RevCir.Four.Part%d public%s'
            % (k - 1, NL))
        text = HEADER % {'k': k, 'n': len(parts), 'prev': prev}
        body = []
        for lem in lems:
            body.extend(emit(lem))
        with io.open(os.path.join(d, 'Part%d.agda' % k), 'w', encoding='utf-8',
                     newline=NL) as fh:
            fh.write(text + NL.join(body) + NL)
        print('Part%d: %d lemmas, %d steps' % (k, len(lems), sum(len(l[3]) for l in lems)))
    return len(parts)


def main():
    rule7()
    pair_orbits()
    relators()
    print('lemmas: %d, steps: %d' % (len(LIB.lemmas), LIB.steps()))
    import inst
    INST.update(inst.all_instances(RELATORS))
    print('with the %d instances: lemmas: %d, steps: %d' % (
        len(INST), len(LIB.lemmas), LIB.steps()))
    import gatesc
    GATE.update(gatesc.gate_lemmas())
    for nm, (lem, word) in GATE.items():
        print('gate %-5s %3d cycles' % (nm, len(word)))
    print('with the gates: lemmas: %d, steps: %d' % (len(LIB.lemmas), LIB.steps()))
    if 'check' not in sys.argv[1:]:
        last = write()
        import mk_rel
        mk_rel.write(INST, GATE, last)


if __name__ == '__main__':
    main()
