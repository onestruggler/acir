HEADER = """------------------------------------------------------------------------
-- Presentations of groups
--
-- The derivations, from the rules on {K} wires, that the
-- Reidemeister–Schreier step from Symmetric's presentation needs
--
-- GENERATED by gen/mk_narrow.py from gen/narrow{K}.json, which
-- gen/narrow.py finds by a proof-producing Knuth–Bendix completion of
-- the rules.  Θ d is the edge Toffoli of the states d and d + 1 along
-- the Gray code, the circuit of their transposition.  The equations
-- order0, …, braid0, … and far0-2, … are the Coxeter relations
-- between the Θ d, and gate-… says which word in the Θ d a gate on
-- its own wires is.  Each is a run of the engine: every step rewrites by an axiom
-- ax-… (a rule of Theory, a law of the swap or a structural rule, at
-- this width) or by a rule R… of the completion, itself derived from
-- earlier ones.  order, braid and far collect them by index, under
-- guards that compute.
------------------------------------------------------------------------

{{-# OPTIONS --cubical-compatible --safe #-}}

module Examples.Groups.Alt16-RevCir.Width{K}.Derivations where

open import Data.Bool.Base using (T)
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (ℕ ; suc ; _+_ ; _≤ᵇ_)
open import Relation.Binary.PropositionalEquality using (refl)
open import Word.Base using (ε ; _•_)

import Presentation.Base as PB

open import Examples.Groups.Alt16-RevCir.Syntactics
  using ( Gen ; Circuit ; X-gate ; CX-gate ; Ex-gate ; CCX-gate
        ; gate₁ ; gate₂ ; gate₃ ; _↥ ; σ-inv ; σ-nat₁ ; σ-nat₂ )
open import Examples.Groups.Alt16-RevCir.Theory
  using (_TRel,_===_ ; r1 ; r2 ; r3 ; r4 ; r5 ; r6 ; module T)

open import Examples.Groups.Alt16-RevCir.Engine _TRel,_===_ public
  using (Eqn ; ⟪_⟫ ; eqn→)
open import Examples.Groups.Alt16-RevCir.Engine _TRel,_===_
  using (eqnʷ ; sym⁼ ; rw ; derive)

------------------------------------------------------------------------
-- Letters

{LETTERS}
"""


def agda_name(name):
    return name.replace('^', '↑').replace('_', '-')


def lst(word):
    if not word:
        return '[]'
    return '(' + ' ∷ '.join(LETTER[x] for x in word) + ' ∷ [])'


def wrap(prefix, items, sep, close, width=78):
    """prefix item sep item ... close, broken at width."""
    lines, cur = [], prefix
    for i, it in enumerate(items):
        piece = it + (sep if i + 1 < len(items) else close)
        if len(cur) + len(piece) > width and cur.strip():
            lines.append(cur.rstrip())
            cur = '     ' + piece
        else:
            cur += piece
    lines.append(cur.rstrip())
    return '\n'.join(lines)


def replay(chain, sides):
    """Run a chain as the engine does; sides(rule) = (lhs, rhs)."""
    word = chain[0][0]
    for new, (rule, pos, fwd) in chain[1:]:
        l, r = sides(rule)
        if not fwd:
            l, r = r, l
        assert word[pos:pos + len(l)] == l, (word, rule, pos, fwd)
        word = word[:pos] + r + word[pos + len(l):]
        assert word == new, (word, new)
    return word


def steps(chain):
    out = []
    for _, (rule, pos, fwd) in chain[1:]:
        e = 'R%d' % rule if fwd else '(sym⁼ R%d)' % rule
        out.append('rw %d %s' % (pos, e))
    return out


def derive(name, l, r, chain):
    body = ['%s : Eqn K' % name,
            '%s = derive %s' % (name, lst(l)),
            '  %s' % lst(r)]
    st = steps(chain)
    if st:
        body.append(wrap('  (', st, ' ∷ ', ' ∷ [])'))
    else:
        body.append('  []')
    body.append('  refl')
    return '\n'.join(body)


def main():
    k = int(sys.argv[1])
    data = json.load(open(os.path.join(HERE, 'narrow%d.json' % k)))
    rules = {x['id']: x for x in data['rules']}
    axioms = {name: (l, r) for name, l, r in data['axioms']}
    theta = data['theta']
    n = len(theta)

    def sides(i):
        return rules[i]['lhs'], rules[i]['rhs']

    out = [HEADER.format(K=k, LETTERS=LETTERS[k])]

    # axioms
    out.append('-' * 72)
    out.append('-- The rules at this width\n')
    used = sorted({x['axiom'][0] for x in data['rules'] if x['axiom']},
                  key=lambda nm: [a for a, _, _ in data['axioms']].index(nm))
    for name in used:
        l, r = axioms[name]
        an = 'ax-' + agda_name(name)
        out.append('%s : Eqn K' % an)
        out.append('%s = eqnʷ %s %s\n  (%s)\n  refl refl\n' % (
            an, lst(l), lst(r), AXIOM[k][name]))

    # rules of the completion
    out.append('-' * 72)
    out.append('-- The rules of the completion that the derivations use\n')
    for i in sorted(rules):
        x = rules[i]
        if x['axiom']:
            name, fwd = x['axiom']
            l, r = axioms[name]
            if not fwd:
                l, r = r, l
            assert (l, r) == (x['lhs'], x['rhs']), i
            an = 'ax-' + agda_name(name)
            out.append('R%d : Eqn K' % i)
            out.append('R%d = %s\n' % (i, an if fwd else 'sym⁼ ' + an))
        else:
            ch = x['chain']
            assert ch[0][0] == x['lhs']
            assert replay(ch, sides) == x['rhs'], i
            assert all(st[0] < i for _, st in ch[1:]), i
            out.append(derive('R%d' % i, x['lhs'], x['rhs'], ch) + '\n')

    # the edge Toffolis
    out.append('-' * 72)
    out.append('-- The edge Toffolis along the Gray code\n')
    out.append('θ : ℕ → List (Gen K)')
    for d, w in enumerate(theta):
        out.append('θ %d = %s' % (d, lst(w).strip('()')))
    out.append('θ _ = []\n')
    out.append('Θ : ℕ → Circuit K')
    out.append('Θ d = ⟪ θ d ⟫\n')

    # targets
    out.append('-' * 72)
    out.append('-- The Coxeter relations and the gates\n')
    for t in data['targets']:
        ch = t['chain']
        assert ch is not None, t['name']
        assert ch[0][0] == t['lhs'] and replay(ch, sides) == t['rhs']
        out.append(derive(agda_name(t['name']), t['lhs'], t['rhs'], ch)
                   + '\n')

    # dispatch
    N = n + 1

    def suc(m, v):
        s = v
        for _ in range(m):
            s = '(suc %s)' % s
        return s

    out.append('-' * 72)
    out.append('-- By index\n')
    out.append('order : ∀ d → T (2 + d ≤ᵇ %d) → K T.⊢ Θ d • Θ d ≈ ε' % N)
    for d in range(n):
        out.append('order %d _ = eqn→ order%d refl refl' % (d, d))
    out.append('order %s ()\n' % suc(n, 'd'))
    out.append('braid : ∀ d → T (3 + d ≤ᵇ %d) →' % N)
    out.append('        K T.⊢ Θ d • Θ (suc d) • Θ d ≈ '
               'Θ (suc d) • Θ d • Θ (suc d)')
    for d in range(n - 1):
        out.append('braid %d _ = eqn→ braid%d refl refl' % (d, d))
    out.append('braid %s ()\n' % suc(n - 1, 'd'))
    out.append('far : ∀ d e → T (2 + d ≤ᵇ e) → T (2 + e ≤ᵇ %d) →' % N)
    out.append('      K T.⊢ Θ e • Θ d ≈ Θ d • Θ e')
    for d in range(max(n - 2, 0)):
        for e in range(n):
            if e >= d + 2:
                out.append('far %d %d _ _ = eqn→ far%d-%d refl refl'
                           % (d, e, d, e))
            else:
                out.append('far %d %d () _' % (d, e))
        out.append('far %d %s _ ()' % (d, suc(n, 'e')))
    for e in range(n):
        out.append('far %s %d () _' % (suc(max(n - 2, 0), 'd'), e))
    out.append('far %s %s _ ()' % (suc(max(n - 2, 0), 'd'), suc(n, 'e')))

    text = '\n'.join(out).replace('Eqn K', 'Eqn %d' % k) \
        .replace('Gen K', 'Gen %d' % k).replace('Circuit K', 'Circuit %d' % k) \
        .replace('K T.⊢', '%d T.⊢' % k) + '\n'
    path = os.path.join(ROOT, 'Width%d' % k)
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, 'Derivations.agda'), 'w',
              encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote Width%d/Derivations.agda: %d axioms, %d rules, %d targets, '
          '%d lines' % (k, len(used), len(rules), len(data['targets']),
                        text.count('\n')))


if __name__ == '__main__':
    main()
