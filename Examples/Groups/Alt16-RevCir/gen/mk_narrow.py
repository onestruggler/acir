"""Write Width2/Derivations.agda and Width3/Derivations.agda from the
derivations that narrow.py found (narrow2.json, narrow3.json).

    python mk_narrow.py 2
    python mk_narrow.py 3

Every chain is replayed here as the engine will run it (the step at a
position must find the left side of its equation there) before anything is
written.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

LETTER = {'a': 'x0', 'b': 'x1', 'd': 'x2', 'c': 'cx0', 'e': 'cx1',
          's': 'ex0', 't': 'ex1', 'T': 'ccx'}

