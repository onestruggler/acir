"""Four/Relations.agda: the relations of Syntactics as statements about
its words, from the lemmas of Four/Part*.

For each family a function of the indices, guarded by a boolean so that
the indices out of range are absurd; for each gate on its own wires the
word in Lafont's cycles that its lemma reaches, and the statement that
the gate is the circuit of that word.
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NL = chr(10)
SUB = '₀₁₂₃₄₅₆₇₈₉'


def sub(k):
    return ''.join(SUB[int(c)] for c in str(k))


def sucs(k, v):
    """The pattern suc (suc (... v)) with k sucs, parenthesised."""
    if k == 0:
        return v
    return '(' + 'suc (' * (k - 1) + 'suc ' + v + ')' * (k - 1) + ')'


HEADER = """------------------------------------------------------------------------
-- Presentations of groups
--
-- Four wires: the relations of Syntactics, from the rules (1)–(7)
--
-- GENERATED by gen/mk_four.py; do not edit.  The lemmas of Four.Part*
-- are equations between letter lists; here they are read as equations
-- between the words of Syntactics: the relations between the cycles
-- (orderᵀ, nearᵀ, farᵀ, apartᵀ: 14, 13, 12 and 66 instances, each
-- transported from one of 24 shapes by a symmetry of the cube), and
-- each gate on its own wires as the circuit of a word in Lafont's
-- cycles (gate-Xᵀ, …).  The words are Translation's for X, CX, CCX and
-- the bottom swap; for the other two swaps they are longer, and
-- Equivalence carries them to Translation's by Lafont's completeness.
-- An index out of range makes the guard false.
------------------------------------------------------------------------

{-# OPTIONS --cubical-compatible --safe #-}

module Examples.Groups.Alt16-RevCir.Four.Relations where

open import Data.Bool.Base using (_∧_) renaming (T to True)
open import Data.Nat.Base using (ℕ ; suc ; _+_ ; _≤ᵇ_)
open import Relation.Binary.PropositionalEquality using (refl)
open import Word.Base using (ε ; _•_ ; _ʷ)

import Examples.Groups.Alternating.Syntactics as L

open import Examples.Groups.Alt16-RevCir.Syntactics
  using (Ω ; X₀ ; CX ; CCX ; Ex₀ ; Ex₁ ; Ex₂)
open import Examples.Groups.Alt16-RevCir.Translation
  using ( g ; ω₀ ; ω₁ ; ω₂ ; ω₃ ; ω₄ ; ω₅ ; ω₆ ; ω₇ ; ω₈ ; ω₉ ; ω₁₀ ; ω₁₁
        ; ω₁₂ ; ω₁₃ )
open import Examples.Groups.Alt16-RevCir.Theory using (module T)
open import Examples.Groups.Alt16-RevCir.FourWire using (eqn→)
open import Examples.Groups.Alt16-RevCir.Four.Part%(last)d
"""


def lafont_word(word):
    lines = []
    cur = ' '
    for k, i in enumerate(word):
        item = ' ω' + sub(i) + (' •' if k + 1 < len(word) else '')
        if len(cur) + len(item) > 70:
            lines.append(cur)
            cur = ' '
        cur += item
    lines.append(cur)
    return lines


def write(inst, gate, last):
    out = [HEADER % {'last': last}]

    def sect(title):
        out.append('-' * 72)
        out.append('-- ' + title)
        out.append('')

    sect('The cycles have order three')
    out.append('orderᵀ : ∀ i → True (i ≤ᵇ 13) → 4 T.⊢ Ω i • Ω i • Ω i ≈ ε')
    for i in range(14):
        out.append('orderᵀ %d _ = eqn→ %s refl refl' % (i, inst[('order', (i,))].name))
    out.append('orderᵀ %s ()' % sucs(14, 'i'))
    out.append('')

    sect('Two cycles one position apart')
    out.append('nearᵀ : ∀ i → True (i ≤ᵇ 12) →')
    out.append('        4 T.⊢ Ω i • Ω (1 + i) • Ω i ≈ Ω (1 + i) • Ω (1 + i)')
    for i in range(13):
        out.append('nearᵀ %d _ = eqn→ %s refl refl' % (i, inst[('near', (i, i + 1))].name))
    out.append('nearᵀ %s ()' % sucs(13, 'i'))
    out.append('')

    sect('Two cycles two positions apart')
    out.append('farᵀ : ∀ i → True (i ≤ᵇ 11) →')
    out.append('       4 T.⊢ Ω i • Ω (2 + i) • Ω i ≈ Ω (2 + i) • Ω i • Ω (1 + i)')
    for i in range(12):
        out.append('farᵀ %d _ = eqn→ %s refl refl' % (
            i, inst[('far', (i, i + 1, i + 2))].name))
    out.append('farᵀ %s ()' % sucs(12, 'i'))
    out.append('')

    sect('Two cycles three or more positions apart')
    out.append('apartᵀ : ∀ i j → True ((j ≤ᵇ 13) ∧ (3 + i ≤ᵇ j)) →')
    out.append('         4 T.⊢ Ω j • Ω i ≈ Ω i • Ω j')
    for j in range(14):
        for i in range(0, j - 2):
            out.append('apartᵀ %d %d _ = eqn→ %s refl refl' % (
                i, j, inst[('apart', (i, j))].name))
        out.append('apartᵀ %s %d ()' % (sucs(max(j - 2, 0), 'i'), j))
    out.append('apartᵀ i %s ()' % sucs(14, 'j'))
    out.append('')

    sect('The gates as circuits of words in the cycles')
    names = [('X0', 'X', 'X₀'), ('CX0', 'CX', 'CX'), ('CCX0', 'CCX', 'CCX'),
             ('Ex0', 'Ex₀', 'Ex₀'), ('Ex1', 'Ex₁', 'Ex₁'), ('Ex2', 'Ex₂', 'Ex₂')]
    for key, nm, circ in names:
        lem, word = gate[key]
        out.append('w%s : L.Circuit 16' % nm)
        out.append('w%s =' % nm)
        out.extend(lafont_word(word))
        out.append('')
        out.append('gate-%sᵀ : 4 T.⊢ %s ≈ (g ʷ) w%s' % (nm, circ, nm))
        out.append('gate-%sᵀ = eqn→ %s refl refl' % (nm, lem.name))
        out.append('')
    path = os.path.join(HERE, '..', 'Four', 'Relations.agda')
    with io.open(path, 'w', encoding='utf-8', newline=NL) as fh:
        fh.write(NL.join(out))
    print('Relations: %d instances, %d gates' % (len(inst), len(gate)))
