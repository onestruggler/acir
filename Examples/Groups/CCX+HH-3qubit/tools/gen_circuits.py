# ------------------------------------------------------------------
# Iso

def ikappa(L):
    """[L] ≈ (ι ʷ) (κ L) in the paper's relation, for a derived letter."""
    r, rhs = defrule[L]
    toks = rhs.split(' • ')
    # right-nested congruence over the RHS letters
    def lem(t):
        return 'ικ-' + t if t in defrule else 'PB.refl'
    parts = [lem(t) for t in toks]
    if all(p == 'PB.refl' for p in parts):
        return 'ax (P.%s)' % r
    acc = parts[-1]
    for p in reversed(parts[:-1]):
        acc = 'PB.cong %s (%s)' % (p, acc) if ' ' in acc else 'PB.cong %s %s' % (p, acc)
    return 'PB.trans (ax (P.%s)) (%s)' % (r, acc)

