    w('%s-dif : %s ZR.- %s ≡ √2ᶻ ZR.* %s' % (name, agda(e[i]), agda(e[j]), agda(be)))
    w('%s-dif = ZG.solve 4 (λ A p q d → %s :- %s := (con √2ᶻ) :* %s) refl A p q d' % (name, zg(e[i]), zg(e[j]), zg(be)))
