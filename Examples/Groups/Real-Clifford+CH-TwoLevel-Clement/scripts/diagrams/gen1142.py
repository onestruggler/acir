# Thesis/Steps1142.agda: the local vectors along the two routes, and the
# identities that let H act at the same scale.

import random

def V(x): return ('v', x)
R2 = ('r',); T2 = ('t',)
def add(x, y): return ('+', x, y)
def sub(x, y): return ('-', x, y)
def mul(x, y): return ('*', x, y)
def neg(x): return ('neg', x)

def agda(e):
    k = e[0]
    if k == 'v': return e[1]
    if k == 'r': return '√2ᶻ'
    if k == 't': return '2ᶻ'
    if k == '+': return '(' + agda(e[1]) + ' ZR.+ ' + agda(e[2]) + ')'
    if k == '-': return '(' + agda(e[1]) + ' ZR.- ' + agda(e[2]) + ')'
    if k == '*': return '(' + agda(e[1]) + ' ZR.* ' + agda(e[2]) + ')'
    return '(ZR.- ' + agda(e[1]) + ')'

def zg(e):
    k = e[0]
    if k == 'v': return e[1]
    if k == 'r': return '(con √2ᶻ)'
    if k == 't': return '(con 2ᶻ)'
    if k == '+': return '(' + zg(e[1]) + ' :+ ' + zg(e[2]) + ')'
    if k == '-': return '(' + zg(e[1]) + ' :- ' + zg(e[2]) + ')'
    if k == '*': return '(' + zg(e[1]) + ' :* ' + zg(e[2]) + ')'
    return '(:- ' + zg(e[1]) + ')'

def ev(e, env):
    k = e[0]
    if k == 'v': return env[e[1]]
    if k == 'r': return (0, 1)
    if k == 't': return (2, 0)
    if k == '+':
        x = ev(e[1], env); y = ev(e[2], env); return (x[0] + y[0], x[1] + y[1])
    if k == '-':
        x = ev(e[1], env); y = ev(e[2], env); return (x[0] - y[0], x[1] - y[1])
    if k == '*':
        x = ev(e[1], env); y = ev(e[2], env); return (x[0] * y[0] + 2 * x[1] * y[1], x[0] * y[1] + x[1] * y[0])
    x = ev(e[1], env); return (-x[0], -x[1])

A, p, q, dd = V('A'), V('p'), V('q'), V('d')
def two(z): return mul(T2, z)
vecs = {'vr': [A, add(A, two(p)), add(A, two(q)), add(A, two(dd))]}
STEPS = []
def step(name, src, i, j, alpha, beta, dst):
    e = vecs[src]
    out = list(e); out[i] = alpha; out[j] = beta
    vecs[dst] = out
    STEPS.append((name, src, i, j, alpha, beta, dst))
def swap(src, i, j, dst):
    e = list(vecs[src]); e[i], e[j] = e[j], e[i]; vecs[dst] = e

Apq = add(add(A, q), dd)
step('h01', 'vr', 0, 1, mul(R2, add(A, p)), neg(mul(R2, p)), 'v0')
step('h23', 'v0', 2, 3, mul(R2, Apq), mul(R2, sub(q, dd)), 'v1')
# S even: PB, X[b,c], PB
step('e13', 'v1', 1, 3, sub(sub(q, dd), p), sub(neg(p), sub(q, dd)), 'v2')
step('e02', 'v2', 0, 2, add(add(A, p), Apq), sub(add(A, p), Apq), 'v3')
swap('v3', 1, 2, 'v4')
step('e13′', 'v4', 1, 3, neg(mul(R2, q)), mul(R2, sub(p, dd)), 'v5')
step('e02′', 'v5', 0, 2, mul(R2, add(A, q)), mul(R2, add(add(A, p), dd)), 'v6')
# S odd: PC, X[b,d], PC
step('o12', 'v1', 1, 2, sub(Apq, p), sub(neg(p), Apq), 'w2')
step('o03', 'w2', 0, 3, add(add(A, p), sub(q, dd)), sub(add(A, p), sub(q, dd)), 'w3')
swap('w3', 1, 3, 'w4')
step('o12′', 'w4', 1, 2, neg(mul(R2, q)), mul(R2, add(add(A, p), dd)), 'w5')
step('o03′', 'w5', 0, 3, mul(R2, add(A, q)), mul(R2, sub(p, dd)), 'w6')

random.seed(1)
for _ in range(200):
    env = {x: (random.randint(-9, 9), random.randint(-9, 9)) for x in ('A', 'p', 'q', 'd')}
    for (name, src, i, j, al, be, dst) in STEPS:
        e = vecs[src]
        s = ev(add(e[i], e[j]), env); r = ev(mul(R2, al), env)
        assert s == r, (name, 'sum')
        s = ev(sub(e[i], e[j]), env); r = ev(mul(R2, be), env)
        assert s == r, (name, 'dif')

