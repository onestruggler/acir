H = lambda a, b: ('H', a, b)
X = lambda a, b: ('X', a, b)
Z = lambda a: ('Z', a)

def pair_name(g):
    if g[0] == 'Z':
        return 'a1-%d' % g[1]
    if g[0] == 'X':
        return 'a2-%d%d' % (g[1], g[2])
    return 'a3-%d%d' % (g[1], g[2])

class D4(Deriver):
    def pair_name(self, g):
        return pair_name(g)

PA = [H(0, 1), H(2, 3)]
PB = [H(0, 2), H(1, 3)]
PC = [H(0, 3), H(1, 2)]
Lf1, Rf1 = PA + PB, PB + PA
LG, RG = PB + PC, [H(0, 1), H(2, 3), X(1, 3), Z(3), H(2, 3), H(0, 1)]
L27 = [H(2, 3)] + PB + [X(1, 2)] + PB + [H(2, 3), H(0, 1), X(1, 2)]
L28 = [H(2, 3)] + PC + [X(1, 3)] + PC + [H(2, 3), H(0, 1), X(1, 2)]
R2728 = [H(0, 1)]

D = D4(4)
D.add_eq('f1e', Lf1, Rf1)
D.add_eq('Ge', LG, RG)

def found(name, l, r, **kw):
    st = search(l, r, D.lib, **kw)
    assert st is not None, name
    verify(l, r, st, D.lib)
    D.derived.append((name, list(l), list(r), st))
    D.lib.add(name, l, r)

# X[b,d] PB PA = PB PA X[c,d], by (f1).
found('xpp', [X(1, 3)] + PB + PA, PB + PA + [X(2, 3)], maxdepth=8, maxlen=10, limit=8000000)
# PC = PB PA X[b,d] Z[d] PA, by (G).
found('pcG', PC, PB + RG, maxdepth=6, maxlen=12, limit=8000000)
# X[c,d] X[b,d] = X[b,d] X[b,c].
found('xx', [X(2, 3), X(1, 3)], [X(1, 3), X(1, 2)], maxdepth=4, maxlen=4, limit=100000)

# The core of (28'): X[b,d] PC PA = PC PA X[b,c].
c = Chain(D, [X(1, 3)] + PC + PA)
c.rw_at('pcG')
c.cancel()
c.rw_at('xpp')
c.rw_at('xx')
c.perm(PB + PA + [X(1, 3), Z(3), X(1, 2)])
c.insert([H(2, 3), H(0, 1)], 6)
c.rw('(sym⁼ pcG)', 0)
c.finish('core', PC + PA + [X(1, 2)])

# (27'), by search.
found('r27', L27, R2728, maxdepth=8, maxlen=12, limit=8000000)

# (28'): the core, then cancellations.
c = Chain(D, L28)
c.perm([H(2, 3)] + PC + [X(1, 3)] + PC + PA + [X(1, 2)])
c.rw('(sym⁼ core)', 4)
c.cancel()
c.finish('r28', R2728)

derivs = D.derived
used = collect(derivs)
for w in (Lf1, Rf1, LG, RG, L27, L28, R2728):
    used |= set(w)

out = []
w = out.append
