#!/usr/bin/env python3
"""Write Natural/Axioms.agda: the natural rules as list equations.

The rules are natproof.RULES, expanded exactly as the enumeration uses
them, so the generated derivations and the Agda equations agree.
Run: python3 -B gen_axioms.py [--check]
"""
import sys
from pathlib import Path
import core as C
import natproof as NP

OUT = Path(__file__).resolve().parents[1] / "Natural" / "Axioms.agda"
SUB = "₀₁₂₃₄₅₆₇₈₉"
WIDTH = {1: "₁₊", 2: "₂₊", 3: "₃₊", 4: "₄₊"}

def letter(base, i):
    gate = {"X": "gate₁ X-gate", "CX": "gate₂ CX-gate", "CCX": "gate₃ CCX-gate", "HH": "gate₂ HH-gate"}[base]
    return gate + " ↥" * i

def name(base, i):
    return {"X": "x", "CX": "cx", "CCX": "ccx", "HH": "hh"}[base] + SUB[i]

def expand_names(text):
    out = []
    for tok in text.split():
        base, i = C.split_name(tok)
        if base == "XC":
            out += [("HH", i), ("CX", i), ("HH", i)]
        elif base == "Ex":
            out += [("CX", i), ("HH", i), ("CX", i), ("HH", i), ("CX", i)]
        else:
            out.append((base, i))
    return out

def span(letters):
    return max(i + C.arity(b) for b, i in letters)

def agda_list(letters):
    return " ∷ ".join(name(b, i) for b, i in letters) + (" ∷ []" if letters else "[]")

def generate():
    s = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- The natural rules as equations between letter lists (Natural.Engine),
-- at every width, for the derivations generated by
-- CCX+HH/Rules/natproof.py.  Letters: x i = X on wire i, cx i = CX
-- targeting wire i, ccx i, hh i.  Generated by CCX+HH/Rules/gen_axioms.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+HH.Natural.Axioms where

open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (ℕ)
import Relation.Binary.PropositionalEquality as Eq
import Presentation.Base as PB
import Presentation.Properties as PP
open import Notations using (₁₊ ; ₂₊ ; ₃₊ ; ₄₊)

open import Examples.Groups.CCX+HH.Natural.Syntactics
open import Examples.Groups.CCX+HH.Natural.Engine using (Eqn ; eqn ; ⟪_⟫ ; invol)

private
  variable
    n : ℕ

'''
    pats = []
    for base, k in (("X", 4), ("CX", 3), ("HH", 3), ("CCX", 2)):
        for i in range(k):
            pats.append(f"pattern {name(base, i)} = {letter(base, i)}")
    s += "\n".join(pats) + "\n"
    s += '''
private
  ax : ∀ {m} {w v : Circuit m} (l r : List (Gen m)) → m N, w === v →
       m ⊢ ⟪ l ⟫ ≈ w → m ⊢ v ≈ ⟪ r ⟫ → Eqn m
  ax l r a p q = eqn l r (PB.trans p (PB.trans (PB.axiom (srel a)) q))

  as : ∀ {m} {w v : Circuit m} →
       PP.to-list (m VRel,_===_) w Eq.≡ PP.to-list (m VRel,_===_) v → m ⊢ w ≈ v
  as {m} = PP.by-assoc (m VRel,_===_)

-- Every letter is an involution.
inv⁼ : Gen n → Eqn n
inv⁼ y = eqn (y ∷ y ∷ []) [] (PB.trans (as Eq.refl) (invol y))
'''
    rules = [("X²", "X0 X0", ""), ("CX²", "CX0 CX0", ""), ("CCX²", "CCX0 CCX0", ""),
             ("HH²", "HH0 HH0", "")] + NP.RULES
    for nm, l, r in rules:
        L, R = expand_names(l), expand_names(r)
        w = WIDTH[span(L + R)]
        s += f"\n{nm}ᵉ : Eqn ({w} n)\n{nm}ᵉ = ax ({agda_list(L)})\n  ({agda_list(R)})\n  {nm} (as Eq.refl) (as Eq.refl)\n"
    return s

if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != text:
            raise SystemExit("Natural/Axioms.agda differs from the generator")
        print("Axioms up to date")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n") if sys.version_info >= (3, 10) and False else open(OUT, "w", encoding="utf-8", newline="\n").write(text)
        print("wrote", OUT)
