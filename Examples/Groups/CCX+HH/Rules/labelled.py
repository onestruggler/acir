#!/usr/bin/env python3
"""Coset enumeration of a subgroup that proves its own labelled table.

proofs.py does this for the trivial subgroup.  Here the subgroup is
generated by *macros*: circuit words that are palindromes of involutions,
so that dec(rev λ) = rev(dec λ) letter for letter and a word λ in the
macros (a *label*) is inverted by reversing it.  Every table entry
c·y = d comes with a label λ and a fact

    rep[c] ++ [y]  ⟶  dec(λ) ++ rep[d]

as rewrite steps (proofs.py's format, which Natural/Engine's `derive`
checks); a coincidence is a fact rep[b] ⟶ dec(w) ++ rep[a].  A macro m
is a "relator" at coset 0 that closes with the label m.

The strategy is Felsch's: cosets are defined in order, and every new
entry is followed by scanning the rotations (and reversals) of every
relator through it, each with its own derivation from the relator's.  Cosets may be seeded with a prefix-closed list of
representatives, defined first, so that they get the smallest numbers;
a coincidence keeps the smaller one, so the seeded cosets survive when
they are pairwise distinct (as cosets of the subgroup).

After the run, every relator traced from a live coset closes with a
label, a word in the macros equal to the identity: a *derived relator*
of the subgroup, with its derivation (Reidemeister–Schreier).
"""
from __future__ import annotations

import proofs as P


class LabelledTC:
    def __init__(self, ngens, axioms, macros, seed=(), limit=500_000):
        self.ngens = ngens
        self.axioms = axioms
        self.macros = dict(macros)
        for m, w in self.macros.items():
            assert tuple(w) == tuple(reversed(w)), m
        self.facts = []
        self.rep, self.table, self.parent = [], [], []
        self.limit = limit
        self.relators = []
        rotations = {}
        for k, ax in enumerate(axioms):
            rel = tuple(ax.lhs) + tuple(reversed(ax.rhs))
            steps = [(0, ("ax", k), True)]
            r = list(ax.rhs)
            for j in range(len(r) - 1, -1, -1):
                steps.append((j, ("inv", r[j]), True))
            f = self._add(rel, (), steps)
            self.relators.append((rel, f, None))
            # rev(r) -> rev(r) r -> ε
            rv = tuple(reversed(rel))
            fr = self._add(rv, (), [(len(rel), ("fact", f), False)] + self.cancel(0, rv))
            for word, wf in ((rel, f), (rv, fr)):
                for i in range(len(word)):
                    a, b = word[:i], word[i:]
                    rot = b + a
                    if rot in rotations:
                        continue
                    if i == 0:
                        rotations[rot] = wf
                    else:
                        # b a -> rev(a) a b a -> rev(a) a -> ε
                        st = self.insert(0, tuple(reversed(a))) + [(len(a), ("fact", wf), True)]
                        st += self.cancel(0, tuple(reversed(a)))
                        rotations[rot] = self._add(rot, (), st)
        self.by_first = [[] for _ in range(ngens)]
        for rot, rf in rotations.items():
            self.by_first[rot[0]].append((rot, rf))
        self.subgroup = [(tuple(w), m) for m, w in self.macros.items()]
        self.seed = [tuple(w) for w in seed]
        self.stack = []

    # ------------------------------------------------------------------
    def _add(self, lhs, rhs, steps):
        self.facts.append(P.Fact(tuple(lhs), tuple(rhs), list(steps)))
        return len(self.facts) - 1

    def dec(self, label):
        out = []
        for m in label:
            out += self.macros[m]
        return tuple(out)

    @staticmethod
    def reverse(steps):
        return [(pos, key, not fwd) for (pos, key, fwd) in reversed(steps)]

    @staticmethod
    def shift(steps, k):
        return [(pos + k, key, fwd) for (pos, key, fwd) in steps]

    @staticmethod
    def cancel(pos, word):
        """Steps turning word ++ rev(word), at pos, into ε (middle out)."""
        return [(pos + j, ("inv", word[j]), True) for j in range(len(word) - 1, -1, -1)]

    def insert(self, pos, word):
        """Steps inserting word ++ rev(word) at pos."""
        return self.reverse(self.cancel(pos, word))

    def join(self, left, right):
        """Free reduction of left ++ right, dec(left) starting at 0."""
        left, right, steps = list(left), list(right), []
        while left and right and left[-1] == right[0]:
            m = left.pop()
            right.pop(0)
            steps += self.cancel(len(self.dec(left)), self.macros[m])
        return tuple(left + right), steps

    def invert(self, label):
        return tuple(reversed(label))

    def front(self, label):
        """Steps inserting rev(dec λ) ++ dec λ at the front."""
        return self.insert(0, self.dec(self.invert(label)))

    # ------------------------------------------------------------------
    def _new(self, c, y):
        if len(self.rep) >= self.limit:
            raise OverflowError
        d = len(self.rep)
        self.rep.append(self.rep[c] + (y,))
        self.table.append([None] * self.ngens)
        self.parent.append(None)
        fwd = self._add(self.rep[c] + (y,), self.rep[d], [])
        back = self._add(self.rep[d] + (y,), self.rep[c], [(len(self.rep[c]), ("inv", y), True)])
        self.table[c][y] = (d, (), fwd)
        self.table[d][y] = (c, (), back)
        self.stack.append((c, y))
        return d

    def find(self, c):
        """(root, label, steps rewriting a prefix rep[c] into dec(label) ++
        rep[root]); compresses the path, so the steps are one fact."""
        if self.parent[c] is None:
            return c, (), []
        a, w, f = self.parent[c]
        r, l2, s2 = self.find(a)
        if r == a:
            return a, w, [(0, ("fact", f), True)]
        steps = [(0, ("fact", f), True)] + self.shift(s2, len(self.dec(w)))
        lab, red = self.join(w, l2)
        g = self._add(self.rep[c], self.dec(lab) + self.rep[r], steps + red)
        self.parent[c] = (r, lab, g)
        return r, lab, [(0, ("fact", g), True)]

    def entry(self, c, y):
        e = self.table[c][y]
        if e is None:
            return None
        d, mu, f = e
        r, l, s = self.find(d)
        if r == d:
            return d, mu, [(0, ("fact", f), True)]
        steps = [(0, ("fact", f), True)] + self.shift(s, len(self.dec(mu)))
        lab, red = self.join(mu, l)
        g = self._add(self.rep[c] + (y,), self.dec(lab) + self.rep[r], steps + red)
        self.table[c][y] = (r, lab, g)
        return r, lab, [(0, ("fact", g), True)]

    def walk(self, c, word):
        """(letters followed, coset, label, steps rewriting a prefix rep[c] ++
        word[:i] into dec(label) ++ rep[coset])."""
        label, steps, cur = (), [], c
        for i, y in enumerate(word):
            e = self.entry(cur, y)
            if e is None:
                return i, cur, label, steps
            d, mu, s = e
            steps += self.shift(s, len(self.dec(label)))
            label, red = self.join(label, mu)
            steps += red
            cur = d
        return len(word), cur, label, steps

    # ------------------------------------------------------------------
    def bridge(self, e, rel, relfact, closing, i, j):
        """Rewrites rep[f] ++ rel[i:j] into dec(λ) ++ rep[b], where f is
        reached from e along rel[:i] and b from e along rev(rel[j:]):
        returns (λ, steps)."""
        _, _, lf, sf = self.walk(e, rel[:i])
        dl = self.dec(lf)
        steps = self.front(lf)                                       # rev(dl) dl rep f ..
        steps += self.shift(self.reverse(sf), len(dl))                # rev(dl) rep e rel[:j]
        base = len(dl) + len(self.rep[e])
        steps += self.insert(base + j, rel[j:])                       # .. rel rev(rel[j:])
        label0 = self.invert(lf)
        if closing is None:
            steps.append((base, ("fact", relfact), True))             # rev(dl) rep e rev(rel[j:])
        else:
            label0 = label0 + (closing,)                              # rep 0 = ε, rel = dec m
        _, _, lb, sb = self.walk(e, tuple(reversed(rel[j:])))
        steps += self.shift(sb, len(self.dec(label0)))
        label, red = self.join(label0, lb)
        return label, steps + red

    def merge(self, a, b, w, f):
        """Coincidence: fact f is rep[b] -> dec(w) ++ rep[a]."""
        queue = [(a, b, w, f)]
        while queue:
            a, b, w, f = queue.pop()
            ra, la, sa = self.find(a)
            rb, lb, sb = self.find(b)
            if ra == rb:
                continue
            # rep rb -> dec(rev lb) rep b -> dec(rev lb) dec(w) rep a -> .. dec(la) rep ra
            steps = self.front(lb) + self.shift(self.reverse(sb), len(self.dec(lb)))
            lab0, red = self.join(self.invert(lb), w)
            steps += self.shift([(0, ("fact", f), True)], len(self.dec(self.invert(lb)))) + red
            steps += self.shift(sa, len(self.dec(lab0)))
            lab, red = self.join(lab0, la)
            steps += red
            if ra > rb:
                ra, rb = rb, ra
                # rep ra -> dec(rev lab) dec(lab) rep ra <- dec(rev lab) rep rb
                steps = self.front(lab) + self.shift(self.reverse(steps), len(self.dec(lab)))
                lab = self.invert(lab)
            link = self._add(self.rep[rb], self.dec(lab) + self.rep[ra], steps)
            self.parent[rb] = (ra, lab, link)
            for y in range(self.ngens):
                e = self.table[rb][y]
                if e is None:
                    continue
                self.table[rb][y] = None
                d, mu, fd = e
                # rep ra y -> dec(rev lab) dec(lab) rep ra y <- dec(rev lab) rep rb y -> dec(rev lab) dec mu rep d
                inv = self.invert(lab)
                st = self.front(lab) + [(len(self.dec(inv)), ("fact", link), False)]
                st += self.shift([(0, ("fact", fd), True)], len(self.dec(inv)))
                nu, red = self.join(inv, mu)
                f1 = self._add(self.rep[ra] + (y,), self.dec(nu) + self.rep[d], st + red)
                cur = self.table[ra][y]
                if cur is None:
                    self.table[ra][y] = (d, nu, f1)
                    self.stack.append((ra, y))
                else:
                    d2, mu2, f2 = cur
                    # rep d -> dec(rev nu) dec(nu) rep d <- dec(rev nu) rep ra y -> dec(rev nu) dec(mu2) rep d2
                    inv2 = self.invert(nu)
                    st2 = self.front(nu) + [(len(self.dec(inv2)), ("fact", f1), False)]
                    st2 += self.shift([(0, ("fact", f2), True)], len(self.dec(inv2)))
                    lab2, red2 = self.join(inv2, mu2)
                    queue.append((d2, d, lab2, self._add(self.rep[d], self.dec(lab2) + self.rep[d2], st2 + red2)))

    def root(self, c):
        while self.parent[c] is not None:
            c = self.parent[c][0]
        return c

    def step(self, c, y):
        e = self.table[c][y]
        return None if e is None else self.root(e[0])

    def scan(self, e, rel, relfact, closing, define=True):
        """Trace without proofs; build a derivation only for a deduction
        or a coincidence."""
        n = len(rel)
        while True:
            e = self.root(e)
            f, i = e, 0
            while i < n:
                d = self.step(f, rel[i])
                if d is None:
                    break
                f, i = d, i + 1
            if i == n:
                if f != e:
                    lab, st = self.bridge(e, rel, relfact, closing, n, n)
                    self.merge(e, f, lab, self._add(self.rep[f], self.dec(lab) + self.rep[e], st))
                return
            b, j = e, n
            while j > i:
                d = self.step(b, rel[j - 1])
                if d is None:
                    break
                b, j = d, j - 1
            if j == i:
                if f != b:
                    lab, st = self.bridge(e, rel, relfact, closing, i, i)
                    self.merge(b, f, lab, self._add(self.rep[f], self.dec(lab) + self.rep[b], st))
                return
            if j == i + 1:
                y = rel[i]
                lab, st = self.bridge(e, rel, relfact, closing, i, i + 1)
                fact = self._add(self.rep[f] + (y,), self.dec(lab) + self.rep[b], st)
                if self.table[f][y] is None:
                    self.table[f][y] = (b, lab, fact)
                    self.stack.append((f, y))
                inv = self.invert(lab)
                st2 = self.front(lab) + [(len(self.dec(inv)), ("fact", fact), False),
                                         (len(self.dec(inv)) + len(self.rep[f]), ("inv", y), True)]
                back = self._add(self.rep[b] + (y,), self.dec(inv) + self.rep[f], st2)
                if self.table[b][y] is None:
                    self.table[b][y] = (f, inv, back)
                    self.stack.append((b, y))
                else:
                    d2, mu2, f2 = self.table[b][y]
                    st3 = self.front(inv) + [(len(self.dec(lab)), ("fact", back), False)]
                    st3 += self.shift([(0, ("fact", f2), True)], len(self.dec(lab)))
                    lab3, red = self.join(lab, mu2)
                    self.merge(d2, f, lab3, self._add(self.rep[f], self.dec(lab3) + self.rep[d2], st3 + red))
                return
            if not define:
                return
            self._new(f, rel[i])

    def process(self):
        """Felsch: scan every relator rotation through each new entry."""
        while self.stack:
            c, y = self.stack.pop()
            if self.parent[c] is not None:
                continue
            for rot, rf in self.by_first[y]:
                self.scan(c, rot, rf, None, define=False)
            for w, m in self.subgroup:
                self.scan(0, w, None, m, define=False)

    def run(self):
        self.rep.append(())
        self.table.append([None] * self.ngens)
        self.parent.append(None)
        index = {(): 0}
        for w in self.seed:
            if w and w not in index:
                index[w] = self._new(index[w[:-1]], w[-1])
        self.process()
        for w, m in self.subgroup:
            self.scan(0, w, None, m)
            self.process()
        for rel, rf, _ in self.relators:
            self.scan(0, rel, rf, None)
            self.process()
        c = 0
        while c < len(self.rep):
            for y in range(self.ngens):
                if self.parent[c] is not None:
                    break
                if self.table[c][y] is None:
                    self._new(c, y)
                    self.process()
            c += 1
        return [c for c in range(len(self.rep)) if self.parent[c] is None]

    # ------------------------------------------------------------------
    def final(self, c, y):
        """For live c: (live d, label, fact rep[c] ++ [y] -> dec(label) ++ rep[d])."""
        d, label, steps = self.entry(c, y)
        return d, label, self._add(self.rep[c] + (y,), self.dec(label) + self.rep[d], steps)

    def derived(self, live):
        """For each live coset and axiom relator, the label it closes with."""
        out = []
        for e in live:
            for k, (rel, rf, m) in enumerate(self.relators):
                i, f, lab, st = self.walk(e, rel)
                assert i == len(rel) and f == e
                out.append((e, k, lab, st))
        return out


def replay_all(tc):
    return [k for k, f in enumerate(tc.facts) if not P.replay(tc, f)]
