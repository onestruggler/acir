"""Labelled enumeration of the natural rules on three wires over the
parabolic subgroup W(E7) generated by seven simple reflections."""
import sys, time, itertools
sys.path.insert(0, '..')
import core as C
import natproof as NP
import labelled as L
from e8 import root_orbit, dot, canon
import importlib, io, contextlib
with contextlib.redirect_stdout(io.StringIO()):
    import simple as S0

def dynkin(simple):
    adj = {i: [] for i in range(8)}
    for i, j in itertools.combinations(range(8), 2):
        if dot(simple[i], simple[j]) != 0:
            adj[i].append(j); adj[j].append(i)
    return adj

def e7_node(adj):
    """The end of the longest arm (removing it leaves E7)."""
    branch = next(i for i in adj if len(adj[i]) == 3)
    best = None
    for start in adj[branch]:
        arm, prev, cur = [start], branch, start
        while True:
            nxt = [k for k in adj[cur] if k != prev]
            if not nxt: break
            prev, cur = cur, nxt[0]; arm.append(cur)
        if best is None or len(arm) > len(best): best = arm
    return best[-1], branch

if __name__ == '__main__':
    import random
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    rnd = random.Random(seed)
    # pick the best simple system from a quick random search
    best = None
    for _ in range(3000):
        f = tuple(rnd.gauss(0, 1) for _ in range(8))
        Ssys = S0.simple_system(f)
        tot = sum(len(S0.circ(r)) for r in Ssys)
        if best is None or tot < best[0]: best = (tot, Ssys)
    tot, Ssys = best
    adj = dynkin(Ssys)
    drop, branch = e7_node(adj)
    print('total length', tot, 'drop node', drop)
    gs = C.GateSet(3)
    macros = {}
    for i, r in enumerate(Ssys):
        if i == drop: continue
        macros[f's{i}'] = tuple(gs.index[t] for t in S0.circ(r))
        print(f's{i}', ' '.join(S0.circ(r)))
    axioms = NP.axioms(gs)
    print('axioms', len(axioms))
    t0 = time.time()
    tc = L.LabelledTC(len(gs.names), axioms, macros, limit=2_000_000)
    live = tc.run()
    print('live cosets', len(live), 'defined', len(tc.rep), 'time', round(time.time() - t0, 1))
    sizes = []
    for c in live:
        for y in range(len(gs.names)):
            d, lab, f = tc.final(c, y)
            sizes.append(len(lab))
    print('label lengths: max', max(sizes), 'mean', sum(sizes) / len(sizes))
