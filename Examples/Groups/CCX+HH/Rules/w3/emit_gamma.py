"""Write Natural/ThreeWire/Gamma.agda: the nine letters, their signed
permutations, and the relators of the tower (pipe.py).

    python3 -B emit_gamma.py
"""
import sys
import pipe as Pp

OUT = '/mnt/d/dwork3/acir/Examples/Groups/CCX+HH/Natural/ThreeWire/Gamma.agda'
FIN = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇']
AG = {'X0': 'x0', 'X1': 'x1', 'X2': 'x2', 'CX0': 'cx0', 'CX1': 'cx1',
      'CXr0': 'cxr0', 'CXr1': 'cxr1', 'CCX0': 'ccx0', 'Z1': 'z1'}

def relname(nm):
    return 'r-' + nm.replace('X', 'x').replace('Z', 'z').replace('C', 'c')

def agda_list(word):
    return ' ∷ '.join(AG[x] for x in word) + ' ∷ []' if word else '[]'

def sp_lit(t):
    return ' ∷ '.join(f'({FIN[j]} , {"true" if s < 0 else "false"})' for (j, s) in t) + ' ∷ []'

def rels():
    free = Pp.free_relators()
    rs = [('inv-' + x, (x, x)) for x in Pp.LET]
    rs += [('comm-%s-%s' % (r[0], r[1]), r) for r in Pp.COMM]
    for nm, ws in free.items():
        rs += [('%s-%d' % (nm, k), r) for k, r in enumerate(ws)]
    rs += list(Pp.THREE.items())
    return rs

def main():
    rs = rels()
    L = []
    w = L.append
    w('''------------------------------------------------------------------------
-- Presentations of groups
--
-- The nine letters of the three-wire tower and its relators.
--
-- The letters are X on each wire, the CNOTs CX0 (wire 1 onto 0), CX1
-- (2 onto 1), CXr0 (0 onto 1), CXr1 (1 onto 2), the Toffoli CCX0 and
-- Z1 (Z on wire 1); each is read as a signed permutation of the eight
-- levels l = x0 + 2 x1 + 4 x2 (`spL`).  The relators (`Rel`) are the
-- involutions, the commutations of letters on disjoint wires, a
-- presentation of each two-wire subgroup, and the three-wire relators
-- of the tower: A1-A3 (the affine group), the Toffoli rules CCX-sym,
-- CCX-neg and CCX-XC, and D1, D2 (Z1).  Every relator is the identity
-- (`rel-sp`).
--
-- Generated by Rules/w3/emit_gamma.py; do not edit.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+HH.Natural.ThreeWire.Gamma where

open import Data.Bool.Base using (Bool ; true ; false ; _∧_)
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (ℕ ; _≡ᵇ_)
open import Data.Nat.Properties using (≡ᵇ⇒≡)
open import Data.Product.Base using (_,_)
open import Data.Vec.Base using (_∷_ ; [])
open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)
open import Word.Base using (Word ; WRel ; [_]ʷ ; ε ; _•_)
open import Notations using (₀ ; ₁ ; ₂ ; ₃ ; ₄ ; ₅ ; ₆ ; ₇)
open import Presentation.Tactics.Words using (module Associative)
open import Examples.Groups.CCX+HH.Natural.ThreeWire.Perm using (SP ; ID ; mul)

open Associative using (word-of-list)

data L : Set where
  x0 x1 x2 cx0 cx1 cxr0 cxr1 ccx0 z1 : L

code : L → ℕ
''')
    for k, x in enumerate(Pp.LET):
        w(f'code {AG[x]} = {k}')
    w('''
eqL : L → L → Bool
eqL a b = code a ≡ᵇ code b

eqL-sound : ∀ a b → eqL a b ≡ true → a ≡ b''')
    for x in Pp.LET:
        w(f'eqL-sound {AG[x]} {AG[x]} _ = refl')
    for x in Pp.LET:
        for y in Pp.LET:
            if x != y:
                w(f'eqL-sound {AG[x]} {AG[y]} ()')
    w('''
-- The signed permutation of each letter.
spL : L → SP''')
    for x in Pp.LET:
        w(f'spL {AG[x]} = {sp_lit(Pp.SPL[x])}')
    w('''
sp : Word L → SP
sp [ a ]ʷ  = spL a
sp ε       = ID
sp (u • v) = mul (sp u) (sp v)

⟪_⟫ : List L → Word L
⟪_⟫ = word-of-list

data Rel : Set where''')
    names = [relname(nm) for nm, _ in rs]
    for i in range(0, len(names), 6):
        w('  ' + ' '.join(names[i:i + 6]) + ' : Rel')
    w('''
relator : Rel → List L''')
    for nm, r in rs:
        w(f'relator {relname(nm)} = {agda_list(r)}')
    w('''
infix 4 _Γ_
data _Γ_ : WRel L where
  rel : (r : Rel) → ⟪ relator r ⟫ Γ ε

rel-sp : ∀ r → sp ⟪ relator r ⟫ ≡ ID''')
    for nm, r in rs:
        w(f'rel-sp {relname(nm)} = refl')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('relators', len(rs))

if __name__ == '__main__':
    main()
