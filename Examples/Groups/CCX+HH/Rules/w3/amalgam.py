"""Is A_{2^n} the amalgam of its half-subgroups (with opposite halves
commuting)?  Classical analogue of the plan for the width induction.

Generators of the alternating group of a set of 8 (or 2^(n-1)) points
p0 < p1 < ...: the involutions s_i s_j = (p_i p_{i+1})(p_j p_{j+1}),
|i - j| >= 2.  Relations per half: all identity words of length <= 4,
plus (a b)^3 for generator pairs whose product is a 3-cycle; checked by
coset enumeration to present A_8.  Halves glued along quarters (words
for each quarter element in both halves), opposite halves commute.  We
enumerate cosets of the subgroup generated by two opposite halves.
"""
import sys, itertools
sys.path.insert(0, '..')
import core as C

n = int(sys.argv[1]) if len(sys.argv) > 1 else 4
N = 2 ** n

def mul(p, q):
    return tuple(q[i] for i in p)
def transp(a, b):
    p = list(range(N)); p[a], p[b] = b, a; return tuple(p)
ID = tuple(range(N))

def half_gens(P):
    k = len(P)
    s = [transp(P[i], P[i + 1]) for i in range(k - 1)]
    out = []
    for i in range(k - 1):
        for j in range(i + 2, k - 1):
            out.append(mul(s[i], s[j]))
    return out

def closure(gens):
    """BFS: element -> shortest word (indices into gens)."""
    W = {ID: ()}
    fr = [ID]
    while fr:
        nw = []
        for p in fr:
            for k, g in enumerate(gens):
                q = mul(p, g)
                if q not in W:
                    W[q] = W[p] + (k,); nw.append(q)
        fr = nw
    return W

def relators(gens, maxlen=4):
    rels = set()
    m = len(gens)
    for L in range(2, maxlen + 1):
        for w in itertools.product(range(m), repeat=L):
            p = ID
            for k in w: p = mul(p, gens[k])
            if p == ID:
                # canonical up to rotation
                rots = [w[i:] + w[:i] for i in range(L)]
                rels.add(min(rots))
    for a, b in itertools.combinations(range(m), 2):
        p = mul(gens[a], gens[b]); p3 = mul(mul(p, p), p)
        if p3 == ID:
            rels.add((a, b) * 3)
    return sorted(rels)

halves = [(w, b) for w in range(n) for b in (0, 1)]
hp = {h: [x for x in range(N) if (x >> h[0] & 1) == h[1]] for h in halves}
offset, allgens = {}, []
for h in halves:
    offset[h] = len(allgens)
    allgens += half_gens(hp[h])
m = len(half_gens(hp[halves[0]]))
print('gens per half', m, 'total', len(allgens), flush=True)

# relators of one half's alternating group, transported to every half
loc = relators(half_gens(list(range(2 ** (n - 1)))), maxlen=4)
print('local relators', len(loc), flush=True)
sub_idx = [(k,) for k in range(m)]
r = C.index_c(m, loc, (), limit=5_000_000)
print('order presented by local relators (index of trivial subgroup):', r, flush=True)

# --- the amalgam
rels = []
for h in halves:
    o = offset[h]
    rels += [tuple(o + k for k in w) for w in loc]
# per-half element -> word tables (needed for quarter identification)
tables = {}
for h in halves:
    tables[h] = closure(half_gens(hp[h]))
    assert len(tables[h]) == 20160 if n == 4 else True
print('half tables built', flush=True)
# quarter identification: for halves h, h' with different wires, the
# alternating group of the quarter: generate it by double transpositions
# of the quarter's points, and equate the words in both halves.
nq = 0
for h, h2 in itertools.combinations(halves, 2):
    if h[0] == h2[0]:
        continue
    Q = [x for x in hp[h] if x in hp[h2]]
    qg = half_gens(Q)      # double transpositions of consecutive pairs of Q
    if not qg and len(Q) == 4:
        qg = [mul(transp(Q[0], Q[1]), transp(Q[2], Q[3]))]
    # also add 3-cycles of the quarter as products of two double transpositions
    elems = set()
    for a in itertools.permutations(Q, 4):
        pass
    for g in qg + [mul(transp(Q[0], Q[1]), transp(Q[2], Q[3])), mul(transp(Q[0], Q[2]), transp(Q[1], Q[3])),
                   mul(mul(transp(Q[0], Q[1]), transp(Q[2], Q[3])), mul(transp(Q[0], Q[2]), transp(Q[1], Q[3])))]:
        pass
    # generators of A(Q): two 3-cycles (as permutations)
    c1 = mul(transp(Q[0], Q[1]), transp(Q[1], Q[2]))
    c2 = mul(transp(Q[1], Q[2]), transp(Q[2], Q[3]))
    for g in (c1, c2):
        w1 = tuple(offset[h] + k for k in tables[h][g])
        w2 = tuple(offset[h2] + k for k in tables[h2][g])
        # relation w1 = w2  ->  relator w1 rev(w2) (generators are involutions)
        rels.append(w1 + tuple(reversed(w2)))
        nq += 1
print('quarter identifications', nq, flush=True)
nc = 0
for w in range(n):
    h0, h1 = (w, 0), (w, 1)
    for a in range(m):
        for b in range(m):
            ga, gb = offset[h0] + a, offset[h1] + b
            rels.append((ga, gb, ga, gb)); nc += 1
print('commutations', nc, 'total relators', len(rels), flush=True)
sub = [(offset[(n - 1, 0)] + k,) for k in range(m)] + [(offset[(n - 1, 1)] + k,) for k in range(m)]
import math
expect = math.factorial(N) // 2 // (math.factorial(N // 2) // 2) ** 2
print('expected index if the amalgam is A_N:', expect, flush=True)
for lim in (2_000_000, 8_000_000):
    print('limit', lim, '->', C.index_c(len(allgens), rels, sub, limit=lim), flush=True)
