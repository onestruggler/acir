# Relators of Gamma, decoded

def dec(word):
    out = []
    for x in word:
        out += list(Pp.Lv.gates(Pp.Lv.MACRO[x]))
    return tuple(out)

def cancel_steps(w):
    """Steps cancelling adjacent equal gates, leftmost first, to ε."""
    w, steps = list(w), []
    while w:
        i = next(i for i in range(len(w) - 1) if w[i] == w[i + 1])
        steps.append((i, f'inv⁼ {G[w[i]]}'))
        del w[i:i + 2]
    return steps

def perm_to(word, target):
    return f'perm ({glist(target)})'

def relator_eqns(roots):
    rels = []
    free = Pp.free_relators()
    rs = [('inv-' + x, (x, x)) for x in Pp.LET]
    rs += [('comm-%s-%s' % (r[0], r[1]), r) for r in Pp.COMM]
    for nm, ws in free.items():
        rs += [('%s-%d' % (nm, k), r) for k, r in enumerate(ws)]
    rs += list(Pp.THREE.items())
    rootlemma = {g: n for n, g in roots.items()}
    out = []
    for nm, r in rs:
        w = dec(r)
        if nm.startswith('inv-'):
            body = ('derive', w, [f'rw {i} ({e})' for i, e in cancel_steps(w)])
        elif nm.startswith('comm-'):
            a, b = dec((r[0],)), dec((r[1],))
            target = a + a + b + b
            body = ('derive', w, [perm_to(w, target)] + [f'rw {i} ({e})' for i, e in cancel_steps(target)])
        elif nm.startswith('f'):
            body = ('eqn', FREE.eqn(w, ()))
        elif nm in ('A1', 'A2', 'A3', 'D1', 'D2'):
            body = ('eqn', f'lemma-{rootlemma[nm]}')
        else:
            rule = {'CCX-sym': 'CCX-sym', 'CCX-neg': 'CCX-neg', 'CCX-XC': 'CCX-XC'}[nm]
            ax = [a for a in NP.axioms(Pp.Lv.gs) if a.name == (rule, 0)][0]
            assert tuple(w[:len(ax.lhs)]) == tuple(ax.lhs), nm
            after = tuple(ax.rhs) + tuple(w[len(ax.lhs):])
            body = ('derive', w, [f'rw 0 ({RULE[rule]})'] + [f'rw {i} ({e})' for i, e in cancel_steps(after)])
        out.append(('Γm.' + relname(nm), w, body))
    return out

def emit_relators(roots, lemma_order):
    eqs = relator_eqns(roots)
    L = [HEADER.format(title='Every relator of the three-wire tower, decoded, derived in Natural.'),
         f'module {MOD}.Relators where\n',
         'open import Data.List.Base using (List ; [] ; _∷_)',
         'open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)',
         f'open import {MOD}.Kit', f'open import {MOD}.Comm', '@FREE@']
    L += [f'open import {MOD}.Lemmas.{n} using (lemma-{n})' for n in roots]
    L += ['import Examples.Groups.CCX+HH.Natural.ThreeWire.Gamma as Γm',
          f'open import {MOD}.Letters using (decoded)', '', 'relN : Γm.Rel → Eqn 3']
    for name, w, body in eqs:
        if body[0] == 'derive':
            L.append(f'relN {name} = derive ({glist(w)}) [] ({" ∷ ".join(body[2])} ∷ []) refl')
        else:
            L.append(f'relN {name} = {body[1]}')
    L += ['', '-- The left side of each is the decoded relator.',
          'relN-lhs : ∀ r → lhs (relN r) ≡ decoded r']
    for name, w, body in eqs:
        L.append(f'relN-lhs {name} = refl')
    L += ['', 'relN-rhs : ∀ r → rhs (relN r) ≡ []']
    for name, w, body in eqs:
        L.append(f'relN-rhs {name} = refl')
    open(f'{ROOT}/Relators.agda', 'w', encoding='utf-8').write('\n'.join(L) + '\n')

def patch_free(paths):
    imp = '\n'.join(FREE.imports())
    for p in paths:
        s = open(p, encoding='utf-8').read().replace('@FREE@', imp)
        open(p, 'w', encoding='utf-8').write(s)

