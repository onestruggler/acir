# Lemmas

def emit_lemmas(data):
    os.makedirs(f'{ROOT}/Lemmas', exist_ok=True)
    lemmas = data['lemmas']
    order = sorted(lemmas, key=lambda s: int(s[1:]))
    for n in order:
        d = lemmas[n]
        axioms = d['axioms']
        facts = d['facts']
        cl = sorted(facts)
        num = {f: k for k, f in enumerate(cl)}
        chunks = [cl[i:i + CHUNK] for i in range(0, len(cl), CHUNK)]

        def eqn_of(kind, key):
            if kind == 'ax':
                nm, l, r = axioms[key]
                return axiom_eqn(nm, l, r, lambda m: f'lemma-{m}')
            if kind == 'inv':
                return f'inv⁼ {G[key]}'
            if kind == 'fact':
                return f'f{num[key]}'
            raise ValueError(kind)

        base_imports = ['open import Data.List.Base using (List ; [] ; _∷_)',
                        'open import Relation.Binary.PropositionalEquality using (refl)',
                        f'open import {MOD}.Kit', f'open import {MOD}.Comm']
        uses = [f'open import {MOD}.Lemmas.{m} using (lemma-{m})' for m in d['uses']]
        # facts
        bodies = []
        for ci, ch in enumerate(chunks):
            B = []
            for f in ch:
                lhs, rhs, st = facts[f]
                B.append(f'f{num[f]} : Eqn 3')
                if len(st) == 1 and st[0][1][0] == 'norm':
                    B.append(f'f{num[f]} = {FREE.eqn(lhs, rhs)}')
                else:
                    B.append(f'f{num[f]} = derive ({glist(lhs)}) ({glist(rhs)})')
                    B.append(f'  {steps_text(st, eqn_of)} refl')
            bodies.append(B)
        final = [f'lemma-{n} : Eqn 3',
                 f'lemma-{n} = derive ({glist(d["gates"])}) []',
                 f'  {steps_text(d["steps"], eqn_of)} refl']
        files = []
        if len(chunks) <= 1:
            files.append((f'{n}', bodies[0] if bodies else [], final, []))
        else:
            for ci, B in enumerate(bodies):
                files.append((f'{n}/Facts{ci}', B, [], [f'open import {MOD}.Lemmas.{n}.Facts{j}' for j in range(ci)]))
            files.append((f'{n}', [], final, [f'open import {MOD}.Lemmas.{n}.Facts{j}' for j in range(len(bodies))]))
        for path, B, fin, extra in files:
            os.makedirs(os.path.dirname(f'{ROOT}/Lemmas/{path}.agda'), exist_ok=True)
            modname = path.replace('/', '.')
            title = f'The three-wire lemma {n}: {d["text"]}' + ('' if fin else ' (derivations)')
            L = [HEADER.format(title=title), f'module {MOD}.Lemmas.{modname} where\n']
            L += base_imports + ['@FREE@'] + uses + extra + [''] + B + [''] + fin
            open(f'{ROOT}/Lemmas/{path}.agda', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    return order

