"""Write the levels of the three-wire tower as Agda: for each level K in
Z2, Aff, S8, D8,
    Natural/ThreeWire/<K>/Base.agda     LevelKit applied to the level below
    Natural/ThreeWire/<K>/Facts<i>.agda the derivations, CHUNK at a time
    Natural/ThreeWire/<K>.agda          the tables, checks, `complete`

    python3 -B emit_levels.py
"""
import os, sys
import pipe as Pp
from emit_gamma import AG, relname, FIN

ROOT = '/mnt/d/dwork3/acir/Examples/Groups/CCX+HH/Natural/ThreeWire'
MOD = 'Examples.Groups.CCX+HH.Natural.ThreeWire'
CHUNK = 400
NAMES = {'z2': 'Z2', 'aff': 'Aff', 's8': 'S8', 'd8': 'D8'}
IOTA = {'z2': 'ιZ', 'aff': 'ιA', 's8': 'ιS', 'd8': 'ιD'}
PSI = {'z2': None, 'aff': ('ψA', 'ψA-letter'), 's8': ('ψS', 'ψS-letter'), 'd8': ('ψD', 'ψD-letter')}

HEADER = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- {title}
--
-- Generated by Rules/w3/emit_levels.py; do not edit.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}
'''

def fin(k):
    return f'# {k}'

def letters_list(word):
    return ' ∷ '.join(AG[x] for x in word) + ' ∷ []' if word else '[]'

def fin_list(idx):
    return ' ∷ '.join(fin(k) for k in idx) + ' ∷ []' if idx else '[]'

def sp_lit(t):
    return ' ∷ '.join(f'({FIN[j]} , {"true" if s < 0 else "false"})' for (j, s) in t) + ' ∷ []'

def bool_list(bs):
    return ' ∷ '.join('true' if b else 'false' for b in bs) + ' ∷ []'

def psi_value(name, g):
    if name in ('z2',):
        return sp_lit(g)
    if name == 'aff':
        j0 = g[0][0]
        return sp_lit(tuple((j ^ j0, s) for (j, s) in g))
    if name == 's8':
        out = []
        for a in range(8):
            for b in range(a + 1, 8):
                for c in range(b + 1, 8):
                    for d in range(c + 1, 8):
                        out.append((g[a][0] ^ g[b][0] ^ g[c][0] ^ g[d][0]) == 0)
        return bool_list(out)
    if name == 'd8':
        return bool_list([s < 0 for (_, s) in g])

def emit_level(lev, below, rels_by_name):
    name, K = lev.name, NAMES[lev.name]
    tc = lev.tc
    letters = lev.letters
    lower = below.letters if below else []
    os.makedirs(f'{ROOT}/{K}', exist_ok=True)
    cl = sorted(Pp.closure(tc, Pp.roots(lev)))
    num = {f: k for k, f in enumerate(cl)}
    chunks = [cl[i:i + CHUNK] for i in range(0, len(cl), CHUNK)]
    where = {}
    for ci, ch in enumerate(chunks):
        for f in ch:
            where[f] = ci
    # Base
    iX = IOTA[name]
    if below:
        iB = IOTA[below.name]
        lowerdef = f'import {MOD}.{NAMES[below.name]} as Below\n\nopen import {MOD}.LevelKit {iX} {iB} Below.complete public\n'
    else:
        iB = 'ι0'
        lowerdef = f'''ι0 : Fin 0 → L
ι0 ()

private
  F0 : Word (Fin 0) → Word L
  F0 = (λ b → [ ι0 b ]ʷ) ʷ

  zero : ∀ l → F0 l ≈ ε
  zero [ () ]ʷ
  zero ε       = PB.refl
  zero (u • v) = PB.trans (PB.cong (zero u) (zero v)) PB.left-unit

  lower : ∀ (l m : Word (Fin 0)) → sp (F0 l) ≡ sp (F0 m) → F0 l ≈ F0 m
  lower l m _ = PB.trans (zero l) (PB.sym (zero m))

open import {MOD}.LevelKit {iX} ι0 lower public
'''
    base = HEADER.format(title=f'The {K} level of the three-wire tower: the kit.') + f'''
module {MOD}.{K}.Base where

open import Data.Fin.Base using (Fin)
open import Relation.Binary.PropositionalEquality using (_≡_)
open import Word.Base using (Word ; [_]ʷ ; ε ; _•_ ; _ʷ)
import Presentation.Base as PB
open import {MOD}.Pure
open import {MOD}.Invariants using (ιZ ; ιA ; ιS ; ιD)

{lowerdef}'''
    open(f'{ROOT}/{K}/Base.agda', 'w', encoding='utf-8').write(base)
    # Facts
    def eqn_of(kind, key, fwd):
        if kind == 'ax':
            e = f'rel⁼ {relname(tc.axioms[key].name)}'
        elif kind == 'inv':
            e = f'inv⁼ {AG[letters[key]]}'
        elif kind == 'fact':
            e = f'f{num[key]}'
        else:
            raise ValueError(kind)
        return e if fwd else f'sym⁼ ({e})'
    for ci, ch in enumerate(chunks):
        L = [HEADER.format(title=f'The {K} level of the three-wire tower: derivations, part {ci}.'),
             f'module {MOD}.{K}.Facts{ci} where\n',
             'open import Data.Fin using (#_)',
             'open import Data.List.Base using (List ; [] ; _∷_)',
             'open import Relation.Binary.PropositionalEquality using (refl)',
             f'open import {MOD}.Pure',
             f'open import {MOD}.{K}.Base using (normE)']
        for j in range(ci):
            L.append(f'open import {MOD}.{K}.Facts{j}')
        L.append('')
        for f in ch:
            fact = tc.facts[f]
            lhs = tuple(letters[x] for x in fact.lhs)
            rhs = tuple(letters[x] for x in fact.rhs)
            L.append(f'f{num[f]} : Eqn')
            st = fact.steps
            if len(st) == 1 and st[0][1][0] == 'norm':
                lab, nf = st[0][1][1]
                u = [lower.index(x) for x in lab]
                v = [lower.index(x) for x in nf]
                L.append(f'f{num[f]} = normE ({fin_list(u)}) ({fin_list(v)}) refl')
            else:
                steps = ' ∷ '.join(f'rw {pos} ({eqn_of(kind, key, fwd)})'
                                   for pos, (kind, key), fwd in st) + ' ∷ []' if st else '[]'
                L.append(f'f{num[f]} = derive ({letters_list(lhs)}) ({letters_list(rhs)})')
                L.append(f'  ({steps}) refl')
        open(f'{ROOT}/{K}/Facts{ci}.agda', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    # Table
    ck = len(lev.live)
    nX, nB = len(letters), len(lower)
    repL = [[letters.index(x) for x in r] for r in lev.reps]
    T = [HEADER.format(title=f'The {K} level of the three-wire tower: its table, and completeness.'),
         f'module {MOD}.{K} where\n',
         'open import Data.Bool.Base using (true ; false)',
         'open import Data.Fin.Base using (Fin)',
         'open import Data.Fin using (#_)',
         'open import Data.List.Base using (List ; [] ; _∷_)',
         'open import Data.Product.Base using (_×_ ; _,_)',
         'open import Data.Vec.Base using (Vec ; [] ; _∷_)',
         'open import Relation.Binary.PropositionalEquality using (refl)',
         'open import Notations using (₀ ; ₁ ; ₂ ; ₃ ; ₄ ; ₅ ; ₆ ; ₇)',
         f'open import {MOD}.Pure',
         f'open import {MOD}.Perm using (SP)',
         f'open import {MOD}.Invariants',
         f'open import {MOD}.{K}.Base']
    for ci in range(len(chunks)):
        T.append(f'open import {MOD}.{K}.Facts{ci}')
    T.append('')
    T.append(f'repL : Vec (List (Fin {nX})) {ck}')
    T.append('repL =')
    for r in repL:
        T.append(f'  ({fin_list(r)}) ∷')
    T.append('  []')
    T.append('')
    T.append(f'tab : Vec (Vec (List (Fin {nB}) × Fin {ck}) {nX}) {ck}')
    T.append('tab =')
    factnames = []
    for c in range(ck):
        row, frow = [], []
        for y in range(nX):
            lab, d, f = lev.table[(c, y)]
            u = [lower.index(x) for x in lab]
            row.append(f'(({fin_list(u)}) , {fin(d)})')
            frow.append(f'f{num[f]}')
        T.append('  (' + ' ∷ '.join(row) + ' ∷ []) ∷')
        factnames.append(frow)
    T.append('  []')
    T.append('')
    T.append(f'factT : Vec (Vec Eqn {nX}) {ck}')
    T.append('factT =')
    for frow in factnames:
        T.append('  (' + ' ∷ '.join(frow) + ' ∷ []) ∷')
    T.append('  []')
    T.append('')
    if PSI[name]:
        psi, psil = PSI[name]
        tty = {'aff': 'SP', 's8': 'List Bool', 'd8': 'Vec Bool 8'}[name]
        eqt = {'aff': 'eqSP', 's8': 'eqLB', 'd8': 'eqVB'}[name]
    else:
        psi, psil, tty, eqt = '(λ g → g)', '(λ { () _ })', 'SP', 'eqSP'
    T.append(f'cosets : List ({tty} × Fin {ck})')
    T.append('cosets =')
    for c in range(ck):
        T.append(f'  (({psi_value(name, lev.repsp[c])}) , {fin(c)}) ∷')
    T.append('  []')
    T.append('')
    T.append(f'open Table repL tab factT {psi} {psil} {eqt} cosets (# 0) refl')
    T.append('open Checked refl refl public using (complete)')
    if name == 's8':
        T[T.index('open import Data.Bool.Base using (true ; false)')] = 'open import Data.Bool.Base using (Bool ; true ; false)'
    if name == 'd8':
        T[T.index('open import Data.Bool.Base using (true ; false)')] = 'open import Data.Bool.Base using (Bool ; true ; false)'
    open(f'{ROOT}/{K}.agda', 'w', encoding='utf-8').write('\n'.join(T) + '\n')
    print(f'{K}: {len(cl)} facts in {len(chunks)} chunks, {ck} cosets', flush=True)

def main():
    rels, free, levels = Pp.build()
    below = None
    for lev in levels:
        emit_level(lev, below, None)
        below = lev

if __name__ == '__main__':
    main()
