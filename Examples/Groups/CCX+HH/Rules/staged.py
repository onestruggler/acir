#!/usr/bin/env python3
"""Staged rule search with derived letters, and exact completeness checks.

An alphabet is a list of letters: primitive gates of `core.GateSet`, or
derived letters defined as words in them (each an involution, e.g. the
reversed CNOT `CXr i = HH i CX i HH i`).  A rule set is a list of
relators in the alphabet.  `complete(...)` bounds the presented group by
a chain of coset enumerations

    |G_R| <= [G_R : K] · |K_R|,   |K_R| <= |P_K|,

where K is generated by a subset of the letters and P_K is presented by
the relators that use only those letters (they hold in G_R, so the
subgroup they generate there is a quotient of P_K).  When the bound
equals the true order, the rules are complete at that width.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import core as C
from search import canonical, free_reduce, reduced_words


class Alphabet:
    def __init__(self, gs: C.GateSet, derived: dict[str, str] | None = None):
        self.gs = gs
        self.letters = list(gs.names)
        self.expand: list[tuple[int, ...]] = [(k,) for k in range(len(gs.names))]
        self.wires = list(gs.wires)
        for name, text in (derived or {}).items():
            word = gs.word(text)
            self.letters.append(name)
            self.expand.append(word)
            self.wires.append(tuple(sorted({w for g in word for w in gs.wires[g]})))
        self.index = {n: k for k, n in enumerate(self.letters)}

    def word(self, text: str) -> tuple[int, ...]:
        return tuple(self.index[t] for t in text.split()) if text.strip() else ()

    def show(self, w) -> str:
        return " ".join(self.letters[g] for g in w) if w else "ε"

    def primitive(self, w) -> tuple[int, ...]:
        return tuple(g for x in w for g in self.expand[x])

    def definitions(self):
        n = len(self.gs.names)
        return [(k,) + tuple(reversed(self.expand[k])) for k in range(n, len(self.letters))]

    def structural(self, letters=None):
        letters = range(len(self.letters)) if letters is None else letters
        letters = list(letters)
        rels = [(g, g) for g in letters]
        for i, a in enumerate(letters):
            for b in letters[i + 1:]:
                if not set(self.wires[a]) & set(self.wires[b]):
                    rels.append((a, b, a, b))
        return rels


def rule(alpha: Alphabet, text: str) -> list[tuple[int, ...]]:
    """`lhs = rhs` (or a relator) at every placement, as relators."""
    if "=" in text:
        lhs, rhs = text.split("=")
        lw, rw = alpha.word(lhs), alpha.word(rhs)
        rel = lw + tuple(reversed(rw))
    else:
        rel = alpha.word(text)
    shifted = []
    for s in range(alpha.gs.n):
        try:
            shifted.append(tuple(alpha.index[shift(alpha.letters[g], s)] for g in rel))
        except KeyError:
            break
    return shifted


def shift(name: str, s: int) -> str:
    base, i = C.split_name(name)
    return f"{base}{i + s}"


def sound(rep: C.PermRep, alpha: Alphabet, rels) -> bool:
    return all(rep.is_identity(alpha.primitive(r)) for r in rels)


def relators(rep: C.PermRep, alpha: Alphabet, letters, half: int):
    """Cyclically reduced relators of length <= 2·half over the letters."""
    letters = list(letters)
    buckets: dict = {}
    for w in reduced_words(len(letters), half):
        word = tuple(letters[g] for g in w)
        buckets.setdefault(rep.evaluate(alpha.primitive(word)), []).append(word)
    found = set()
    for ws in buckets.values():
        for i, a in enumerate(ws):
            for b in ws[i + 1:]:
                c = canonical(free_reduce(a + tuple(reversed(b))))
                if c:
                    found.add(c)
    return sorted(found, key=lambda r: (len(r), r))


def index(alpha: Alphabet, rels, subgroup_letters=(), limit=500_000):
    return C.index(len(alpha.letters), list(rels) + alpha.definitions(),
                   [(g,) for g in subgroup_letters], limit)


def restricted_index(alpha: Alphabet, rels, letters, subgroup_letters=(), limit=500_000):
    """Index in P_K, presented by the relators using only `letters`."""
    letters = list(letters)
    pos = {g: k for k, g in enumerate(letters)}
    own = [tuple(pos[g] for g in r) for r in rels if all(g in pos for g in r)]
    sub = [(pos[g],) for g in subgroup_letters]
    if (Path(__file__).resolve().parent / "tc").exists():
        return C.index_c(len(letters), own, sub, limit)
    return C.index(len(letters), own, sub, limit)
