def fin(k):
    return f'# {k}'


def lst(xs):
    return '(' + ' ∷ '.join(list(xs) + ['[]']) + ')'


class Level:
    def __init__(self, k, letters, rels):
        self.k, self.letters, self.rels = k, letters, rels
        self.next = R.LEVELS[k + 1]
        self.loc = {g: i for i, g in enumerate(letters)}
        self.tc, self.live, _ = R.enumerate_level(k, rels)
        assert len(self.live) == R.want(k)
        self.cosets = {c: i for i, c in enumerate(self.live)}
        self.entries = {}
        for c in self.live:
            for y in range(len(letters)):
                d, lab, f = self.tc.final(c, y)
                self.entries[(self.cosets[c], y)] = (lab, self.cosets[d], f)
        self.derived = {}
        for e, j, lab, st in self.tc.derived(self.live):
            if len(lab) > R.MAXLAB:
                continue
            c = R.canonical(lab)
            if c and c not in self.derived:
                self.derived[c] = (e, j, lab, st)

    def name(self, y):
        """The L letter of a local index."""
        return AG[self.letters[y]]

    def relator_fact(self, word):
        """A fact `word ⟶ ε` for a relator of level k+1 (word in L letters,
        canonical), from the trace of a level-k relator that closes with it."""
        tc = self.tc
        e, j, lab, st = self.derived[word]
        rep = tc.rep[e]
        rel = tuple(tc.axioms[j].lhs)
        dl = tc.dec(lab)
        # dl -> dl rep rev(rep) -> rep rel rev(rep) -> rep rev(rep) -> ε
        steps = tc.insert(len(dl), rep)
        walk = tc._add(rep + rel, dl + rep, st)
        steps += [(0, ('fact', walk), False)]
        steps += [(len(rep), ('ax', j), True)]
        steps += tc.cancel(0, rep)
        f = tc._add(dl, (), steps)
        # free reduction, then rotation and reversal into the canonical word
        cur, f = self.reduce_fact(dl, f)
        loc = tuple(self.loc[g] for g in word)
        return self.rotate_to(cur, f, loc)

    def reduce_fact(self, w, f):
        """From a fact w ⟶ ε, one for its free (then cyclic) reduction."""
        tc = self.tc
        w = list(w)
        while True:
            i = next((i for i in range(len(w) - 1) if w[i] == w[i + 1]), None)
            if i is None:
                break
            y = w[i]
            v = w[:i] + w[i + 2:]
            # v -> v[:i] y y v[i:] = w -> ε
            st = tc.insert(i, (y,)) + [(0, ('fact', f), True)]
            f = tc._add(tuple(v), (), st)
            w = v
        while len(w) > 1 and w[0] == w[-1]:
            y = w[0]
            v = w[1:-1]
            # v -> y y v y y -> y (y v y) y = y w y ... use: v -> y y v = rev? keep simple:
            # v -> y y v -> y (y v y) y with y v y = w, -> y y -> ε
            st = tc.insert(0, (y,)) + tc.insert(len(v) + 2, (y,))
            st += [(1, ('fact', f), True), (0, ('inv', y), True)]
            f = tc._add(tuple(v), (), st)
            w = v
        return tuple(w), f

    def rotate_to(self, w, f, target):
        """From a fact w ⟶ ε, one for target, a rotation of w or of its reverse."""
        tc = self.tc
        n = len(w)
        for rv in (False, True):
            base, fb = w, f
            if rv:
                base = tuple(reversed(w))
                # rev(w) -> rev(w) w -> ε
                fb = tc._add(base, (), [(n, ('fact', f), False)] + tc.cancel(0, base))
            for i in range(n):
                a, b = base[:i], base[i:]
                if b + a == target:
                    if i == 0:
                        return fb
                    # b a -> rev(a) a b a -> rev(a) a -> ε
                    st = tc.insert(0, tuple(reversed(a))) + [(len(a), ('fact', fb), True)]
                    st += tc.cancel(0, tuple(reversed(a)))
                    return tc._add(target, (), st)
        raise ValueError('not a rotation')


REL0 = None


def eqn_of(lev, kind, key, fwd, num):
    global REL0
    if REL0 is None:
        REL0 = {r: j for j, r in enumerate(T.relators_tower())}
    if kind == 'ax':
        e = f'rel⁼ r{REL0[lev.rels[key]]}' if lev.k == 0 else f'd{lev.k}-{key}'
    elif kind == 'inv':
        e = f'inv⁼ {lev.name(key)}'
    elif kind == 'fact':
        e = f't{lev.k}-{num[key]}'
    else:
        raise ValueError(kind)
    return e if fwd else f'sym⁼ ({e})'


def closure(tc, roots):
    seen, stack = set(), list(roots)
    while stack:
        f = stack.pop()
        if f in seen:
            continue
        seen.add(f)
        for (_, (kind, key), _) in tc.facts[f].steps:
            if kind == 'fact':
                stack.append(key)
    return seen


def emit(levels):
    for idx, lev in enumerate(levels):
        k = lev.k
        tc = lev.tc
        nxt = levels[idx + 1] if idx + 1 < len(levels) else None
        relfacts = [lev.relator_fact(w) for w in nxt.rels] if nxt else []
        roots = [f for (_, _, f) in lev.entries.values()] + relfacts
        cl = sorted(closure(tc, roots))
        num = {f: i for i, f in enumerate(cl)}
        chunks = [cl[i:i + CHUNK] for i in range(0, len(cl), CHUNK)]
        (ROOT / f'T{k}').mkdir(parents=True, exist_ok=True)
        for ci, ch in enumerate(chunks):
            out = [HEADER.format(title=f'Level {k} of the four-wire classical tower: facts, part {ci}.'),
                   f'module {MOD}.T{k}.Facts{ci} where\n',
                   'open import Data.List.Base using (List ; [] ; _∷_)',
                   'open import Relation.Binary.PropositionalEquality using (refl)',
                   f'open import {MOD}.Pure']
            if k > 0:
                out.append(f'open import {MOD}.Rels{k}')
            for j in range(ci):
                out.append(f'open import {MOD}.T{k}.Facts{j}')
            out.append('')
            for f in ch:
                fact = tc.facts[f]
                out.append(f't{k}-{num[f]} : Eqn')
                lhs = ' ∷ '.join([lev.name(y) for y in fact.lhs] + ['[]'])
                rhs = ' ∷ '.join([lev.name(y) for y in fact.rhs] + ['[]'])
                steps = ' ∷ '.join([f'rw {pos} ({eqn_of(lev, kind, key, fwd, num)})'
                                    for pos, (kind, key), fwd in fact.steps] + ['[]'])
                out.append(f't{k}-{num[f]} = derive ({lhs}) ({rhs})\n  ({steps}) refl')
            (ROOT / f'T{k}' / f'Facts{ci}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
        # the next level's relators
        if nxt:
            out = [HEADER.format(title=f'Level {nxt.k} of the four-wire classical tower: its relators, '
                                       f'derived at level {k}.'),
                   f'module {MOD}.Rels{nxt.k} where\n',
                   f'open import {MOD}.Pure']
            out += [f'open import {MOD}.T{k}.Facts{ci}' for ci in range(len(chunks))]
            out.append('')
            for j, f in enumerate(relfacts):
                out.append(f'd{nxt.k}-{j} : Eqn')
                out.append(f'd{nxt.k}-{j} = t{k}-{num[f]}')
            (ROOT / f'Rels{nxt.k}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
        emit_level(lev, nxt, num, len(chunks))
        print(f'level {k}: {len(cl)} facts in {len(chunks)} chunks', flush=True)


def emit_level(lev, nxt, num, nchunks):
    k = lev.k
    nX, nB, ck = len(lev.letters), len(lev.next), len(lev.live)
    bpos = {g: i for i, g in enumerate(lev.next)}
    iX = f'ιX{k}'
    out = [HEADER.format(title=f'Level {k} of the four-wire classical tower: its table, and completeness.'),
           f'module {MOD}.L{k} where\n',
           'open import Data.Bool.Base using (Bool ; true ; false)',
           'open import Data.Fin.Base using (Fin)',
           'open import Data.Fin using (#_)',
           'open import Data.List.Base using (List ; [] ; _∷_)',
           'open import Data.Product.Base using (_×_ ; _,_)',
           'open import Data.Vec.Base using (Vec ; [] ; _∷_ ; lookup)',
           'open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)',
           'open import Word.Base using (Word ; [_]ʷ ; ε ; _•_ ; _ʷ)',
           'import Presentation.Base as PB',
           f'open import {MOD}.Pure',
           'open import Examples.Groups.CCX+HH.Natural.ThreeWire.Fin8 using (allFin ; allFin-sound ; eqF)']
    out += [f'open import {MOD}.T{k}.Facts{ci}' for ci in range(nchunks)]
    out.append('')
    out.append(f'{iX} : Fin {nX} → L')
    out.append(f'{iX} = lookup ({" ∷ ".join([AG[g] for g in lev.letters] + ["[]"])})')
    out.append('')
    if nxt:
        out.append(f'ιB{k} : Fin {nB} → L')
        out.append(f'ιB{k} = lookup ({" ∷ ".join([AG[g] for g in lev.next] + ["[]"])})')
        out.append('')
        out.append(f'import {MOD}.L{nxt.k} as Below')
        out.append(f'open import {MOD}.LevelKit {iX} ιB{k} Below.complete')
        p = T.CHAIN[k]
        out.append(f'open import {MOD}.Stab (# {p}) using (ψ ; fixes ; ψ-mul ; eqV)')
    else:
        out.append(f'ι0 : Fin 0 → L')
        out.append('ι0 ()')
        out.append('''
private
  F0 : Word (Fin 0) → Word L
  F0 = (λ b → [ ι0 b ]ʷ) ʷ

  zero′ : ∀ l → F0 l ≈ ε
  zero′ [ () ]ʷ
  zero′ ε       = PB.refl
  zero′ (u • v) = PB.trans (PB.cong (zero′ u) (zero′ v)) PB.left-unit

  lower : ∀ (l m : Word (Fin 0)) → sp (F0 l) ≡ sp (F0 m) → F0 l ≈ F0 m
  lower l m _ = PB.trans (zero′ l) (PB.sym (zero′ m))
''')
        out.append(f'open import {MOD}.LevelKit {iX} ι0 lower')
    out.append('')
    # representatives
    out.append(f'repL : Vec (List (Fin {nX})) {ck}')
    out.append('repL =')
    for c in lev.live:
        out.append('  ' + lst(fin(y) for y in lev.tc.rep[c]) + ' ∷')
    out.append('  []\n')
    out.append(f'tab : Vec (Vec (List (Fin {max(nB, 0)}) × Fin {ck}) {nX}) {ck}')
    out.append('tab =')
    for ci in range(ck):
        row = []
        for y in range(nX):
            lab, d, f = lev.entries[(ci, y)]
            row.append(f'({lst(fin(bpos[g]) for g in lab)} , # {d})')
        out.append('  (' + ' ∷ '.join(row + ['[]']) + ') ∷')
    out.append('  []\n')
    out.append(f'factT : Vec (Vec Eqn {nX}) {ck}')
    out.append('factT =')
    for ci in range(ck):
        row = [f't{k}-{num[lev.entries[(ci, y)][2]]}' for y in range(nX)]
        out.append('  (' + ' ∷ '.join(row + ['[]']) + ') ∷')
    out.append('  []\n')
    if nxt:
        p = T.CHAIN[k]
        out.append(f'ψ-letter : ∀ b g → ψ (mul (spL (ιB{k} b)) g) ≡ ψ g')
        out.append(f'ψ-letter b = ψ-mul (ιB{k} b) (allFin-sound {nB} (λ b → fixes (ιB{k} b)) refl b)')
        out.append('')
        out.append(f'cosets : List (Vec Bool 16 × Fin {ck})')
        out.append('cosets =')
        for ci, c in enumerate(lev.live):
            g = R_sp([lev.letters[y] for y in lev.tc.rep[c]])
            bits = ['true' if g[x] == p else 'false' for x in range(16)]
            out.append(f'  ({lst(bits)} , # {ci}) ∷')
        out.append('  []\n')
        out.append(f'open Table repL tab factT ψ ψ-letter eqV cosets (# 0) refl')
    else:
        out.append('''eqP : P → P → Bool
eqP u v = allFin 16 (λ i → eqF (lookup u i) (lookup v i))
''')
        out.append(f'cosets : List (P × Fin {ck})')
        out.append('cosets =')
        for ci, c in enumerate(lev.live):
            g = R_sp([lev.letters[y] for y in lev.tc.rep[c]])
            out.append(f'  ({lst(fin(x) for x in g)} , # {ci}) ∷')
        out.append('  []\n')
        out.append('open Table repL tab factT (λ g → g) (λ ()) eqP cosets (# 0) refl')
    out.append('open Checked refl refl public using (complete)')
    (ROOT / f'L{k}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')


def R_sp(word):
    p = tuple(range(16))
    for g in reversed(word):
        q = T.PERMS[g]
        p = tuple(q[x] for x in p)
    return p


def main():
    data = pickle.load(open(HERE / 'rs4.pkl', 'rb'))
    levels = [Level(k, letters, rels) for k, letters, rels in data]
    emit(levels)


if __name__ == '__main__':
    main()
