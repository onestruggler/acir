#!/usr/bin/env python3
"""Write the four-wire classical tower of `pipe4.py` as Agda, under
NaturalP/FourWire/Classical/:

    Extras.agda          the extra relators (ext4.txt), each derived from
                         level 0's relators by a local enumeration
                         (local4.py)
    L<k>/Base.agda       LevelKit applied to the level below
    L<k>/Facts<i>.agda   level k's derivations, CHUNK at a time
    L<k>.agda            level k's table, coset invariant and `complete`

    python3 -B emit_pipe4.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import tower4 as T
import pipe4 as Pp
import local4 as LO
from emit_gamma4 import AG

ROOT = HERE.parents[1] / 'NaturalP' / 'FourWire' / 'Classical'
MOD = 'Examples.Groups.CCX+HH.NaturalP.FourWire.Classical'
CHUNK = 400
REL0 = {r: j for j, r in enumerate(T.relators_tower())}

HEADER = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- {title}
--
-- Generated by Rules/w4/emit_pipe4.py; do not edit.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}
'''


def fin(k):
    return f'# {k}'


def lst(xs):
    xs = list(xs)
    return '[]' if not xs else ' ∷ '.join(xs + ['[]'])


def closure(tc, roots):
    seen, stack = set(), list(roots)
    while stack:
        f = stack.pop()
        if f in seen:
            continue
        seen.add(f)
        for (_, (kind, key), _) in tc.facts[f].steps:
            if kind == 'fact':
                stack.append(key)
    return seen


# ---------------------------------------------------------------------
# Extras

def emit_extras(extras):
    out = [HEADER.format(title='The extra relators of the four-wire classical tower, each derived '
                               'from level 0 by a local enumeration.'),
           f'module {MOD}.Extras where\n',
           'open import Data.List.Base using (List ; [] ; _∷_)',
           'open import Relation.Binary.PropositionalEquality using (refl)',
           f'open import {MOD}.Pure', '']
    for j, (nm, word) in enumerate(extras):
        res = LO.derive(word)
        assert res is not None, nm
        A, tc, f0 = res
        cl = sorted(closure(tc, [f0]))
        num = {f: i for i, f in enumerate(cl)}
        def eqn(kind, key, fwd):
            if kind == 'ax':
                e = f'rel⁼ r{int(tc.axioms[key].name[1:])}'
            elif kind == 'inv':
                e = f'inv⁼ {AG[A[key]]}'
            else:
                e = f'{nm}-{num[key]}'
            return e if fwd else f'sym⁼ ({e})'
        for f in cl:
            fact = tc.facts[f]
            out.append(f'{nm}-{num[f]} : Eqn')
            steps = lst(f'rw {p} ({eqn(k, key, fw)})' for p, (k, key), fw in fact.steps)
            out.append(f'{nm}-{num[f]} = derive ({lst(AG[A[y]] for y in fact.lhs)}) '
                       f'({lst(AG[A[y]] for y in fact.rhs)})\n  ({steps}) refl')
        out.append(f'{nm} : Eqn')
        out.append(f'{nm} = {nm}-{num[f0]}\n')
        print(f'  extra {nm}: alphabet of {len(A)}, {len(cl)} facts', flush=True)
    (ROOT / 'Extras.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')


# ---------------------------------------------------------------------
# Levels

def emit_level(lev, below):
    k = lev.k
    K = f'L{k}'
    tc = lev.tc
    letters = lev.letters
    lower = below.letters if below else []
    nX, nB, ck = len(letters), len(lower), len(lev.live)
    (ROOT / K).mkdir(parents=True, exist_ok=True)
    # Base
    base = [HEADER.format(title=f'Level {k} of the four-wire classical tower: the kit.'),
            f'module {MOD}.{K}.Base where\n',
            'open import Data.Fin.Base using (Fin)',
            'open import Data.Vec.Base using (_∷_ ; [] ; lookup)',
            'open import Relation.Binary.PropositionalEquality using (_≡_)',
            'open import Word.Base using (Word ; [_]ʷ ; ε ; _•_ ; _ʷ)',
            'import Presentation.Base as PB',
            f'open import {MOD}.Pure', '',
            f'ιX : Fin {nX} → L',
            f'ιX = lookup ({lst(AG[g] for g in letters)})', '']
    if below:
        base += [f'ιB : Fin {nB} → L',
                 f'ιB = lookup ({lst(AG[g] for g in lower)})', '',
                 f'import {MOD}.L{below.k} as Below', '',
                 f'open import {MOD}.LevelKit ιX ιB Below.complete public']
    else:
        base += ['ιB : Fin 0 → L', 'ιB ()', '',
                 'private',
                 '  F0 : Word (Fin 0) → Word L',
                 '  F0 = (λ b → [ ιB b ]ʷ) ʷ', '',
                 '  zero′ : ∀ l → F0 l ≈ ε',
                 '  zero′ [ () ]ʷ',
                 '  zero′ ε       = PB.refl',
                 '  zero′ (u • v) = PB.trans (PB.cong (zero′ u) (zero′ v)) PB.left-unit', '',
                 '  lower : ∀ (l m : Word (Fin 0)) → sp (F0 l) ≡ sp (F0 m) → F0 l ≈ F0 m',
                 '  lower l m _ = PB.trans (zero′ l) (PB.sym (zero′ m))', '',
                 f'open import {MOD}.LevelKit ιX ιB lower public']
    (ROOT / K / 'Base.agda').write_text('\n'.join(base) + '\n', encoding='utf-8')
    # Facts
    roots = [f for (_, _, f) in lev.table.values()]
    cl = sorted(closure(tc, roots))
    num = {f: i for i, f in enumerate(cl)}
    chunks = [cl[i:i + CHUNK] for i in range(0, len(cl), CHUNK)]
    def eqn(kind, key, fwd):
        if kind == 'ax':
            nm = tc.axioms[key].name
            e = f'rel⁼ {nm}' if nm.startswith('r') else nm
        elif kind == 'inv':
            e = f'inv⁼ {AG[letters[key]]}'
        elif kind == 'fact':
            e = f'f{num[key]}'
        else:
            raise ValueError(kind)
        return e if fwd else f'sym⁼ ({e})'
    for ci, ch in enumerate(chunks):
        out = [HEADER.format(title=f'Level {k} of the four-wire classical tower: derivations, part {ci}.'),
               f'module {MOD}.{K}.Facts{ci} where\n',
               'open import Data.Fin using (#_)',
               'open import Data.List.Base using (List ; [] ; _∷_)',
               'open import Relation.Binary.PropositionalEquality using (refl)',
               f'open import {MOD}.Pure',
               f'open import {MOD}.Extras',
               f'open import {MOD}.{K}.Base using (normE)']
        out += [f'open import {MOD}.{K}.Facts{j}' for j in range(ci)]
        out.append('')
        for f in ch:
            fact = tc.facts[f]
            st = fact.steps
            out.append(f'f{num[f]} : Eqn')
            if len(st) == 1 and st[0][1][0] == 'norm':
                lab, nf = st[0][1][1]
                u = [fin(lower.index(x)) for x in lab]
                v = [fin(lower.index(x)) for x in nf]
                out.append(f'f{num[f]} = normE ({lst(u)}) ({lst(v)}) refl')
            else:
                steps = lst(f'rw {p} ({eqn(kk, key, fw)})' for p, (kk, key), fw in st)
                out.append(f'f{num[f]} = derive ({lst(AG[letters[y]] for y in fact.lhs)}) '
                           f'({lst(AG[letters[y]] for y in fact.rhs)})\n  ({steps}) refl')
        (ROOT / K / f'Facts{ci}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    # Table
    out = [HEADER.format(title=f'Level {k} of the four-wire classical tower: its table, and completeness.'),
           f'module {MOD}.{K} where\n',
           'open import Data.Bool.Base using (Bool ; true ; false)',
           'open import Data.Fin.Base using (Fin)',
           'open import Data.Fin using (#_)',
           'open import Data.List.Base using (List ; [] ; _∷_)',
           'open import Data.Product.Base using (_×_ ; _,_)',
           'open import Data.Vec.Base using (Vec ; [] ; _∷_ ; lookup)',
           'open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)',
           f'open import {MOD}.Pure',
           'open import Examples.Groups.CCX+HH.Natural.ThreeWire.Fin8 using (allFin ; allFin-sound ; eqF)',
           f'open import {MOD}.{K}.Base']
    out += [f'open import {MOD}.{K}.Facts{ci}' for ci in range(len(chunks))]
    out.append('')
    out.append(f'repL : Vec (List (Fin {nX})) {ck}')
    out.append('repL =')
    for c in range(ck):
        out.append(f'  ({lst(fin(letters.index(x)) for x in lev.reps[c])}) ∷')
    out.append('  []\n')
    out.append(f'tab : Vec (Vec (List (Fin {nB}) × Fin {ck}) {nX}) {ck}')
    out.append('tab =')
    frows = []
    for c in range(ck):
        row, frow = [], []
        for y in range(nX):
            lab, d, f = lev.table[(c, y)]
            row.append(f'(({lst(fin(lower.index(x)) for x in lab)}) , {fin(d)})')
            frow.append(f'f{num[f]}')
        out.append('  (' + ' ∷ '.join(row) + ' ∷ []) ∷')
        frows.append(frow)
    out.append('  []\n')
    out.append(f'factT : Vec (Vec Eqn {nX}) {ck}')
    out.append('factT =')
    for frow in frows:
        out.append('  (' + ' ∷ '.join(frow) + ' ∷ []) ∷')
    out.append('  []\n')
    if below:
        p = T.CHAIN[k]
        out.append(f'open import {MOD}.Stab (# {p}) using (ψ ; fixes ; ψ-mul ; eqV)\n')
        out.append(f'ψ-letter : ∀ b g → ψ (mul (spL (ιB b)) g) ≡ ψ g')
        out.append(f'ψ-letter b = ψ-mul (ιB b) (allFin-sound {nB} (λ b → fixes (ιB b)) refl b)\n')
        out.append(f'cosets : List (Vec Bool 16 × Fin {ck})')
        out.append('cosets =')
        for c in range(ck):
            g = lev.repsp[c]
            out.append(f'  (({lst("true" if g[x] == p else "false" for x in range(16))}) , {fin(c)}) ∷')
        out.append('  []\n')
        out.append(f'open Table repL tab factT ψ ψ-letter eqV cosets (# 0) refl')
    else:
        out.append('eqP : P → P → Bool')
        out.append('eqP u v = allFin 16 (λ i → eqF (lookup u i) (lookup v i))\n')
        out.append(f'cosets : List (P × Fin {ck})')
        out.append('cosets =')
        for c in range(ck):
            out.append(f'  (({lst(fin(x) for x in lev.repsp[c])}) , {fin(c)}) ∷')
        out.append('  []\n')
        out.append('open Table repL tab factT (λ g → g) (λ ()) eqP cosets (# 0) refl')
    out.append('open Checked refl refl public using (complete)')
    (ROOT / f'{K}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'level {k}: {len(cl)} facts in {len(chunks)} chunks, {ck} cosets', flush=True)


def main():
    rels, levels = Pp.build()
    extras = [(nm, r) for nm, r in rels if nm.startswith('e')]
    emit_extras(extras)
    below = None
    for lev in levels:              # bottom up
        emit_level(lev, below)
        below = lev


if __name__ == '__main__':
    main()
