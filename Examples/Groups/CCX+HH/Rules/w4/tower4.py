#!/usr/bin/env python3
"""Four wires, classical: a tower of point stabilisers with small indices.

    python3 -B tower4.py

The letters are the placed classical gates: X t, CX c>t, CCX t;ab, SW ab
(34 in all), acting on the 16 basis states.  The relators are the
natural classical rules (`../classical3.py`, the Toffoli-CNOT commutator
of `../natural3.py`, the four-wire rules of `check4.py`) at every
placement of their wires, the structural rules (involutions, disjoint
commutations) and the naturality of the swaps.

For a chain of basis states p1, p2, ..., H_k is generated by the letters
fixing p1 ... pk.  For each k this prints |H_k|, the orbit of p_(k+1)
under H_k (the index of H_(k+1) when H_(k+1) is the whole stabiliser),
and the index of H_(k+1) found by coset enumeration in the group that
H_k's letters present with the relators among them alone.  Where the
two agree, H_k's own relators present it, given H_(k+1)'s."""
import sys
import itertools
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import core as C
import ss
from classical3 import CLASSICAL_RULES
from natural3 import TOFFOLI_CNOT
from check4 import FOUR

N = 4
D = 1 << N

# Fixing these points one at a time, the letters that fix them generate
# the whole pointwise stabiliser in A16 at every step, down to A7.
CHAIN = [0, 1, 2, 4, 8, 3, 5, 10, 12]


def norm(g):
    k = g[0]
    if k == 'CCX':
        _, t, a, b = g
        return ('CCX', t, min(a, b), max(a, b))
    if k == 'SW':
        _, a, b = g
        return ('SW', min(a, b), max(a, b))
    return g


LETTERS = [('X', t) for t in range(N)]
LETTERS += [('CX', c, t) for c in range(N) for t in range(N) if c != t]
LETTERS += [('CCX', t, a, b) for t in range(N) for a in range(N) for b in range(a + 1, N) if t not in (a, b)]
LETTERS += [('SW', a, b) for a in range(N) for b in range(a + 1, N)]
INDEX = {g: k for k, g in enumerate(LETTERS)}


def wires(g):
    return set(g[1:])


def perm(g):
    k = g[0]
    def f(x):
        if k == 'X':
            return x ^ (1 << g[1])
        if k == 'CX':
            _, c, t = g
            return x ^ (1 << t) if x >> c & 1 else x
        if k == 'CCX':
            _, t, a, b = g
            return x ^ (1 << t) if (x >> a & 1) and (x >> b & 1) else x
        _, a, b = g
        return x ^ (1 << a) ^ (1 << b) if (x >> a & 1) != (x >> b & 1) else x
    return tuple(f(x) for x in range(D))


PERMS = [perm(g) for g in LETTERS]


def adjacent(name):
    """A letter of the adjacent alphabet, on wires 0 1 2 3."""
    base = name.rstrip('0123456789')
    i = int(name[len(base):])
    return {'X': ('X', i), 'CX': ('CX', i + 1, i), 'CXr': ('CX', i, i + 1),
            'SW': ('SW', i, i + 1), 'CCX': ('CCX', i, i + 1, i + 2)}[base]


def placed(text):
    """Every placement of a rule `lhs = rhs` (or a relator) as relators."""
    if '=' in text:
        l, r = text.split('=')
        word = [adjacent(x) for x in l.split()] + [adjacent(x) for x in reversed(r.split())]
    else:
        word = [adjacent(x) for x in text.split()]
    used = sorted({w for g in word for w in g[1:]})
    out = set()
    for img in itertools.permutations(range(N), len(used)):
        f = dict(zip(used, img))
        w = tuple(INDEX[norm((g[0],) + tuple(f[x] for x in g[1:]))] for g in word)
        out.add(w)
    return out


def relators():
    rels = set()
    for t in CLASSICAL_RULES + [TOFFOLI_CNOT['commutator']] + FOUR:
        rels |= placed(t)
    n = len(LETTERS)
    for g in range(n):
        rels.add((g, g))
        for h in range(g + 1, n):
            if not wires(LETTERS[g]) & wires(LETTERS[h]):
                rels.add((g, h, g, h))
    # naturality of the swaps: SW ab · g · SW ab = g with a and b exchanged
    for s in [g for g in LETTERS if g[0] == 'SW']:
        _, a, b = s
        tr = {a: b, b: a}
        for g in LETTERS:
            h = norm((g[0],) + tuple(tr.get(x, x) for x in g[1:]))
            rels.add((INDEX[s], INDEX[g], INDEX[s], INDEX[h]))
    return sorted(rels, key=lambda r: (len(r), r))


def is_identity(word):
    p = tuple(range(D))
    for g in word:
        q = PERMS[g]
        p = tuple(q[x] for x in p)
    return p == tuple(range(D))


def main():
    rels = relators()
    bad = [r for r in rels if not is_identity(r)]
    assert not bad, [[LETTERS[g] for g in r] for r in bad[:3]]
    print(len(LETTERS), 'letters,', len(rels), 'relators', flush=True)
    chain = CHAIN
    lim = int(sys.argv[1]) if len(sys.argv) > 1 else 5_000_000
    for k in range(len(chain)):
        fixed = chain[:k]
        lets = [g for g in range(len(LETTERS)) if all(PERMS[g][p] == p for p in fixed)]
        nxt = [g for g in lets if PERMS[g][chain[k]] == chain[k]]
        order = ss.order([PERMS[g] for g in lets])
        sub = ss.order([PERMS[g] for g in nxt]) if nxt else 1
        orb = {chain[k]}
        fr = [chain[k]]
        while fr:
            fr = [PERMS[g][x] for x in fr for g in lets if PERMS[g][x] not in orb and not orb.add(PERMS[g][x])]
        pos = {g: i for i, g in enumerate(lets)}
        own = [tuple(pos[g] for g in r) for r in rels if all(g in pos for g in r)]
        idx = C.index_c(len(lets), own, [(pos[g],) for g in nxt], lim)
        print(f'k={k:2d} fix {fixed}: {len(lets):2d} letters, |H|={order}, '
              f'orbit of {chain[k]}: {len(orb)}, [H:H_next] by orders {order // sub}, '
              f'enumerated {idx}, {len(own)} own relators', flush=True)


if __name__ == '__main__':
    main()
