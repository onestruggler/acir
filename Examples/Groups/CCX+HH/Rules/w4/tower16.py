#!/usr/bin/env python3
"""The tower for A16 with the S7 bottom, and its extra relators.

    python3 -B tower16.py [half] [--extend]

Levels: 0 … 7 fix the points 0, 1, 2, 4, 8, 3, 5 in turn (the letters
fixing them generate the whole pointwise stabiliser, down to A9);
level 8 is generated by level 7's letters preserving the pair {6, 7}
(the whole setwise stabiliser, S7, acting on 9 … 15).  Inside S7 the
chain goes on by subgroups generated by letters, each the stabiliser
of its orbit colouring (SUB): orders 144, 36 and 4 (indices 35, 4, 9),
and the bottom is the last over the trivial group (4 cosets).  (A chain
by points, S6 and S5, needs relators longer than twelve letters.)  Each level's relators are those of the base
(tower4.relators_tower() and the affine extras of aff4extra.txt) among
its letters, the extras chosen below it, and new extras: true relators
w1 · rev(w2), words of at most `half` letters, shortest first, thinned,
until coset enumeration of the next level closes at the true index.
Writes tower16extra.txt (level, relator)."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import core as C
import ss
import tower4 as T
import ext4 as X

POINTS = [0, 1, 2, 4, 8, 3, 5]
PAIR = (6, 7)
# inside S7: the subgroups these letters generate, each the stabiliser
# of its orbit colouring of the sixteen levels (indices 35, 4, 9, 4)
SUB_LETTERS = [['CCX0;12', 'CCX0;13', 'CCX0;23', 'CCX1;03'],
               ['CCX0;12', 'CCX0;13', 'CCX1;03'],
               ['CCX0;12', 'CCX0;13']]


def orbits(gens):
    """The orbit colouring: each level coloured by the least level of its orbit."""
    col = list(range(T.D))
    changed = True
    while changed:
        changed = False
        for g in gens:
            p = T.PERMS[g]
            for x in range(T.D):
                a, b = col[x], col[p[x]]
                if a != b:
                    m = min(a, b)
                    col = [m if c in (a, b) else c for c in col]
                    changed = True
    return tuple(col)


SUB = [('colour', orbits([T.INDEX_N[x] for x in ls])) for ls in SUB_LETTERS]


def keeps(g, kind):
    p = T.PERMS[g]
    if kind[0] == 'point':
        return p[kind[1]] == kind[1]
    if kind[0] == 'pair':
        return {p[kind[1]], p[kind[2]]} == {kind[1], kind[2]}
    col = kind[1]
    return all(col[p[x]] == col[x] for x in range(T.D))


def kinds():
    """The kind of each level but the bottom: which subgroup is next."""
    return [('point', p) for p in POINTS] + [('pair',) + PAIR] + SUB


def levels():
    lv = [list(range(len(T.LETTERS)))]
    for kind in kinds():
        lv.append([g for g in lv[-1] if keeps(g, kind)])
    lv.append([])
    return lv


def base():
    rels = list(T.relators_tower())
    path = HERE / 'aff4extra.txt'
    for line in path.read_text().splitlines():
        if line.strip():
            rels.append(tuple(T.INDEX_N[x] for x in line.split()))
    return rels


def index(lets, rels, sub, want):
    pos = {g: i for i, g in enumerate(lets)}
    own = [tuple(pos[g] for g in r) for r in rels if all(g in pos for g in r)]
    return C.index_c(len(lets), own, [(pos[g],) for g in sub], max(20_000, 50 * want))


def thin(lets, rels, cand, sub, want):
    cand = sorted(cand, key=lambda r: (len(r), r))
    lo, hi = 0, len(cand)
    while lo < hi:
        mid = (lo + hi) // 2
        if index(lets, rels + cand[:mid], sub, want) == want:
            hi = mid
        else:
            lo = mid + 1
    keep = sorted(cand[:lo], key=lambda r: (-len(r), r))
    size = max(1, len(keep) // 2)
    while True:
        i = 0
        while i < len(keep):
            trial = keep[:i] + keep[i + size:]
            if trial != keep and index(lets, rels + trial, sub, want) == want:
                keep = trial
            else:
                i += size
        if size == 1:
            break
        size = max(1, size // 2)
    return keep


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    half = int(args[0]) if args else 5
    rels = base()
    lv = levels()
    extras = []
    if '--extend' in sys.argv:
        # keep the extras found so far, under their names; add new ones
        for line in (HERE / 'tower16extra.txt').read_text().splitlines():
            ws = line.split()
            if ws:
                extras.append((int(ws[0]), tuple(T.INDEX_N[x] for x in ws[1:])))
    for k in range(len(lv) - 2, -1, -1):
        lets, nxt = lv[k], lv[k + 1]
        want = ss.order([T.PERMS[g] for g in lets]) // (ss.order([T.PERMS[g] for g in nxt]) if nxt else 1)
        if index(lets, rels + [r for _, r in extras], nxt, want) == want:
            print(f'level {k}: {len(lets)} letters, index {want}, closes', flush=True)
            continue
        for h in range(2, half + 1):
            cand = [r for r in X.candidates(lets, h) if r not in set(rels)]
            ok = index(lets, rels + [r for _, r in extras] + cand, nxt, want) == want
            print(f'level {k}: {len(lets)} letters, index {want}; {len(cand)} candidates '
                  f'(words <= {h}) {"close" if ok else "do not close"}', flush=True)
            if ok:
                break
        else:
            print('  not enough; raise half')
            return
        keep = thin(lets, rels + [r for _, r in extras], cand, nxt, want)
        print(f'  kept {len(keep)}:', ['·'.join(T.NAME[g] for g in r) for r in keep], flush=True)
        extras += [(k, r) for r in keep]
    (HERE / 'tower16extra.txt').write_text(''.join(f'{k} ' + ' '.join(T.NAME[g] for g in r) + '\n'
                                                   for k, r in extras))
    print(len(extras), 'extras in all')


if __name__ == '__main__':
    main()
