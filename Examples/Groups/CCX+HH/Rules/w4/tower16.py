#!/usr/bin/env python3
"""The tower for A16 with the S7 bottom, and its extra relators.

    python3 -B tower16.py [half]

Levels: 0 … 7 fix the points 0, 1, 2, 4, 8, 3, 5 in turn (the letters
fixing them generate the whole pointwise stabiliser, down to A9);
level 8 is generated by level 7's letters preserving the pair {6, 7}
(the whole setwise stabiliser, S7); the bottom is level 8 over the
trivial group.  Each level's relators are those of the base
(tower4.relators_tower() and the affine extras of aff4extra.txt) among
its letters, the extras chosen below it, and new extras: true relators
w1 · rev(w2), words of at most `half` letters, shortest first, thinned,
until coset enumeration of the next level closes at the true index.
Writes tower16extra.txt (level, relator)."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import core as C
import ss
import tower4 as T
import ext4 as X

POINTS = [0, 1, 2, 4, 8, 3, 5]
PAIR = (6, 7)


def levels():
    lv = [[g for g in range(len(T.LETTERS)) if all(T.PERMS[g][p] == p for p in POINTS[:k])]
          for k in range(len(POINTS) + 1)]
    lv.append([g for g in lv[-1] if {T.PERMS[g][PAIR[0]], T.PERMS[g][PAIR[1]]} == set(PAIR)])
    lv.append([])
    return lv


def base():
    rels = list(T.relators_tower())
    path = HERE / 'aff4extra.txt'
    for line in path.read_text().splitlines():
        if line.strip():
            rels.append(tuple(T.INDEX_N[x] for x in line.split()))
    return rels


def index(lets, rels, sub, want):
    pos = {g: i for i, g in enumerate(lets)}
    own = [tuple(pos[g] for g in r) for r in rels if all(g in pos for g in r)]
    return C.index_c(len(lets), own, [(pos[g],) for g in sub], max(20_000, 50 * want))


def thin(lets, rels, cand, sub, want):
    cand = sorted(cand, key=lambda r: (len(r), r))
    lo, hi = 0, len(cand)
    while lo < hi:
        mid = (lo + hi) // 2
        if index(lets, rels + cand[:mid], sub, want) == want:
            hi = mid
        else:
            lo = mid + 1
    keep = sorted(cand[:lo], key=lambda r: (-len(r), r))
    size = max(1, len(keep) // 2)
    while True:
        i = 0
        while i < len(keep):
            trial = keep[:i] + keep[i + size:]
            if trial != keep and index(lets, rels + trial, sub, want) == want:
                keep = trial
            else:
                i += size
        if size == 1:
            break
        size = max(1, size // 2)
    return keep


def main():
    half = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    rels = base()
    lv = levels()
    extras = []
    for k in range(len(lv) - 2, -1, -1):
        lets, nxt = lv[k], lv[k + 1]
        want = ss.order([T.PERMS[g] for g in lets]) // (ss.order([T.PERMS[g] for g in nxt]) if nxt else 1)
        if index(lets, rels + [r for _, r in extras], nxt, want) == want:
            print(f'level {k}: {len(lets)} letters, index {want}, closes', flush=True)
            continue
        for h in range(2, half + 1):
            cand = [r for r in X.candidates(lets, h) if r not in set(rels)]
            ok = index(lets, rels + [r for _, r in extras] + cand, nxt, want) == want
            print(f'level {k}: {len(lets)} letters, index {want}; {len(cand)} candidates '
                  f'(words <= {h}) {"close" if ok else "do not close"}', flush=True)
            if ok:
                break
        else:
            print('  not enough; raise half')
            return
        keep = thin(lets, rels + [r for _, r in extras], cand, nxt, want)
        print(f'  kept {len(keep)}:', ['·'.join(T.NAME[g] for g in r) for r in keep], flush=True)
        extras += [(k, r) for r in keep]
    (HERE / 'tower16extra.txt').write_text(''.join(f'{k} ' + ' '.join(T.NAME[g] for g in r) + '\n'
                                                   for k, r in extras))
    print(len(extras), 'extras in all')


if __name__ == '__main__':
    main()
