#!/usr/bin/env python3
"""The affine tower on four wires: AGL(4, 2) by point stabilisers, and
the affine relators it needs beyond the tower's level 0.

    python3 -B aff4.py

Levels fix 0, e0, e1, e2 in turn (AGL > GL > … > the translations
along e3 > 1); level k is generated by the affine letters fixing the
points so far.  Bottom up, each level gets the relators of
tower4.relators_tower() among its letters, the extra affine relators
chosen below it, and new ones (true relators w1 · rev(w2), words of at
most three letters, shortest first, thinned) until coset enumeration of
the next level closes at the true index.  The extra relators, each an
identity of affine circuits that NaturalP derives by affine
completeness (NaturalP/AffineComplete), are written to aff4extra.txt.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import core as C
import ss
import tower4 as T
import ext4 as X

CHAIN = [0, 1, 2, 4, 8]
AFF = [g for g in range(len(T.LETTERS)) if T.LETTERS[g][0] != 'CCX']


def levels():
    return [[g for g in AFF if all(T.PERMS[g][p] == p for p in CHAIN[:k])] for k in range(len(CHAIN))] + [[]]


def index(lets, rels, sub, want):
    pos = {g: i for i, g in enumerate(lets)}
    own = [tuple(pos[g] for g in r) for r in rels if all(g in pos for g in r)]
    return C.index_c(len(lets), own, [(pos[g],) for g in sub], max(20_000, 50 * want))


def main():
    base = T.relators_tower()
    lv = levels()
    extras = []
    for k in range(len(lv) - 2, -1, -1):
        lets, nxt = lv[k], lv[k + 1]
        want = ss.order([T.PERMS[g] for g in lets]) // (ss.order([T.PERMS[g] for g in nxt]) if nxt else 1)
        if index(lets, base + extras, nxt, want) == want:
            print(f'level {k}: {len(lets)} letters, index {want}, closes', flush=True)
            continue
        cand = [r for r in X.candidates(lets, 3) if r not in set(base)]
        cand.sort(key=lambda r: (len(r), r))
        assert index(lets, base + extras + cand, nxt, want) == want, k
        lo, hi = 0, len(cand)
        while lo < hi:
            mid = (lo + hi) // 2
            if index(lets, base + extras + cand[:mid], nxt, want) == want:
                hi = mid
            else:
                lo = mid + 1
        keep = cand[:lo]
        for r in sorted(keep, key=lambda r: -len(r)):
            trial = [x for x in keep if x != r]
            if index(lets, base + extras + trial, nxt, want) == want:
                keep = trial
        print(f'level {k}: {len(lets)} letters, index {want}, {len(keep)} extra:',
              ['·'.join(T.NAME[g] for g in r) for r in keep], flush=True)
        extras += keep
    (HERE / 'aff4extra.txt').write_text(''.join(' '.join(T.NAME[g] for g in r) + '\n' for r in extras))
    print(len(extras), 'affine extras')


if __name__ == '__main__':
    main()
