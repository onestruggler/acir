#!/usr/bin/env python3
"""Four wires, classical: the point-stabiliser tower by Reidemeister–
Schreier, every relator of every level derived.

    python3 -B rs4.py

Level 0 is A16 on the 34 placed letters with the relators of
`tower4.py` (the natural classical rules at every placement, and the
structural rules).  Level k+1 is generated by the letters fixing one
more point of tower4.CHAIN.  A plain labelled coset enumeration of level
k (`../labelled.py`, macros the letters of level k+1) traces every
relator of level k from every coset; each closes with a label, a word in
level k+1's letters equal to the identity with a derivation from level
k's relators.  These are level k+1's candidate relators; a subset that
still closes the enumeration of level k+2 (or, at the bottom, of the
trivial group) at the true index is kept, greedily.  So every relator
used anywhere is derived from the rules.

Prints, per level, the cosets, the candidate and kept relators, and the
facts their derivations need."""
import sys
import time
import pickle
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import core as C
import labelled as LB
import proofs as PR
import ss
import tower4 as T

LIM = 2_000_000


def level_letters():
    return [[g for g in range(len(T.LETTERS)) if all(T.PERMS[g][p] == p for p in T.CHAIN[:k])]
            for k in range(len(T.CHAIN) + 1)] + [[]]


def index(lets, rels, sub, want=None):
    pos = {g: i for i, g in enumerate(lets)}
    own = [tuple(pos[g] for g in r) for r in rels]
    lim = LIM if want is None else max(20_000, 50 * want)
    return C.index_c(len(lets), own, [(pos[g],) for g in sub], lim)


def reduce(w):
    out = []
    for g in w:
        if out and out[-1] == g:
            out.pop()
        else:
            out.append(g)
    return tuple(out)


def canonical(w):
    """A canonical rotation of a cyclically reduced relator, or its reverse."""
    w = list(reduce(w))
    while len(w) > 1 and w[0] == w[-1]:
        w = w[1:-1]
    if not w:
        return ()
    rots = [tuple(w[i:] + w[:i]) for i in range(len(w))]
    rv = list(reversed(w))
    rots += [tuple(rv[i:] + rv[:i]) for i in range(len(rv))]
    return min(rots)


def thin(lets, cands, sub, want):
    """A small subset of cands closing the enumeration at want."""
    cands = sorted(set(cands), key=lambda r: (len(r), r))
    lo, hi = 0, len(cands)
    if index(lets, cands, sub, want) != want:
        return None
    while lo < hi:
        mid = (lo + hi) // 2
        if index(lets, cands[:mid], sub, want) == want:
            hi = mid
        else:
            lo = mid + 1
    keep = list(cands[:lo])
    for r in sorted(keep, key=lambda r: -len(r)):
        trial = [x for x in keep if x != r]
        if index(lets, trial, sub, want) == want:
            keep = trial
    return keep


def main():
    levels = level_letters()
    rels = T.relators()
    out = []
    for k in range(len(levels) - 1):
        lets, nxt = levels[k], levels[k + 1]
        order = ss.order([T.PERMS[g] for g in lets])
        want = order // (ss.order([T.PERMS[g] for g in nxt]) if nxt else 1)
        loc = {g: i for i, g in enumerate(lets)}
        axioms = [PR.Axiom(f'L{k}-{j}', tuple(loc[g] for g in r), ()) for j, r in enumerate(rels)]
        macros = {g: (loc[g],) for g in nxt}
        t0 = time.time()
        tc = LB.LabelledTC(len(lets), axioms, macros, limit=500_000)
        live = tc.run()
        assert len(live) == want, (k, len(live), want)
        der = tc.derived(live)
        cand = {}
        for e, j, lab, st in der:
            c = canonical(lab)
            if c and c not in cand:
                cand[c] = (e, j, lab)
        print(f'level {k}: {len(lets)} letters, {len(live)} cosets (want {want}), {len(rels)} relators, '
              f'{len(cand)} derived candidates, {len(tc.facts)} facts, {round(time.time() - t0, 1)} s', flush=True)
        out.append((k, lets, live, tc.rep, rels))
        if not nxt:
            break
        # the next level's relators: a subset of the derived ones
        lets2 = nxt
        nxt2 = levels[k + 2]
        order2 = ss.order([T.PERMS[g] for g in lets2])
        want2 = order2 // (ss.order([T.PERMS[g] for g in nxt2]) if nxt2 else 1)
        words = list(cand)
        t0 = time.time()
        keep = thin(lets2, words, nxt2, want2)
        if keep is None:
            print(f'  level {k + 1}: the derived relators do not close at {want2}!', flush=True)
            return
        # the proof-producing enumeration collapses faster with the short
        # derived relators too; every one of them comes with a derivation
        short = sorted((w for w in words if len(w) <= 6), key=lambda r: (len(r), r))[:400]
        rels = sorted(set(keep) | set(short), key=lambda r: (len(r), r))
        print(f'  level {k + 1}: kept {len(keep)} of {len(words)} (lengths {sorted(map(len, keep))[-5:]}), '
              f'{len(rels)} with the short ones, {round(time.time() - t0, 1)} s', flush=True)
    pickle.dump(out, open(HERE / 'rs4.pkl', 'wb'))


if __name__ == '__main__':
    main()
