#!/usr/bin/env python3
"""Four wires, classical: the point-stabiliser tower by Reidemeister–
Schreier, every relator of every level derived.

    python3 -B rs4.py

Level 0 is A16 on the 34 placed letters with the relators of
`tower4.py` (the natural classical rules at every placement, and the
structural rules).  Level k+1 is generated by the letters fixing one
more point of tower4.CHAIN; the last level, A7, is enumerated over the
trivial group.

A plain labelled coset enumeration of level k (`../labelled.py`, macros
the letters of level k+1) traces every relator of level k from every
coset; each closes with a label, a word in level k+1's letters equal to
the identity, derived from level k's relators.  Level k+1's relators
are chosen among these.  The tower is certified from the bottom up:
level 9's enumeration over the trivial group closes at |A7|, and if
level k+1 is presented by its relators, which are consequences of level
k's, and level k's enumeration closes at the true index, then level k is
presented by its relators.  So a choice is good as soon as every
enumeration closes; a choice is made by growing the set (a minimal
closing subset, then the shortest of the rest) until the relators
derived from it close the next level's enumeration too.

Writes rs4.pkl: per level, its letters and relators."""
import sys
import time
import pickle
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import core as C
import labelled as LB
import proofs as PR
import ss
import tower4 as T

LIM = 2_000_000
MAXLAB = 40          # longer derived relators are not wanted


def level_letters():
    return [[g for g in range(len(T.LETTERS)) if all(T.PERMS[g][p] == p for p in T.CHAIN[:k])]
            for k in range(len(T.CHAIN) + 1)] + [[]]


LEVELS = level_letters()


def want(k):
    lets, nxt = LEVELS[k], LEVELS[k + 1]
    return ss.order([T.PERMS[g] for g in lets]) // (ss.order([T.PERMS[g] for g in nxt]) if nxt else 1)


def index(k, rels):
    lets, sub = LEVELS[k], LEVELS[k + 1]
    pos = {g: i for i, g in enumerate(lets)}
    own = [tuple(pos[g] for g in r) for r in rels]
    lim = max(20_000, 50 * want(k))
    return C.index_c(len(lets), own, [(pos[g],) for g in sub], lim)


def reduce(w):
    out = []
    for g in w:
        if out and out[-1] == g:
            out.pop()
        else:
            out.append(g)
    return tuple(out)


def canonical(w):
    """A canonical rotation of a cyclically reduced relator, or its reverse."""
    w = list(reduce(w))
    while len(w) > 1 and w[0] == w[-1]:
        w = w[1:-1]
    if not w:
        return ()
    rots = [tuple(w[i:] + w[:i]) for i in range(len(w))]
    rv = list(reversed(w))
    rots += [tuple(rv[i:] + rv[:i]) for i in range(len(rv))]
    return min(rots)


def seed(k):
    """Prefix-closed representatives of the cosets of level k+1 in level k
    (local letters), by breadth-first search: a word w is in the coset
    read off by w⁻¹ of the fixed point (by w itself at the bottom)."""
    lets = LEVELS[k]
    if k + 1 < len(LEVELS) - 1 or LEVELS[k + 1]:
        p = T.CHAIN[k]
        key = lambda w, x: T.PERMS[lets[x]][w]
        start = p
    else:
        key = lambda w, x: tuple(w[i] for i in T.PERMS[lets[x]])   # w · letter
        start = tuple(range(T.D))
    seen = {start: ()}
    fr = [start]
    while fr:
        nxt = []
        for s in fr:
            for x in range(len(lets)):
                t = key(s, x)
                if t not in seen:
                    seen[t] = seen[s] + (x,)
                    nxt.append(t)
        fr = nxt
    return sorted(seen.values(), key=lambda w: (len(w), w))


def enumerate_level(k, rels):
    """The labelled enumeration of level k: (tc, live, derived candidates)."""
    lets, nxt = LEVELS[k], LEVELS[k + 1]
    loc = {g: i for i, g in enumerate(lets)}
    axioms = [PR.Axiom(f'L{k}-{j}', tuple(loc[g] for g in r), ()) for j, r in enumerate(rels)]
    macros = {g: (loc[g],) for g in nxt}
    tc = LB.LabelledTC(len(lets), axioms, macros, seed=seed(k), limit=200_000)
    live = tc.run()
    cand = {}
    lens = []
    for e, j, lab, st in tc.derived(live):
        lens.append(len(lab))
        if len(lab) > MAXLAB:
            continue
        c = canonical(lab)
        if c and c not in cand:
            cand[c] = (e, j)
    lens.sort()
    print(f'      level {k}: labels of traced relators, median {lens[len(lens) // 2]}, '
          f'max {lens[-1]}; {len(cand)} short ones', flush=True)
    return tc, live, cand


def minimal(k, cands):
    """A small subset of cands closing level k at its index, or None."""
    cands = sorted(set(cands), key=lambda r: (len(r), r))
    if index(k, cands) != want(k):
        return None
    lo, hi = 0, len(cands)
    while lo < hi:
        mid = (lo + hi) // 2
        if index(k, cands[:mid]) == want(k):
            hi = mid
        else:
            lo = mid + 1
    keep = list(cands[:lo])
    for r in sorted(keep, key=lambda r: -len(r)):
        trial = [x for x in keep if x != r]
        if index(k, trial) == want(k):
            keep = trial
    return keep


def choose(k, cands):
    """Relators for level k among the candidates derived from level k-1:
    they close level k, and (if k is not the bottom) the relators derived
    from them close level k+1."""
    words = sorted(cands, key=lambda r: (len(r), r))
    keep = minimal(k, words)
    if keep is None:
        return None
    if k + 1 == len(LEVELS) - 1:
        return keep
    n = 200
    while True:
        rels = sorted(set(keep) | set(words[:n]), key=lambda r: (len(r), r))
        try:
            tc, live, nxt = enumerate_level(k, rels)
            ahead = index(k + 1, list(nxt)) if len(live) == want(k) else None
            ok = ahead == want(k + 1)
            what = f'{len(live)} cosets, {len(nxt)} derived, next level closes at {ahead}'
        except OverflowError:
            ok, what = False, 'overflow'
        print(f'    level {k}: {len(rels)} relators: {what}', flush=True)
        if ok:
            print(f'    level {k}: {len(keep)} minimal + {n} shortest = {len(rels)} relators look ahead', flush=True)
            return rels
        if n >= len(words):
            return None
        n = 2 * n


def main():
    rels = T.relators_tower()
    out = []
    for k in range(len(LEVELS) - 1):
        t0 = time.time()
        if k > 0:
            rels = choose(k, cands)
            if rels is None:
                print(f'level {k}: no choice closes', flush=True)
                return
        tc, live, cands = enumerate_level(k, rels)
        print(f'level {k}: {len(LEVELS[k])} letters, {len(live)} cosets (want {want(k)}), '
              f'{len(rels)} relators, {len(cands)} derived, {len(tc.facts)} facts, '
              f'{round(time.time() - t0, 1)} s', flush=True)
        assert len(live) == want(k)
        out.append((k, LEVELS[k], rels))
    pickle.dump(out, open(HERE / 'rs4.pkl', 'wb'))
    print('tower certified: every level closes')


if __name__ == '__main__':
    main()
