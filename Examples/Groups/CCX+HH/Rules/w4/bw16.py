#!/usr/bin/env python3
"""The graph of Barnes–Wall lattices g·BW16 (g in the four-wire group).

    python3 -B bw16.py [limit]

The four-wire Clifford group Cl4 = <X, CX, HH, SW> fixes the lattice
L0 spanned by its orbit of e0 (4320 vectors, the minimal vectors of the
Barnes–Wall lattice).  The four-wire group is generated by Cl4 and CCX,
so the lattices g·L0 form a connected graph with L0's neighbours the
lattices c·CCX·L0, c in Cl4.  This counts them: the Cl4-orbit of
CCX·L0, by breadth-first search on Hermite normal forms."""
import sys
from pathlib import Path

N = 4
D = 1 << N
K = 6                   # vectors are integer vectors scaled by 2^K


def flip(t, ctrls):
    def f(v):
        return tuple(v[x ^ (1 << t)] if all(x >> c & 1 for c in ctrls) else v[x] for x in range(D))
    return f


def swap(a, b):
    def f(v):
        def g(x):
            return x ^ (1 << a) ^ (1 << b) if (x >> a & 1) != (x >> b & 1) else x
        return tuple(v[g(x)] for x in range(D))
    return f


def hh(a, b):
    def f(v):
        w = list(v)
        for t in (a, b):
            out = list(w)
            for x in range(D):
                if not x >> t & 1:
                    y = x | 1 << t
                    out[x], out[y] = w[x] + w[y], w[x] - w[y]
            w = out
        assert all(c % 2 == 0 for c in w)
        return tuple(c // 2 for c in w)
    return f


CLIFF = [flip(t, ()) for t in range(N)]
CLIFF += [flip(t, (c,)) for c in range(N) for t in range(N) if c != t]
CLIFF += [swap(a, b) for a in range(N) for b in range(a + 1, N)]
CLIFF += [hh(a, b) for a in range(N) for b in range(a + 1, N)]
CCX = flip(0, (1, 2))


def hnf(vectors):
    """Row Hermite normal form of the lattice the integer vectors span."""
    rows = [list(v) for v in vectors if any(v)]
    basis = []
    col = 0
    while rows and col < D:
        rows = [r for r in rows if any(r)]
        piv = [r for r in rows if r[col] != 0]
        if not piv:
            col += 1
            continue
        # gcd reduction in this column
        while len(piv) > 1:
            piv.sort(key=lambda r: abs(r[col]))
            p = piv[0]
            nxt = [p]
            for r in piv[1:]:
                q = r[col] // p[col]
                r2 = [a - q * b for a, b in zip(r, p)]
                if r2[col] != 0:
                    nxt.append(r2)
                else:
                    rows.append(r2)
            piv = nxt
            rows = [r for r in rows if r[col] == 0] + []
            rows = [r for r in rows if any(r)]
        p = piv[0]
        if p[col] < 0:
            p = [-a for a in p]
        basis.append(p)
        rows = [r for r in rows if r[col] == 0]
        col += 1
    # reduce above the pivots
    for i in range(len(basis)):
        c = next(j for j in range(D) if basis[i][j])
        for k in range(i):
            q = basis[k][c] // basis[i][c]
            if q:
                basis[k] = [a - q * b for a, b in zip(basis[k], basis[i])]
    return tuple(tuple(r) for r in basis)


def lattice_of(gens_vectors):
    return hnf(gens_vectors)


def orbit_vectors(start, gens):
    seen = {start}
    fr = [start]
    while fr:
        nxt = []
        for v in fr:
            for g in gens:
                u = g(v)
                if u not in seen:
                    seen.add(u)
                    nxt.append(u)
        fr = nxt
    return seen


def main():
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 2_000_000
    e0 = tuple((1 << K) if x == 0 else 0 for x in range(D))
    mins = orbit_vectors(e0, CLIFF)
    print('Cl4-orbit of e0:', len(mins), flush=True)
    L0 = lattice_of(mins)
    for g in CLIFF:
        assert lattice_of([g(v) for v in L0]) == L0
    print('L0 is Cl4-invariant; det index', flush=True)
    L1 = lattice_of([CCX(v) for v in L0])
    assert L1 != L0
    seen = {L1}
    fr = [L1]
    while fr and len(seen) < limit:
        nxt = []
        for L in fr:
            for g in CLIFF:
                M = lattice_of([g(v) for v in L])
                if M not in seen:
                    seen.add(M)
                    nxt.append(M)
        fr = nxt
        print('  orbit so far', len(seen), flush=True)
    print('neighbours of L0 (Cl4-orbit of CCX·L0):', len(seen), '(complete)' if not fr else '(limit)')


if __name__ == '__main__':
    main()
