#!/usr/bin/env python3
"""Write NaturalP/FourWire/Classical/Gamma.agda: the 34 placed classical
letters on four wires, their permutations of the 16 levels, and the
relators of `tower4.py` (the natural classical rules at every
placement, the structural rules, the naturality of the swaps).

    python3 -B emit_gamma4.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import tower4 as T

ROOT = HERE.parents[1] / 'NaturalP' / 'FourWire' / 'Classical'
MOD = 'Examples.Groups.CCX+HH.NaturalP.FourWire.Classical'


def agda_name(g):
    l = T.LETTERS[g]
    if l[0] == 'X':
        return f'x{l[1]}'
    if l[0] == 'CX':
        return f'cx{l[1]}-{l[2]}'
    if l[0] == 'CCX':
        return f'ccx{l[1]}-{l[2]}{l[3]}'
    return f'sw{l[1]}{l[2]}'


AG = [agda_name(g) for g in range(len(T.LETTERS))]


def fin(k):
    return f'# {k}'


def main():
    rels = T.relators()
    ROOT.mkdir(parents=True, exist_ok=True)
    out = []
    w = out.append
    w('''------------------------------------------------------------------------
-- Presentations of groups
--
-- The 34 placed classical letters on four wires and their relators.
--
-- The letters are X on each wire (x i), the CNOTs (cx c-t, control c,
-- target t), the Toffolis (ccx t-ab, target t, controls a b) and the
-- swaps (sw ab); each is read as a permutation of the sixteen levels
-- l = x0 + 2 x1 + 4 x2 + 8 x3 (`spL`).  The relators (`Rel`) are the
-- natural classical rules at every placement of their wires, the
-- involutions, the commutations of letters on disjoint wires and the
-- naturality of the swaps.  Every relator is the identity (`rel-sp`).
--
-- Generated by Rules/w4/emit_gamma4.py; do not edit.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}
''')
    w(f'module {MOD}.Gamma where\n')
    w('''open import Data.Bool.Base using (Bool ; true ; false)
open import Data.Fin using (#_)
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Maybe.Base using (Maybe ; just ; nothing)
open import Data.Nat.Base using (ℕ ; zero ; suc ; _≡ᵇ_)
open import Data.Nat.Properties using (≡ᵇ⇒≡)
open import Data.Vec.Base using (_∷_ ; [])
open import Relation.Binary.PropositionalEquality using (_≡_ ; refl ; cong ; trans ; sym)
open import Word.Base using (Word ; WRel ; [_]ʷ ; ε ; _•_)
open import Presentation.Tactics.Words using (module Associative)

open import Examples.Groups.CCX+HH.NaturalP.FourWire.Classical.Perm 16 public
  using (P ; ID ; mul)

open Associative using (word-of-list)
''')
    w('data L : Set where')
    w('  ' + ' '.join(AG) + ' : L\n')
    w('code : L → ℕ')
    for k, a in enumerate(AG):
        w(f'code {a} = {k}')
    w('')
    w('letters : List L')
    w('letters = ' + ' ∷ '.join(AG) + ' ∷ []\n')
    w('''private
  nth : List L → ℕ → Maybe L
  nth []       _       = nothing
  nth (x ∷ xs) zero    = just x
  nth (x ∷ xs) (suc n) = nth xs n

decode : ℕ → Maybe L
decode = nth letters
''')
    w('decode-code : ∀ a → decode (code a) ≡ just a')
    for a in AG:
        w(f'decode-code {a} = refl')
    w('''
private
  just-inj : ∀ {a b : L} → just a ≡ just b → a ≡ b
  just-inj refl = refl

eqL : L → L → Bool
eqL a b = code a ≡ᵇ code b

eqL-sound : ∀ a b → eqL a b ≡ true → a ≡ b
eqL-sound a b h = just-inj (trans (sym (decode-code a))
  (trans (cong decode (≡ᵇ⇒≡ (code a) (code b) (Tᵇ h))) (decode-code b)))
  where
  open import Data.Bool.Base using (T)
  open import Data.Unit.Base using (tt)
  open import Relation.Binary.PropositionalEquality using (subst)
  Tᵇ : ∀ {x} → x ≡ true → T x
  Tᵇ e = subst T (sym e) tt
''')
    w('-- The permutation of each letter: the images of the levels 0 … 15.')
    w('spL : L → P')
    for g, a in enumerate(AG):
        w(f'spL {a} = ' + ' ∷ '.join(f'# {x}' for x in T.PERMS[g]) + ' ∷ []')
    w('''
sp : Word L → P
sp [ a ]ʷ  = spL a
sp ε       = ID
sp (u • v) = mul (sp u) (sp v)

⟪_⟫ : List L → Word L
⟪_⟫ = word-of-list
''')
    w('data Rel : Set where')
    names = [f'r{k}' for k in range(len(rels))]
    for i in range(0, len(names), 16):
        w('  ' + ' '.join(names[i:i + 16]) + ' : Rel')
    w('')
    w('relator : Rel → List L')
    for nm, r in zip(names, rels):
        w(f'relator {nm} = ' + ' ∷ '.join(AG[g] for g in r) + ' ∷ []')
    w('')
    w('-- The involution of each letter.')
    w('invRel : L → Rel')
    for g, a in enumerate(AG):
        w(f'invRel {a} = {names[rels.index((g, g))]}')
    w('')
    w('invRel-ok : ∀ a → relator (invRel a) ≡ a ∷ a ∷ []')
    for a in AG:
        w(f'invRel-ok {a} = refl')
    w('')
    w('rel-sp : ∀ r → sp ⟪ relator r ⟫ ≡ ID')
    for nm in names:
        w(f'rel-sp {nm} = refl')
    w('''
infix 4 _Γ_
data _Γ_ : WRel L where
  rel : (r : Rel) → ⟪ relator r ⟫ Γ ε
''')
    (ROOT / 'Gamma.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('wrote', ROOT / 'Gamma.agda', len(rels), 'relators')


if __name__ == '__main__':
    main()
