#!/usr/bin/env python3
"""The four-wire classical tower as data: A16 presented in the 34 placed
classical letters, level by level, with proof-producing tables.

    python3 -B pipe4.py        # build, replay every fact, report sizes

The letters and the relators are `tower4.py`'s (the natural classical
rules at every placement, the structural rules, the naturality of the
swaps) together with the extras of `ext4.txt`.  Level k is generated by
the letters fixing the first k points of CHAIN; each level is enumerated
over the one below by a labelled coset enumeration (`../labelled.py`)
whose labels, words in the lower letters, are kept canonical; rewriting
a label to its canonical word is a "norm" step, justified in Agda by the
completeness of the level below (as `../w3/pipe.py`)."""
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import labelled as LB
import proofs as PR
import tower4 as T
import ext4 as X

CHAIN = T.CHAIN
D = T.D
ID = tuple(range(D))
NAMES = [X.name(g) for g in range(len(T.LETTERS))]
IX = {n: k for k, n in enumerate(NAMES)}


def mul(a, b):
    """The matrix product A B: b acts first."""
    return tuple(a[x] for x in b)


def inv(a):
    r = [0] * D
    for i, j in enumerate(a):
        r[j] = i
    return tuple(r)


def sp(word):
    p = ID
    for g in reversed(word):
        p = mul(T.PERMS[g], p)
    return p


def relators():
    rels = [(f'r{k}', r) for k, r in enumerate(T.relators())]
    path = HERE / 'ext4.txt'
    if path.exists():
        for k, line in enumerate(path.read_text().splitlines()):
            if line.strip():
                rels.append((f'e{k}', tuple(IX[x] for x in line.split())))
    for nm, r in rels:
        assert sp(r) == ID, nm
    return rels


def level_letters():
    return [(k, [g for g in range(len(T.LETTERS)) if all(T.PERMS[g][p] == p for p in CHAIN[:k])])
            for k in range(len(CHAIN) + 1)]


def closure_set(gens):
    seen = {ID}
    fr = [ID]
    while fr:
        nxt = []
        for p in fr:
            for g in gens:
                q = mul(T.PERMS[g], p)
                if q not in seen:
                    seen.add(q)
                    nxt.append(q)
        fr = nxt
    return seen


class Level:
    def __init__(self, k, letters, below, relators, full):
        self.k, self.letters, self.below = k, letters, below
        self.loc = {x: i for i, x in enumerate(letters)}
        self.relators = [(nm, r) for nm, r in relators if all(x in self.loc for x in r)]
        self.full = full                  # is the level the whole pointwise stabiliser?
        self.elements = None if full else closure_set(letters)
        sub = below.letters if below else []
        macros = {x: (self.loc[x],) for x in sub}
        axioms = [PR.Axiom(nm, tuple(self.loc[x] for x in r), ()) for nm, r in self.relators]
        level = self

        class TC(LB.LabelledTC):
            def join(tc, left, right):
                lab = tuple(left) + tuple(right)
                nf = level.below_canon(lab)
                if nf == lab:
                    return lab, []
                f = tc._add(tc.dec(lab), tc.dec(nf), [(0, ("norm", (lab, nf)), True)])
                return nf, [(0, ("fact", f), True)]

        self.tc = TC(len(letters), axioms, macros, limit=200_000)
        self.live = self.tc.run()
        self.cosets = {c: i for i, c in enumerate(self.live)}
        self.reps = [tuple(letters[y] for y in self.tc.rep[c]) for c in self.live]
        self.repsp = [sp(r) for r in self.reps]
        self.table = {}
        for c in self.live:
            for y in range(len(letters)):
                d, lab, f = self.tc.final(c, y)
                self.table[(self.cosets[c], y)] = (lab, self.cosets[d], f)

    def member(self, g):
        if self.full:
            return all(g[p] == p for p in CHAIN[:self.k])
        return g in self.elements

    def below_canon(self, lab):
        if not self.below:
            assert lab == (), lab
            return ()
        return self.below.canon(sp(lab))

    def coset(self, g):
        hits = []
        for i, r in enumerate(self.repsp):
            h = mul(g, inv(r))
            if (self.below.member(h) if self.below else h == ID):
                hits.append((i, h))
        assert len(hits) == 1, (self.k, len(hits))
        return hits[0]

    def canon(self, g):
        c, h = self.coset(g)
        lowc = self.below.canon(h) if self.below else ()
        return lowc + self.reps[c]


def build():
    rels = relators()
    levs = level_letters()
    out = []
    below = None
    for k, lets in reversed(levs):
        full = True                       # every level is a whole pointwise stabiliser
        t0 = time.time()
        lev = Level(k, lets, below, rels, full)
        print(f'level {k}: {len(lets)} letters, {len(lev.live)} cosets, {len(lev.relators)} relators, '
              f'{len(lev.tc.facts)} facts, {round(time.time() - t0, 1)} s', flush=True)
        out.append(lev)
        below = lev
    return rels, out


def roots(lev):
    return [f for (_, _, f) in lev.table.values()]


def closure(tc, rs):
    seen, stack = set(), list(rs)
    while stack:
        f = stack.pop()
        if f in seen:
            continue
        seen.add(f)
        for (_, (kind, key), _) in tc.facts[f].steps:
            if kind == 'fact':
                stack.append(key)
    return seen


def replay(lev, f):
    tc = lev.tc
    fact = tc.facts[f]
    xs = list(fact.lhs)
    for pos, (kind, key), fwd in fact.steps:
        if kind == 'ax':
            l, r = tc.axioms[key].lhs, tc.axioms[key].rhs
        elif kind == 'inv':
            l, r = (key, key), ()
        elif kind == 'fact':
            l, r = tc.facts[key].lhs, tc.facts[key].rhs
        elif kind == 'norm':
            lab, nf = key
            assert sp(lab) == sp(nf)
            l, r = tc.dec(lab), tc.dec(nf)
        if not fwd:
            l, r = r, l
        if tuple(xs[pos:pos + len(l)]) != tuple(l):
            return False
        xs = xs[:pos] + list(r) + xs[pos + len(l):]
    return tuple(xs) == tuple(fact.rhs)


def report(lev):
    cl = closure(lev.tc, roots(lev))
    bad = [f for f in cl if not replay(lev, f)]
    steps = sum(len(lev.tc.facts[f].steps) for f in cl)
    print(f'level {lev.k}: closure {len(cl)} facts, {steps} steps, {len(bad)} failing replay', flush=True)
    return cl


if __name__ == '__main__':
    rels, levels = build()
    total = 0
    for lev in levels:
        total += len(report(lev))
    print('facts in all:', total)
