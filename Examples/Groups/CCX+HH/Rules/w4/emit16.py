#!/usr/bin/env python3
"""Write the four-wire classical towers as Agda, under
NaturalP/FourWire/Classical/:

    Aff/L<k>/Base.agda, Aff/L<k>/Facts<i>.agda, Aff/L<k>.agda
        the affine tower (pipe16 aff); Aff/L0.complete is affine
        completeness for the 22 affine letters
    Extras/Norm.agda     affine norm steps, by Aff/L0.complete
    Extras/E<j>.agda     each extra relator of the A16 tower, derived
                         (derive16.pkl)
    Extras.agda          the extras e0, e1, …
    A16/L<k>/…, A16/L<k>.agda
        the A16 tower with the S7 bottom (pipe16 a16)

    python3 -B emit16.py [aff] [extras] [a16]
"""
import sys
import pickle
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import tower4 as T
import pipe16 as P16
from emit_gamma4 import AG

ROOT = HERE.parents[1] / 'NaturalP' / 'FourWire' / 'Classical'
MOD = 'Examples.Groups.CCX+HH.NaturalP.FourWire.Classical'
CHUNK = 400
XCHUNK = 1500
AFF = [g for g in range(len(T.LETTERS)) if T.LETTERS[g][0] != 'CCX']

HEADER = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- {title}
--
-- Generated by Rules/w4/emit16.py; do not edit.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}
'''


def fin(k):
    return f'# {k}'


def lst(xs):
    xs = list(xs)
    return '[]' if not xs else ' ∷ '.join(xs + ['[]'])


def ax_eqn(name):
    """The equation of a named relator: level 0 or affine extra (axioms of
    Γ), or a derived extra."""
    if name[0] in 'ra':
        return f'rel⁼ {name}'
    return name


# ---------------------------------------------------------------------
# A tower

def emit_tower(tag, levels, title):
    for lev in levels:          # bottom first
        emit_level(tag, lev, title)


def emit_level(tag, lev, title):
    k = lev.k
    K = f'{tag}.L{k}'
    D = ROOT / tag / f'L{k}'
    D.mkdir(parents=True, exist_ok=True)
    tc = lev.tc
    letters = lev.letters
    below = lev.below
    lower = below.letters if below else []
    nX, nB, ck = len(letters), len(lower), len(lev.live)
    base = [HEADER.format(title=f'{title}, level {k}: the kit.'),
            f'module {MOD}.{K}.Base where\n',
            'open import Data.Fin.Base using (Fin)',
            'open import Data.List.Base using (List ; map)',
            'open import Data.Vec.Base using (_∷_ ; [] ; lookup)',
            'open import Relation.Binary.PropositionalEquality using (_≡_)',
            'open import Word.Base using (Word ; [_]ʷ ; ε ; _•_ ; _ʷ)',
            'import Presentation.Base as PB',
            f'open import {MOD}.Pure', '',
            f'ιX : Fin {nX} → L',
            f'ιX = lookup ({lst(AG[g] for g in letters)})', '']
    if below:
        base += [f'ιB : Fin {nB} → L',
                 f'ιB = lookup ({lst(AG[g] for g in lower)})', '',
                 f'import {MOD}.{tag}.L{below.k} as Below', '',
                 f'open import {MOD}.LevelKit ιX ιB Below.complete public']
    else:
        base += ['ιB : Fin 0 → L', 'ιB ()', '',
                 'private',
                 '  F0 : Word (Fin 0) → Word L',
                 '  F0 = (λ b → [ ιB b ]ʷ) ʷ', '',
                 '  zero′ : ∀ l → F0 l ≈ ε',
                 '  zero′ [ () ]ʷ',
                 '  zero′ ε       = PB.refl',
                 '  zero′ (u • v) = PB.trans (PB.cong (zero′ u) (zero′ v)) PB.left-unit', '',
                 '  lower : ∀ (l m : Word (Fin 0)) → sp (F0 l) ≡ sp (F0 m) → F0 l ≈ F0 m',
                 '  lower l m _ = PB.trans (zero′ l) (PB.sym (zero′ m))', '',
                 f'open import {MOD}.LevelKit ιX ιB lower public']
    base += ['',
             '-- Norm steps through a plain definition: a use of the module',
             "-- application's own normE carries its parameters, the whole",
             '-- tower below, into every term that mentions it.',
             f'normB : (u v : List (Fin {nB})) → sp ⟪ map ιB u ⟫ ≡ sp ⟪ map ιB v ⟫ → Eqn',
             'normB = normE']
    (D / 'Base.agda').write_text('\n'.join(base) + '\n', encoding='utf-8')
    roots = [f for (_, _, f) in lev.table.values()]
    cl = sorted(P16.closure(tc, roots))
    num = {f: i for i, f in enumerate(cl)}
    chunks = [cl[i:i + CHUNK] for i in range(0, len(cl), CHUNK)]

    def eqn(kind, key, fwd):
        if kind == 'ax':
            e = ax_eqn(tc.axioms[key].name)
        elif kind == 'inv':
            e = f'inv⁼ {AG[letters[key]]}'
        elif kind == 'fact':
            e = f'f{num[key]}'
        else:
            raise ValueError(kind)
        return e if fwd else f'sym⁼ ({e})'

    chunk_of = {f: ci for ci, ch in enumerate(chunks) for f in ch}
    for ci, ch in enumerate(chunks):
        out = [HEADER.format(title=f'{title}, level {k}: derivations, part {ci}.'),
               f'module {MOD}.{K}.Facts{ci} where\n',
               'open import Data.Fin using (#_)',
               'open import Data.List.Base using (List ; [] ; _∷_)',
               'open import Relation.Binary.PropositionalEquality using (refl)',
               f'open import {MOD}.Pure',
               f'open import {MOD}.{K}.Base using (normB)']
        # only the extras and the earlier chunks this chunk cites
        steps = [(kk, key) for f in ch for _, (kk, key), _ in tc.facts[f].steps]
        used = sorted({tc.axioms[key].name for kk, key in steps
                       if kk == 'ax' and tc.axioms[key].name[0] == 'e'}, key=lambda n: int(n[1:]))
        out += [f'open import {MOD}.Extras.{u.upper()} using ({u})' for u in used]
        cited = sorted({chunk_of[key] for kk, key in steps if kk == 'fact' and chunk_of[key] != ci})
        out += [f'open import {MOD}.{K}.Facts{j}' for j in cited]
        out.append('')
        for f in ch:
            fact = tc.facts[f]
            st = fact.steps
            out.append(f'f{num[f]} : Eqn')
            if len(st) == 1 and st[0][1][0] == 'norm':
                lab, nf = st[0][1][1]
                out.append(f'f{num[f]} = normB ({lst(fin(lower.index(x)) for x in lab)}) '
                           f'({lst(fin(lower.index(x)) for x in nf)}) refl')
            else:
                steps = lst(f'rw {p} ({eqn(kk, key, fw)})' for p, (kk, key), fw in st)
                out.append(f'f{num[f]} = derive ({lst(AG[letters[y]] for y in fact.lhs)}) '
                           f'({lst(AG[letters[y]] for y in fact.rhs)})\n  ({steps}) refl')
        (D / f'Facts{ci}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    out = [HEADER.format(title=f'{title}, level {k}: its table, and completeness.'),
           f'module {MOD}.{K} where\n',
           'open import Data.Bool.Base using (Bool ; true ; false)',
           'open import Data.Fin.Base using (Fin)',
           'open import Data.Fin using (#_)',
           'open import Data.List.Base using (List ; [] ; _∷_)',
           'open import Data.Product.Base using (_×_ ; _,_)',
           'open import Data.Vec.Base using (Vec ; [] ; _∷_ ; lookup)',
           'open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)',
           'open import Word.Base using (Word ; [_]ʷ ; _ʷ)',
           f'open import {MOD}.Pure',
           'open import Examples.Groups.CCX+HH.Natural.ThreeWire.Fin8 using (allFin ; allFin-sound ; eqF)',
           f'open import {MOD}.{K}.Base']
    out += [f'open import {MOD}.{K}.Facts{ci}' for ci in range(len(chunks))]
    out.append('')
    out.append(f'repL : Vec (List (Fin {nX})) {ck}')
    out.append('repL =')
    for c in range(ck):
        out.append(f'  ({lst(fin(letters.index(x)) for x in lev.reps[c])}) ∷')
    out.append('  []\n')
    out.append(f'tab : Vec (Vec (List (Fin {nB}) × Fin {ck}) {nX}) {ck}')
    out.append('tab =')
    frows = []
    for c in range(ck):
        row, frow = [], []
        for y in range(nX):
            lab, d, f = lev.table[(c, y)]
            row.append(f'(({lst(fin(lower.index(x)) for x in lab)}) , {fin(d)})')
            frow.append(f'f{num[f]}')
        out.append('  (' + ' ∷ '.join(row) + ' ∷ []) ∷')
        frows.append(frow)
    out.append('  []\n')
    out.append(f'factT : Vec (Vec Eqn {nX}) {ck}')
    out.append('factT =')
    for frow in frows:
        out.append('  (' + ' ∷ '.join(frow) + ' ∷ []) ∷')
    out.append('  []\n')
    kind = lev.kind
    if kind[0] == 'point':
        p = kind[1]
        out.append(f'open import {MOD}.Stab (# {p}) using (ψ ; fixes ; ψ-mul ; eqV)\n')
        out.append('ψ-letter : ∀ b g → ψ (mul (spL (ιB b)) g) ≡ ψ g')
        out.append(f'ψ-letter b = ψ-mul (ιB b) (allFin-sound {nB} (λ b → fixes (ιB b)) refl b)\n')
        inv = lambda g: ['true' if g[x] == p else 'false' for x in range(16)]
    elif kind[0] == 'pair':
        p, q = kind[1], kind[2]
        out.append(f'open import {MOD}.Stab (# 0) using (eqV)')
        out.append(f'open import {MOD}.StabPair (# {p}) (# {q}) using (ψ ; keeps ; ψ-mul)\n')
        out.append('ψ-letter : ∀ b g → ψ (mul (spL (ιB b)) g) ≡ ψ g')
        out.append(f'ψ-letter b = ψ-mul (ιB b) (allFin-sound {nB} (λ b → keeps (ιB b)) refl b)\n')
        inv = lambda g: ['true' if g[x] in (p, q) else 'false' for x in range(16)]
    elif kind[0] == 'colour':
        col = kind[1]
        out.append(f'open import {MOD}.StabCol (lookup ({lst(fin(c) for c in col)})) using (ψ ; keeps ; ψ-mul ; eqC)\n')
        out.append('ψ-letter : ∀ b g → ψ (mul (spL (ιB b)) g) ≡ ψ g')
        out.append(f'ψ-letter b = ψ-mul (ιB b) (allFin-sound {nB} (λ b → keeps (ιB b)) refl b)\n')
        out.append(f'cosets : List (Vec (Fin 16) 16 × Fin {ck})')
        out.append('cosets =')
        for c in range(ck):
            out.append(f'  (({lst(fin(col[lev.repsp[c][x]]) for x in range(16))}) , {fin(c)}) ∷')
        out.append('  []\n')
        out.append('open Table repL tab factT ψ ψ-letter eqC cosets (# 0) refl')
        inv = None
    else:
        inv = None
    if kind[0] == 'colour':
        pass
    elif inv:
        out.append(f'cosets : List (Vec Bool 16 × Fin {ck})')
        out.append('cosets =')
        for c in range(ck):
            out.append(f'  (({lst(inv(lev.repsp[c]))}) , {fin(c)}) ∷')
        out.append('  []\n')
        out.append('open Table repL tab factT ψ ψ-letter eqV cosets (# 0) refl')
    else:
        out.append('eqP : P → P → Bool')
        out.append('eqP u v = allFin 16 (λ i → eqF (lookup u i) (lookup v i))\n')
        out.append(f'cosets : List (P × Fin {ck})')
        out.append('cosets =')
        for c in range(ck):
            out.append(f'  (({lst(fin(x) for x in lev.repsp[c])}) , {fin(c)}) ∷')
        out.append('  []\n')
        out.append('open Table repL tab factT (λ g → g) (λ ()) eqP cosets (# 0) refl')
    out.append('open Checked refl refl using () renaming (complete to complete′)\n')
    out.append('-- A plain definition, for the level above (see Base.normB).')
    out.append(f'complete : ∀ (l m : Word (Fin {nX})) → sp (((λ x → [ ιX x ]ʷ) ʷ) l) ≡ sp (((λ x → [ ιX x ]ʷ) ʷ) m) →')
    out.append('           ((λ x → [ ιX x ]ʷ) ʷ) l ≈ ((λ x → [ ιX x ]ʷ) ʷ) m')
    out.append('complete = complete′')
    (ROOT / tag / f'L{k}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{tag} level {k}: {len(cl)} facts in {len(chunks)} chunks, {ck} cosets', flush=True)


