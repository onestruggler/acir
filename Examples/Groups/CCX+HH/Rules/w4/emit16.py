# Extras

def emit_extras(derivs):
    (ROOT / 'Extras').mkdir(parents=True, exist_ok=True)
    norm = [HEADER.format(title='Affine norm steps for the derivations of the extras.'),
            f'module {MOD}.Extras.Norm where\n',
            'open import Data.Fin.Base using (Fin)',
            'open import Data.List.Base using (List ; map)',
            'open import Data.Vec.Base using (_∷_ ; [] ; lookup)',
            'open import Relation.Binary.PropositionalEquality using (_≡_)',
            f'open import {MOD}.Pure',
            f'import {MOD}.Aff.L0 as Aff',
            f'open import {MOD}.Aff.L0.Base using () renaming (ιX to ιA)', '',
            '-- every letter; the affine letters below are those of Aff.L0',
            f'ιX : Fin {len(AG)} → L',
            f'ιX = lookup ({lst(AG)})', '',
            f'open import {MOD}.LevelKit ιX ιA Aff.complete using (normE)', '',
            '-- a plain definition (see Aff/L0/Base.normB)',
            f'normA : (u v : List (Fin {len(AFF)})) → sp ⟪ map ιA u ⟫ ≡ sp ⟪ map ιA v ⟫ → Eqn',
            'normA = normE']
    (ROOT / 'Extras' / 'Norm.agda').write_text('\n'.join(norm) + '\n', encoding='utf-8')
    names = sorted(derivs, key=lambda n: int(n[1:]))
    for nm in names:
        r, top, facts, axnames = derivs[nm]
        ids = sorted(facts)
        num = {f: i for i, f in enumerate(ids)}

        def eqn(kind, key, fwd):
            if kind == 'ax':
                e = ax_eqn(axnames[key])
            elif kind == 'inv':
                e = f'inv⁼ {AG[key]}'
            elif kind == 'fact':
                e = f'{nm}-{num[key]}'
            else:
                raise ValueError(kind)
            return e if fwd else f'sym⁼ ({e})'

        # facts only cite earlier facts, so chunks in order are closed
        chunks = [ids[i:i + XCHUNK] for i in range(0, len(ids), XCHUNK)]
        (ROOT / 'Extras' / nm.upper()).mkdir(parents=True, exist_ok=True)
        for ci, ch in enumerate(chunks):
            out = [HEADER.format(title=f'The extra relator {nm} of the four-wire classical tower, derived '
                                       f'from level 0 by a partial enumeration over the affine group: '
                                       f'part {ci}.'),
                   f'module {MOD}.Extras.{nm.upper()}.P{ci} where\n',
                   'open import Data.Fin using (#_)',
                   'open import Data.List.Base using (List ; [] ; _∷_)',
                   'open import Relation.Binary.PropositionalEquality using (refl)',
                   f'open import {MOD}.Pure',
                   f'open import {MOD}.Extras.Norm using (normA)']
            used = sorted({axnames[key] for f in ch for _, (kk, key), _ in facts[f].steps
                           if kk == 'ax' and axnames[key][0] == 'e'}, key=lambda n: int(n[1:]))
            out += [f'open import {MOD}.Extras.{u.upper()} using ({u})' for u in used]
            out += [f'open import {MOD}.Extras.{nm.upper()}.P{j}' for j in range(ci)]
            out.append('')
            for f in ch:
                fact = facts[f]
                st = fact.steps
                out.append(f'{nm}-{num[f]} : Eqn')
                if len(st) == 1 and st[0][1][0] == 'norm':
                    lab, nf = st[0][1][1]
                    out.append(f'{nm}-{num[f]} = normA ({lst(fin(AFF.index(x)) for x in lab)}) '
                               f'({lst(fin(AFF.index(x)) for x in nf)}) refl')
                else:
                    steps = lst(f'rw {p} ({eqn(kk, key, fw)})' for p, (kk, key), fw in st)
                    out.append(f'{nm}-{num[f]} = derive ({lst(AG[y] for y in fact.lhs)}) '
                               f'({lst(AG[y] for y in fact.rhs)})\n  ({steps}) refl')
            (ROOT / 'Extras' / nm.upper() / f'P{ci}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
        last = next(ci for ci, ch in enumerate(chunks) if top in ch)
        out = [HEADER.format(title=f'The extra relator {nm} of the four-wire classical tower.'),
               f'module {MOD}.Extras.{nm.upper()} where\n',
               f'open import {MOD}.Pure using (Eqn)',
               f'open import {MOD}.Extras.{nm.upper()}.P{last} using ({nm}-{num[top]})', '',
               f'{nm} : Eqn',
               f'{nm} = {nm}-{num[top]}']
        (ROOT / 'Extras' / f'{nm.upper()}.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    out = [HEADER.format(title='The extra relators of the four-wire classical tower.'),
           f'module {MOD}.Extras where\n']
    out += [f'open import {MOD}.Extras.{nm.upper()} public using ({nm})' for nm in names]
    (ROOT / 'Extras.agda').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(len(names), 'extras written', flush=True)


def main():
    which = sys.argv[1:] or ['aff', 'extras', 'a16']
    if 'aff' in which:
        rels_aff = P16.named_relators([('a', HERE / 'aff4extra.txt')])
        aff_levels = P16.build(P16.aff_spec(), rels_aff)
        emit_tower('Aff', aff_levels, 'The affine tower on four wires')
    if 'extras' in which:
        derivs = pickle.load(open(HERE / 'derive16.pkl', 'rb'))
        emit_extras(derivs)
    if 'a16' in which:
        rels = P16.named_relators([('a', HERE / 'aff4extra.txt'), ('e', HERE / 'tower16extra.txt')])
        a16_levels = P16.build(P16.a16_spec(), rels)
        emit_tower('A16', a16_levels, 'The four-wire classical tower')


if __name__ == '__main__':
    main()
