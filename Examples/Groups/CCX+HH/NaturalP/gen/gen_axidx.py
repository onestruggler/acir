"""Generate NaturalP/AxIdx.agda: the indices of each relation of Table 1.

For every constructor of CCX+HH-TwoLevel/Syntactics._===_ this lists
its index variables (padded to eight by repeating the first) and, for
any property Q of indices that holds of those eight, the proof that it
holds of every index of every letter of both sides (AllW (GenQ Q)).

Run from this directory:  python3 gen_axidx.py > ../AxIdx.agda
"""

# name, number of explicit arguments, index variables, lhs letters, rhs letters.
# A letter is ('M', x), ('X', x, y) or ('K', x, y, z, w).
REL = [
    ('r1a', 1, 'a b', 'X a b ; X a b', ''),
    ('r1b', 0, 'a', 'M a ; M a', ''),
    ('r1c', 3, 'a b c d', 'K a b c d ; K a b c d', ''),
    ('r2a', 6, 'a b c d', 'X a b ; X c d', 'X c d ; X a b'),
    ('r2b', 3, 'a b c', 'X a b ; M c', 'M c ; X a b'),
    ('r2c', 12, 'a b c d e f', 'X a b ; K c d e f', 'K c d e f ; X a b'),
    ('r2d', 1, 'a b', 'M a ; M b', 'M b ; M a'),
    ('r2e', 7, 'a b c d e', 'M a ; K b c d e', 'K b c d e ; M a'),
    ('r2f', 22, 'a b c d e f g h', 'K a b c d ; K e f g h', 'K e f g h ; K a b c d'),
    ('r3a', 3, "a a′ b", "X a a′ ; X a b", "X a′ b ; X a a′"),
    ('r3b', 3, "a b b′", "X b b′ ; X a b", "X a b′ ; X b b′"),
    ('r3c', 1, 'a b', 'X a b ; M b', 'M a ; X a b'),
    ('r3d', 5, "a a′ b c d", "X a a′ ; K a b c d", "K a′ b c d ; X a a′"),
    ('r3e', 6, "a b b′ c d", "X b b′ ; K a b c d", "K a b′ c d ; X b b′"),
    ('r3f', 6, "a b c c′ d", "X c c′ ; K a b c d", "K a b c′ d ; X c c′"),
    ('r3g', 5, "a b c d d′", "X d d′ ; K a b c d", "K a b c d′ ; X d d′"),
    ('r4a', 4, 'a b c d', 'X a b ; K a b c d', 'K a b c d ; X b d ; M b ; M d'),
    ('r4b', 3, 'a b c d', 'X b c ; K a b c d', 'M a ; K a b c d ; M a ; K a b c d ; M a'),
    ('r4c', 4, 'a b c d', 'X c d ; K a b c d', 'K a b c d ; X b d'),
    ('r5a', 7, 'a b c d e f', 'K a b c d ; K b d e f', 'K c d e f ; K a b c e'),
    ('r6a', 8, 'a b c d e f g h',
     'M a ; M e ; X a e ; K e f g h ; K a b c d ; X d e ; K a b c d ; K e f g h ; X a e ; M a ; M e',
     'K e f g h ; K a b c d ; X d e ; K a b c d ; K e f g h'),
]

FIN = ['0F', '1F', '2F', '3F', '4F', '5F', '6F', '7F']


def letters(s):
    return [l.split() for l in s.split(';') if l.strip()]


def qletter(l, pos):
    xs = ['q ' + FIN[pos[v]] for v in l[1:]]
    if len(xs) == 1:
        return xs[0]
    return '(' + ' , '.join(xs) + ')'


def qword(ls, pos):
    if not ls:
        return 'tt'
    if len(ls) == 1:
        return qletter(ls[0], pos)
    return '(' + ' , '.join(qletter(l, pos) for l in ls) + ')'


ORDER = {'r2e': 'b c d e a'}


def pattern(name, nexp, vs):
    if name in ORDER:
        vs = ORDER[name].split()
    imps = ' '.join('{' + v + ' = ' + v + '}' for v in vs)
    return '(' + name + ' ' + imps + ' ' + ' '.join(['_'] * nexp) + ')'


out = []
out.append('''------------------------------------------------------------------------
-- Presentations of groups
--
-- The indices of each relation of Table 1.
--
-- Generated by gen/gen_axidx.py.  `AxIdx ax` lists the index variables
-- of the relation ax (at most eight, padded by repeating the first),
-- and `ax-in` says that a property of indices holding of those holds of
-- every index of every letter on both sides.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+HH.NaturalP.AxIdx where

open import Data.Fin.Base using (Fin)
open import Data.Fin.Patterns using (0F ; 1F ; 2F ; 3F ; 4F ; 5F ; 6F ; 7F)
open import Data.Nat.Base using (ℕ)
open import Data.Product.Base using (_×_ ; _,_)
open import Data.Unit.Base using (tt)
open import Data.Vec.Base using (Vec ; [] ; _∷_ ; lookup)
open import Word.Base using (Word)

open import Examples.Groups.CCX+HH-TwoLevel.Syntactics using (Gen ; _===_)
open _===_
open import Examples.Groups.CCX+HH.NaturalP.PlanArgs using (AllW ; GenQ)

AxIdx : ∀ {n} {u v : Word (Gen n)} → u === v → Vec (Fin n) 8''')
for (name, nexp, vs, lhs, rhs) in REL:
    vs = vs.split()
    padded = vs + [vs[0]] * (8 - len(vs))
    out.append('AxIdx ' + pattern(name, nexp, vs) + ' = ' + ' ∷ '.join(padded) + ' ∷ []')

out.append('')
out.append('ax-in : ∀ {n} {u v : Word (Gen n)} (ax : u === v) (Q : Fin n → Set) → (∀ i → Q (lookup (AxIdx ax) i)) →')
out.append('  AllW (GenQ Q) u × AllW (GenQ Q) v')
for (name, nexp, vs, lhs, rhs) in REL:
    vl = vs.split()
    pos = {v: i for i, v in enumerate(vl)}
    out.append('ax-in ' + pattern(name, nexp, vl) + ' Q q =')
    out.append('  ' + qword(letters(lhs), pos) + ' , ' + qword(letters(rhs), pos))
print('\n'.join(out))
