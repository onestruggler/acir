#!/usr/bin/env python3
"""Generate the certified 69-relation reduction of the HH two-wire theory.

The output retains generator involutions and distinct cyclically reduced
relators.  Every old axiom has an Agda-checked certificate relating it to
one selected relator; selected relators are transported back from old
axioms by the same bidirectional theorem.  Run Agda on the generated
ReducedPresentation module after generation; --check only checks files.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

import build_table1_cases as CASES
from exact_matrices import evaluate, identity


HERE = Path(__file__).resolve().parent
TAGS = ("X-gen", "(X-gen ↥)", "CX-gen", "HH-gen")
ABSURD = ("(gate₀ ())", "((gate₀ ()) ↥)", "((gate₀ ()) ↥ ↥)")


def reduce(word):
    result = []
    for g in word:
        if result and result[-1] == g:
            result.pop()
        else:
            result.append(g)
    return tuple(result)


def classify(relation):
    original = reduce(relation["left"] + relation["right"][::-1])
    start, end = 0, len(original)
    while end - start >= 2 and original[start] == original[end - 1]:
        start += 1
        end -= 1
    prefix, middle = original[:start], original[start:end]
    if not middle:
        return (), prefix, 0, False
    selected = min(v[k:] + v[:k] for v in (middle, middle[::-1]) for k in range(len(middle)))
    for backwards in (False, True):
        oriented = selected[::-1] if backwards else selected
        for turns in range(len(oriented)):
            if oriented[turns:] + oriented[:turns] == middle:
                assert original == prefix + middle + prefix[::-1]
                return selected, prefix, turns, backwards
    raise AssertionError("no rotation witness")


def agda_list(word):
    return " ∷ ".join([TAGS[g] for g in word] + ["[]"])


def certificate(classification):
    _, prefix, turns, backwards = classification
    return f"(R.certificate ({agda_list(prefix)}) {turns} {'true' if backwards else 'false'} Eq.refl)"


def generate():
    data = json.loads((HERE.parent / "two_qubit_schreier.json").read_text(encoding="utf-8"))
    relations = data["circuit_relations"]
    classified = [classify(relation) for relation in relations]
    selected = sorted({row[0] for row in classified if row[0]})
    ids = {word: i for i, word in enumerate(selected)}
    table1, count = CASES.EXPORT.source_relations(4)
    case_ids = {(rule, tuple(indices)): i for i, (rule, indices, _, _) in enumerate(table1[:count])}
    origins = {}
    rows = {}
    roundtrips = {}
    for r, (relation, classification) in enumerate(zip(relations, classified)):
        if classification[0]:
            origins.setdefault(ids[classification[0]], r)
        name, raw = re.fullmatch(r"([^\[]+)\[([^]]*)\]", relation["source"]).groups()
        indices = tuple(map(int, raw.split(","))) if raw else ()
        if name == "roundtrip":
            roundtrips[indices[0]] = r
        else:
            rows[relation["coset"], case_ids[name, indices]] = r
    if len(rows) != 174 or len(roundtrips) != 4 or len(selected) != 65:
        raise ValueError("the audited HH2 instance or reduction counts have changed")

    source = """------------------------------------------------------------------------
-- Presentations of groups
--
-- The 178 two-wire Clément equations reduce to 69: four generator
-- involutions and 65 distinct cyclic relators.  Checked certificates
-- derive every old axiom and transport each selected relator back.
-- Generated by scripts/build_reduced_relations.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+HH.TwoQubit.ReducedPresentation where

open import Data.Bool.Base using (false ; true)
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Product.Base using (proj₂)
open import Relation.Binary.Definitions using (DecidableEquality)
open import Relation.Binary.PropositionalEquality as Eq using (_≡_)
open import Relation.Nullary.Decidable using (yes ; no)
open import Word.Base using (WRel ; [_]ʷ ; ε ; _•_)
import Presentation.Base as PB
import Presentation.GroupLike as GL
open import Examples.Groups.CCX+HH.Syntactics
import Examples.Groups.CCX+HH.Semantics as Physical
import Examples.Groups.CCX+HH.LowWidth as Low
import Examples.Groups.CCX+HH.RelatorReduction as Reduction
import Examples.Groups.CCX+HH.Table1Cases4 as Cases
import Examples.Groups.CCX+HH.TwoQubit.Presentation as Old
import Examples.Groups.CCX+HH.TwoQubit.Table as Table

private
  eq : DecidableEquality (Gen 2)
"""
    for i, left in enumerate(TAGS):
        for j, right in enumerate(TAGS):
            result = "yes Eq.refl" if i == j else "no (λ ())"
            source += f"  eq {left} {right} = {result}\n"
    for pattern in ABSURD:
        source += f"  eq {pattern} g\n  eq g {pattern}\n"
    source += """
module R = Reduction eq

data Index : Set where
"""
    for start in range(0, len(selected), 10):
        source += "  " + " ".join(f"r{i:02d}" for i in range(start, min(start + 10, len(selected)))) + " : Index\n"
    source += "\nselected : Index → List (Gen 2)\n"
    for i, word in enumerate(selected):
        source += f"selected r{i:02d} = {agda_list(word)}\n"
    source += """
data Relations : WRel (Gen 2) where
  square : ∀ g → Relations ([ g ]ʷ • [ g ]ʷ) ε
  relator : ∀ i → Relations (R.read (selected i)) ε

open PB Relations public hiding (_===_)

grouplike : GL.Grouplike Relations
grouplike g = [ g ]ʷ , axiom (square g)
  where open import Data.Product.Base using (_,_)

private
  module Calc = R.Theory Relations (λ g → axiom (square g))
  module OldCalc = R.Theory Old._===_ (λ g → proj₂ (Low.Two.grouplike g))

  canonical : ∀ c {u v} → Cases.Canonical u v → Table.decode c u ≈ Table.decode c v
"""
    for (coset, case), r in sorted(rows.items()):
        cls = classified[r]
        chosen = f"selected r{ids[cls[0]]:02d}" if cls[0] else "[]"
        proof = f"(axiom (relator r{ids[cls[0]]:02d}))" if cls[0] else "refl"
        source += f"  canonical Table.c{coset} Cases.instance{case:02d} =\n"
        source += f"    Calc.derive-equation {{selected = {chosen}}} {certificate(cls)} {proof}\n"
    source += """
translated-axiom : ∀ {u v} → Old._===_ u v → u ≈ v
translated-axiom (Old.translated c ax) = canonical c (Cases.cover ax)
"""
    for gate, r in sorted(roundtrips.items()):
        cls = classified[r]
        chosen = f"selected r{ids[cls[0]]:02d}" if cls[0] else "[]"
        proof = f"(axiom (relator r{ids[cls[0]]:02d}))" if cls[0] else "refl"
        source += f"translated-axiom (Old.roundtrip {TAGS[gate]}) =\n"
        source += f"  Calc.derive-equation {{selected = {chosen}}} {certificate(cls)} {proof}\n"
    for pattern in ABSURD:
        source += f"translated-axiom (Old.roundtrip {pattern})\n"
    source += """
from-translated : ∀ {u v} → u Old.≈ v → u ≈ v
from-translated PB.refl = refl
from-translated (PB.sym p) = sym (from-translated p)
from-translated (PB.trans p q) = trans (from-translated p) (from-translated q)
from-translated (PB.cong p q) = cong (from-translated p) (from-translated q)
from-translated PB.assoc = assoc
from-translated PB.left-unit = left-unit
from-translated PB.right-unit = right-unit
from-translated (PB.axiom ax) = translated-axiom ax

private
  transport : ∀ {u v chosen} → R.Certificate (R.relator u v) chosen →
    Old._===_ u v → R.read chosen Old.≈ ε
  transport cert ax = OldCalc.recover-selected cert
    (OldCalc.equation-to-relator (PB.axiom ax))

  to-translated-axiom : ∀ {u v} → Relations u v → u Old.≈ v
  to-translated-axiom (square g) = proj₂ (Low.Two.grouplike g)
"""
    reverse_rows = {r: (coset, case) for (coset, case), r in rows.items()}
    for i, r in sorted(origins.items()):
        cls = classified[r]
        if r in reverse_rows:
            coset, case = reverse_rows[r]
            axiom = f"(Old.translated Table.c{coset} (Cases.original Cases.instance{case:02d}))"
        else:
            gate = next(g for g, rr in roundtrips.items() if rr == r)
            axiom = f"(Old.roundtrip {TAGS[gate]})"
        source += f"  to-translated-axiom (relator r{i:02d}) =\n"
        source += f"    transport {{chosen = selected r{i:02d}}} {certificate(cls)} {axiom}\n"
    source += """
to-translated : ∀ {u v} → u ≈ v → u Old.≈ v
to-translated refl = PB.refl
to-translated (sym p) = PB.sym (to-translated p)
to-translated (trans p q) = PB.trans (to-translated p) (to-translated q)
to-translated (cong p q) = PB.cong (to-translated p) (to-translated q)
to-translated assoc = PB.assoc
to-translated left-unit = PB.left-unit
to-translated right-unit = PB.right-unit
to-translated (axiom ax) = to-translated-axiom ax

sound : ∀ {u v} → u ≈ v → Physical.interpret u ≡ Physical.interpret v
sound p = Low.Two.soundness (to-translated p)

complete : ∀ {u v : Circuit 2} → Physical.interpret u ≡ Physical.interpret v → u ≈ v
complete p = from-translated (Low.Two.completeness p)
"""
    output = {
        "format": "clement-involutory-relator-reduction-v1",
        "wires": 2, "gate_set": "HH", "word_order": "matrix product order",
        "circuit_generators": data["circuit_generators"],
        "source": "two_qubit_schreier.json",
        "source_relation_count": len(relations),
        "formal_entrypoint": "TwoQubit/ReducedPresentation.agda",
        "relations": ([{"kind": "involution", "left": [i, i], "right": []} for i in range(4)] +
                      [{"kind": "relator", "left": list(w), "right": [],
                        "source_relation": origins[i]} for i, w in enumerate(selected)]),
        "certificates": [{"source_relation": i, "selected_relator": ids.get(c[0]),
                          "conjugating_prefix": list(c[1]), "rotations": c[2], "reversed": c[3]}
                         for i, c in enumerate(classified)],
    }
    gates = [(g["gate"], tuple(g["wires"])) for g in data["circuit_generators"]]
    for relation in output["relations"]:
        if evaluate(tuple(relation["left"]), gates, 2) != identity(2):
            raise ValueError("a reduced equation failed independent exact matrix verification")
    return source, json.dumps(output, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, data = generate()
    files = {HERE.parent / "TwoQubit" / "ReducedPresentation.agda": source,
             HERE.parent / "two_qubit_reduced.json": data}
    for path, content in files.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated file differs: {path}")
        else:
            path.write_text(content, encoding="utf-8")
    print("Verified 178 reduction certificates, 65 selected relators and 4 involutions; generated Agda still requires typechecking.")


if __name__ == "__main__":
    main()
