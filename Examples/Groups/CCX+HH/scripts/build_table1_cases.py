#!/usr/bin/env python3
"""Generate an Agda-checked exhaustive finite cover of Table 1 at N=4.

The concrete equations come from the existing relation exporter.  The
generated cover is separately proved exhaustive from every constructor
of the source relation: invalid index tuples contradict an original
order or distinctness premise.  Thus the exporter is not trusted for
completeness.  Use --check to verify source reproduction without edits.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
PATH = HERE.parent.parent / "CCX+H" / "scripts" / "translated_relations.py"
SPEC = importlib.util.spec_from_file_location("ccx_table1_export", PATH)
EXPORT = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(EXPORT)
NUM = "₀₁₂₃₄₅₆₇"


def ordered(*pairs):
    return [("lt", a, b) for a, b in pairs]


def distinct(*pairs):
    return [("ne", a, b) for a, b in pairs]


# Each list follows the exact constructor argument order in Syntactics.
RULES = {
    "r1a": (["a", "b"], ordered(("a", "b"))),
    "r1b": (["a"], []),
    "r1c": (list("abcd"), ordered(("a", "b"), ("b", "c"), ("c", "d"))),
    "r2a": (list("abcd"), ordered(("a", "b"), ("c", "d")) + distinct(("a", "c"), ("a", "d"), ("b", "c"), ("b", "d"))),
    "r2b": (list("abc"), ordered(("a", "b")) + distinct(("c", "a"), ("c", "b"))),
    "r2c": (list("abcdef"), ordered(("a", "b"), ("c", "d"), ("d", "e"), ("e", "f")) + distinct(*[(a, b) for a in "ab" for b in "cdef"])),
    "r2d": (list("ab"), distinct(("a", "b"))),
    "r2e": (list("abcde"), ordered(("b", "c"), ("c", "d"), ("d", "e")) + distinct(*[("a", b) for b in "bcde"])),
    "r2f": (list("abcdefgh"), ordered(("a", "b"), ("b", "c"), ("c", "d"), ("e", "f"), ("f", "g"), ("g", "h")) + distinct(*[(a, b) for a in "abcd" for b in "efgh"])),
    "r3a": (["a", "a′", "b"], ordered(("a", "a′"), ("a′", "b"), ("a", "b"))),
    "r3b": (["a", "b", "b′"], ordered(("a", "b"), ("b", "b′"), ("a", "b′"))),
    "r3c": (list("ab"), ordered(("a", "b"))),
    "r3d": (["a", "a′", "b", "c", "d"], ordered(("a", "a′"), ("a′", "b"), ("b", "c"), ("c", "d"), ("a", "b"))),
    "r3e": (["a", "b", "b′", "c", "d"], ordered(("a", "b"), ("b", "b′"), ("b′", "c"), ("c", "d"), ("b", "c"), ("a", "b′"))),
    "r3f": (["a", "b", "c", "c′", "d"], ordered(("a", "b"), ("b", "c"), ("c", "c′"), ("c′", "d"), ("c", "d"), ("b", "c′"))),
    "r3g": (["a", "b", "c", "d", "d′"], ordered(("a", "b"), ("b", "c"), ("c", "d"), ("d", "d′"), ("c", "d′"))),
    "r4a": (list("abcd"), ordered(("a", "b"), ("b", "c"), ("c", "d"), ("b", "d"))),
    "r4b": (list("abcd"), ordered(("a", "b"), ("b", "c"), ("c", "d"))),
    "r4c": (list("abcd"), ordered(("a", "b"), ("b", "c"), ("c", "d"), ("b", "d"))),
    "r5a": (list("abcdef"), ordered(("a", "b"), ("b", "c"), ("c", "d"), ("d", "e"), ("e", "f"), ("b", "d"), ("c", "e"))),
    "r6a": (list("abcdefgh"), ordered(*list(zip("abcdefg", "bcdefgh")), ("a", "e"))),
}

# Agda orders inferred implicit variables by first occurrence in each
# constructor type.  r2e mentions the K block before the sign index.
IMPLICIT_ORDER = {"r2e": list("bcdea")}


def less(a, b):
    if a >= b:
        raise ValueError("invalid concrete order proof")
    return "(" + "s≤s (" * (a + 1) + "z≤n" + ")" * (a + 1) + ")"


def letter(g):
    kind, *ix = g
    if kind == "M":
        return f"U.M {NUM[ix[0]]}"
    bounds = " ".join(less(a, b) for a, b in zip(ix, ix[1:]))
    return f"U.{kind} " + " ".join(NUM[a] for a in ix) + " " + bounds


def word(w):
    return " • ".join("(" + letter(g) + ")" for g in w) if w else "ε"


def generate():
    instances, count = EXPORT.source_relations(4)
    instances = instances[:count]
    ids = {(kind, tuple(indices)): i for i, (kind, indices, _, _) in enumerate(instances)}
    source = """------------------------------------------------------------------------
-- Presentations of groups
--
-- The 58 finite instances of Table 1 in dimension four.  `cover`
-- proves exhaustiveness by inspecting the original order/distinctness
-- premises.  No semantic equations or postulates are introduced.
-- Generated by scripts/build_table1_cases.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+HH.Table1Cases4 where

open import Data.Empty using (⊥-elim)
open import Data.Fin.Base using (Fin ; _<_)
import Data.Fin.Properties as FP
open import Data.Nat.Base using (s≤s ; z≤n)
open import Relation.Binary.PropositionalEquality using (_≢_ ; refl)
open import Relation.Nullary.Decidable using (recompute)
open import Notations
open import Word.Base using (WRel ; ε ; _•_)
import Examples.Groups.CCX+HH-TwoLevel.Syntactics as U

data Canonical : WRel (U.Gen 4) where
"""
    for i, (_, _, left, right) in enumerate(instances):
        source += f"  instance{i:02d} : Canonical ({word(left)}) ({word(right)})\n"
    source += "\noriginal : ∀ {u v} → Canonical u v → u U.=== v\n"
    for i, (kind, indices, _, _) in enumerate(instances):
        names, guards = RULES[kind]
        env = dict(zip(names, indices))
        args = [less(env[a], env[b]) if tag == "lt" else "(λ ())" for tag, a, b in guards]
        source += f"original instance{i:02d} = U.{kind}" + (" " + " ".join(args) if args else "") + "\n"
    source += """
private
  Goal : ∀ {u v} → u U.=== v → Set
  Goal {u} {v} ax = Canonical u v

  lt : ∀ {a b : Fin 4} → .(a < b) → a < b
  lt {a} {b} p = recompute (a FP.<? b) p

"""
    clauses = 0
    valid = 0
    for kind, (names, guards) in RULES.items():
        proof_names = [f"p{i}" for i in range(len(guards))]
        params = [f"({p} : {a} {'<' if tag == 'lt' else '≢'} {b})"
                  for p, (tag, a, b) in zip(proof_names, guards)]
        implicit = " ".join(f"{{{a} = {a}}}" for a in IMPLICIT_ORDER.get(kind, names))
        constructor = f"U.{kind} {implicit}" + (" " + " ".join(proof_names) if proof_names else "")
        source += f"  cover-{kind} : ({' '.join(names)} : Fin 4) " + " ".join(params) + f" → Goal ({constructor})\n"

        def descend(values):
            nonlocal source, clauses, valid
            env = dict(zip(names, values))
            bad = next(((i, tag, a, b) for i, (tag, a, b) in enumerate(guards)
                        if a in env and b in env and
                        not (env[a] < env[b] if tag == "lt" else env[a] != env[b])), None)
            if bad is None and len(values) < len(names):
                for value in range(4):
                    descend(values + [value])
                return
            pats = [NUM[v] for v in values] + ["_"] * (len(names) - len(values))
            proofs = ["_"] * len(guards)
            if bad is not None:
                i, tag, a, b = bad
                if tag == "lt":
                    absurd = "()"
                    for _ in range(env[b]):
                        absurd = f"(s≤s {absurd})"
                    proofs[i] = absurd
                    rhs = ""
                else:
                    proofs[i] = "contra"
                    rhs = " = ⊥-elim (contra refl)"
            else:
                index = ids[kind, tuple(values)]
                rhs = f" = instance{index:02d}"
                valid += 1
            source += f"  cover-{kind} " + " ".join(pats + proofs) + rhs + "\n"
            clauses += 1

        descend([])
        source += "\n"
    source += "cover : ∀ {u v} → u U.=== v → Canonical u v\n"
    for kind, (names, guards) in RULES.items():
        proof_names = [f"p{i}" for i in range(len(guards))]
        pattern = f"U.{kind} " + " ".join(f"{{{a} = {a}}}" for a in IMPLICIT_ORDER.get(kind, names))
        if proof_names:
            pattern += " " + " ".join(proof_names)
        args = names + [f"(lt {p})" if tag == "lt" else p for p, (tag, _, _) in zip(proof_names, guards)]
        source += f"cover ({pattern}) = cover-{kind} " + " ".join(args) + "\n"
    if valid != 58:
        raise ValueError(f"expected 58 valid index cases, got {valid}")
    return source, {"instances": valid, "coverage_clauses": clauses, "source_constructors": len(RULES)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, report = generate()
    target = HERE.parent / "Table1Cases4.agda"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != source:
            raise SystemExit(f"Generated module differs: {target}")
    else:
        target.write_text(source, encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
