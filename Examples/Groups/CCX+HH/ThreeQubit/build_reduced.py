#!/usr/bin/env python3
"""Generate the finite selection used by the reduced three-wire table.

Retain every self-loop and one orientation of each non-tree edge.
The 134 forward BFS tree transitions are literal reassociations with
empty emitted words.  Reverse transitions are handled by the generic
proof in ReducedPresentation.agda, not asserted by this generator.
Use --check to compare generated source without writing it.  Agda must
still typecheck the generated cases and the reduction theorem.
"""

from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
PATTERN = {
    "X0": "X-gen", "X1": "(X-gen ↥)", "X2": "(X-gen ↥ ↥)",
    "CX10": "CX-gen", "CX21": "(CX-gen ↥)", "CCX210": "CCX-gen",
    "HH01": "HH-gen", "HH12": "(HH-gen ↥)",
}
ABSURD = ("(gate₀ ())", "((gate₀ ()) ↥)",
          "((gate₀ ()) ↥ ↥)", "((gate₀ ()) ↥ ↥ ↥)")


def generate(data: dict) -> tuple[str, dict]:
    names, rows, reps = data["generators"], data["factorizations"], data["representative_words"]
    if names != list(PATTERN) or len(rows) != 135 or len(reps) != 135:
        raise ValueError("unexpected three-wire alphabet or coset count")
    tree, kept, choices = set(), set(), {}
    loops, pairs = 0, 0
    for c, row in enumerate(rows):
        if len(row) != len(names):
            raise ValueError("incomplete transition row")
        for g, cell in enumerate(row):
            target = cell["next"]
            reverse = rows[target][g]
            if reverse["next"] != c:
                raise ValueError("coset transition is not involutive")
            composed = [cell["permutation"][i] for i in reverse["permutation"]]
            signs = set(cell["negative_outputs"]) ^ {
                cell["permutation"][i] for i in reverse["negative_outputs"]}
            if composed != list(range(8)) or signs:
                raise ValueError("opposite signed-permutation factors are not inverses")
            loops += target == c
            pairs += c < target
            if reps[target] == reps[c] + [names[g]]:
                if cell["stabilizer_word_matrix_order"]:
                    raise ValueError("tree transition has a nonempty emitted word")
                tree.add((c, g))
    if len(tree) != len(rows) - 1:
        raise ValueError("representative paths do not describe a spanning tree")
    for c, row in enumerate(rows):
        for g, cell in enumerate(row):
            target = cell["next"]
            if (c, g) in tree:
                choices[c, g] = "tree", c
            elif (target, g) in tree:
                choices[c, g] = "back-tree", target
            elif c <= target:
                choices[c, g] = "direct", c
                kept.add((c, g))
            else:
                choices[c, g] = "back-direct", target
    for (_, g), (kind, source) in choices.items():
        if kind in ("direct", "back-direct") and (source, g) not in kept:
            raise ValueError("selection points to a missing retained relation")
    counts = Counter(kind for kind, _ in choices.values())
    summary = {
        "cosets": len(rows), "directed_cells": len(choices), "self_loops": loops,
        "undirected_nonloop_edges": pairs, "forward_tree_edges": len(tree),
        "retained_table_relations": len(kept), "choices": dict(sorted(counts.items())),
        "base_relations": 105,
        "total_with_eight_generator_involutions": 105 + 8 + len(kept),
    }
    if summary["retained_table_relations"] != 534:
        raise ValueError("the audited transition selection has changed")
    source = """------------------------------------------------------------------------
-- Presentations of groups
--
-- The 534 retained three-wire transition relations: all 256 self-loops
-- and one direction of the 278 non-tree edges.  Forward tree cells are
-- empty-word reassociations.  Reverse cells are reduced generically.
-- Generated by ThreeQubit/build_reduced.py from finite_cosets.json.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+HH.ThreeQubit.ReducedTableData where

open import Data.Empty using (⊥)
open import Data.List.Base using (List)
open import Data.Product.Base using (proj₁ ; proj₂)
open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)
open import Word.Base using (Word ; [_]ʷ ; ε ; _•_)
import Presentation.Tactic.AssociativitySolver as Assoc
open import Examples.Groups.CCX+HH.Syntactics
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.ThreeQubit.StabilizerGenerators using (Letter)
open import Examples.Groups.CCX+HH.ThreeQubit.Table using (h)

private module Flat = Assoc.Assoc (λ (_ _ : Circuit 3) → ⊥)

flatten : Circuit 3 → List (Gen 3)
flatten = Flat.to-list

next : Coset → Gen 3 → Coset
next c g = proj₂ (h c g)

emitted : Coset → Gen 3 → Word Letter
emitted c g = proj₁ (h c g)

data Kept : Coset → Gen 3 → Set where
"""
    for c, g in sorted(kept):
        source += f"  keep{c:03d}-{g} : Kept c{c:03d} {PATTERN[names[g]]}\n"
    source += """
record Tree (c : Coset) (g : Gen 3) : Set where
  constructor tree-data
  field
    empty : emitted c g ≡ ε
    path : flatten (rep c • [ g ]ʷ) ≡ flatten (rep (next c g))

data Choice (c : Coset) (g : Gen 3) : Set where
  direct : Kept c g → Choice c g
  tree : Tree c g → Choice c g
  back-direct : Kept (next c g) g → Choice c g
  back-tree : Tree (next c g) g → Choice c g

choice : ∀ c g → Choice c g
"""
    for (c, g), (kind, origin) in sorted(choices.items()):
        witness = f"keep{origin:03d}-{g}" if kind in ("direct", "back-direct") else "(tree-data refl refl)"
        source += f"choice c{c:03d} {PATTERN[names[g]]} = {kind} {witness}\n"
    source += "".join(f"choice c {pattern}\n" for pattern in ABSURD)
    return source, summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated source without rewriting it")
    args = parser.parse_args()
    data = json.loads(HERE.joinpath("finite_cosets.json").read_text(encoding="utf-8"))
    source, summary = generate(data)
    target = HERE / "ReducedTableData.agda"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != source:
            raise SystemExit(f"Generated module differs: {target}")
    else:
        target.write_text(source, encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
