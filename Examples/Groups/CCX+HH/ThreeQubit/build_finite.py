#!/usr/bin/env python3
"""Generate finite three-wire Clément data and exact Agda obligations.

Use --check to verify that all generated modules match the stored exact data
without writing any files.  Typechecking the modules is a separate check.
"""

from fractions import Fraction
from pathlib import Path
import argparse
import json
import finite_cosets as F

HERE = Path(__file__).resolve().parent
DATA = json.loads(HERE.joinpath("finite_cosets.json").read_text(encoding="utf-8"))
CHECK = False
NUM = "₀₁₂₃₄₅₆₇"
PHYSICAL = {"X0": "X", "X1": "(X ↑)", "X2": "(X ↑ ↑)",
            "CX10": "CX", "CX21": "(CX ↑)", "CCX210": "CCX",
            "HH01": "HH", "HH12": "(HH ↑)"}
PATTERN = {"X0": "X-gen", "X1": "(X-gen ↥)", "X2": "(X-gen ↥ ↥)",
           "CX10": "CX-gen", "CX21": "(CX-gen ↥)", "CCX210": "CCX-gen",
           "HH01": "HH-gen", "HH12": "(HH-gen ↥)"}
ABSURD = ["(gate₀ ())", "((gate₀ ()) ↥)", "((gate₀ ()) ↥ ↥)", "((gate₀ ()) ↥ ↥ ↥)"]


def word(items):
    items = list(items)
    return " • ".join(items) if items else "ε"


def header(name, description):
    return ("------------------------------------------------------------------------\n"
            "-- Presentations of groups\n--\n-- " + description + "\n"
            "-- Generated by ThreeQubit/build_finite.py.\n"
            "------------------------------------------------------------------------\n\n"
            "{-# OPTIONS --without-K --safe #-}\n\n"
            f"module Examples.Groups.CCX+HH.ThreeQubit.{name} where\n\n")


def write(name, source):
    path = HERE.joinpath(name + ".agda")
    if CHECK:
        if not path.is_file() or path.read_text(encoding="utf-8") != source:
            raise SystemExit(f"Generated module differs: {path}")
    else:
        path.parent.mkdir(exist_ok=True)
        path.write_text(source, encoding="utf-8")


def cosets():
    s = header("Cosets", "The 135 coordinate-frame cosets and physical representatives.")
    s += "open import Word.Base using (ε ; _•_)\n"
    s += "open import Examples.Groups.CCX+HH.Syntactics\n\n"
    s += "data Coset : Set where\n"
    for i in range(0, 135, 9):
        s += "  " + " ".join(f"c{j:03d}" for j in range(i, min(i + 9, 135))) + " : Coset\n"
    s += "\nrep : Coset → Circuit 3\n"
    for i, route in enumerate(DATA["representative_words"]):
        s += f"rep c{i:03d} = {word(PHYSICAL[g] for g in route)}\n"
    write("Cosets", s)


def signature():
    vectors = [F.apply_word((4, 8, 12, 20, 28, 44, 52, 68), reversed(w))
               for w in DATA["representative_words"]]
    values = [sum(x ** 4 for x in v) for v in vectors]
    assert len(set(values)) == 135
    s = header("Signature", "Exact quartic signatures distinguish all 135 coset representatives.")
    s += """open import Data.Bool.Base using (if_then_else_)
open import Data.Integer.Base using (+_ ; -[1+_])
open import Data.Maybe.Base using (Maybe ; just ; nothing)
open import Data.Nat.Base using (ℕ ; _≡ᵇ_)
open import Data.Vec.Base using (Vec ; [] ; _∷_)
open import Data.Unit.Base using (tt)
open import Relation.Binary.PropositionalEquality as Eq using (_≡_ ; refl)
open import Examples.Groups.CCX+HH.Decide using (by-eqᵛ)
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.ThreeQubit.QuarticInvariant
import Examples.Groups.CCX+HH.StructuralEncoding as E
import Examples.Groups.CCX+HH-TwoLevel.Semantics as S
open import Examples.Groups.CCX+HH-TwoLevel.Ring
  using (D ; ι ; ι-injective ; _+ᴰ_ ; _*ᴰ_ ; -ᴰ_)
open S using (actV ; set₁ ; set₂)

expected-vector : Coset → Vec D 8
"""
    integer = lambda n: f"ι (+ {n})" if n >= 0 else f"ι (-[1+ {(-n) - 1} ])"
    for i, vector in enumerate(vectors):
        s += f"expected-vector c{i:03d} = " + " ∷ ".join(map(integer, vector)) + " ∷ []\n"
    s += "\nvalue : Coset → ℕ\n"
    for i, value in enumerate(values):
        s += f"value c{i:03d} = {value}\n"
    s += "\nopaque\n  unfolding actV set₁ set₂ _+ᴰ_ _*ᴰ_ -ᴰ_\n\n"
    s += "  checked-vector : ∀ c → S.actVʷ (E.encode (rep c)) probe ≡ expected-vector c\n"
    for i in range(135):
        s += f"  checked-vector c{i:03d} = by-eqᵛ tt\n"
    s += "\n  checked-value : ∀ c → quartic (expected-vector c) ≡ ι (+ value c)\n"
    for i in range(135):
        s += f"  checked-value c{i:03d} = refl\n"
    s += """
checked : ∀ c → signature (E.encode (rep c)) ≡ ι (+ value c)
checked c = Eq.trans (Eq.cong quartic (checked-vector c)) (checked-value c)

-- The inverse is a finite table using builtin natural equality.  The
-- 135 section checks establish injectivity without 18,090 pair cases.
recover : ℕ → Maybe Coset
recover n =
"""
    for i in range(135):
        s += f"  if n ≡ᵇ value c{i:03d} then just c{i:03d} else\n"
    s += "  nothing\n\nrecover-value : ∀ c → recover (value c) ≡ just c\n"
    for i in range(135):
        s += f"recover-value c{i:03d} = refl\n"
    s += """
private
  just-injective : ∀ {a b : Coset} → just a ≡ just b → a ≡ b
  just-injective refl = refl

  positive-injective : ∀ {a b : ℕ} → + a ≡ + b → a ≡ b
  positive-injective refl = refl

value-injective : ∀ {a b} → value a ≡ value b → a ≡ b
value-injective {a} {b} p = just-injective
  (Eq.trans (Eq.sym (recover-value a))
    (Eq.trans (Eq.cong recover p) (recover-value b)))

signature-injective : ∀ {a b} →
  signature (E.encode (rep a)) ≡ signature (E.encode (rep b)) → a ≡ b
signature-injective {a} {b} p = value-injective
  (positive-injective (ι-injective
    (Eq.trans (Eq.sym (checked a)) (Eq.trans p (checked b)))))
"""
    write("Signature", s)


def stabilizer():
    macros = ("x0", "x1", "x2", "cx10", "cx21", "cx01", "cx12", "ccx", "z0", "z1", "z2")
    physical = {"x0": "X", "x1": "(X ↑)", "x2": "(X ↑ ↑)",
                "cx10": "CX", "cx21": "(CX ↑)", "ccx": "CCX",
                "cx01": "HH • CX • HH", "cx12": "(HH ↑) • (CX ↑) • (HH ↑)",
                "z0": "HH • X • HH", "z1": "HH • (X ↑) • HH",
                "z2": "(HH ↑) • (X ↑ ↑) • (HH ↑)"}
    swaps = {"x0": [(0,1),(2,3),(4,5),(6,7)], "x1": [(0,2),(1,3),(4,6),(5,7)],
             "x2": [(0,4),(1,5),(2,6),(3,7)], "cx10": [(2,3),(6,7)],
             "cx21": [(4,6),(5,7)], "cx01": [(1,3),(5,7)],
             "cx12": [(2,6),(3,7)], "ccx": [(6,7)]}
    def transposition(a,b):
        proof = "z≤n"
        for _ in range(a+1):
            proof = f"(s≤s {proof})"
        return f"T.X {NUM[a]} {NUM[b]} {proof}"
    def compress(route):
        route, result = list(route), []
        triples = {("HH01","CX10","HH01"): "cx01", ("HH12","CX21","HH12"): "cx12",
                   ("HH01","X0","HH01"): "z0", ("HH01","X1","HH01"): "z1",
                   ("HH12","X2","HH12"): "z2"}
        singles = {"X0":"x0", "X1":"x1", "X2":"x2", "CX10":"cx10", "CX21":"cx21", "CCX210":"ccx"}
        while route:
            triple = tuple(route[:3])
            if triple in triples:
                result.append(triples[triple])
                del route[:3]
            else:
                result.append(singles[route.pop(0)])
        return list(reversed(result))
    s = header("StabilizerGenerators", "Fourteen even signed-permutation generators and their physical decoders.")
    s += """open import Data.Fin.Base as F using (Fin ; _<_)
open import Data.Nat.Base using (s≤s ; z≤n)
open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)
open import Notations
open import Word.Base using (Word ; [_]ʷ ; ε ; _•_ ; _ʷ)
open import Examples.Groups.CCX+HH.Syntactics
import Examples.Groups.CCX+HH.StructuralEncoding as E
import Examples.Groups.CCX+HH-TwoLevel.Syntactics as T
import Examples.Groups.CCX+HH-TwoLevel.Semantics as S
import Examples.Groups.CCX+HH-TwoLevel.MainLemma as Main
import Presentation.Base as PB
import Examples.Groups.CCX+HH.ThreeQubit.QuarticInvariant as Q
open import Examples.Groups.CCX+HH-TwoLevel.Ring using (_+ᴰ_ ; _*ᴰ_ ; -ᴰ_)
open S using (actV ; set₁ ; set₂)
private module A = PB (T._===_ {8})

data Letter : Set where
  exchange phase : Fin 7 → Letter

private
  adjacent : ∀ {n} (i : Fin n) → F.inject₁ i < F.suc i
  adjacent F.zero = s≤s z≤n
  adjacent (F.suc i) = s≤s (adjacent i)

b : Letter → Word (T.Gen 8)
b (exchange i) = T.X (F.inject₁ i) (F.suc i) (adjacent i)
b (phase i) = T.M F.zero • T.M (F.suc i)

b-signed : ∀ g → Q.Signed (b g)
b-signed (exchange i) = Q.exchange (F.inject₁ i) (F.suc i) (adjacent i)
b-signed (phase i) = Q.product (Q.minus F.zero) (Q.minus (F.suc i))

data Macro : Set where
"""
    s += "  " + " ".join(macros) + " : Macro\n\nrealise : Macro → Circuit 3\n"
    for macro in macros:
        s += f"realise {macro} = {physical[macro]}\n"
    s += "\naux : Macro → Word (T.Gen 8)\n"
    for macro in macros:
        if macro in swaps:
            expression = word(transposition(a,b) for a,b in swaps[macro])
        else:
            k = int(macro[1])
            expression = word(f"T.M {NUM[i]}" for i in range(8) if i & (1 << k))
        s += f"aux {macro} = {expression}\n"
    s += "\nplan : Letter → Word Macro\n"
    for i in range(7):
        route = DATA["stabilizer_generator_words"][f"X[{i},{i+1}]"]
        s += f"plan (exchange {NUM[i]}) = {word(f'[ {m} ]ʷ' for m in compress(route))}\n"
    for i in range(7):
        route = DATA["stabilizer_generator_words"][f"M[0] M[{i+1}]"]
        s += f"plan (phase {NUM[i]}) = {word(f'[ {m} ]ʷ' for m in compress(route))}\n"
    s += "\nd : Letter → Circuit 3\nd g = (realise ʷ) (plan g)\n\n"
    s += "opaque\n  unfolding actV set₁ set₂ _+ᴰ_ _*ᴰ_ -ᴰ_\n\n"
    s += "  checked-macro : ∀ g → S.⟦ E.encode (realise g) ⟧ᵐ ≡ S.⟦ aux g ⟧ᵐ\n"
    for macro in macros:
        s += f"  checked-macro {macro} = refl\n"
    s += "\n  checked-plan : ∀ g → S.⟦ (aux ʷ) (plan g) ⟧ᵐ ≡ S.⟦ b g ⟧ᵐ\n"
    for kind in ("exchange", "phase"):
        for i in range(7):
            s += f"  checked-plan ({kind} {NUM[i]}) = refl\n"
    s += """
realise-correct : ∀ w → E.encode ((realise ʷ) w) A.≈ (aux ʷ) w
realise-correct [ g ]ʷ = Main.completeness (checked-macro g)
realise-correct ε = A.refl
realise-correct (u • v) = A.cong (realise-correct u) (realise-correct v)

d-correct : ∀ g → E.encode (d g) A.≈ b g
d-correct g = A.trans (realise-correct (plan g)) (Main.completeness (checked-plan g))
"""
    write("StabilizerGenerators", s)


# Representative matrices are proved in groups of 27, so that no one
# module evaluates more than 27 of them.
MATRIX_GROUPS = range(0, 135, 27)


def physical_matrix(name):
    """The 8 × 8 matrix of a gate, entry [y][x] = ⟨y|G|x⟩, wire 0 the low bit."""
    def flip(target, controls=()):
        return lambda x: x ^ (1 << target) if all(x >> c & 1 for c in controls) else x

    def permutation(f):
        return [[Fraction(int(y == f(x))) for x in range(8)] for y in range(8)]

    def hh(a, b):
        mask = (1 << a) | (1 << b)
        return [[Fraction((-1) ** bin(y & x & mask).count("1"), 2) if (y & ~mask) == (x & ~mask)
                 else Fraction(0) for x in range(8)] for y in range(8)]

    gates = {"X0": lambda: permutation(flip(0)), "X1": lambda: permutation(flip(1)),
             "X2": lambda: permutation(flip(2)), "CX10": lambda: permutation(flip(0, (1,))),
             "CX21": lambda: permutation(flip(1, (2,))),
             "CCX210": lambda: permutation(flip(0, (1, 2))),
             "HH01": lambda: hh(0, 1), "HH12": lambda: hh(1, 2)}
    return gates[name]()


def representative_matrix(route):
    """The matrix of rep c: the product of its gates in written order."""
    m = [[Fraction(int(i == j)) for j in range(8)] for i in range(8)]
    for name in route:
        g = physical_matrix(name)
        m = [[sum(m[i][k] * g[k][j] for k in range(8)) for j in range(8)] for i in range(8)]
    return m


def dyadic_name(v):
    """A name for the canonical dyadic a / 2^k: p (or m for negative) a x k."""
    k = v.denominator.bit_length() - 1
    assert v.denominator == 1 << k
    return ("p" if v >= 0 else "m") + f"{abs(v.numerator)}x{k}"


def dyadic_literal(v):
    k = v.denominator.bit_length() - 1
    a = v.numerator
    numerator = f"(+ {a})" if a >= 0 else f"-[1+ {-a - 1} ]"
    return f"Dyadic' {numerator} {k} _"


def matrices():
    ms = [representative_matrix(route) for route in DATA["representative_words"]]
    values = sorted({v for m in ms for row in m for v in row})
    s = header("Checks.Matrices", "The matrices of the 135 coset representatives, as literals.")
    s += """open import Data.Integer.Base using (+_ ; -[1+_])
open import Data.Vec.Base using ([] ; _∷_)
open import Quantum.Synthesis.Ring using (Dyadic')
open import Quantum.Synthesis.Matrix using (Matrix ; Matrix')
open import Examples.Groups.CCX+HH-TwoLevel.Ring using (D)

-- The entries: pAxK is A / 2^K and mAxK is -A / 2^K.
private
"""
    s += "  " + " ".join(dyadic_name(v) for v in values) + " : D\n"
    for v in values:
        s += f"  {dyadic_name(v)} = {dyadic_literal(v)}\n"
    s += "\n-- A matrix is listed by columns.\n"
    for c, m in enumerate(ms):
        columns = [" ∷ ".join(dyadic_name(m[r][x]) for r in range(8)) + " ∷ []" for x in range(8)]
        s += f"\nm{c:03d} : Matrix 8 8 D\nm{c:03d} = Matrix'\n  ( "
        s += "\n  ∷ ".join(f"({col})" for col in columns) + "\n  ∷ [])\n"
    write("Checks/Matrices", s)
    for first in MATRIX_GROUPS:
        last = min(first + 27, 135) - 1
        s = header(f"Checks.Matrices{first:03d}",
                   f"The stored matrices of representatives {first} through {last} are theirs.")
        s += """open import Data.Unit.Base using (tt)
open import Relation.Binary.PropositionalEquality using (_≡_)
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.Decide using (by-eq)
open import Examples.Groups.CCX+HH.ThreeQubit.Checks.Matrices
import Examples.Groups.CCX+HH.StructuralEncoding as E
import Examples.Groups.CCX+HH-TwoLevel.Semantics as S
open import Examples.Groups.CCX+HH-TwoLevel.Ring using (_+ᴰ_ ; _*ᴰ_ ; -ᴰ_)
open S using (actV ; set₁ ; set₂)

opaque
  unfolding actV set₁ set₂ _+ᴰ_ _*ᴰ_ -ᴰ_
"""
        for c in range(first, last + 1):
            s += f"\n  ok{c:03d} : S.⟦ E.encode (rep c{c:03d}) ⟧ᵐ ≡ m{c:03d}\n  ok{c:03d} = by-eq tt\n"
        write(f"Checks/Matrices{first:03d}", s)


def table():
    s = header("Table","The exact 135-state factorization table over fourteen stabilizer generators.")
    s += """open import Data.Product.Base using (_×_ ; _,_ ; proj₁ ; proj₂)
open import Notations
open import Word.Base using (Word ; [_]ʷ ; ε ; _•_)
open import Examples.Groups.CCX+HH.Syntactics
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.ThreeQubit.StabilizerGenerators using (Letter ; exchange ; phase)

h : Coset → Gen 3 → Word Letter × Coset
"""
    for c, row in enumerate(DATA["factorizations"]):
        for g, cell in zip(DATA["generators"], row):
            expression = word(f"[ {'exchange' if kind == 'X' else 'phase'} {NUM[index if kind == 'X' else index-1]} ]ʷ"
                              for kind,index in cell["stabilizer_word_matrix_order"])
            s += f"h c{c:03d} {PATTERN[g]} = ({expression}) , c{cell['next']:03d}\n"
    for pattern in ABSURD:
        s += f"h c {pattern}\n"
    write("Table", s)
    s = header("Checks.Base", "The source-matrix equation for one finite coset table cell.")
    s += """open import Data.Product.Base using (proj₁ ; proj₂)
open import Relation.Binary.PropositionalEquality using (_≡_)
open import Word.Base using (_•_ ; _ʷ)
open import Examples.Groups.CCX+HH.Syntactics
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.ThreeQubit.Table
open import Examples.Groups.CCX+HH.ThreeQubit.StabilizerGenerators using (b)
import Examples.Groups.CCX+HH.StructuralEncoding as E
import Examples.Groups.CCX+HH-TwoLevel.Semantics as S

Checked : Coset → Gen 3 → Set
Checked c g = S.⟦ E.encode (rep c) • E.e g ⟧ᵐ ≡
  S.⟦ (b ʷ) (proj₁ (h c g)) • E.encode (rep (proj₂ (h c g))) ⟧ᵐ
"""
    write("Checks/Base", s)
    for start in range(0, 135, 9):
        s = header(f"Checks.Rows{start:03d}", f"Exact source factorizations for cosets {start} through {start+8}.")
        s += """open import Data.Unit.Base using (tt)
open import Examples.Groups.CCX+HH.Syntactics
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.ThreeQubit.Checks.Base
open import Examples.Groups.CCX+HH.Decide using (by-eq)
open import Examples.Groups.CCX+HH.ThreeQubit.Checks.Assemble using (assemble)
open import Examples.Groups.CCX+HH.ThreeQubit.Checks.Matrices
"""
        for first in MATRIX_GROUPS:
            s += f"open import Examples.Groups.CCX+HH.ThreeQubit.Checks.Matrices{first:03d}\n"
        s += """open import Examples.Groups.CCX+HH-TwoLevel.Ring using (_+ᴰ_ ; _*ᴰ_ ; -ᴰ_ ; adjᴰ)
open import Examples.Groups.CCX+HH-TwoLevel.Semantics using (actV ; set₁ ; set₂)

opaque
  unfolding actV set₁ set₂ _+ᴰ_ _*ᴰ_ -ᴰ_ adjᴰ

"""
        for c in range(start, start+9):
            s += f"  checked{c:03d} : ∀ g → Checked c{c:03d} g\n"
            for g, cell in zip(DATA["generators"], DATA["factorizations"][c]):
                n = cell["next"]
                s += (f"  checked{c:03d} {PATTERN[g]} = assemble c{c:03d} {PATTERN[g]}"
                      f" m{c:03d} m{n:03d} ok{c:03d} ok{n:03d} (by-eq tt)\n")
            for pattern in ABSURD:
                s += f"  checked{c:03d} {pattern}\n"
            s += "\n"
        write(f"Checks/Rows{start:03d}", s)
    s = header("Factorizations", "All 1080 table cells as derivations from Table 1.")
    s += """open import Data.Product.Base using (proj₁ ; proj₂)
open import Word.Base using (_•_ ; _ʷ)
open import Examples.Groups.CCX+HH.Syntactics
open import Examples.Groups.CCX+HH.ThreeQubit.Cosets
open import Examples.Groups.CCX+HH.ThreeQubit.Table
open import Examples.Groups.CCX+HH.ThreeQubit.StabilizerGenerators using (b)
import Examples.Groups.CCX+HH.StructuralEncoding as E
import Examples.Groups.CCX+HH-TwoLevel.Syntactics as T
import Examples.Groups.CCX+HH-TwoLevel.MainLemma as Main
import Presentation.Base as PB
"""
    for start in range(0, 135, 9):
        s += f"open import Examples.Groups.CCX+HH.ThreeQubit.Checks.Rows{start:03d}\n"
    s += """
factor : ∀ c g → PB._≈_ (T._===_ {8})
  (E.encode (rep c) • E.e g)
  ((b ʷ) (proj₁ (h c g)) • E.encode (rep (proj₂ (h c g))))
"""
    for c in range(135):
        s += f"factor c{c:03d} g = Main.completeness (checked{c:03d} g)\n"
    write("Factorizations", s)


