"""Generate Auxiliary/Bridge/TwoQubit.agda.

TwoQubit reads the auxiliary generators through its own (private)
copies of the one- and two-level matrices; the generated module checks
that they agree entry by entry with those of Auxiliary.Matrices, which
Bridge.Matrix reads at code = bits, one `refl` per entry.

Usage: python3 gen2q.py [OUTFILE]   (default: ../TwoQubit.agda)
"""
import os, sys
fins = ['₀','₁','₂','₃']
bv = {'ff':'(false ∷ false ∷ [])','tf':'(true ∷ false ∷ [])','ft':'(false ∷ true ∷ [])','tt':'(true ∷ true ∷ [])'}
bs = list(bv.values())
out = []
w = out.append
w("""------------------------------------------------------------------------
-- Presentations of groups
--
-- The two-qubit matrices of the auxiliary generators, numbered by code
--
-- TwoQubit reads the generators (−1)_[a], X_[a,b], H_[a,b] on four
-- basis vectors, numbered by its table bits, through its own copies of
-- the one- and two-level matrices; they agree entry by entry with those
-- of Auxiliary.Matrices that Bridge.Matrix reads at code = bits
-- (agreeZ, agreeX, agreeH, decided on all 4 × 4 × 4 × 4 entries), so
-- Φ reads them alike (Φ-agree).  Generated by gen/gen2q.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.Real-Clifford+CH.Auxiliary.Bridge.TwoQubit where

open import Data.Bool.Base using (true ; false)
open import Data.Fin.Base using (Fin)
open import Data.Product.Base using (proj₂)
open import Data.Vec.Base using ([] ; _∷_)
open import Relation.Binary.PropositionalEquality using (_≡_ ; refl)

open import Notations using (₀ ; ₁ ; ₂ ; ₃)
open import Examples.Groups.Real-Clifford+CH.Semantics.Algebra using (Bits ; _≐_)
open import Examples.Groups.Real-Clifford+CH.TwoQubit using (bits ; ⟦_⟧ʸ)
import Examples.Groups.Real-Clifford+CH.Auxiliary.Syntactics as G
open G using (−1[_] ; X[_,_] ; H[_,_])
import Examples.Groups.Real-Clifford+CH.Auxiliary.Bridge.Matrix as Matrix

------------------------------------------------------------------------
-- The numbering and its inverse

index : Bits 2 → Fin 4
index (false ∷ false ∷ []) = ₀
index (true  ∷ false ∷ []) = ₁
index (false ∷ true  ∷ []) = ₂
index (true  ∷ true  ∷ []) = ₃

code-index : ∀ g → bits (index g) ≡ g
code-index (false ∷ false ∷ []) = refl
code-index (true  ∷ false ∷ []) = refl
code-index (false ∷ true  ∷ []) = refl
code-index (true  ∷ true  ∷ []) = refl

index-code : ∀ a → index (bits a) ≡ a
index-code ₀ = refl
index-code ₁ = refl
index-code ₂ = refl
index-code ₃ = refl

open Matrix 2 bits index code-index index-code public

------------------------------------------------------------------------
-- Agreement, entry by entry
""")
w("agreeZ : ∀ a → proj₂ ⟦ −1[ a ] ⟧ʸ ≐ proj₂ ⟦ −1[ a ] ⟧c")
for a in fins:
    for x in bs:
        w(f"agreeZ {a} {x} y = refl")
w("")
w("agreeX : ∀ a b → proj₂ ⟦ X[ a , b ] ⟧ʸ ≐ proj₂ ⟦ X[ a , b ] ⟧c")
for a in fins:
    for b in fins:
        for x in bs:
            w(f"agreeX {a} {b} {x} y = refl")
w("")
w("agreeH : ∀ a b → proj₂ ⟦ H[ a , b ] ⟧ʸ ≐ proj₂ ⟦ H[ a , b ] ⟧c")
for a in fins:
    for b in fins:
        for x in bs:
            for y in bs:
                w(f"agreeH {a} {b} {x} {y} = refl")
w("""
Φ-agree : ∀ g → Φ ⟦ g ⟧ʸ ≡ Φ ⟦ g ⟧c
Φ-agree −1[ a ]    = Φ-≐ {0} {proj₂ ⟦ −1[ a ] ⟧ʸ} {proj₂ ⟦ −1[ a ] ⟧c} (agreeZ a)
Φ-agree X[ a , b ] = Φ-≐ {0} {proj₂ ⟦ X[ a , b ] ⟧ʸ} {proj₂ ⟦ X[ a , b ] ⟧c} (agreeX a b)
Φ-agree H[ a , b ] = Φ-≐ {1} {proj₂ ⟦ H[ a , b ] ⟧ʸ} {proj₂ ⟦ H[ a , b ] ⟧c} (agreeH a b)""")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'TwoQubit.agda')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
