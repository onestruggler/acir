"""Writes KData.agda: a Coxeter word for each letter on the lower three
wires, whose circuit (Pc) has the letter's function on the Gray
positions.  Pc v realises the inverse of act v, so v is the word of the
inverse of the letter's permutation (each letter is an involution)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from clabels import GRAY, POS, word_of, inverse  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), 'KData.agda')
W = ['₀', '₁', '₂', '₃']


def X(t):
    return lambda x: x ^ (1 << t)


def CX(c, t):
    return lambda x: x ^ (((x >> c) & 1) << t)


def CCX(a, b, t):
    return lambda x: x ^ ((((x >> a) & (x >> b)) & 1) << t)


LOWER = [('Xᵖ %s' % W[t], X(t)) for t in range(3)] + \
        [('CXᵖ %s %s' % (W[c], W[t]), CX(c, t)) for c in range(3) for t in range(3) if c != t] + \
        [('CCXᵖ ₀ ₁ ₂', CCX(0, 1, 2)), ('CCXᵖ ₀ ₂ ₁', CCX(0, 2, 1)), ('CCXᵖ ₁ ₂ ₀', CCX(1, 2, 0))]


def cw(w):
    if not w:
        return 'ε'
    return ' • '.join('[ s%s ]ʷ' % '₀₁₂₃₄₅₆'[d] for d in w)


HDR = r'''------------------------------------------------------------------------
-- Presentations of groups
--
-- Coxeter words for the letters of the lower wires
--
-- For each of the twelve letters on wires 0, 1, 2, a word of S₈'s
-- Coxeter generators whose circuit (PFrames' Pc) has the letter's
-- function on the eight Gray positions of the lower states; any other
-- letter gets ε.  KFaithful checks each of them.  Generated by
-- gen/mk_kdata.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.XCXCCX-4bit.KData where

open import Word.Base using ([_]ʷ ; ε ; _•_)

open import Notations using (₀ ; ₁ ; ₂)

open import Examples.Groups.XCXCCX-4bit.Placed using (PG ; Xᵖ ; CXᵖ ; CCXᵖ)
open import Examples.Groups.XCXCCX-4bit.PFrames using (CW)
open import Examples.Groups.XCXCCX-4bit.CLabels using (s₀ ; s₁ ; s₂ ; s₃ ; s₄ ; s₅ ; s₆)

rg : PG → CW
'''


def main():
    o = [HDR.rstrip('\n')]
    for n, f in LOWER:
        fwd = tuple(POS[f(GRAY[i])] for i in range(8))
        assert inverse(fwd) == fwd
        w = word_of(inverse(fwd))
        o.append('rg (%s) = %s' % (n, cw(w)))
    o.append('rg _ = ε')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(o) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
