"""Writes NFTables.agda: the case tables of the block normal form (the
states of half b at Gray position p, Four's numbering of the sixteen
states by halves, the reversal of the eight positions)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'NFTables.agda')
F8 = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇']
F16 = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇', '₈', '₉', '₁₀', '₁₁', '₁₂', '₁₃', '₁₄', '₁₅']
GRAY = [0b000, 0b001, 0b011, 0b010, 0b110, 0b111, 0b101, 0b100]
B = lambda b: 'true' if b else 'false'


def bits3(s):
    return [(s >> k) & 1 for k in range(3)]


def vec(bs):
    return '(' + ' ∷ '.join(B(b) for b in bs) + ' ∷ [])'


# Four's numbering: index i < 8 is the lower state at Gray position i;
# index 8 + j is the upper state at Gray position 7 - j.
def four(i):
    if i < 8:
        return bits3(GRAY[i]) + [0]
    return bits3(GRAY[15 - i]) + [1]


def idx(b, p):
    return p if not b else 15 - p


o = [HDR := r'''------------------------------------------------------------------------
-- Presentations of groups
--
-- Tables for the block normal form
--
-- The state of half b (wire 3) at Gray position p of the lower wires
-- (st), Four's numbering of the sixteen states (lower half first in
-- Gray order, upper half in reflected Gray order: idx), and the
-- reversal of the eight positions (rev8), with their case-by-case
-- laws.  Generated by gen/mk_nftables.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.XCXCCX-4bit.NFTables where

open import Data.Bool.Base using (Bool ; true ; false ; not)
open import Data.Fin.Base using (Fin ; zero ; suc ; toℕ)
open import Data.Fin.Permutation using (Permutation′ ; permutation ; _⟨$⟩ʳ_)
open import Data.Nat.Base using (_<ᵇ_)
open import Data.Vec.Base using ([] ; _∷_)
import Data.Vec.Base as V
open import Relation.Binary.PropositionalEquality as Eq using (_≡_)

open import Notations using (₀ ; ₁ ; ₂ ; ₃ ; ₄ ; ₅ ; ₆ ; ₇ ; ₈ ; ₉ ; ₁₀ ; ₁₁ ; ₁₂ ; ₁₃ ; ₁₄ ; ₁₅)

open import Examples.Groups.XCXCCX-4bit.Semantics using (Bits)
import Examples.Groups.XCXCCX-4bit.Width3 as W3
open import Examples.Groups.XCXCCX-4bit.CSem using (enc8 ; pos)

-- Wire 3 of a state.
w3 : Bits 4 → Bool
w3 (_ ∷ _ ∷ _ ∷ b ∷ []) = b

-- The state of half b at Gray position p.
st : Bool → Fin 8 → Bits 4
st b p = W3.enc p V.++ (b ∷ [])
''']
o.append('w3-st : ∀ b p → w3 (st b p) ≡ b')
for b in (0, 1):
    for p in range(8):
        o.append('w3-st %s %s = Eq.refl' % (B(b), F8[p]))
o.append('')
o.append('pos-st : ∀ b p → pos (st b p) ≡ p')
for b in (0, 1):
    for p in range(8):
        o.append('pos-st %s %s = Eq.refl' % (B(b), F8[p]))
o.append('')
o.append('st-eta : ∀ x → st (w3 x) (pos x) ≡ x')
for s in range(16):
    bs = [(s >> k) & 1 for k in range(4)]
    o.append('st-eta %s = Eq.refl' % vec(bs))
o.append('')
o.append('enc8-st : ∀ p → enc8 p ≡ st true p')
for p in range(8):
    o.append('enc8-st %s = Eq.refl' % F8[p])
o.append('')
o.append('-- Four\'s index of the state of half b at position p.')
o.append('idx : Bool → Fin 8 → Fin 16')
for b in (0, 1):
    for p in range(8):
        o.append('idx %s %s = %s' % (B(b), F8[p], F16[idx(b, p)]))
o.append('')
o.append('-- Four\'s numbering, as a table (equal to Four.enc, checked there).')
o.append('enc′ : Fin 16 → Bits 4')
for i in range(16):
    o.append('enc′ %s = %s' % (F16[i], vec(four(i))))
o.append('')
o.append('enc′-idx : ∀ b p → enc′ (idx b p) ≡ st b p')
for b in (0, 1):
    for p in range(8):
        o.append('enc′-idx %s %s = Eq.refl' % (B(b), F8[p]))
o.append('')
o.append('isHi′ : Fin 16 → Bool')
o.append('isHi′ i = w3 (enc′ i)')
o.append('')
o.append('pos4′ : Fin 16 → Fin 8')
o.append('pos4′ i = pos (enc′ i)')
o.append('')
o.append('idx-eta : ∀ i → idx (isHi′ i) (pos4′ i) ≡ i')
for i in range(16):
    o.append('idx-eta %s = Eq.refl' % F16[i])
o.append('')
o.append('isHi-lt : ∀ i → isHi′ i ≡ not (toℕ i <ᵇ 8)')
for i in range(16):
    o.append('isHi-lt %s = Eq.refl' % F16[i])
o.append('')
o.append('-- The reversal of the eight positions.')
o.append('rv : Fin 8 → Fin 8')
for p in range(8):
    o.append('rv %s = %s' % (F8[p], F8[7 - p]))
o.append('')
o.append('rv-rv : ∀ p → rv (rv p) ≡ p')
for p in range(8):
    o.append('rv-rv %s = Eq.refl' % F8[p])
o.append('')
o.append('rev8 : Permutation′ 8')
o.append('rev8 = permutation rv rv rv-rv rv-rv')
o.append('')
o.append('-- The upper index of a position: eight above its reversal.')
o.append('hi-lift : ∀ y → idx true y ≡ suc (suc (suc (suc (suc (suc (suc (suc (rev8 ⟨$⟩ʳ y))))))))')
for p in range(8):
    o.append('hi-lift %s = Eq.refl' % F8[p])
with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('\n'.join(o) + '\n')
print('wrote', OUT)
