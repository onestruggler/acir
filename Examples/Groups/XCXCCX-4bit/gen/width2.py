def fin(i):
    s = 'zero'
    for _ in range(i):
        s = 'suc (%s)' % s if ' ' in s else 'suc %s' % s
    return s


def sgen(d):
    return '(Sym.gate₂ Sym.σ-gate' + ' Sym.↥' * d + ')'


def tact(N, n_wires):
    lines = ['T-act : ∀ (g : Cox.SG %d) (i : Fin %d) → ⟦ T (Cox.tr 0 g) ⟧ (enc i) ≡ enc (Sym⟦ g ⟧ i)'
             % (N, N)]
    for d in range(N - 1):
        for i in range(N):
            lines.append('T-act %s (%s) = refl' % (sgen(d), fin(i)))
    for d in range(N + 1):
        lines.append('T-act (Sym.gate₀ ()%s) i' % (' Sym.↥' * d))
        if d < N:
            lines.append('T-act (Sym.gate₁ ()%s) i' % (' Sym.↥' * d))
    return '\n'.join(lines) + '\n'


