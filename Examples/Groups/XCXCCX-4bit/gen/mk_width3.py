MID = r'''
------------------------------------------------------------------------
-- An equation between letter lists, as one between any two words with
-- those letters.

via : ∀ {n} (e : Eqn n) {w v : Circuit n} →
      PP.to-list (n VRel,_===_) ⟪ lhs⁼ e ⟫ ≡ PP.to-list (n VRel,_===_) w →
      PP.to-list (n VRel,_===_) ⟪ rhs⁼ e ⟫ ≡ PP.to-list (n VRel,_===_) v → n ⊢ w ≈ v
via {n} e e₁ e₂ = PB.trans (PP.by-assoc (n VRel,_===_) (Eq.sym e₁))
                    (PB.trans (prf e) (PP.by-assoc (n VRel,_===_) e₂))

------------------------------------------------------------------------
-- The transpositions of consecutive states

T : ℕ → Circuit 3
'''


def coxeter_record():
    lines = []
    lines.append('private')
    lines.append('  no : ∀ {m} → 9 + m ≤ 8 → ⊥')
    lines.append('  no (s≤s (s≤s (s≤s (s≤s (s≤s (s≤s (s≤s (s≤s ()))))))))')
    lines.append('')
    lines.append('cox : Cox.Circuits.Coxeter 8 T (3 VRel,_===_)')
    lines.append('cox = record { order = order ; braid = braid ; far = far }')
    lines.append('  where')
    lines.append('  order : ∀ i → 2 + i ≤ 8 → 3 ⊢ T i • T i ≈ ε')
    for i in range(7):
        lines.append('  order %d _ = via T%d²⁼ refl refl' % (i, i))
    lines.append('  order (suc (suc (suc (suc (suc (suc (suc i))))))) p = ⊥-elim (no p)')
    lines.append('  braid : ∀ i → 3 + i ≤ 8 → 3 ⊢ T i • T (suc i) • T i ≈ T (suc i) • T i • T (suc i)')
    for i in range(6):
        lines.append('  braid %d _ = via braid%d⁼ refl refl' % (i, i))
    lines.append('  braid (suc (suc (suc (suc (suc (suc i)))))) p = ⊥-elim (no p)')
    lines.append('  far : ∀ i j → 2 + i ≤ j → 2 + j ≤ 8 → 3 ⊢ T i • T j ≈ T j • T i')
    lines.append('  far i (suc (suc (suc (suc (suc (suc (suc j))))))) p q = ⊥-elim (no q)')
    for i in range(7):
        for j in range(7):
            if j >= i + 2:
                lines.append('  far %d %d _ _ = via far%d%d⁼ refl refl' % (i, j, i, j))
            else:
                pat = '()'
                for _ in range(j):
                    pat = '(s≤s %s)' % pat
                lines.append('  far %d %d %s _' % (i, j, pat))
    lines.append('  far (suc (suc (suc (suc (suc (suc (suc i))))))) j p q =')
    lines.append('    ⊥-elim (no (ℕP.≤-trans (ℕP.+-monoʳ-≤ 2 p) q))')
    return '\n'.join(lines) + '\n'


def bits(g):
    return '(%s ∷ %s ∷ %s ∷ [])' % tuple('true' if (g >> w) & 1 else 'false' for w in (0, 1, 2))


def fin(i):
    s = 'zero'
    for _ in range(i):
        s = 'suc (%s)' % s if ' ' in s else 'suc %s' % s
    return s


def numbering():
    L = ['------------------------------------------------------------------------',
         '-- The numbering of the states, and the action of the T d', '',
         'enc : Fin 8 → Bits 3']
    for i, g in enumerate(GRAY):
        L.append('enc (%s) = %s' % (fin(i), bits(g)))
    L += ['', 'dec : Bits 3 → Fin 8']
    for i, g in enumerate(GRAY):
        L.append('dec %s = %s' % (bits(g), fin(i)))
    L += ['', 'dec-enc : ∀ i → dec (enc i) ≡ i']
    for i in range(8):
        L.append('dec-enc (%s) = refl' % fin(i))
    L += ['', 'private', '  Sym⟦_⟧ : Cox.SG 8 → Fin 8 → Fin 8', '  Sym⟦ g ⟧ i = SymI.⟦ [ g ]ʷ ⟧ ⟨$⟩ʳ i', '',
          'T-act : ∀ (g : Cox.SG 8) (i : Fin 8) → ⟦ T (Cox.tr 0 g) ⟧ (enc i) ≡ enc (Sym⟦ g ⟧ i)']
    for d in range(7):
        for i in range(8):
            L.append('T-act (Sym.gate₂ Sym.σ-gate%s) (%s) = refl' % (' Sym.↥' * d, fin(i)))
    for d in range(9):
        L.append('T-act (Sym.gate₀ ()%s) i' % (' Sym.↥' * d))
    for d in range(8):
        L.append('T-act (Sym.gate₁ ()%s) i' % (' Sym.↥' * d))
    return '\n'.join(L) + '\n'


