AG = {'X0': 'X', 'X1': 'X ↑', 'X2': 'X ↑ ↑', 'CX0': 'CX', 'CX1': 'CX ↑', 'SW0': 'σ', 'SW1': 'σ ↑',
      'CCX0': 'CCX'}


def agda_word(s):
    toks = s.split()
    if not toks:
        return 'ε'
    return ' • '.join(AG[t] for t in toks)


