# Writes Five/Transport.agda: transport of four-wire derivations under the
# controlled functor (the joint paper's Lemma transport at n = 5), from
# the (F1) items (a record of them, so that the module checks before they
# are emitted) and (F2).  The only generated part is the disjointness of
# the two generators of every structural commutation (Five.F2.apart, at
# each depth of cong↑), a finite enumeration.
#   python3 gen_transport.py
import os
HERE = os.path.dirname(os.path.abspath(__file__))
FIVE = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'Five')
NL = '\n'


def gens(k):
    """the generators of Gen k, as Agda patterns."""
    if k == 0:
        return ['I-gen']
    out = ['I-gen', 'S-gen', 'K-gen'] + (['CS-gen'] if k >= 2 else [])
    return out + [f'{g} ↥' for g in gens(k - 1)]


def up(s, j):
    return s + ''.join(' ↥' for _ in range(j))


SUB = '₀₁₂₃₄'


def ap_defs():
    out = []
    # comm₁ at width w (1..4), under 4 - w cong↑: g : Gen (w - 1)
    for w in range(4, 0, -1):
        j = 4 - w
        nm = f'ap₁{SUB[w]}'
        out.append(f'{nm} : (h : Gate 1) (g : Gen {w - 1}) → T (apart ({up("g ↥", j)}) ({up("gate₁ h", j)}))')
        for h in ('S-gate', 'K-gate'):
            for g in gens(w - 1):
                out.append(f'{nm} {h} ({g}) = _')
        out.append('')
    # comm₂ at width w (2..4): g : Gen (w - 2)
    for w in range(4, 1, -1):
        j = 4 - w
        nm = f'ap₂{SUB[w]}'
        out.append(f'{nm} : (h : Gate 2) (g : Gen {w - 2}) → T (apart ({up("g ↥ ↥", j)}) ({up("gate₂ h", j)}))')
        for g in gens(w - 2):
            out.append(f'{nm} CS-gate ({g}) = _')
        out.append('')
    return NL.join(out)


HEAD = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- Transport: four-wire derivations under the controlled functor
--
-- The joint paper's Lemma transport at n = 5: if two circuits on four
-- wires are equal then so are their controlled versions on five, under
-- a black control (λ¹) and under a white one (λ⁰).  By induction on the
-- derivation: the monoid laws and congruence are the functor's, a rule
-- of Syntactics at any placement is an item of (F1), a structural
-- commutation one of (F2), and the scalar's rule ω↑=ω holds on the
-- nose (λ¹ of the scalar is S on the top wire, at every depth).  The
-- (F1) items are a record here (F1), so that this module does not
-- depend on their derivations; Five.F1 provides it.  Low and Mid carry
-- two- and three-wire derivations on the top domain wires with only
-- the items they meet.  Generated by
-- scratchpad/five/gen_transport.py (the disjointness proofs).
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.Clifford+CS.Five.Transport where

open import Data.Bool using (T)
open import Data.Nat using (ℕ ; zero ; suc)
open import Relation.Binary.PropositionalEquality as Eq using ()
open import Word.Base using (Word ; [_]ʷ ; ε ; _•_)

open import Notations using (₄ ; ₁₊)

import Presentation.Base as PB

open import Examples.Groups.Clifford+CS.Syntactics
open import Examples.Groups.Clifford+CS.Tools using (module Tools)
open import Examples.Groups.Clifford+CS.Completeness using (complete₁)
open import Examples.Groups.Clifford+CS.Five.WinSig using (Ws)
open import Examples.Groups.Clifford+CS.SemanticSteps using (module Below)
open import Examples.Groups.Clifford+CS.Lambda using (λ¹ ; λ⁰ ; λ¹ʷ ; λ⁰ʷ ; Xᵗ)
open import Examples.Groups.Clifford+CS.Five.Rules
open import Examples.Groups.Clifford+CS.Five.F2 using (f2 ; apart)

private
  variable
    n : ℕ
    w v : Word (Gen n)

------------------------------------------------------------------------
-- (F1), as a record

record F1 : Set where
  field
    f1₀ : ∀ {w v} → 4 SRel, w === v → 5 ⊢ₓ λ¹ʷ w ≈ λ¹ʷ v
    f1₁ : ∀ {w v} → 3 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑) ≈ λ¹ʷ (v ↑)
    f1₂ : ∀ {w v} → 2 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑) ≈ λ¹ʷ (v ↑ ↑)
    f1₃ : ∀ {w v} → 1 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑)
    f1₄ : ∀ {w v} → 0 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑ ↑)

------------------------------------------------------------------------
-- The two generators of a structural commutation are apart

'''

TAIL = '''------------------------------------------------------------------------
-- Transport under a black control

-- The (F1) items at the offsets 2 to 4 -- the rules of at most two wires
-- on the wires 2, 3 -- carry a two-wire derivation (Low); with those at
-- the offset 1, a three-wire one (Mid); with all of (F1), a four-wire
-- one.  So the transport of a two-wire equation rests on no item of a
-- rule of three or four wires, and that of a three-wire equation on no
-- item of a four-wire rule.

module Low (c4 : Ws)
  (f1₂ : ∀ {w v} → 2 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑) ≈ λ¹ʷ (v ↑ ↑))
  (f1₃ : ∀ {w v} → 1 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑))
  (f1₄ : ∀ {w v} → 0 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑ ↑)) where

  ax₀ : 0 VRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑ ↑)
  ax₀ (srel r) = f1₄ r

  ax₁ : 1 VRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑)
  ax₁ (srel r)       = f1₃ r
  ax₁ (cong↑ a)      = ax₀ a
  ax₁ (comm₁ h g)    = f2 c4 (g ↥ ↥ ↥ ↥) (gate₁ h ↥ ↥ ↥) (ap₁₁ h g)
  ax₁ (ω↑=ω I-gate)  = PB.refl

  ax₂ : 2 VRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑) ≈ λ¹ʷ (v ↑ ↑)
  ax₂ (srel r)       = f1₂ r
  ax₂ (cong↑ a)      = ax₁ a
  ax₂ (comm₁ h g)    = f2 c4 (g ↥ ↥ ↥) (gate₁ h ↥ ↥) (ap₁₂ h g)
  ax₂ (comm₂ h g)    = f2 c4 (g ↥ ↥ ↥ ↥) (gate₂ h ↥ ↥) (ap₂₂ h g)
  ax₂ (ω↑=ω I-gate)  = PB.refl

  transport² : 2 ⊢ w ≈ v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑) ≈ λ¹ʷ (v ↑ ↑)
  transport² PB.refl          = PB.refl
  transport² (PB.sym e)       = PB.sym (transport² e)
  transport² (PB.trans e e′)  = PB.trans (transport² e) (transport² e′)
  transport² (PB.cong e e′)   = PB.cong (transport² e) (transport² e′)
  transport² PB.assoc         = PB.assoc
  transport² PB.left-unit     = PB.left-unit
  transport² PB.right-unit    = PB.right-unit
  transport² (PB.axiom a)     = ax₂ a

module Mid (c4 : Ws)
  (f1₁ : ∀ {w v} → 3 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑) ≈ λ¹ʷ (v ↑))
  (f1₂ : ∀ {w v} → 2 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑) ≈ λ¹ʷ (v ↑ ↑))
  (f1₃ : ∀ {w v} → 1 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑))
  (f1₄ : ∀ {w v} → 0 SRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑ ↑ ↑ ↑) ≈ λ¹ʷ (v ↑ ↑ ↑ ↑)) where

  open Low c4 f1₂ f1₃ f1₄ using (ax₂)

  ax₃ : 3 VRel, w === v → 5 ⊢ₓ λ¹ʷ (w ↑) ≈ λ¹ʷ (v ↑)
  ax₃ (srel r)       = f1₁ r
  ax₃ (cong↑ a)      = ax₂ a
  ax₃ (comm₁ h g)    = f2 c4 (g ↥ ↥) (gate₁ h ↥) (ap₁₃ h g)
  ax₃ (comm₂ h g)    = f2 c4 (g ↥ ↥ ↥) (gate₂ h ↥) (ap₂₃ h g)
  ax₃ (ω↑=ω I-gate)  = PB.refl

  transport³ : 3 ⊢ w ≈ v → 5 ⊢ₓ λ¹ʷ (w ↑) ≈ λ¹ʷ (v ↑)
  transport³ PB.refl          = PB.refl
  transport³ (PB.sym e)       = PB.sym (transport³ e)
  transport³ (PB.trans e e′)  = PB.trans (transport³ e) (transport³ e′)
  transport³ (PB.cong e e′)   = PB.cong (transport³ e) (transport³ e′)
  transport³ PB.assoc         = PB.assoc
  transport³ PB.left-unit     = PB.left-unit
  transport³ PB.right-unit    = PB.right-unit
  transport³ (PB.axiom a)     = ax₃ a

module _ (c4 : Ws) (F : F1) where
  open F1 F

  private
    open Mid c4 f1₁ f1₂ f1₃ f1₄ using (ax₃)

    ax₄ : 4 VRel, w === v → 5 ⊢ₓ λ¹ʷ w ≈ λ¹ʷ v
    ax₄ (srel r)       = f1₀ r
    ax₄ (cong↑ a)      = ax₃ a
    ax₄ (comm₁ h g)    = f2 c4 (g ↥) (gate₁ h) (ap₁₄ h g)
    ax₄ (comm₂ h g)    = f2 c4 (g ↥ ↥) (gate₂ h) (ap₂₄ h g)
    ax₄ (ω↑=ω I-gate)  = PB.refl

  transport¹ : 4 ⊢ w ≈ v → 5 ⊢ₓ λ¹ʷ w ≈ λ¹ʷ v
  transport¹ PB.refl          = PB.refl
  transport¹ (PB.sym e)       = PB.sym (transport¹ e)
  transport¹ (PB.trans e e′)  = PB.trans (transport¹ e) (transport¹ e′)
  transport¹ (PB.cong e e′)   = PB.cong (transport¹ e) (transport¹ e′)
  transport¹ PB.assoc         = PB.assoc
  transport¹ PB.left-unit     = PB.left-unit
  transport¹ PB.right-unit    = PB.right-unit
  transport¹ (PB.axiom a)     = ax₄ a

------------------------------------------------------------------------
-- Under a white control: λ⁰ʷ w is λ¹ʷ w between two X on the top wire

private
  module S₁ = Below 1 complete₁

Xᵗ² : ∀ k → (₁₊ k) ⊢ₓ Xᵗ k • Xᵗ k ≈ ε
Xᵗ² zero    = embed (S₁.by-sem₀ (X • X) ε Eq.refl)
Xᵗ² (suc k) = lemma-cong↑ₓ (Xᵗ k • Xᵗ k) ε (Xᵗ² k)

λ⁰-conj : (w : Circuit 4) → 5 ⊢ₓ λ⁰ʷ w ≈ Xᵗ ₄ • λ¹ʷ w • Xᵗ ₄
λ⁰-conj [ g ]ʷ  = PB.refl
λ⁰-conj ε       = begin
  ε                    ≈⟨ sym (Xᵗ² ₄) ⟩
  Xᵗ ₄ • Xᵗ ₄          ≈⟨ back _ (sym left-unit) ⟩
  Xᵗ ₄ • ε • Xᵗ ₄ ∎
  where open Tools (5 XVRel,_===_)
λ⁰-conj (u • v) = begin
  λ⁰ʷ u • λ⁰ʷ v
    ≈⟨ cong (λ⁰-conj u) (λ⁰-conj v) ⟩
  (Xt • λ¹ʷ u • Xt) • (Xt • λ¹ʷ v • Xt)
    ≈⟨ by-passoc ((□ • □ • □) • (□ • □ • □)) (□ • □ • (□ • □) • □ • □) Eq.refl ⟩
  Xt • λ¹ʷ u • (Xt • Xt) • λ¹ʷ v • Xt
    ≈⟨ back _ (back _ (front _ (Xᵗ² ₄))) ⟩
  Xt • λ¹ʷ u • ε • λ¹ʷ v • Xt
    ≈⟨ back _ (back _ left-unit) ⟩
  Xt • λ¹ʷ u • λ¹ʷ v • Xt
    ≈⟨ back _ (sym assoc) ⟩
  Xt • (λ¹ʷ u • λ¹ʷ v) • Xt ∎
  where
  open Tools (5 XVRel,_===_)
  Xt = Xᵗ ₄

module _ (c4 : Ws) (F : F1) where

  transport⁰ : 4 ⊢ w ≈ v → 5 ⊢ₓ λ⁰ʷ w ≈ λ⁰ʷ v
  transport⁰ {w = w} {v} e = begin
    λ⁰ʷ w                   ≈⟨ λ⁰-conj w ⟩
    Xᵗ ₄ • λ¹ʷ w • Xᵗ ₄     ≈⟨ back _ (front _ (transport¹ c4 F e)) ⟩
    Xᵗ ₄ • λ¹ʷ v • Xᵗ ₄     ≈⟨ sym (λ⁰-conj v) ⟩
    λ⁰ʷ v ∎
    where open Tools (5 XVRel,_===_)
'''

if __name__ == '__main__':
    with open(os.path.join(FIVE, 'Transport.agda'), 'w', encoding='utf-8', newline=NL) as f:
        f.write(HEAD + ap_defs() + NL + TAIL)
    print('Transport.agda written')
