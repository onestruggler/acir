# Spellings of the hybrid gadget L_abc(kappa) = [L_bc(V^2), Lambda_a(beta)]
# reachable by moves each derivable by windows:
#   (i)  V -> V' with V'^2 = V^2 W^2, W in C(beta)  (L(V^2 W^2) = L(V^2) L(W^2)
#        on three wires, and L(W^2)'s Barenco letters pass Lambda_a(beta));
#   (ii) beta -> beta delta, delta in C(V)          (Lambda_a(delta) passes
#        Barenco's letters).
# A target unit u white on a control of the Barenco pair passes the
# gadget when u is in C(beta), so the units that pass generate
# H = < C(beta) : beta reachable >.  Elements of <S, K> with phases.
import itertools
I = 1j; g = 1 / (1 + I)
def mm(A, B): return tuple(tuple(sum(A[r][k] * B[k][c] for k in range(2)) for c in range(2)) for r in range(2))
def key(A): return tuple(complex(round(x.real, 6), round(x.imag, 6)) for r in A for x in r)
S = ((1, 0), (0, I)); K = ((g, g), (g, -g)); E = ((1, 0), (0, 1))
# the group <S, K>
G = {key(E): E}; fr = [E]
while fr:
    nf = []
    for A in fr:
        for B in (S, K):
            C = mm(A, B)
            if key(C) not in G: G[key(C)] = C; nf.append(C)
    fr = nf
els = list(G.values())
print('|<S,K>| =', len(els))
def inv(A):
    for B in els:
        if key(mm(A, B)) == key(E): return B
def comm(A, B): return mm(mm(A, B), mm(inv(A), inv(B)))
def cent(A): return [B for B in els if key(mm(A, B)) == key(mm(B, A))]
def sq(A): return mm(A, A)
V0 = mm(mm(S, S), mm(K, S)); kappa = comm(sq(V0), K)
start = (key(V0), key(K))
seen = {start}; fr = [start]; byk = {key(A): A for A in els}
while fr:
    nf = []
    for (v, b) in fr:
        V, B = byk[v], byk[b]
        for D in cent(V):                                   # (ii)
            st = (v, key(mm(B, D)))
            if st not in seen: seen.add(st); nf.append(st)
        for W in cent(B):                                   # (i)
            T = mm(sq(V), sq(W))
            for V2 in els:
                if key(sq(V2)) == key(T):
                    st = (key(V2), b)
                    if st not in seen: seen.add(st); nf.append(st)
    fr = nf
betas = {b for (_, b) in seen}
print('reachable spellings', len(seen), 'betas', len(betas))
assert all(key(comm(sq(byk[v]), byk[b])) == key(kappa) for (v, b) in seen)
# H = the group generated by the centralizers of the reachable betas
gens = {key(D): D for b in betas for D in cent(byk[b])}
H = {key(E): E}; fr = [E]
while fr:
    nf = []
    for A in fr:
        for D in gens.values():
            C = mm(A, D)
            if key(C) not in H: H[key(C)] = C; nf.append(C)
    fr = nf
print('|H| =', len(H), ' S in H:', key(S) in H, ' K in H:', key(K) in H)

# the other role: the separating wire is the single control a; a target
# unit white on a passes Lambda_a(beta) by a window and Barenco's letters
# when it commutes with V
vs = {v for (v, _) in seen}
gens = {key(D): D for v in vs for D in cent(byk[v])}
HB = {key(E): E}; fr = [E]
while fr:
    nf = []
    for A in fr:
        for D in gens.values():
            C = mm(A, D)
            if key(C) not in HB: HB[key(C)] = C; nf.append(C)
    fr = nf
print('|H_B| =', len(HB), ' S in H_B:', key(S) in HB, ' K in H_B:', key(K) in HB)
both = {key(D): D for D in list(H.values()) + list(HB.values())}
J = {key(E): E}; fr = [E]
while fr:
    nf = []
    for A in fr:
        for D in both.values():
            C = mm(A, D)
            if key(C) not in J: J[key(C)] = C; nf.append(C)
    fr = nf
print('|<H, H_B>| =', len(J))

Xm = ((0, 1), (1, 0)); Zm = ((1, 0), (0, -1))
print('X in H:', key(Xm) in H, ' Z in H:', key(Zm) in H, ' iI in H:', key(((I, 0), (0, I))) in H)
for name, P in (('X', Xm), ('Z', Zm), ('XZ', mm(Xm, Zm))):
    J = dict(H); fr = list(H.values())
    gensJ = list(H.values()) + [P]
    while fr:
        nf = []
        for A in fr:
            for D in gensJ:
                C = mm(A, D)
                if key(C) not in J: J[key(C)] = C; nf.append(C)
        fr = nf
    print(f'|<H, {name}>| =', len(J), ' S in it:', key(S) in J)
for name, P in (('X', Xm), ('Z', Zm), ('XZ', mm(Xm, Zm))):
    J = dict(HB); fr = list(HB.values())
    gensJ = list(HB.values()) + [P]
    while fr:
        nf = []
        for A in fr:
            for D in gensJ:
                C = mm(A, D)
                if key(C) not in J: J[key(C)] = C; nf.append(C)
        fr = nf
    print(f'|<H_B, {name}>| =', len(J))

def gen_size(base, extra):
    J = dict(base); fr = list(base.values()); gs = list(base.values()) + extra
    while fr:
        nf = []
        for A in fr:
            for D in gs:
                C = mm(A, D)
                if key(C) not in J: J[key(C)] = C; nf.append(C)
        fr = nf
    return len(J)
best = {}
for u in els:
    best.setdefault(gen_size(HB, [u]), []).append(u)
print('single role: |<H_B, u>| ->', {k: len(v) for k, v in sorted(best.items())})
bestp = {}
for u in els:
    bestp.setdefault(gen_size(H, [u]), []).append(u)
print('pair role:   |<H, u>|   ->', {k: len(v) for k, v in sorted(bestp.items())})
for nm, u in (('K', K), ('S', S), ('X', Xm), ('Z', Zm)):
    print(nm, 'single:', gen_size(HB, [u]), ' pair:', gen_size(H, [u]))

# iX (and X up to a phase on the control) as a product of conjugates of V^{+-2}
V2 = sq(V0); V2i = inv(V2)
conjs = {}
for u in els:
    for e, M in (('+', V2), ('-', V2i)):
        conjs.setdefault(key(mm(mm(u, M), inv(u))), (key(u), e))
print('conjugates of V^+-2:', len(conjs))
target = key(((0, I), (I, 0)))
cl = list(conjs.items())
found = None
for (k1, d1) in cl:
    if k1 == target: found = [d1]; break
if not found:
    for (k1, d1) in cl:
        for (k2, d2) in cl:
            if key(mm(byk[k1], byk[k2])) == target: found = [d1, d2]; break
        if found: break
if not found:
    for (k1, d1) in cl:
        for (k2, d2) in cl:
            p = mm(byk[k1], byk[k2])
            for (k3, d3) in cl:
                if key(mm(p, byk[k3])) == target: found = [d1, d2, d3]; break
            if found: break
        if found: break
print('iX as product of', len(found) if found else None, 'conjugates:', [(W[u], e) for (u, e) in found] if found else None)
