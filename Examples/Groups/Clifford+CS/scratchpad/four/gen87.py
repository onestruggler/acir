# Writes the Agda assembly of Lemma 8.7 at n = 4 (Lemma87/Sem/*.agda and
# Lemma87/Four.agda): every base case of l87d.py as a list of parts — a
# consecutive letter with its gadget block (Four.Facts.Bridges,
# HBridges) and its matrix checked (Lemma87.Chk), or the word of a gate
# done before — chained (Lemma87.Parts), the four-wire derivation of the
# flattened blocks (Four.D), and Lemma 8.7 for every generator by
# Lemma87.Decodes.by-decodes.  Run after emit_hyb.py, whose INDEX.txt
# names the modules of the lemmas.
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.dirname(HERE))
os.environ.setdefault('DERIV_QUIET', '1')
from emit import mname, lemname, ROOT
import l87d

NL = chr(10)
REPO = os.path.dirname(os.path.dirname(HERE))           # .../Clifford+CS
OUT = os.path.join(REPO, 'Lemma87')
INDEX = {}
for line in open(os.path.join(ROOT, 'D', 'INDEX.txt'), encoding='utf-8'):
    if line.strip():
        mod, n, name = line.rstrip(NL).split(' ', 2)
        INDEX[name] = mod

KN = {'p': 'p', "p'": 'p′', 'l': 'l', 'h': 'h', 'k': 'k'}

def letter_term(a, kind):
    A, B = f'(# {a})', f'(# {a + 1})'
    return {'p': f'pp {A} {B}', "p'": f'pp {B} {A}',
            'l': f'px {A} {A} {B} (lt {A} {B})', 'h': f'px {B} {A} {B} (lt {A} {B})',
            'k': f'ki {A} {B} {A} (lt {A} {B})'}[kind]

def has_unit(kind): return kind in ('p', "p'", 'k')        # d of the letter is the gadget • ε

def semname(a, kind): return f's-{KN[kind]}-{a}'
def ptname(a, kind): return f'pt-{KN[kind]}-{a}'
def gname(g): return mname(g)

HEADER = '''------------------------------------------------------------------------
-- Presentations of groups
--
{doc}
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}

module Examples.Groups.Clifford+CS.Lemma87.{mod} where
'''

def write(rel, text):
    path = os.path.join(OUT, rel + '.agda')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8', newline=NL).write(text)

def sem_modules(letters):
    """the checks, a few per module (Agda frees an evaluation's memory only
    when its module is done)."""
    ks = [x for x in letters if x[1] == 'k']; rest = [x for x in letters if x[1] != 'k']
    groups = [ks[i:i + 2] for i in range(0, len(ks), 2)] + [rest[i:i + 4] for i in range(0, len(rest), 4)]
    mods = {}
    for i, grp in enumerate(groups, 1):
        mod = f'Sem.S{i:02d}'
        out = [HEADER.format(mod=mod, doc='-- Lemma 8.7 on four qubits: decoded consecutive letters have their\n-- matrices (one boolean each).  Generated by scratchpad/four/gen87.py.'),
               'open import Data.Fin using (#_)',
               'open import Relation.Binary.PropositionalEquality as Eq using ()',
               'open import Word.Base using ([_]ʷ)',
               '',
               'open import Examples.Groups.Clifford+CS.Semantics using (_~_)',
               'open import Examples.Groups.Clifford+CS.Interpretation using (⟦_⟧)',
               'open import Examples.Groups.Clifford+CS.BridgeGray 4 using (⟦_⟧PY)',
               'open import Examples.Groups.Clifford+CS.Decoding 0 using (d)',
               'open import Examples.Groups.Clifford+CS.Auxiliary.P using (pp ; px ; ki)',
               'open import Examples.Groups.Clifford+CS.Lemma87.Chk using (chk-sem ; lt)',
               '']
        for (a, kind) in grp:
            t = letter_term(a, kind)
            out.append(f'{semname(a, kind)} : ⟦ d ({t}) ⟧ ~ ⟦ [ {t} ]ʷ ⟧PY')
            out.append(f'{semname(a, kind)} = chk-sem ({t}) Eq.refl')
            out.append('')
            mods[(a, kind)] = mod
        write(mod.replace('.', os.sep), NL.join(out))
    return mods

def main():
    bases = l87d.make_all()                        # [((name, lhs), items)]
    # the letters used, in order of first use
    letters = []
    for (_, items) in bases:
        for it in items:
            if it[0] == 'b' and it[2] not in letters: letters.append(it[2])
    semmod = sem_modules(letters)
    out = []
    # the letter parts
    out.append('------------------------------------------------------------------------')
    out.append('-- The consecutive letters as parts')
    out.append('')
    for (a, kind) in letters:
        t = letter_term(a, kind); br = f'br-{KN[kind]}-{a}'
        prf = f'trans right-unit {br}' if has_unit(kind) else br
        out.append(f'{ptname(a, kind)} : Part')
        out.append(f'{ptname(a, kind)} = part [ {t} ]ʷ B-{KN[kind]}-{a}')
        out.append(f'  (≈ᵈ (letterᵈ ({t}) {semname(a, kind)}) ({prf}))')
        out.append('')
    # the bases
    out.append('------------------------------------------------------------------------')
    out.append('-- The base cases: each gate as a word of parts')
    out.append('')
    done_gates = set()
    for ((name, lhs), items) in bases:
        tag = name.split(' ', 1)[1]                 # S0, CS1, X2, K3, iI
        parts = []
        for it in items:
            if it[0] == 'b': parts.append(ptname(*it[2]))
            else:
                for g in it[1]:
                    gn = gname(g); assert gn in done_gates, (name, gn)
                    parts.append(f'pt-{gn}')
        rhs = l87d.L[name][1]; assert len(rhs) == 1
        gn = gname(rhs[0])
        out.append(f'ps-{tag} : List Part')
        out.append(f'ps-{tag} = ' + ' ∷ '.join(parts) + ' ∷ []')
        out.append('')
        out.append(f'dec-{gn} : Decodes (words ps-{tag}) ⟪ {gn} ∷ [] ⟫ʷ')
        out.append(f'dec-{gn} = ≈ᵈ (chainᵈ ps-{tag}) {lemname(name)}')
        out.append('')
        out.append(f'pt-{gn} : Part')
        out.append(f'pt-{gn} = part (words ps-{tag}) (blk (xb false false false false) ({gn} ∷ [])) dec-{gn}')
        out.append('')
        done_gates.add(gn)
    deps = {}
    for ((name, lhs), items) in bases: deps.setdefault(INDEX.get(name, 'MISSING'), []).append(lemname(name))
    dep_lines = NL.join(f'open import Examples.Groups.Clifford+CS.Four.D.{m} using ({" ; ".join(ns)})'
                        for m, ns in sorted(deps.items()))
    sem_lines = {}
    for x, m in semmod.items(): sem_lines.setdefault(m, []).append(semname(*x))
    sem_imports = NL.join(f'open import Examples.Groups.Clifford+CS.Lemma87.{m} using ({" ; ".join(ns)})'
                          for m, ns in sorted(sem_lines.items()))
    doc = '''-- Lemma 8.7 on four qubits: the decoding inverts the encoding
--
-- Each gate is decoded from a word over P′ chosen for the derivation it
-- makes (Lemma87.Decodes): consecutive letters whose gadgets merge in
-- pairs over one wire, and gates done before (l87.py, l87b.py: the
-- words have the gates' matrices).  The four-wire derivations are
-- Four.D's `L87` lemmas (scratchpad/l87d.py); by Lemma 8.8 on four
-- qubits (Four.Hybrid) and the completeness of the rules of P′, the
-- decoding of the encoding of each generator is the generator.
-- Generated by scratchpad/four/gen87.py.'''
    head = HEADER.format(mod='Four', doc=doc) + f'''
open import Data.Bool using (true ; false)
open import Data.Fin using (#_)
open import Data.List using (List ; [] ; _∷_)
open import Word.Base using ([_]ʷ)

open import Examples.Groups.Clifford+CS.Syntactics
  using (Gen ; gate₀ ; gate₁ ; gate₂ ; _↥ ; I-gate ; S-gate ; K-gate ; CS-gate ; cong↑ ; ω↑=ω ; _⊢_≈_)
open import Examples.Groups.Clifford+CS.Auxiliary.P using (pp ; px ; ki)
open import Examples.Groups.Clifford+CS.CompletenessInduction using (D∘E)
open import Examples.Groups.Clifford+CS.Four.Chain
open import Examples.Groups.Clifford+CS.Four.TransportTables using (xb)
open import Examples.Groups.Clifford+CS.Four.Transport using (blk)
open import Examples.Groups.Clifford+CS.Four.Facts.Bridges
open import Examples.Groups.Clifford+CS.Four.Facts.HBridges
open import Examples.Groups.Clifford+CS.Four.Hybrid using (dwd₄)
open import Examples.Groups.Clifford+CS.Lemma87.Chk using (lt)
open import Examples.Groups.Clifford+CS.Lemma87.Parts
{dep_lines}
{sem_imports}

'''
    tail = '''------------------------------------------------------------------------
-- Lemma 8.7 on four qubits

private
  ι↑ : 4 ⊢ [ gate₀ I-gate ↥ ]ʷ ≈ ⟪ ι ∷ [] ⟫ʷ
  ι↑ = axiom (ω↑=ω I-gate)

  ι↑↑ : 4 ⊢ [ gate₀ I-gate ↥ ↥ ]ʷ ≈ ⟪ ι ∷ [] ⟫ʷ
  ι↑↑ = trans (axiom (cong↑ (ω↑=ω I-gate))) (axiom (ω↑=ω I-gate))

  ι↑↑↑ : 4 ⊢ [ gate₀ I-gate ↥ ↥ ↥ ]ʷ ≈ ⟪ ι ∷ [] ⟫ʷ
  ι↑↑↑ = trans (axiom (cong↑ (cong↑ (ω↑=ω I-gate)))) ι↑↑

  ι↑↑↑↑ : 4 ⊢ [ gate₀ I-gate ↥ ↥ ↥ ↥ ]ʷ ≈ ⟪ ι ∷ [] ⟫ʷ
  ι↑↑↑↑ = trans (axiom (cong↑ (cong↑ (cong↑ (ω↑=ω I-gate))))) ι↑↑↑

d∘e₄ : D∘E 0
d∘e₄ (gate₀ I-gate)           = by-decodes dwd₄ _ dec-ι refl
d∘e₄ (gate₁ S-gate)           = by-decodes dwd₄ _ dec-S0 refl
d∘e₄ (gate₁ K-gate)           = by-decodes dwd₄ _ dec-K0 refl
d∘e₄ (gate₂ CS-gate)          = by-decodes dwd₄ _ dec-CS01 refl
d∘e₄ (gate₀ I-gate ↥)         = by-decodes dwd₄ _ dec-ι ι↑
d∘e₄ (gate₁ S-gate ↥)         = by-decodes dwd₄ _ dec-S1 refl
d∘e₄ (gate₁ K-gate ↥)         = by-decodes dwd₄ _ dec-K1 refl
d∘e₄ (gate₂ CS-gate ↥)        = by-decodes dwd₄ _ dec-CS12 refl
d∘e₄ (gate₀ I-gate ↥ ↥)       = by-decodes dwd₄ _ dec-ι ι↑↑
d∘e₄ (gate₁ S-gate ↥ ↥)       = by-decodes dwd₄ _ dec-S2 refl
d∘e₄ (gate₁ K-gate ↥ ↥)       = by-decodes dwd₄ _ dec-K2 refl
d∘e₄ (gate₂ CS-gate ↥ ↥)      = by-decodes dwd₄ _ dec-CS23 refl
d∘e₄ (gate₀ I-gate ↥ ↥ ↥)     = by-decodes dwd₄ _ dec-ι ι↑↑↑
d∘e₄ (gate₁ S-gate ↥ ↥ ↥)     = by-decodes dwd₄ _ dec-S3 refl
d∘e₄ (gate₁ K-gate ↥ ↥ ↥)     = by-decodes dwd₄ _ dec-K3 refl
d∘e₄ (gate₀ I-gate ↥ ↥ ↥ ↥)   = by-decodes dwd₄ _ dec-ι ι↑↑↑↑
'''
    write('Four', head + NL.join(out) + NL + tail)
    print('written: bases', len(bases), 'letters', len(letters), 'sem modules', len(set(semmod.values())))

if __name__ == '__main__':
    main()
