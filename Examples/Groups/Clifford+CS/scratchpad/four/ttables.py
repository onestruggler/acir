# Writes Four/TransportTables.agda: the action of the adjacent swaps on the
# macro letters, which letters it applies to, and the dispatchers from
# each table entry to its emitted lemma (four/table.py, Four/D/*).
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.dirname(HERE))
from emit import mname, lemname, all_letters, ROOT
from table import letters, tau, BITS, bstr, tog, pb, sw_name
from deriv import rename_letter

NL = chr(10)
INDEX = {}
for line in open(os.path.join(ROOT, 'D', 'INDEX.txt'), encoding='utf-8'):
    if line.strip():
        mod, n, name = line.rstrip(NL).split(' ', 2)
        INDEX[name] = mod

used = {}
def lem(name):
    mod = INDEX[name]; used.setdefault(mod, set()).add(lemname(name)); return lemname(name)

SWS = ['s₀', 's₁', 's₂']
WIS = ['w₀', 'w₁', 'w₂', 'w₃']
def bits_pat(bits): return 'xb ' + ' '.join('true' if b else 'false' for b in bits)

def main():
    allL = all_letters()
    okL = set(letters())
    out = []
    out.append('-- The action of a swap on the letters.')
    out.append('πL : Sw → Mac → Mac')
    for j in range(3):
        for g in allL:
            if g[0] in ('iI', 'iIi') or g[0] == 'SWAP': h = g
            else: h = rename_letter(g, tau(j))
            out.append(f'πL {SWS[j]} {mname(g)} = {mname(h)}')
    out.append('')
    out.append('-- The letters it acts on letter by letter: all but the swaps and scalars.')
    out.append('ok : Mac → Bool')
    for g in allL:
        out.append(f'ok {mname(g)} = {"true" if g in okL else "false"}')
    out.append('')
    out.append('ok-π : ∀ s ℓ → ok (πL s ℓ) ≡ ok ℓ')
    for j in range(3):
        for g in allL: out.append(f'ok-π {SWS[j]} {mname(g)} = Eq.refl')
    out.append('')
    out.append('tbl : ∀ s ℓ → T (ok ℓ) → ⟪ swL s ∷ ℓ ∷ swL s ∷ [] ⟫ʷ ≈ ⟪ πL s ℓ ∷ [] ⟫ʷ')
    for j in range(3):
        for g in allL:
            if g in okL: out.append(f'tbl {SWS[j]} {mname(g)} _ = {lem(sw_name(j, g))}')
            else: out.append(f'tbl {SWS[j]} {mname(g)} ()')
    out.append('')
    out.append('swsw : ∀ s → ⟪ swL s ∷ swL s ∷ [] ⟫ʷ ≈ ⟪ [] ⟫ʷ')
    for j in range(3): out.append(f'swsw {SWS[j]} = {lem(f"swsw{j}")}')
    out.append('')
    out.append('xx : ∀ w → ⟪ xL w ∷ xL w ∷ [] ⟫ʷ ≈ ⟪ [] ⟫ʷ')
    for w in range(4): out.append(f'xx {WIS[w]} = {lem(f"xx{w}")}')
    out.append('')
    out.append('xc : ∀ v w → ⟪ xL v ∷ xL w ∷ [] ⟫ʷ ≈ ⟪ xL w ∷ xL v ∷ [] ⟫ʷ')
    for v in range(4):
        for w in range(4):
            if v == w: out.append(f'xc {WIS[v]} {WIS[w]} = refl')
            else: out.append(f'xc {WIS[v]} {WIS[w]} = {lem(f"xc{v}{w}")}')
    out.append('')
    for side, ty in (('t', '⟪ xL w ∷ Xs b ⟫ʷ'), ('s', '⟪ Xs b ++ xL w ∷ [] ⟫ʷ')):
        out.append(f'x{side} : ∀ w b → {ty} ≈ ⟪ Xs (tog w b) ⟫ʷ')
        for w in range(4):
            for bits in BITS:
                out.append(f'x{side} {WIS[w]} ({bits_pat(bits)}) = {lem(f"x{side}{w} {bstr(bits)}")}')
        out.append('')
    out.append('xr : ∀ s b → ⟪ map (πL s) (Xs b) ⟫ʷ ≈ ⟪ Xs (πB s b) ⟫ʷ')
    for j in range(3):
        for bits in BITS:
            out.append(f'xr {SWS[j]} ({bits_pat(bits)}) = {lem(f"xr{j} {bstr(bits)}")}')
    imports = NL.join(f'open import Examples.Groups.Clifford+CS.Four.D.{m} using ({" ; ".join(sorted(ns))})'
                      for m, ns in sorted(used.items()))
    head = f'''------------------------------------------------------------------------
-- Presentations of groups
--
-- The tables of the four-wire transport (generated by
-- scratchpad/four/ttables.py): the action of the adjacent swaps on the
-- macro letters, and the lemmas that conjugating a letter by a swap is
-- the renamed letter, that X letters commute and square to the empty
-- word, and how an X letter merges into a sorted list of them.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}

module Examples.Groups.Clifford+CS.Four.TransportTables where

open import Data.Bool using (Bool ; true ; false ; T ; if_then_else_ ; not)
open import Data.List using (List ; [] ; _∷_ ; _++_ ; map)
open import Relation.Binary.PropositionalEquality as Eq using (_≡_)

open import Examples.Groups.Clifford+CS.Four.Chain
{imports}

------------------------------------------------------------------------
-- Swaps, wires and sets of X letters

data Sw : Set where
  s₀ s₁ s₂ : Sw

swL : Sw → Mac
swL s₀ = Sw01
swL s₁ = Sw12
swL s₂ = Sw23

data Wi : Set where
  w₀ w₁ w₂ w₃ : Wi

xL : Wi → Mac
xL w₀ = X0
xL w₁ = X1
xL w₂ = X2
xL w₃ = X3

-- A set of wires, as its four bits (wire 0 first), and its X letters in
-- increasing order.
data XB : Set where
  xb : Bool → Bool → Bool → Bool → XB

opt : Bool → Mac → List Mac
opt true  x = x ∷ []
opt false x = []

Xs : XB → List Mac
Xs (xb a b c d) = opt a X0 ++ opt b X1 ++ opt c X2 ++ opt d X3

tog : Wi → XB → XB
tog w₀ (xb a b c d) = xb (not a) b c d
tog w₁ (xb a b c d) = xb a (not b) c d
tog w₂ (xb a b c d) = xb a b (not c) d
tog w₃ (xb a b c d) = xb a b c (not d)

-- The set renamed by a swap.
πB : Sw → XB → XB
πB s₀ (xb a b c d) = xb b a c d
πB s₁ (xb a b c d) = xb a c b d
πB s₂ (xb a b c d) = xb a b d c

------------------------------------------------------------------------
-- The tables

'''
    text = head + NL.join(out) + NL
    open(os.path.join(ROOT, 'TransportTables.agda'), 'w', encoding='utf-8', newline=NL).write(text)
    print('written', len(out), 'lines')

if __name__ == '__main__':
    main()
