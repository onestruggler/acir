FAM = {'p': 'dPP₁', "p'": 'dPP₁′', 'l': 'lo₁', 'h': 'hi₁', 'k': 'dKI₁'}
KN = {'p': 'p', "p'": 'p′', 'l': 'l', 'h': 'h', 'k': 'k'}
WIS = FG.WIS

def bname(a, kind): return f'B-{KN[kind]}-{a}'
def brname(a, kind): return f'br-{KN[kind]}-{a}'

# ------------------------------------------------------------ HBridges
def hbridges():
    out = ['''------------------------------------------------------------------------
-- The decoding's hybrid gadget in the spelling of the derivations

G-ki-≈ : G-ki 1 ≈ ⟪ ''' + lst(F4.KIMID) + ''' ⟫ʷ
G-ki-≈ = trans (by-assoc Eq.refl) lem-bridge-G-ki

------------------------------------------------------------------------
-- The decoded hybrids as blocks
''']
    for a in range(15):
        b = F4.decoded(a, 'k')
        out.append(f'{bname(a, "k")} : Blk'); out.append(f'{bname(a, "k")} = {blk(b)}'); out.append('')
    for a in range(15):
        t, x = F4.layout(4, a)
        beta = x[t] ^ F4.FLIP['k']
        ws = [w for w in range(4) if w != t and x[w] == 0]
        rels = [('rel', j) for j in range(t - 1, -1, -1)] + ([('col', 0)] if beta else [])
        frame = [('col', w) for w in ws] + rels
        assert frame == F4.frame(a, 'k')
        wl = '(' + ' ∷ '.join(WIS[w] for w in ws) + ' ∷ [])' if ws else '[]'
        out.append(f'{brname(a, "k")} : dKI₁ {a} ≈ ⟪ flatB {bname(a, "k")} ⟫ʷ')
        out.append(f'{brname(a, "k")} =')
        out.append(f'  trans (mc-cong {"true" if beta else "false"} (layout□ {a}) G-ki-≈)')
        out.append(f'  (trans (by-assoc Eq.refl)')
        out.append(f'  (trans (negs-F {wl} (F⟪ {ops(rels)} ⟫ ⟪ {lst(F4.KIMID)} ⟫ʷ))')
        out.append(f'         (F-blocks {ops(frame)} (blk (xb false false false false) {lst(F4.KIMID)} ∷ []) tt)))')
        out.append('')
    extra = ('open import Examples.Groups.Clifford+CS.MultiControlled using (Layout ; mc ; G-ki)' + NL +
             'open import Examples.Groups.Clifford+CS.Decoding 0 using (layout□ ; dKI₁)' + NL +
             'open import Examples.Groups.Clifford+CS.Four.Facts.Bridges using (mc-cong ; negs-F)' + NL +
             imports_of(['bridge G-ki']) + NL)
    doc = ('''-- The decoded hybrids at four wires as gadget blocks
--
-- A decoded hybrid is the hybrid gadget [Bar(V^2), CK] conjugated by the
-- X letters of its white controls, the swaps that bring its target to
-- wire 0 and X on the target for its orientation: the canonical block
-- carried by that frame (`F-blocks`).  Generated by
-- scratchpad/four/factsgen_hyb.py.''')
    write('HBridges', header('HBridges', doc, extra) + NL + NL.join(out) + NL)

# ------------------------------------------------------------ HClasses
def hclasses(plan):
    out = []; names = {}; used = []
    for (inst, ops_, fn, kl, kr, sw, rs) in plan:
        if fn in names: continue
        i = len(names); names[fn] = (f'hcls-{i}', [f'HC{i}-{j}' for j in range(len(kl))],
                                     [f'HC{i}-{j}' for j in range(len(kl), len(kl) + len(kr))])
        used.append((fn, kl, kr))
    for fn, kl, kr in used:
        cn, ln, rn = names[fn]
        lhs, rhs = L[fn]
        assert norm(F4.flat(kl)) == list(lhs) and F4.flat(kl) == norm(F4.flat(kl)), fn
        assert norm(F4.flat(kr)) == list(rhs) and F4.flat(kr) == norm(F4.flat(kr)), fn
        for n, b in zip(ln + rn, kl + kr):
            out.append(f'{n} : Blk'); out.append(f'{n} = {blk(b)}'); out.append('')
        out.append(f'-- {fn}')
        out.append(f'{cn} : ⟪ flat {blist(ln)} ⟫ʷ ≈ ⟪ flat {blist(rn)} ⟫ʷ')
        out.append(f'{cn} = {lemname(fn)}')
        out.append('')
    extra = imports_of([fn for fn, _, _ in used]) + NL
    doc = ('''-- The canonical class facts of the hybrid at four wires
--
-- Every instance of the hybrid facts the generic layer asks for is
-- carried by a transport (Four.Transport) to one of these, up to the
-- spelling of its middle words.  Generated by
-- scratchpad/four/factsgen_hyb.py.''')
    write('HClasses', header('HClasses', doc, extra) + NL + NL.join(out) + NL)
    return names

# ------------------------------------------------------------ instances
RESP_USED = set()

def resp_term(Lt, Lc):
    parts = []
    for bt, bc in zip(Lt, Lc):
        assert bt[0] == bc[0]
        mt, mc = tuple(norm(list(bt[1]))), tuple(norm(list(bc[1])))
        if mt == mc: parts.append('same (')
        else:
            if len(mt) == len(F4.KIMID): n = HS.respell_hyb(mt, mc)
            else:
                n = F4.respell(mt); assert tuple(L[n][1]) == mc, (show(list(mt)), show(list(mc)))
            RESP_USED.add(n); parts.append(f're {lemname(n)} (')
    return ''.join(parts) + '[]ʳ' + ')' * len(parts)

def side_word(side): return ' • '.join(f'{FAM[k]} {a}' for a, k in side) if side else 'ε'

def side_bridge(side):
    if not side: return 'refl'
    names = [(brname(a, k), bname(a, k)) for a, k in side]
    def go(i):
        br, b = names[i]
        if i == len(names) - 1: return br
        rest = blist([n for _, n in names[i + 1:]])
        return f'(trans (cong {br} {go(i + 1)}) (sym (++≈ (flatB {b}) (flat {rest}))))'
    return go(0)

def iname(inst): return f'i-{inst[0]}-{inst[1]}'

def instance(entry, cls):
    (inst, ops_, fn, kl, kr, sw, rs) = entry
    name, a, l, r = inst
    nm = iname(inst)
    Lb = blist([bname(p, k) for p, k in l]); Rb = blist([bname(p, k) for p, k in r])
    Lt = F4.TF(ops_, HPL.blocks(l)); Rt = F4.TF(ops_, HPL.blocks(r))
    cn, ln, rn = cls[fn]
    LC, RC = blist(ln), blist(rn)
    G, GI = ops(ops_), ops(list(reversed(ops_)))
    if not sw:
        e = (f'trans (resp {{TF {G} {Lb}}} {{{LC}}} ({resp_term(Lt, kl)}))' + NL +
             f'      (trans {cn} (sym (resp {{TF {G} {Rb}}} {{{RC}}} ({resp_term(Rt, kr)}))))')
    else:
        e = (f'trans (resp {{TF {G} {Lb}}} {{{RC}}} ({resp_term(Lt, kr)}))' + NL +
             f'      (trans (sym {cn}) (sym (resp {{TF {G} {Rb}}} {{{LC}}} ({resp_term(Rt, kl)}))))')
    lines = [f'{nm} : {side_word(l)} ≈ {side_word(r)}',
             f'{nm} = trans {side_bridge(l)}',
             f'  (trans (transport {GI} (TF {G} {Lb}) (TF {G} {Rb}) tt tt e)',
             f'         (sym {side_bridge(r)}))',
             f'  where',
             f'  e : ⟪ flat (TF {G} {Lb}) ⟫ʷ ≈ ⟪ flat (TF {G} {Rb}) ⟫ʷ',
             f'  e = {e}',
             '']
    return NL.join(lines)

def dispatchers():
    out = []
    for fam, kind in (('far-p', 'p'), ('far-l', 'l'), ('far-k', 'k')):
        f = 'd-' + fam
        out.append(f'{f} : ∀ j → suc (suc j) ≤ 14 → dKI₁ 14 • {FAM[kind]} j ≈ {FAM[kind]} j • dKI₁ 14')
        for j in range(13): out.append(f'{f} {j} _ = i-{fam}-{j}')
        out.append(f'{f} {sucs(13, "k")} {sles(14, "()")}')
        out.append('')
    out.append('d-shift : ∀ j → suc (suc j) < 16 → (lo₁ j • lo₁ (suc j)) • dKI₁ j ≈ dKI₁ (suc j) • (lo₁ j • lo₁ (suc j))')
    for c in range(14): out.append(f'd-shift {c} _ = trans assoc i-shift-{c}')
    out.append(f'd-shift {sucs(14, "k")} {sles(16, "()")}')
    out.append('')
    out.append('d-sc : (dPP₁′ 13 • dPP₁′ 13 • dPP₁′ 14) • dKI₁ 14 ≈ dKI₁ 14 • (dPP₁′ 13 • dPP₁′ 13 • dPP₁′ 14)')
    out.append('d-sc = trans (trans assoc (back (dPP₁′ 13) assoc)) i-sc-14')
    return NL.join(out) + NL

def main():
    plan, missing = HPL.plan()
    assert not missing, missing
    hbridges()
    cls = hclasses(plan)
    RESP_USED.clear()
    body = [instance(e, cls) for e in plan]
    body.append(dispatchers())
    extra = ('open import Examples.Groups.Clifford+CS.Decoding 0 using (dPP₁ ; dPP₁′ ; lo₁ ; hi₁ ; dKI₁)' + NL +
             'open import Examples.Groups.Clifford+CS.Four.Facts.Bridges' + NL +
             'open import Examples.Groups.Clifford+CS.Four.Facts.HBridges' + NL +
             'open import Examples.Groups.Clifford+CS.Four.Facts.Classes using (Resp ; []ʳ ; same ; re ; resp)' + NL +
             'open import Examples.Groups.Clifford+CS.Four.Facts.HClasses' + NL +
             imports_of(sorted(RESP_USED)) + NL)
    doc = ('''-- The hybrid facts at four wires that Lemma88.HybridRules asks for:
-- far-p, far-l, far-k at the top pair, the shifts, the pair scalar
--
-- Each instance is its decoded letters as blocks (Bridges, HBridges),
-- carried by a transport to a hybrid class fact (HClasses).  Generated
-- by scratchpad/four/factsgen_hyb.py.''')
    write('H1', header('H1', doc, extra) + NL + NL.join(body))
    print('written', len(plan), 'instances,', len(cls), 'class facts,', len(RESP_USED), 'respellings')

if __name__ == '__main__':
    main()
