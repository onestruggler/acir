"""Emit Agda modules for lemmas of a Store (two wires).

wire0(i): the lemma has only n h s and depends only on such lemmas; it is
declared at Eqn (₁₊ n) so that lift⁼ moves it to wire 1.  Other lemmas
are declared at Eqn (₂₊ n)."""
AG = {'n': '𝕟', 'h': 'h₀', 's': 's₀', 'H': 'h₁', 'S': 's₁', 'c': 'c₀'}

def alist(w):
    return ' ∷ '.join([AG[c] for c in w] + ['[]'])

class Emitter:
    def __init__(self, S):
        self.S = S
        self.memo0 = {}

    def is_wire0(self, i):
        if i in self.memo0: return self.memo0[i]
        e = self.S.eqs[i]
        nm = e['name']
        if isinstance(nm, tuple): r = False           # a lifted lemma
        elif nm is not None:
            r = nm in ('C₁ᵉ', 'C₂ᵉ', 'C₃ᵉ', 'C₄ᵉ', 'C₅ᵉ', 'comm-hn', 'comm-sn')
        else:
            r = all(ch in 'nhs' for ch in e['l'] + e['r']) and \
                all(j == 'P' or self.is_wire0(j) for (_, j, _) in e['steps'])
        self.memo0[i] = r
        return r

    def ref(self, i):
        nm = self.S.eqs[i]['name']
        if isinstance(nm, tuple):            # ('LIFT', base)
            return '(lift⁼ E%d)' % nm[1]
        if nm is not None:
            return nm
        return 'E%d' % i

    def step(self, st):
        p, i, d = st
        r = self.ref(i)
        return 'rw %d %s' % (p, r if d > 0 else '(sym⁼ %s)' % r)

    def steps(self, l, sts):
        out = []; w = l; pend = None
        for (p, j, d) in sts:
            w = self.S.apply(w, p, j, d)
            if j == 'P':
                pend = w
            else:
                if pend is not None:
                    out.append('perm (%s)' % alist(pend)); pend = None
                out.append(self.step((p, j, d)))
        if pend is not None:
            out.append('perm (%s)' % alist(pend))
        return ' ∷ '.join(out + ['[]'])

    def lemma(self, i):
        e = self.S.eqs[i]
        ty = 'Eqn (₁₊ n)' if self.is_wire0(i) else 'Eqn (₂₊ n)'
        steps = self.steps(e['l'], e['steps'])
        return 'E%d : %s\nE%d = derive (%s)\n  (%s)\n  (%s) refl\n' % (
            i, ty, i, alist(e['l']), alist(e['r']), steps)

    def generated(self, need):
        """the generated lemmas among need, and the bases of lifted ones"""
        out = set()
        for i in need:
            nm = self.S.eqs[i]['name']
            if nm is None: out.add(i)
            elif isinstance(nm, tuple): out.add(nm[1])
        # the bases' own dependencies
        stack = list(out)
        while stack:
            i = stack.pop()
            for (_, j, _) in self.S.eqs[i]['steps'] or []:
                if j == 'P': continue
                nm = self.S.eqs[j]['name']
                if nm is None and j not in out:
                    out.add(j); stack.append(j)
                elif isinstance(nm, tuple) and nm[1] not in out:
                    out.add(nm[1]); stack.append(nm[1])
        return sorted(out)

