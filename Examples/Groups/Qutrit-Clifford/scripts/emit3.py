"""Emit Box3/Part*.agda, Box3/Steps*.agda and Box3.agda from br3.pkl (made
by br3gen.py).

Each distinct equation on two adjacent wires is one lemma of a Steps
module, decided once, its evidence left to a metavariable (which Agda
solves by eta for ⊤: an explicit tt makes it evaluate the same boolean
about six times slower); the parts refer to the lemmas by name.  The
relations take 4134 such steps, of which 896 are distinct."""
import sys, os, pickle
QT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get('BR3OUTDIR', os.path.normpath(os.path.join(QT, '..')))

AGN = {('H', 0): 'h₀', ('H', 1): 'h₁', ('H', 2): 'h₂', ('S', 0): 's₀', ('S', 1): 's₁',
       ('S', 2): 's₂', ('CZ', 0): 'c₀', ('CZ', 1): 'c₁', ('nu',): '𝕟'}
AXN = {'C15': 'C₁₅ᵉ', 'C16': 'C₁₆ᵉ', 'C17': 'C₁₇ᵉ', 'C18': 'C₁₈ᵉ'}

def alist(ts):
    return ' ∷ '.join([AGN[t] for t in reversed(ts)] + ['[]'])

def down(ts):
    return [t if t[0] == 'nu' else (t[0], t[1] - 1) for t in ts]

# The distinct two-wire steps, in order of first use.
STEPS = {}

def step(l, r):
    key = (alist(l), alist(r))
    if key not in STEPS:
        STEPS[key] = len(STEPS)
    return 't2-%d' % STEPS[key]

def eqn(old, new, j):
    k = j[0]
    if k == 'sem':
        if j[1] == '01':
            return step(old, new)
        return '(lift⁼ %s)' % step(down(old), down(new))
    if k == 'perm':
        return '(permE (%s) (%s) refl)' % (alist(old), alist(new))
    if k == 'ax':
        return AXN[j[1]] if j[2] > 0 else '(sym⁼ %s)' % AXN[j[1]]
    if k == 'cancel':
        e = '(cancelˡ (%s))' % alist(j[1])
        return e if j[2] > 0 else '(sym⁼ %s)' % e
    if k == 'cancelL':
        e = '(cancelʳ (%s))' % alist(j[1])
        return e if j[2] > 0 else '(sym⁼ %s)' % e
    raise ValueError(j)

def steps(l, sts):
    N = len(l)
    out = []
    for (pos, old, new, j) in sts:
        p = N - pos - len(old)
        out.append('rw %d %s' % (p, eqn(old, new, j)))
        N = N - len(old) + len(new)
    return ' ∷ '.join(out + ['[]'])

def lname(nm):
    return 'r-' + nm

HEAD = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- {title}
--
-- Generated by scripts/br3gen.py: each relation is the loop of
-- l inv(r) in the graph of hyperbolic planes, filled by translates of
-- the loops of C₁₅–C₁₈; every step is an axiom, a cancellation, a
-- reordering of letters on disjoint wires, or an equation on two
-- adjacent wires, true by completeness on two qutrits (Box3/Steps*).
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}

module Examples.Groups.Qutrit-Clifford.{mod} where
'''

PART_IMPORTS = '''
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (ℕ)
open import Relation.Binary.PropositionalEquality using (refl)

open import Notations using (₃₊)
open import Examples.Groups.Qutrit-Clifford.Syntactics
open import Examples.Groups.Qutrit-Clifford.Engine using (Eqn ; sym⁼ ; lift⁼ ; derive ; rw)
open import Examples.Groups.Qutrit-Clifford.Axioms
open import Examples.Groups.Qutrit-Clifford.Box3.Kit using (cancelˡ ; cancelʳ ; permE)
{steps}
private
  variable
    n : ℕ

'''

STEPS_HEAD = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- Two-wire steps of the three-qutrit box relations, {k} of {m}
--
-- Generated by scripts/emit3.py: each lemma is an equation between
-- circuits on the bottom two wires, true by completeness on two qutrits
-- (Box3.Kit.sem₀₁), decided once here and used by name in Box3/Part*.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}

module Examples.Groups.Qutrit-Clifford.Box3.Steps{k} where

open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (ℕ)

open import Notations using (₂₊)
open import Examples.Groups.Qutrit-Clifford.Syntactics
open import Examples.Groups.Qutrit-Clifford.Engine using (Eqn)
open import Examples.Groups.Qutrit-Clifford.Axioms
open import Examples.Groups.Qutrit-Clifford.Box3.Kit using (sem₀₁)

private
  variable
    n : ℕ
'''

# Letters per Steps module: a step costs about its length.
STEP_LETTERS = 3000

def emit_steps():
    """Write the Steps modules, split by total length; their names."""
    chunks, cur, size = [], [], 0
    for (l, r), i in STEPS.items():
        w = l.count('∷') + r.count('∷')
        if cur and size + w > STEP_LETTERS:
            chunks.append(cur)
            cur, size = [], 0
        cur.append(((l, r), i))
        size += w
    if cur:
        chunks.append(cur)
    for k, ch in enumerate(chunks, 1):
        txt = STEPS_HEAD.format(k=k, m=len(chunks))
        for (l, r), i in ch:
            txt += '\nt2-%d : Eqn (₂₊ n)\nt2-%d = sem₀₁ (%s) (%s) _\n' % (i, i, l, r)
        open(ROOT + '/Box3/Steps%d.agda' % k, 'w', encoding='utf-8').write(txt)
    return ['Examples.Groups.Qutrit-Clifford.Box3.Steps%d' % k for k in range(1, len(chunks) + 1)]

def main(per=20):
    res = pickle.load(open(os.environ.get('BR3PKL', 'br3.pkl'), 'rb'))
    names = list(res.keys())
    parts = [names[i:i + per] for i in range(0, len(names), per)]
    os.makedirs(ROOT + '/Box3', exist_ok=True)
    bodies = []
    for ps in parts:
        txt = ''
        for nm in ps:
            field, args, l, r, sts = res[nm]
            txt += '%s : Eqn (₃₊ n)\n%s = derive (%s)\n  (%s)\n  (%s) refl\n\n' % (
                lname(nm), lname(nm), alist(l), alist(r), steps(l, sts))
        bodies.append(txt)
    smods = emit_steps()
    imports = ''.join('open import %s\n' % m for m in smods)
    for k, body in enumerate(bodies, 1):
        txt = HEAD.format(title='Three-qutrit box relations, part %d of %d' % (k, len(parts)),
                          mod='Box3.Part%d' % k) + PART_IMPORTS.format(steps=imports) + body
        open(ROOT + '/Box3/Part%d.agda' % k, 'w', encoding='utf-8').write(txt)
    # the record
    txt = HEAD.format(title='The box relations on three qutrits (Appendix C.4), derived from C₁₅–C₁₈',
                      mod='Box3')
    txt += '''
open import Data.List.Base using (List ; [] ; _∷_ ; _++_ ; map)
open import Data.Product.Base using (proj₁ ; proj₂)
open import Data.Nat.Base using (ℕ)

open import Notations using (₃₊)
open import Examples.Groups.Qutrit-Clifford.Syntactics
open import Examples.Groups.Qutrit-Clifford.Engine using (prf ; ⟪_⟫)
open import Examples.Groups.Qutrit-Clifford.Axioms
open import Examples.Groups.Qutrit-Clifford.NormalForm
open import Examples.Groups.Qutrit-Clifford.Tables
'''
    for k in range(1, len(parts) + 1):
        txt += 'open import Examples.Groups.Qutrit-Clifford.Box3.Part%d\n' % k
    txt += '''
br₃ : BoxRelations₃
br₃ = record { ruleS-ok = S-ok ; ruleBB-ok = BB-ok ; ruleDD-ok = DD-ok }
  where
  S-ok : ∀ {n} (b : BT) →
    (₃₊ n) ⊢ ⟪ map _↥ (Bl b) ++ c₀ ∷ [] ⟫ ≈ ⟪ P2ls (proj₂ (ruleS b)) ++ map _↥ (Bl (proj₁ (ruleS b))) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleS':
            txt += '  S-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    txt += '''  BB-ok : ∀ {n} (b₀ b₁ : BT) →
    (₃₊ n) ⊢ ⟪ map _↥ (Bl b₁) ++ Bl b₀ ++ c₁ ∷ [] ⟫ ≈ ⟪ BBr (ruleBB b₀ b₁) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleBB':
            txt += '  BB-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    txt += '''  DD-ok : ∀ {n} (d₁ d₀ : DT) →
    (₃₊ n) ⊢ ⟪ Dl d₀ ++ map _↥ (Dl d₁) ++ c₀ ∷ [] ⟫ ≈ ⟪ DDr (ruleDD d₁ d₀) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleDD':
            txt += '  DD-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    open(ROOT + '/Box3.agda', 'w', encoding='utf-8').write(txt)
    print(len(parts), 'parts', sum(os.path.getsize(ROOT + '/Box3/Part%d.agda' % k) for k in range(1, len(parts) + 1)),
          len(smods), 'step modules,', len(STEPS), 'distinct two-wire steps')

if __name__ == '__main__':
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 20)
