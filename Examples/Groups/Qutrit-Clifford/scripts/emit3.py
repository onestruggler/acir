# Letters per Sem module: an equation costs about its length (3000 made
# modules of 20–31 s), H the most.
STEP_LETTERS = 1800
# Steps per Steps module: each is a short derivation.
STEP_COUNT = 160

# Runs that an axiom makes the identity, on the two wires of a step:
# deleted by rw (or rwˡ, one wire up) of the axiom, put back by rwˢ (rwˢˡ).
# They are inverses, which a cancellation writes letter by letter
# (H⁻¹ = H H H), and they are 45% of the letters of the steps, most of
# them H, whose evaluation costs most.
POWERS = [('HHHH', 'rw', 'C₂ᵉ'), ('IIII', 'rwˡ', 'C₂ᵉ'), ('SSS', 'rw', 'C₃ᵉ'),
          ('TTT', 'rwˡ', 'C₃ᵉ'), ('CCC', 'rw', 'C₆ᵉ'), ('nnnnnn', 'rw', 'C₁ᵉ')]

def reduce(w):
    """w with such runs deleted, leftmost first, and the deletions."""
    dels = []
    while True:
        found = [(w.find(pat), pat, op, ax) for pat, op, ax in POWERS if pat in w]
        if not found:
            return w, dels
        i, pat, op, ax = min(found)
        dels.append((i, op, ax))
        w = w[:i] + w[i + len(pat):]

# The distinct reduced equations, in order of first use.
SEMS = {}

def sem(x, y):
    """(name, backwards) of the reduced equation x = y."""
    if (y, x) in SEMS:
        return 's2-%d' % SEMS[(y, x)], True
    if (x, y) not in SEMS:
        SEMS[(x, y)] = len(SEMS)
    return 's2-%d' % SEMS[(x, y)], False

def chunk(items, cost, limit):
    chunks, cur, size = [], [], 0
    for it in items:
        if cur and size + cost(it) > limit:
            chunks.append(cur)
            cur, size = [], 0
        cur.append(it)
        size += cost(it)
    if cur:
        chunks.append(cur)
    return chunks

def emit_steps():
    """Write the Sem and Steps modules; the names of the Steps modules."""
    defs = []
    for (l, r), i in STEPS.items():
        x, y = l[1:-1], r[1:-1]
        x2, dx = reduce(x)
        y2, dy = reduce(y)
        if not dx and not dy:
            t, back = sem(x, y)
            defs.append((i, 'sym⁼ ' + t if back else t))
            continue
        sts = ['%s %d %s' % (op, j, ax) for j, op, ax in dx]
        if x2 != y2:
            t, back = sem(x2, y2)
            sts.append('%s 0 %s' % ('rwˢ' if back else 'rw', t))
        sts += ['%s %d %s' % (op.replace('rw', 'rwˢ', 1), j, ax) for j, op, ax in reversed(dy)]
        defs.append((i, 'deriveℓ %s %s\n  (%s ∷ []) refl' % (l, r, ' ∷ '.join(sts))))
    sems = chunk(list(SEMS.items()), lambda e: len(e[0][0]) + len(e[0][1]), STEP_LETTERS)
    for k, ch in enumerate(sems, 1):
        txt = SEM_HEAD.format(k=k, m=len(sems))
        for (x, y), j in ch:
            txt += '\ns2-%d : Eqn (₂₊ n)\ns2-%d = semℓ "%s" "%s" _\n' % (j, j, x, y)
        open(ROOT + '/Box3/Sem%d.agda' % k, 'w', encoding='utf-8').write(txt)
    imports = ''.join('open import Examples.Groups.Qutrit-Clifford.Box3.Sem%d\n' % k
                      for k in range(1, len(sems) + 1))
    steps = chunk(defs, lambda d: 1, STEP_COUNT)
    for k, ch in enumerate(steps, 1):
        txt = STEPS_HEAD.format(k=k, m=len(steps), sems=imports)
        for i, body in ch:
            txt += '\nt2-%d : Eqn (₂₊ n)\nt2-%d = %s\n' % (i, i, body)
        open(ROOT + '/Box3/Steps%d.agda' % k, 'w', encoding='utf-8').write(txt)
    print(len(SEMS), 'two-wire equations decided,', sum(len(a) + len(b) for a, b in SEMS), 'letters')
    return ['Examples.Groups.Qutrit-Clifford.Box3.Steps%d' % k for k in range(1, len(steps) + 1)]

def main(per=20):
    res = pickle.load(open(os.environ.get('BR3PKL', 'br3.pkl'), 'rb'))
    names = list(res.keys())
    parts = [names[i:i + per] for i in range(0, len(names), per)]
    os.makedirs(ROOT + '/Box3', exist_ok=True)
    bodies = []
    for ps in parts:
        txt = ''
        for nm in ps:
            field, args, l, r, sts = res[nm]
            txt += '%s : Eqn (₃₊ n)\n%s = deriveℓ %s\n  %s\n  (%s) refl\n\n' % (
                lname(nm), lname(nm), word(l), word(r), steps(l, sts))
        bodies.append(txt)
    smods = emit_steps()
    imports = ''.join('open import %s\n' % m for m in smods)
    for k, body in enumerate(bodies, 1):
        txt = HEAD.format(title='Three-qutrit box relations, part %d of %d' % (k, len(parts)),
                          mod='Box3.Part%d' % k) + PART_IMPORTS.format(steps=imports) + body
        open(ROOT + '/Box3/Part%d.agda' % k, 'w', encoding='utf-8').write(txt)
    # the record
    txt = HEAD.format(title='The box relations on three qutrits (Appendix C.4), derived from C₁₅–C₁₈',
                      mod='Box3')
    txt += '''
open import Data.List.Base using (List ; [] ; _∷_ ; _++_ ; map)
open import Data.Product.Base using (proj₁ ; proj₂)
open import Data.Nat.Base using (ℕ)

open import Notations using (₃₊)
open import Examples.Groups.Qutrit-Clifford.Syntactics
open import Examples.Groups.Qutrit-Clifford.Engine using (prf ; ⟪_⟫)
open import Examples.Groups.Qutrit-Clifford.Axioms
open import Examples.Groups.Qutrit-Clifford.NormalForm
open import Examples.Groups.Qutrit-Clifford.Tables
'''
    for k in range(1, len(parts) + 1):
        txt += 'open import Examples.Groups.Qutrit-Clifford.Box3.Part%d\n' % k
    txt += '''
br₃ : BoxRelations₃
br₃ = record { ruleS-ok = S-ok ; ruleBB-ok = BB-ok ; ruleDD-ok = DD-ok }
  where
  S-ok : ∀ {n} (b : BT) →
    (₃₊ n) ⊢ ⟪ map _↥ (Bl b) ++ c₀ ∷ [] ⟫ ≈ ⟪ P2ls (proj₂ (ruleS b)) ++ map _↥ (Bl (proj₁ (ruleS b))) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleS':
            txt += '  S-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    txt += '''  BB-ok : ∀ {n} (b₀ b₁ : BT) →
    (₃₊ n) ⊢ ⟪ map _↥ (Bl b₁) ++ Bl b₀ ++ c₁ ∷ [] ⟫ ≈ ⟪ BBr (ruleBB b₀ b₁) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleBB':
            txt += '  BB-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    txt += '''  DD-ok : ∀ {n} (d₁ d₀ : DT) →
    (₃₊ n) ⊢ ⟪ Dl d₀ ++ map _↥ (Dl d₁) ++ c₀ ∷ [] ⟫ ≈ ⟪ DDr (ruleDD d₁ d₀) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleDD':
            txt += '  DD-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    open(ROOT + '/Box3.agda', 'w', encoding='utf-8').write(txt)
    print(len(parts), 'parts', sum(os.path.getsize(ROOT + '/Box3/Part%d.agda' % k) for k in range(1, len(parts) + 1)),
          len(smods), 'step modules,', len(STEPS), 'distinct two-wire steps')

if __name__ == '__main__':
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 20)
