"""Emit Box3/Part*.agda and Box3.agda from br3.pkl (made by br3gen.py)."""
import sys, os, pickle
QT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get('BR3OUTDIR', os.path.normpath(os.path.join(QT, '..')))

AGN = {('H', 0): 'h₀', ('H', 1): 'h₁', ('H', 2): 'h₂', ('S', 0): 's₀', ('S', 1): 's₁',
       ('S', 2): 's₂', ('CZ', 0): 'c₀', ('CZ', 1): 'c₁', ('nu',): '𝕟'}
AXN = {'C15': 'C₁₅ᵉ', 'C16': 'C₁₆ᵉ', 'C17': 'C₁₇ᵉ', 'C18': 'C₁₈ᵉ'}

def alist(ts):
    return ' ∷ '.join([AGN[t] for t in reversed(ts)] + ['[]'])

def down(ts):
    return [t if t[0] == 'nu' else (t[0], t[1] - 1) for t in ts]

def eqn(old, new, j):
    k = j[0]
    if k == 'sem':
        if j[1] == '01':
            return '(sem₀₁ (%s) (%s) tt)' % (alist(old), alist(new))
        return '(lift⁼ (sem₀₁ (%s) (%s) tt))' % (alist(down(old)), alist(down(new)))
    if k == 'perm':
        return '(permE (%s) (%s) refl)' % (alist(old), alist(new))
    if k == 'ax':
        return AXN[j[1]] if j[2] > 0 else '(sym⁼ %s)' % AXN[j[1]]
    if k == 'cancel':
        e = '(cancelˡ (%s))' % alist(j[1])
        return e if j[2] > 0 else '(sym⁼ %s)' % e
    if k == 'cancelL':
        e = '(cancelʳ (%s))' % alist(j[1])
        return e if j[2] > 0 else '(sym⁼ %s)' % e
    raise ValueError(j)

def steps(l, sts):
    N = len(l)
    out = []
    for (pos, old, new, j) in sts:
        p = N - pos - len(old)
        out.append('rw %d %s' % (p, eqn(old, new, j)))
        N = N - len(old) + len(new)
    return ' ∷ '.join(out + ['[]'])

def lname(nm):
    return 'r-' + nm

HEAD = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- {title}
--
-- Generated by scripts/br3gen.py: each relation is the loop of
-- l inv(r) in the graph of hyperbolic planes, filled by translates of
-- the loops of C₁₅–C₁₈; every step is an axiom, a cancellation, a
-- reordering of letters on disjoint wires, or an equation on two
-- adjacent wires, true by completeness on two qutrits.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}

module Examples.Groups.Qutrit-Clifford.{mod} where
'''

PART_IMPORTS = '''
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (ℕ)
open import Data.Unit using (tt)
open import Relation.Binary.PropositionalEquality using (refl)

open import Notations using (₃₊)
open import Examples.Groups.Qutrit-Clifford.Syntactics
open import Examples.Groups.Qutrit-Clifford.Engine using (Eqn ; sym⁼ ; lift⁼ ; derive ; rw)
open import Examples.Groups.Qutrit-Clifford.Axioms
open import Examples.Groups.Qutrit-Clifford.Box3.Kit using (sem₀₁ ; cancelˡ ; cancelʳ ; permE)

private
  variable
    n : ℕ

'''

def main(per=20):
    res = pickle.load(open(os.environ.get('BR3PKL', 'br3.pkl'), 'rb'))
    names = list(res.keys())
    parts = [names[i:i + per] for i in range(0, len(names), per)]
    os.makedirs(ROOT + '/Box3', exist_ok=True)
    for k, ps in enumerate(parts, 1):
        txt = HEAD.format(title='Three-qutrit box relations, part %d of %d' % (k, len(parts)),
                          mod='Box3.Part%d' % k) + PART_IMPORTS
        for nm in ps:
            field, args, l, r, sts = res[nm]
            txt += '%s : Eqn (₃₊ n)\n%s = derive (%s)\n  (%s)\n  (%s) refl\n\n' % (
                lname(nm), lname(nm), alist(l), alist(r), steps(l, sts))
        open(ROOT + '/Box3/Part%d.agda' % k, 'w', encoding='utf-8').write(txt)
    # the record
    txt = HEAD.format(title='The box relations on three qutrits (Appendix C.4), derived from C₁₅–C₁₈',
                      mod='Box3')
    txt += '''
open import Data.List.Base using (List ; [] ; _∷_ ; _++_ ; map)
open import Data.Product.Base using (proj₁ ; proj₂)
open import Data.Nat.Base using (ℕ)

open import Notations using (₃₊)
open import Examples.Groups.Qutrit-Clifford.Syntactics
open import Examples.Groups.Qutrit-Clifford.Engine using (prf ; ⟪_⟫)
open import Examples.Groups.Qutrit-Clifford.Axioms
open import Examples.Groups.Qutrit-Clifford.NormalForm
open import Examples.Groups.Qutrit-Clifford.Tables
'''
    for k in range(1, len(parts) + 1):
        txt += 'open import Examples.Groups.Qutrit-Clifford.Box3.Part%d\n' % k
    txt += '''
br₃ : BoxRelations₃
br₃ = record { ruleS-ok = S-ok ; ruleBB-ok = BB-ok ; ruleDD-ok = DD-ok }
  where
  S-ok : ∀ {n} (b : BT) →
    (₃₊ n) ⊢ ⟪ map _↥ (Bl b) ++ c₀ ∷ [] ⟫ ≈ ⟪ P2ls (proj₂ (ruleS b)) ++ map _↥ (Bl (proj₁ (ruleS b))) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleS':
            txt += '  S-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    txt += '''  BB-ok : ∀ {n} (b₀ b₁ : BT) →
    (₃₊ n) ⊢ ⟪ map _↥ (Bl b₁) ++ Bl b₀ ++ c₁ ∷ [] ⟫ ≈ ⟪ BBr (ruleBB b₀ b₁) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleBB':
            txt += '  BB-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    txt += '''  DD-ok : ∀ {n} (d₁ d₀ : DT) →
    (₃₊ n) ⊢ ⟪ Dl d₀ ++ map _↥ (Dl d₁) ++ c₀ ∷ [] ⟫ ≈ ⟪ DDr (ruleDD d₁ d₀) ⟫
'''
    for nm in names:
        f, a = res[nm][0], res[nm][1]
        if f == 'ruleDD':
            txt += '  DD-ok %s = prf %s\n' % (' '.join(a), lname(nm))
    open(ROOT + '/Box3.agda', 'w', encoding='utf-8').write(txt)
    print(len(parts), 'parts', sum(os.path.getsize(ROOT + '/Box3/Part%d.agda' % k) for k in range(1, len(parts) + 1)))

if __name__ == '__main__':
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 20)
