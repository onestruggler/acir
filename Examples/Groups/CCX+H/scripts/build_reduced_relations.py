#!/usr/bin/env python3
"""Generate the certified 42-equation reduction of the H two-wire theory.

This retains five gate involutions and 37 cyclic relators from the existing
Clément translation.  Agda checks exhaustive source coverage and every
bidirectional reduction certificate; --check reproduces files and checks
the reduced equations independently with exact physical matrices.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
HH = HERE.parent.parent / "CCX+HH" / "scripts"
sys.path.insert(0, str(HH))
import build_table1_cases as CASES
from exact_matrices import evaluate, identity

SPEC = importlib.util.spec_from_file_location("hh_relator_reduction", HH / "build_reduced_relations.py")
REDUCE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(REDUCE)

TAGS = ("X-gen", "(X-gen ↥)", "CX-gen", "H-gen", "(H-gen ↥)")
ABSURD = ("(gate₀ ())", "((gate₀ ()) ↥)", "((gate₀ ()) ↥ ↥)")


def agda_list(word):
    return " ∷ ".join([TAGS[g] for g in word] + ["[]"])


def certificate(classification):
    _, prefix, turns, backwards = classification
    return f"(R.certificate ({agda_list(prefix)}) {turns} {'true' if backwards else 'false'} Eq.refl)"


def generate():
    data = json.loads((HERE.parent / "two_qubit_relations.json").read_text(encoding="utf-8"))
    relations = data["relations"]
    classified = [REDUCE.classify(relation) for relation in relations]
    selected = sorted({row[0] for row in classified if row[0]})
    ids = {word: i for i, word in enumerate(selected)}
    origins = {}
    for r, cls in enumerate(classified):
        if cls[0]:
            origins.setdefault(ids[cls[0]], r)
    if len(relations) != 69 or len(selected) != 37:
        raise ValueError("the audited H2 instance or reduction counts have changed")

    def derive(r):
        cls = classified[r]
        chosen = f"selected r{ids[cls[0]]:02d}" if cls[0] else "[]"
        proof = f"(axiom (relator r{ids[cls[0]]:02d}))" if cls[0] else "refl"
        return f"Calc.derive-equation {{selected = {chosen}}} {certificate(cls)} {proof}"

    source = """------------------------------------------------------------------------
-- Presentations of groups
--
-- The 69 two-wire Clément equations reduce to 42: five generator
-- involutions and 37 cyclic relators.  Every omitted equation and every
-- retained equation have checked certificates in the opposite theory.
-- Generated by scripts/build_reduced_relations.py.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+H.TwoQubit.ReducedPresentation where

open import Data.Bool.Base using (false ; true)
open import Data.Fin.Base using (Fin ; _<_ ; toℕ)
import Data.Fin.Properties as FP
open import Data.List.Base using (List ; [] ; _∷_)
open import Data.Nat.Base using (suc ; s≤s ; z≤n ; _%_)
open import Data.Product.Base using (_,_)
open import Relation.Binary.Definitions using (DecidableEquality)
open import Relation.Binary.PropositionalEquality as Eq using (_≡_)
open import Relation.Nullary.Decidable using (yes ; no ; recompute)
open import Notations
open import Word.Base using (WRel ; [_]ʷ ; ε ; _•_)
import Presentation.Base as PB
import Presentation.GroupLike as GL
open import Examples.Groups.CCX+H.Syntactics
import Examples.Groups.CCX+H.GeneralN.PhysicalSemantics as Physical
import Examples.Groups.CCX+H.GeneralN.SmallPhysicalSemantics as Bridge
import Examples.Groups.CCX+H.GeneralN.GateInvolutions as Involutions
import Examples.Groups.CCX+H.TwoQubit as Old
import Examples.Groups.CCX+HH.RelatorReduction as Reduction
import Examples.Groups.CCX+HH.Table1Cases4 as Cases
import Examples.Groups.CCX+HH.TwoQubit.Table as Table
import Examples.Groups.CCX+HH-TwoLevel.Scaled.Syntactics as T

pattern X-gen = gate₁ X-gate
pattern H-gen = gate₁ H-gate
pattern CX-gen = gate₂ CX-gate

private
  eq : DecidableEquality (Gen 2)
"""
    for i, left in enumerate(TAGS):
        for j, right in enumerate(TAGS):
            result = "yes Eq.refl" if i == j else "no (λ ())"
            source += f"  eq {left} {right} = {result}\n"
    for pattern in ABSURD:
        source += f"  eq {pattern} g\n  eq g {pattern}\n"
    source += "\nmodule R = Reduction eq\n\ndata Index : Set where\n"
    for start in range(0, len(selected), 10):
        source += "  " + " ".join(f"r{i:02d}" for i in range(start, min(start + 10, len(selected)))) + " : Index\n"
    source += "\nselected : Index → List (Gen 2)\n"
    for i, word in enumerate(selected):
        source += f"selected r{i:02d} = {agda_list(word)}\n"
    source += """
data Relations : WRel (Gen 2) where
  square : ∀ g → Relations ([ g ]ʷ • [ g ]ʷ) ε
  relator : ∀ i → Relations (R.read (selected i)) ε

open PB Relations public hiding (_===_)

grouplike : GL.Grouplike Relations
grouplike g = [ g ]ʷ , axiom (square g)

private
  old-involution : ∀ g → ([ g ]ʷ • [ g ]ʷ) Old.Circuit.≈ ε
  old-involution g = Old.complete
    (Eq.trans (Eq.sym (Bridge.two ([ g ]ʷ • [ g ]ʷ)))
      (Eq.trans (Involutions.matrix-involutive g) (Bridge.two ε)))

  module Calc = R.Theory Relations (λ g → axiom (square g))
  module OldCalc = R.Theory Old._===_ old-involution

  canonical : ∀ {u v} → Cases.Canonical u v →
    Old.Rules.D T.⌊ u ⌋ʷ ≈ Old.Rules.D T.⌊ v ⌋ʷ
"""
    for r in range(58):
        source += f"  canonical Cases.instance{r:02d} =\n    {derive(r)}\n"
    source += """
  lt : ∀ {a b : Fin 4} → .(a < b) → a < b
  lt {a} {b} p = recompute (a FP.<? b) p

  even-block : ∀ (x y : Fin 4) (p : x < y) →
    (q : toℕ y ≡ suc (toℕ x)) → (r : toℕ x % 2 ≡ 0) →
    Old.Rules.D (T.H • T.Xᴸ x y p • T.H) ≈ Old.Rules.D (T.Mᴸ y)
"""
    for x in range(4):
        for y in range(4):
            args = "p q r"
            if x >= y:
                # The impossible proof is y successive successors followed by ().
                absurd = "()"
                for _ in range(y):
                    absurd = "(s≤s " + absurd + ")"
                args = f"{absurd} q r"
                rhs = ""
            elif y != x + 1:
                args, rhs = "p () r", ""
            elif x % 2:
                args, rhs = "p q ()", ""
            else:
                r = 61 if x == 0 else 63
                rhs = " =\n    " + derive(r)
            source += f"  even-block {CASES.NUM[x]} {CASES.NUM[y]} {args}{rhs}\n"
    source += """
translated-axiom : ∀ {u v} → Old._===_ u v → u ≈ v
translated-axiom (Old.decoded (T.table1 ax)) = canonical (Cases.cover ax)
"""
    source += f"translated-axiom (Old.decoded T.r7a) =\n  {derive(58)}\n"
    source += """translated-axiom (Old.decoded (T.r7b {a} {b} {c} {d} p q r _ _ _ _))
  with Table.full4 a b c d (lt p) (lt q) (lt r)
... | Eq.refl , Eq.refl , Eq.refl , Eq.refl =
""" + "  " + derive(59) + "\n"
    source += """translated-axiom (Old.decoded (T.r7c {a} {b} p ea eb))
  with FP.toℕ-injective {i = a} {j = ₀} ea | FP.toℕ-injective {i = b} {j = ₁} eb
... | Eq.refl | Eq.refl =
""" + "  " + derive(60) + "\n"
    source += """translated-axiom (Old.decoded (T.r7d₀ {x} {y} p q r)) = even-block x y (lt p) q r
translated-axiom (Old.decoded (T.r7d₁ {a} {b} {c} {d} p q r _ _ _ _))
  with Table.full4 a b c d (lt p) (lt q) (lt r)
... | Eq.refl , Eq.refl , Eq.refl , Eq.refl =
""" + "  " + derive(62) + "\n"
    for gate in range(5):
        source += f"translated-axiom (Old.recover {TAGS[gate]}) =\n  {derive(64 + gate)}\n"
    for pattern in ABSURD:
        source += f"translated-axiom (Old.recover {pattern})\n"
    source += """
from-translated : ∀ {u v} → u Old.Circuit.≈ v → u ≈ v
from-translated PB.refl = refl
from-translated (PB.sym p) = sym (from-translated p)
from-translated (PB.trans p q) = trans (from-translated p) (from-translated q)
from-translated (PB.cong p q) = cong (from-translated p) (from-translated q)
from-translated PB.assoc = assoc
from-translated PB.left-unit = left-unit
from-translated PB.right-unit = right-unit
from-translated (PB.axiom ax) = translated-axiom ax

private
  transport : ∀ {u v chosen} → R.Certificate (R.relator u v) chosen →
    Old._===_ u v → R.read chosen Old.Circuit.≈ ε
  transport cert ax = OldCalc.recover-selected cert
    (OldCalc.equation-to-relator (PB.axiom ax))

  to-translated-axiom : ∀ {u v} → Relations u v → u Old.Circuit.≈ v
  to-translated-axiom (square g) = old-involution g
"""
    source_axioms = {
        58: "T.r7a",
        59: "T.r7b (s≤s z≤n) (s≤s (s≤s z≤n)) (s≤s (s≤s (s≤s z≤n))) Eq.refl Eq.refl Eq.refl Eq.refl",
        60: "T.r7c (s≤s z≤n) Eq.refl Eq.refl",
        61: "T.r7d₀ {x = ₀} {y = ₁} (s≤s z≤n) Eq.refl Eq.refl",
        62: "T.r7d₁ (s≤s z≤n) (s≤s (s≤s z≤n)) (s≤s (s≤s (s≤s z≤n))) Eq.refl Eq.refl Eq.refl Eq.refl",
        63: "T.r7d₀ {x = ₂} {y = ₃} (s≤s (s≤s (s≤s z≤n))) Eq.refl Eq.refl",
    }
    for i, r in sorted(origins.items()):
        if r < 58:
            ax = f"Old.decoded (T.table1 (Cases.original Cases.instance{r:02d}))"
        elif r < 64:
            ax = "Old.decoded (" + source_axioms[r] + ")"
        else:
            ax = f"Old.recover {TAGS[r - 64]}"
        source += f"  to-translated-axiom (relator r{i:02d}) =\n"
        source += f"    transport {{chosen = selected r{i:02d}}} {certificate(classified[r])} ({ax})\n"
    source += """
to-translated : ∀ {u v} → u ≈ v → u Old.Circuit.≈ v
to-translated refl = PB.refl
to-translated (sym p) = PB.sym (to-translated p)
to-translated (trans p q) = PB.trans (to-translated p) (to-translated q)
to-translated (cong p q) = PB.cong (to-translated p) (to-translated q)
to-translated assoc = PB.assoc
to-translated left-unit = PB.left-unit
to-translated right-unit = PB.right-unit
to-translated (axiom ax) = to-translated-axiom ax

sound : ∀ {u v} → u ≈ v → Physical.interpret u ≡ Physical.interpret v
sound {u} {v} p = Eq.trans (Bridge.two u)
  (Eq.trans (Old.sound {w = u} {v = v} (to-translated p)) (Eq.sym (Bridge.two v)))

complete : ∀ {u v : Circuit 2} → Physical.interpret u ≡ Physical.interpret v → u ≈ v
complete {u} {v} p = from-translated (Old.complete {w = u} {v = v}
  (Eq.trans (Eq.sym (Bridge.two u)) (Eq.trans p (Bridge.two v))))
"""
    output = {
        "format": "clement-involutory-relator-reduction-v1",
        "wires": 2, "gate_set": "H", "word_order": "matrix product order",
        "circuit_generators": data["circuit_generators"],
        "source": "two_qubit_relations.json", "source_relation_count": len(relations),
        "formal_entrypoint": "TwoQubit/ReducedPresentation.agda",
        "relations": ([{"kind": "involution", "left": [i, i], "right": []} for i in range(5)] +
                      [{"kind": "relator", "left": list(w), "right": [],
                        "source_relation": origins[i]} for i, w in enumerate(selected)]),
        "certificates": [{"source_relation": i, "selected_relator": ids.get(c[0]),
                          "conjugating_prefix": list(c[1]), "rotations": c[2], "reversed": c[3]}
                         for i, c in enumerate(classified)],
    }
    gates = [(g["gate"], tuple(g["wires"])) for g in data["circuit_generators"]]
    for relation in output["relations"]:
        if evaluate(tuple(relation["left"]), gates, 2) != identity(2):
            raise ValueError("a reduced equation failed exact physical matrix verification")
    return source, json.dumps(output, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, data = generate()
    files = {HERE.parent / "TwoQubit" / "ReducedPresentation.agda": source,
             HERE.parent / "two_qubit_reduced.json": data}
    for path, content in files.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated file differs: {path}")
        else:
            path.write_text(content, encoding="utf-8")
    print("Verified 69 certificates, 37 selected relators and 5 involutions; typecheck the generated Agda proof.")


if __name__ == "__main__":
    main()
