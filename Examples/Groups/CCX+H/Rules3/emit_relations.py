"""Write CCX+H/NaturalP/ThreeWire/Relations.agda: every relation of Tables 1
and 2, decoded, is derived (`decoded`), constructor by constructor."""
import os
from table import T1, T2, order
from emit_family import fid, arg_names

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'NaturalP', 'ThreeWire', 'Relations.agda')
MODP = 'Examples.Groups.CCX+H.NaturalP.ThreeWire'

L = ['''------------------------------------------------------------------------
-- Presentations of groups
--
-- Every relation of Tables 1 and 2 on eight levels, decoded, holds in
-- the CCX+H rules on three wires: each constructor at each choice of its
-- indices is one module of Disp/.
--
-- Generated by CCX+H/Rules3/emit_relations.py; do not edit.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+H.NaturalP.ThreeWire.Relations where

open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Kit using (_⊢_≈_)
open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Decoder using (D′)
import Examples.Groups.CCX+H.NaturalP.Bridge as Br
import Examples.Groups.CCX+HH-TwoLevel.Syntactics as S
import Examples.Groups.CCX+HH-TwoLevel.Scaled.Syntactics as T
open import Examples.Groups.CCX+HH-TwoLevel.Scaled.Syntactics using (⌊_⌋ʷ)''']
for con in T1 + T2:
    L.append(f'import {MODP}.Disp.{fid(con[0])} as D-{fid(con[0])}')


def clause(con, ctor):
    vs = con[1].split()
    nms = arg_names(con[2])
    # generalised variables come in order of first occurrence in the type
    occ = []
    for t in [x for a in con[2] for x in a[1:]] + [x for g in con[3] + con[4] for x in g[1:]]:
        if isinstance(t, str) and t in vs and t not in occ:
            occ.append(t)
    parts = [ctor] + [f'{{{v} = {v}}}' for v in occ] + nms
    pat = '(' + ' '.join(parts) + ')' if len(parts) > 1 else ctor
    return pat, ' '.join(order(con) + nms)


L.append('''
t1 : ∀ {w v} → w S.=== v → 3 ⊢ Br.ι (D′ ⌊ w ⌋ʷ) ≈ Br.ι (D′ ⌊ v ⌋ʷ)''')
for con in T1:
    pat, args = clause(con, 'S.' + con[0])
    L.append(f't1 {pat} = D-{fid(con[0])}.d {args}'.rstrip())
L.append('''
decoded : ∀ {u v} → u T.===ᴸ v → 3 ⊢ Br.ι (D′ u) ≈ Br.ι (D′ v)
decoded (T.table1 h) = t1 h''')
for con in T2:
    pat, args = clause(con, 'T.' + con[0])
    L.append(f'decoded {pat} = D-{fid(con[0])}.d {args}'.rstrip())
open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote', OUT)
