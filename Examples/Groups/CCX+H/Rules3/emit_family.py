def emit_insts(con, chunk):
    name = con[0]
    insts = instances(con)
    mods = []
    tot = collections.Counter()
    for lo in range(0, len(insts), chunk):
        hi = min(lo + chunk, len(insts))
        mod = f'{fid(name)}-{lo // chunk}'
        names = Names()
        priv, pub = [], []
        for k in range(lo, hi):
            v = insts[k]
            lel = elements([gen_of(g, v) for g in con[3]])
            rel = elements([gen_of(g, v) for g in con[4]])
            L, Lp, body, c = chain_src(names, lel, rel)
            tot.update(c)
            priv.append(f'  L{k} L{k}′ : List El\n  L{k} = {L}\n  L{k}′ = {Lp}')
            pub.append(f'i{k} : 3 ⊢ ⦅ map ⟦_⟧ₑ (L{k} ++ invL L{k}′) ⦆ ≈ ε\n'
                       f'i{k} = run {{map ⟦_⟧ₑ (L{k} ++ invL L{k}′)}}\n    ( {body} )\n')
        text = INST_HEADER.format(fam=name, lo=lo, hi=hi - 1, modp=MODP, mod=mod)
        text += 'private\n' + '\n'.join(names.defs) + '\n\n'
        text += 'private\n' + '\n'.join(priv) + '\n\n' + '\n'.join(pub)
        os.makedirs(os.path.join(TW, 'Inst'), exist_ok=True)
        open(os.path.join(TW, 'Inst', mod + '.agda'), 'w', encoding='utf-8').write(text)
        mods.append((mod, lo, hi))
    return insts, mods, tot


# ---------------------------------------------------------------- dispatch

def arg_names(args):
    out = []
    np = nn = ne = 0
    for a in args:
        if a[0] == 'lt':
            np += 1
            out.append(f'p{np}')
        elif a[0] == 'ne':
            nn += 1
            out.append(f'n{nn}')
        else:
            ne += 1
            out.append(f'e{ne}')
    return out


def binder(a, nm):
    if a[0] == 'lt':
        return f'.({nm} : {a[1]} < {a[2]})'
    if a[0] == 'ne':
        return f'({nm} : {a[1]} ≢ {a[2]})'
    if a[0] == 'eqk':
        return f'({nm} : toℕ {a[1]} ≡ {a[2]})'
    if a[0] == 'suc':
        return f'({nm} : toℕ {a[1]} ≡ suc (toℕ {a[2]}))'
    if a[0] == 'mod':
        return f'({nm} : toℕ {a[1]} % 2 ≡ {a[2]})'
    raise ValueError(a)


def side(gens, args, names, table):
    def lt(x, y):
        for a, nm in zip(args, names):
            if a[0] == 'lt' and a[1] == x and a[2] == y:
                return nm
        raise ValueError((x, y))
    parts = []
    for g in gens:
        if g[0] == 'H':
            parts.append('T.H')
        elif g[0] == 'M':
            parts.append(f'S.M {g[1]}' if table == 1 else f'T.Mᴸ {g[1]}')
        elif g[0] == 'X':
            parts.append((f'S.X {g[1]} {g[2]} ' if table == 1 else f'T.Xᴸ {g[1]} {g[2]} ') + lt(g[1], g[2]))
        elif g[0] == 'K':
            a, b, c, d = g[1:]
            parts.append((f'S.K {a} {b} {c} {d} ' if table == 1 else f'T.Kᴸ {a} {b} {c} {d} ')
                         + f'{lt(a, b)} {lt(b, c)} {lt(c, d)}')
    w = ' • '.join(parts) if parts else 'ε'
    return f'⌊ {w} ⌋ʷ' if table == 1 else w


