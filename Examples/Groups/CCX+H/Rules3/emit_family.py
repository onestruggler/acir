"""Write, for one constructor of Tables 1 and 2, its instance modules
(Inst/<F>_<n>.agda, a chain per instance) and its dispatch module
(Disp/<F>.agda: d-<F> by cases on the indices, refuting the impossible ones).

    python3 -B emit_family.py r2a [chunk]
"""
import sys, os, collections
from table import T1, T2, instances, gen_of, order
from decoder import dec, seg_tokens
from chain import Line
from agda_words import nat, alist, wlist
from syn import inv

HERE = os.path.dirname(os.path.abspath(__file__))
TW = os.path.join(HERE, '..', 'NaturalP', 'ThreeWire')
FL = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇']
ASCII = {'r7d₀': 'r7d0', 'r7d₁': 'r7d1'}
MODP = 'Examples.Groups.CCX+H.NaturalP.ThreeWire'
SPLIT = {'r2f': 4}


def fid(name):
    return ASCII.get(name, name)


class Names:
    def __init__(self):
        self.ids = {}
        self.defs = []

    def word(self, w):
        w = tuple(w)
        if not w:
            return 'ε'
        if w not in self.ids:
            n = f'w{len(self.ids)}'
            self.ids[w] = n
            self.defs.append(f'  {n} : N.Circuit 3\n  {n} = {nat(w)}')
        return self.ids[w]


def elements(gens):
    els = []
    for g in gens:
        for e in dec(g):
            els.append(e if e == 'H' else ('T', seg_tokens(e)))
    return els


def chain_src(names, lel, rel):
    """the El lists (Agda) and the chain body for the loop lel ++ invL rel"""
    def ag(els):
        return (' ∷ '.join('hE' if e == 'H' else f'th {names.word(e[1])}' for e in els) + ' ∷ []') if els else '[]'
    line = [('T', e[1], names.word(e[1])) if e != 'H' else 'H' for e in lel]
    for e in reversed(rel):
        line.append('H' if e == 'H' else ('T', inv(e[1]), f'(invN {names.word(e[1])})'))
    Ln = Line([('T', x[1]) if x != 'H' else 'H' for x in line])
    steps = Ln.run()
    cur = [x[2] if x != 'H' else 'H' for x in line]
    W = names.word
    out = []

    def cfw(c):
        phi, psi, alpha, beta, omega = c
        return f'(cfw {W(phi)} {wlist(psi)} {alist(alpha)} {alist(beta)} Eq.refl Eq.refl)'

    for s in steps:
        kind = s[0]
        if kind == 'MG':
            _, k, a, b, t = s
            out.append(f'at {k} 2 (Θ {W(t)} ∷ []) (MG {cur[k]} {cur[k + 1]} {W(t)} Eq.refl)')
            cur[k:k + 2] = [W(t)]
        elif kind == 'HH':
            _, k = s
            out.append(f'at {k} 2 [] H²')
            del cur[k:k + 2]
        elif kind == 'E0':
            _, k = s
            out.append(f'at {k} 0 (Θ ε ∷ []) refl')
            cur.insert(k, 'ε')
        elif kind == 'BT':
            _, k, p, sw, q, t, alpha = s
            out.append(f'at {k} 5 (Θ {W(t)} ∷ []) (BT {cur[k]} {cur[k + 2]} {cur[k + 4]} {W(t)} {alist(alpha)} Eq.refl Eq.refl)')
            cur[k:k + 5] = [W(t)]
        elif kind == 'SQ':
            _, k, p1, p2, p3, q1, q2, r_, t, cX, cY = s
            out.append(f'at {k} 5 (Θ {W(q1)} ∷ H ∷ Θ {W(q2)} ∷ H ∷ Θ {W(t)} ∷ []) '
                       f'(SQ {cur[k]} {cur[k + 2]} {cur[k + 4]} {W(q1)} {W(q2)} {W(r_)} {W(t)} '
                       f'{cfw(cX)} {cfw(cY)} Eq.refl Eq.refl Eq.refl)')
            cur[k:k + 5] = [W(q1), 'H', W(q2), 'H', W(t)]
        elif kind == 'FIN':
            out.append(f'at 0 1 [] (TH {cur[0]} ε Eq.refl)')
            cur = []
    assert cur == []
    body = '\n    ▸ '.join(out) + '\n    ▸ done' if out else 'done'
    return ag(lel), ag(rel), body, collections.Counter(x[0] for x in steps)


