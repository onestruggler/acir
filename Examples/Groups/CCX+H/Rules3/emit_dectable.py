"""Write CCX+H/NaturalP/ThreeWire/DecTable.agda: the decoder as element lists."""
import os
from decoder import dec, AUX, seg_tokens
from agda_words import nat

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'NaturalP', 'ThreeWire', 'DecTable.agda')
F = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇']


def els(gen):
    out = []
    for e in dec(gen):
        out.append('hE' if e == 'H' else f'th {nat(seg_tokens(e))}')
    return ' ∷ '.join(out) + ' ∷ []'


L = ['''------------------------------------------------------------------------
-- Presentations of groups
--
-- The decoder on eight levels, as lists of theta-words and H.
--
--   X[a,b] = the transposition, a word in the nine letters of W(D8)
--   M[a]   = k CCZ k⁻¹, k a permutation sending 7 to a
--   K[s]   = r K₀ r⁻¹, K₀ = H θ₂ H θ₃ the K on the levels 0 1 2 3
--   IH     = H
--
-- Generated by CCX+H/Rules3/emit_dectable.py; do not edit.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+H.NaturalP.ThreeWire.DecTable where

open import Data.List.Base using (List ; [] ; _∷_)
open import Word.Base using (ε)
open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Elements using (El ; th ; hE)
open import Examples.Groups.CCX+HH.Natural.Axioms using (x₀ ; x₁ ; x₂ ; cx₀ ; cx₁ ; hh₀ ; hh₁ ; ccx₀)
open import Examples.Groups.CCX+HH.Natural.Engine using (⟪_⟫)
open import Examples.Groups.CCX+HH-TwoLevel.Syntactics using (M-gen ; X-gen ; K-gen)
open import Examples.Groups.CCX+HH-TwoLevel.Scaled.Syntactics using (Genᴸ ; ⌊_⌋ ; IH)
open import Notations using (₀ ; ₁ ; ₂ ; ₃ ; ₄ ; ₅ ; ₆ ; ₇)

Lels : Genᴸ 8 → List El''']
for gen in AUX:
    g, lv = gen['gate'], gen['levels']
    if g == 'M':
        L.append(f'Lels ⌊ M-gen {F[lv[0]]} ⌋ = {els(gen)}')
    elif g == 'X':
        L.append(f'Lels ⌊ X-gen {F[lv[0]]} {F[lv[1]]} _ ⌋ = {els(gen)}')
    elif g == 'K':
        L.append(f'Lels ⌊ K-gen {" ".join(F[x] for x in lv)} _ _ _ ⌋ = {els(gen)}')
    elif g == 'IH':
        L.append(f'Lels IH = hE ∷ []')
L.append('Lels _ = []')
open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote', OUT, len(AUX))
