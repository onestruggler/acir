"""Write CCX+H/NaturalP/ThreeWire/Letters.agda: CCZ past the nine letters of W(D8)."""
import os
from letters import LETW, LET, HC, YW, ZCH, AL
from syn import M
from deriv import mm
from agda_words import nat, alist, wlist, WLN, ALN

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'NaturalP', 'ThreeWire', 'Letters.agda')


def hc(w):
    out = ()
    for t in w:
        out += HC[t]
    return out


# check the facts the module decides
for x in LET:
    if x == 'CCX0':
        continue
    xa = LETW[x]
    y = YW[x]
    assert mm(hc(xa), ('CCX0',)) == mm(('CCX0',), y), x
    assert M(hc(y)) == M(ZCH[x]), x
cz = ('HH0', 'CX1', 'HH0')
assert M(cz + ('CCX0',)) == M(ZCH['CCX0'])

L = []
L.append('''------------------------------------------------------------------------
-- Presentations of groups
--
-- CCZ = H CCX H past the nine letters of W(D8) on three wires.
--
-- For every letter x but CCX, x^H (H x H, `hc`) is a CCX-free theta-word
-- and CCX x^H CCX = y is again one, so x CCZ = H x^H CCX H = H CCX y H =
-- CCZ y^H, with two matrix checks (`zc-via`).  For CCX itself this is
-- CCX CCZ CCX CCZ = CZ↑, the rule CCXH⁴, and CZ↑ commutes with CCZ.
--
-- Generated by CCX+H/Rules3/emit_letters.py; do not edit.
------------------------------------------------------------------------

{-# OPTIONS --without-K --safe #-}

module Examples.Groups.CCX+H.NaturalP.ThreeWire.Letters where

open import Data.Bool.Base using (true)
open import Data.List.Base using (List ; [] ; _∷_)
open import Relation.Binary.PropositionalEquality as Eq using (_≡_)
open import Word.Base using ([_]ʷ ; ε ; _•_)
import Presentation.Base as PB
import Presentation.Properties as PP
import Relation.Binary.Reasoning.Setoid as SR

open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Kit
import Examples.Groups.CCX+H.NaturalP.Syntactics as NH
import Examples.Groups.CCX+HH.Natural.Syntactics as N
open import Examples.Groups.CCX+HH.Natural.Axioms using (x₀ ; x₁ ; x₂ ; cx₀ ; cx₁ ; hh₀ ; hh₁ ; ccx₀)
open import Examples.Groups.CCX+HH.Natural.Engine using (⟪_⟫)

private
  module R3 = SR (PP.word-setoid (3 VRel,_===_))
  open R3

------------------------------------------------------------------------
-- The letters

data WL : Set where
  wx₀ wx₁ wx₂ wcx₀ wcx₁ wccx wcr₀ wcr₁ wz₁ : WL

-- The letters but CCX, as words in A.
WA : WL → List AL
WA wx₀  = ax₀ ∷ []
WA wx₁  = ax₁ ∷ []
WA wx₂  = ax₂ ∷ []
WA wcx₀ = acx₀ ∷ []
WA wcx₁ = acx₁ ∷ []
WA wccx = []
WA wcr₀ = ahh₀ ∷ acx₀ ∷ ahh₀ ∷ []
WA wcr₁ = ahh₁ ∷ acx₁ ∷ ahh₁ ∷ []
WA wz₁  = ahh₀ ∷ ax₁ ∷ ahh₀ ∷ []

⌊_⌋ʷˡ : WL → N.Circuit 3
⌊ wccx ⌋ʷˡ = [ ccx₀ ]ʷ • ε
⌊ x ⌋ʷˡ    = ⌊ WA x ⌋ᴬ

⌊_⌋ᵂ : List WL → N.Circuit 3
⌊ [] ⌋ᵂ     = ε
⌊ x ∷ xs ⌋ᵂ = ⌊ x ⌋ʷˡ • ⌊ xs ⌋ᵂ

-- CCZ x CCZ, as a theta-word.
ZC : WL → N.Circuit 3''')
for x in LET:
    L.append(f'ZC {WLN[x]} = {nat(ZCH[x])}')
L.append('''
zcW : List WL → N.Circuit 3
zcW []       = ε
zcW (x ∷ xs) = ZC x • zcW xs

CCZ : Circuit 3
CCZ = H • (Θ [ ccx₀ ]ʷ • H)

------------------------------------------------------------------------
-- CCZ past a letter

private
  c : Circuit 3
  c = Θ [ ccx₀ ]ʷ

  -- x CCZ = CCZ z, through x^H CCX = CCX y and y^H = z.
  zc-via : ∀ (xa y : List AL) (z : N.Circuit 3) →
           fastCheck (hcW xa • [ ccx₀ ]ʷ) ([ ccx₀ ]ʷ • ⌊ y ⌋ᴬ) ≡ true →
           fastCheck (hcW y) z ≡ true →
           3 ⊢ Θ ⌊ xa ⌋ᴬ • CCZ ≈ CCZ • Θ z
  zc-via xa y z h₁ h₂ = begin
    Θ ⌊ xa ⌋ᴬ • (H • (c • H))              ≈⟨ sym assoc ⟩
    (Θ ⌊ xa ⌋ᴬ • H) • (c • H)              ≈⟨ cong (hc xa) refl ⟩
    (H • Θ (hcW xa)) • (c • H)             ≈⟨ assoc ⟩
    H • (Θ (hcW xa) • (c • H))             ≈⟨ cong refl (sym assoc) ⟩
    H • ((Θ (hcW xa) • c) • H)             ≈⟨ cong refl (cong (Θstep (hcW xa • [ ccx₀ ]ʷ) ([ ccx₀ ]ʷ • ⌊ y ⌋ᴬ) h₁) refl) ⟩
    H • ((c • Θ ⌊ y ⌋ᴬ) • H)               ≈⟨ cong refl assoc ⟩
    H • (c • (Θ ⌊ y ⌋ᴬ • H))               ≈⟨ cong refl (cong refl (hc y)) ⟩
    H • (c • (H • Θ (hcW y)))              ≈⟨ cong refl (sym assoc) ⟩
    H • ((c • H) • Θ (hcW y))              ≈⟨ sym assoc ⟩
    (H • (c • H)) • Θ (hcW y)              ≈⟨ cong refl (Θstep (hcW y) z h₂) ⟩
    (H • (c • H)) • Θ z                    ∎

  -- The rule, as CCX CCZ CCX CCZ = CZ↑.
  rule : 3 ⊢ c • (CCZ • (c • CCZ)) ≈ CZ ↑
  rule = trans (cong refl (trans assoc (cong refl assoc)))
    (PB.axiom (srel (srel (nh NH.CCXH⁴))))

  cz : List AL
  cz = ahh₀ ∷ acx₁ ∷ ahh₀ ∷ []

  -- CZ on the wires 1, 2 as a theta-word.
  CZ↑-Θ : 3 ⊢ CZ ↑ ≈ Θ ⌊ cz ⌋ᴬ
  CZ↑-Θ = sym (begin
    (H • H ↑) • (CX ↑ • ((H • H ↑) • ε))     ≈⟨ cong refl (cong refl right-unit) ⟩
    (H • H ↑) • (CX ↑ • (H • H ↑))           ≈⟨ assoc ⟩
    H • (H ↑ • (CX ↑ • (H • H ↑)))           ≈⟨ cong refl (cong refl (sym assoc)) ⟩
    H • (H ↑ • ((CX ↑ • H) • H ↑))           ≈⟨ cong refl (cong refl (cong (comm-gate₁-w↑ H-gate CX) refl)) ⟩
    H • (H ↑ • ((H • CX ↑) • H ↑))           ≈⟨ cong refl (cong refl assoc) ⟩
    H • (H ↑ • (H • (CX ↑ • H ↑)))           ≈⟨ cong refl (sym assoc) ⟩
    H • ((H ↑ • H) • (CX ↑ • H ↑))           ≈⟨ cong refl (cong (comm-gate₁-w↑ H-gate H) refl) ⟩
    H • ((H • H ↑) • (CX ↑ • H ↑))           ≈⟨ cong refl assoc ⟩
    H • (H • (H ↑ • (CX ↑ • H ↑)))           ≈⟨ cancel H² _ ⟩
    H ↑ • (CX ↑ • H ↑)                       ∎)

  T : Circuit 3
  T = Θ ⌊ cz ⌋ᴬ

  c² : 3 ⊢ c • c ≈ ε
  c² = Θstep ([ ccx₀ ]ʷ • [ ccx₀ ]ʷ) ε Eq.refl

  CCZ² : 3 ⊢ CCZ • CCZ ≈ ε
  CCZ² = begin
    (H • (c • H)) • (H • (c • H))      ≈⟨ assoc ⟩
    H • ((c • H) • (H • (c • H)))      ≈⟨ cong refl assoc ⟩
    H • (c • (H • (H • (c • H))))      ≈⟨ cong refl (cong refl (cancel H² _)) ⟩
    H • (c • (c • H))                  ≈⟨ cong refl (cancel c² _) ⟩
    H • H                              ≈⟨ H² ⟩
    ε                                  ∎

  -- T commutes with CCZ: H fixes it, and so does CCX.
  T-c : 3 ⊢ T • c ≈ c • T
  T-c = Θstep (⌊ cz ⌋ᴬ • [ ccx₀ ]ʷ) ([ ccx₀ ]ʷ • ⌊ cz ⌋ᴬ) Eq.refl

  T-CCZ : 3 ⊢ T • CCZ ≈ CCZ • T
  T-CCZ = begin
    T • (H • (c • H))                  ≈⟨ sym assoc ⟩
    (T • H) • (c • H)                  ≈⟨ cong (hc cz) refl ⟩
    (H • T) • (c • H)                  ≈⟨ assoc ⟩
    H • (T • (c • H))                  ≈⟨ cong refl (sym assoc) ⟩
    H • ((T • c) • H)                  ≈⟨ cong refl (cong T-c refl) ⟩
    H • ((c • T) • H)                  ≈⟨ cong refl assoc ⟩
    H • (c • (T • H))                  ≈⟨ cong refl (cong refl (hc cz)) ⟩
    H • (c • (H • T))                  ≈⟨ cong refl (sym assoc) ⟩
    H • ((c • H) • T)                  ≈⟨ sym assoc ⟩
    (H • (c • H)) • T                  ∎

  -- c CCZ c CCZ = T, so c CCZ = T CCZ c = CCZ T c.
  zc-ccx : 3 ⊢ c • CCZ ≈ CCZ • (T • c)
  zc-ccx = begin
    c • CCZ                                        ≈⟨ sym right-unit ⟩
    (c • CCZ) • ε                                  ≈⟨ cong refl (sym (trans (cong refl (cancel CCZ² c)) c²)) ⟩
    (c • CCZ) • (c • (CCZ • (CCZ • c)))            ≈⟨ PP.by-assoc (3 VRel,_===_) Eq.refl ⟩
    (c • (CCZ • (c • CCZ))) • (CCZ • c)            ≈⟨ cong (trans rule CZ↑-Θ) refl ⟩
    T • (CCZ • c)                                  ≈⟨ sym assoc ⟩
    (T • CCZ) • c                                  ≈⟨ cong T-CCZ refl ⟩
    (CCZ • T) • c                                  ≈⟨ assoc ⟩
    CCZ • (T • c)                                  ∎''')
L.append('''
zc₁ : ∀ x → 3 ⊢ Θ ⌊ x ⌋ʷˡ • CCZ ≈ CCZ • Θ (ZC x)''')
for x in LET:
    if x == 'CCX0':
        L.append(f'zc₁ wccx = begin\n'
                 f'  (c • ε) • CCZ                ≈⟨ cong right-unit refl ⟩\n'
                 f'  c • CCZ                      ≈⟨ zc-ccx ⟩\n'
                 f'  CCZ • (T • c)                ≈⟨ cong refl (Θstep (⌊ cz ⌋ᴬ • [ ccx₀ ]ʷ) {nat(ZCH["CCX0"])} Eq.refl) ⟩\n'
                 f'  CCZ • Θ (ZC wccx)            ∎')
    else:
        L.append(f'zc₁ {WLN[x]} = zc-via (WA {WLN[x]}) {alist(YW[x])} (ZC {WLN[x]}) Eq.refl Eq.refl')
L.append('''
zc : ∀ ψ → 3 ⊢ Θ ⌊ ψ ⌋ᵂ • CCZ ≈ CCZ • Θ (zcW ψ)
zc []       = trans left-unit (sym right-unit)
zc (x ∷ xs) = begin
  (Θ ⌊ x ⌋ʷˡ • Θ ⌊ xs ⌋ᵂ) • CCZ            ≈⟨ assoc ⟩
  Θ ⌊ x ⌋ʷˡ • (Θ ⌊ xs ⌋ᵂ • CCZ)            ≈⟨ cong refl (zc xs) ⟩
  Θ ⌊ x ⌋ʷˡ • (CCZ • Θ (zcW xs))           ≈⟨ sym assoc ⟩
  (Θ ⌊ x ⌋ʷˡ • CCZ) • Θ (zcW xs)           ≈⟨ cong (zc₁ x) refl ⟩
  (CCZ • Θ (ZC x)) • Θ (zcW xs)            ≈⟨ assoc ⟩
  CCZ • (Θ (ZC x) • Θ (zcW xs))            ∎
''')
open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
print('wrote', OUT)
