"""Write instance modules: for each relation instance, the loop D(lhs) D(rhs)^-1
contracted by a chain of steps (Steps.agda), as

    iN : 3 ⊢ ⦅ map ⟦_⟧ₑ (lhs ++ invL rhs) ⦆ ≈ ε

python3 -B emit_inst.py MODNAME first last
"""
import sys, os, collections
from decoder import dec, AUX, REL, seg_tokens
from chain import Line
from agda_words import nat, alist, wlist
from syn import inv

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(HERE, '..', 'NaturalP', 'ThreeWire', 'Inst')


class Names:
    def __init__(self):
        self.ids = {}
        self.defs = []

    def word(self, w):
        w = tuple(w)
        if not w:
            return 'ε'
        if w not in self.ids:
            n = f'w{len(self.ids)}'
            self.ids[w] = n
            self.defs.append(f'  {n} : N.Circuit 3\n  {n} = {nat(w)}')
        return self.ids[w]


def gen_els(names, gens):
    """El list for a list of generator indices; returns (agda list, python elements)"""
    els = []
    for i in gens:
        for e in dec(AUX[i]):
            els.append(e if e == 'H' else ('T', seg_tokens(e)))
    agda = ' ∷ '.join('hE' if e == 'H' else f'th {names.word(e[1])}' for e in els)
    return (agda + ' ∷ []') if els else '[]', els


def instance(names, idx, r):
    L, lel = gen_els(names, r['auxiliary_left'])
    Lp, rel = gen_els(names, r['auxiliary_right'])
    # the line: lhs ++ invL rhs; terms: inverted words are invN w
    line = [('T', e[1], names.word(e[1])) if e != 'H' else 'H' for e in lel]
    for e in reversed(rel):
        if e == 'H':
            line.append('H')
        else:
            line.append(('T', inv(e[1]), f'(invN {names.word(e[1])})'))
    Ln = Line([('T', x[1]) if x != 'H' else 'H' for x in line])
    steps = Ln.run()
    # replay with Agda terms
    cur = [x[2] if x != 'H' else 'H' for x in line]
    out = []

    def W(w):
        return names.word(w)

    def cfw(c):
        phi, psi, alpha, beta, omega = c
        return f'(cfw {W(phi)} {wlist(psi)} {alist(alpha)} {alist(beta)} Eq.refl Eq.refl)'

    for s in steps:
        kind = s[0]
        if kind == 'MG':
            _, k, a, b, t = s
            out.append(f'at {k} 2 (Θ {W(t)} ∷ []) (MG {cur[k]} {cur[k + 1]} {W(t)} Eq.refl)')
            cur[k:k + 2] = [W(t)]
        elif kind == 'HH':
            _, k = s
            out.append(f'at {k} 2 [] H²')
            del cur[k:k + 2]
        elif kind == 'E0':
            _, k = s
            out.append(f'at {k} 0 (Θ ε ∷ []) refl')
            cur.insert(k, 'ε')
        elif kind == 'BT':
            _, k, p, sw, q, t, alpha = s
            out.append(f'at {k} 5 (Θ {W(t)} ∷ []) (BT {cur[k]} {cur[k + 2]} {cur[k + 4]} {W(t)} {alist(alpha)} Eq.refl Eq.refl)')
            cur[k:k + 5] = [W(t)]
        elif kind == 'SQ':
            _, k, p1, p2, p3, q1, q2, r_, t, cX, cY = s
            out.append(f'at {k} 5 (Θ {W(q1)} ∷ H ∷ Θ {W(q2)} ∷ H ∷ Θ {W(t)} ∷ []) '
                       f'(SQ {cur[k]} {cur[k + 2]} {cur[k + 4]} {W(q1)} {W(q2)} {W(r_)} {W(t)} '
                       f'{cfw(cX)} {cfw(cY)} Eq.refl Eq.refl Eq.refl)')
            cur[k:k + 5] = [W(q1), 'H', W(q2), 'H', W(t)]
        elif kind == 'FIN':
            _, a = s
            out.append(f'at 0 1 [] (TH {cur[0]} ε Eq.refl)')
            cur = []
    assert cur == []
    body = '\n    ▸ '.join(out) + '\n    ▸ done' if out else 'done'
    src = (f'  L{idx} L{idx}′ : List El\n  L{idx} = {L}\n  L{idx}′ = {Lp}\n\n'
           f'i{idx} : 3 ⊢ ⦅ map ⟦_⟧ₑ (L{idx} ++ invL L{idx}′) ⦆ ≈ ε\n'
           f'i{idx} = run {{map ⟦_⟧ₑ (L{idx} ++ invL L{idx}′)}}\n    ( {body} )\n')
    return src, collections.Counter(x[0] for x in steps)


HEADER = '''------------------------------------------------------------------------
-- Presentations of groups
--
-- Decoded relations on three wires, {what}.
--
-- Generated by CCX+H/Rules3/emit_inst.py; do not edit.
------------------------------------------------------------------------

{{-# OPTIONS --without-K --safe #-}}

module Examples.Groups.CCX+H.NaturalP.ThreeWire.Inst.{mod} where

open import Data.List.Base using (List ; [] ; _∷_ ; _++_ ; map)
open import Relation.Binary.PropositionalEquality as Eq using (_≡_)
open import Word.Base using (ε)

open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Kit
open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Letters using (WL ; wx₀ ; wx₁ ; wx₂ ; wcx₀ ; wcx₁ ; wccx ; wcr₀ ; wcr₁ ; wz₁)
open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Steps
open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Chain
open import Examples.Groups.CCX+H.NaturalP.ThreeWire.Elements
import Examples.Groups.CCX+HH.Natural.Syntactics as N
open import Examples.Groups.CCX+HH.Natural.Axioms using (x₀ ; x₁ ; x₂ ; cx₀ ; cx₁ ; hh₀ ; hh₁ ; ccx₀)
open import Examples.Groups.CCX+HH.Natural.Engine using (⟪_⟫)

'''


def emit(mod, idxs, what):
    names = Names()
    parts = []
    tot = collections.Counter()
    for i in idxs:
        src, c = instance(names, i, REL['relations'][i])
        parts.append(src)
        tot.update(c)
    os.makedirs(OUTDIR, exist_ok=True)
    text = HEADER.format(mod=mod, what=what)
    text += 'private\n' + '\n'.join(names.defs) + '\n\n'
    # the El lists are private too; the instances are public
    priv = []
    pub = []
    for p in parts:
        a, b = p.split('\n\n', 1)
        priv.append(a)
        pub.append(b)
    text += 'private\n' + '\n'.join(priv) + '\n\n' + '\n'.join(pub)
    open(os.path.join(OUTDIR, mod + '.agda'), 'w', encoding='utf-8').write(text)
    return tot


if __name__ == "__main__":
    mod, lo, hi = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    idxs = [i for i in range(lo, hi) if REL['relations'][i]['source'] != 'roundtrip']
    print(emit(mod, idxs, f'instances {lo} to {hi - 1}'))
