def det_frac(M):
    M = [row[:] for row in M]; n = len(M); d = F(1)
    for i in range(n):
        p = next((r for r in range(i, n) if M[r][i] != 0), None)
        if p is None: return F(0)
        if p != i: M[i], M[p] = M[p], M[i]; d = -d
        d *= M[i][i]
        for r in range(i+1, n):
            f = M[r][i] / M[i][i]
            if f: M[r] = [a - f*b for a, b in zip(M[r], M[i])]
    return d

def smith_divisors(M):
    """elementary divisors (abs, as python ints) of an integer matrix (list of rows)"""
    A = [row[:] for row in M]
    m, n = len(A), len(A[0])
    divs = []
    t = 0
    while t < min(m, n):
        # find nonzero pivot with min abs
        best = None
        for i in range(t, m):
            for j in range(t, n):
                if A[i][j] != 0 and (best is None or abs(A[i][j]) < abs(A[best[0]][best[1]])):
                    best = (i, j)
        if best is None: break
        i, j = best
        A[t], A[i] = A[i], A[t]
        for r in A: r[t], r[j] = r[j], r[t]
        done = False
        while not done:
            done = True
            p = A[t][t]
            for i in range(t+1, m):
                q = A[i][t] // p
                if q: A[i] = [a - q*b for a, b in zip(A[i], A[t])]
                if A[i][t] != 0:
                    done = False
            for j in range(t+1, n):
                q = A[t][j] // p
                if q:
                    for r in A: r[j] -= q * r[t]
                if A[t][j] != 0:
                    done = False
            if not done:
                # bring smallest nonzero in row/col t to pivot
                best = (t, t)
                for i in range(t, m):
                    if A[i][t] != 0 and abs(A[i][t]) < abs(A[best[0]][best[1]]): best = (i, t)
                for j in range(t, n):
                    if A[t][j] != 0 and abs(A[t][j]) < abs(A[best[0]][best[1]]): best = (t, j)
                i, j = best
                A[t], A[i] = A[i], A[t]
                for r in A: r[t], r[j] = r[j], r[t]
            else:
                # divisibility condition
                bad = None
                for i in range(t+1, m):
                    for j in range(t+1, n):
                        if A[i][j] % p != 0: bad = (i, j); break
                    if bad: break
                if bad:
                    A[t] = [a + b for a, b in zip(A[t], A[bad[0]])]
                    done = False
        divs.append(abs(A[t][t]))
        t += 1
    return divs

