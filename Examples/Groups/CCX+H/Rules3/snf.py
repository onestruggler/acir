def basisE():
    B = []
    B.append([F(1,2), F(-1,2), F(-1,2), F(-1,2), F(-1,2), F(-1,2), F(-1,2), F(1,2)])
    v = [F(0)]*8; v[0] = F(1); v[1] = F(1); B.append(v)
    v = [F(0)]*8; v[1] = F(1); v[0] = F(-1); B.append(v)
    for i in range(2, 7):
        v = [F(0)]*8; v[i] = F(1); v[i-1] = F(-1); B.append(v)
    assert abs(det_frac([list(r) for r in zip(*B)])) == 1, det_frac([list(r) for r in zip(*B)])
    return B

def invariants(Mcols):
    """Mcols: g as cols[j][i] = (a, b) scaled by S. Returns sorted O-exponents of gE_O rel E_O."""
    BE = basisE()
    # g applied to basis of E: vectors over Q(sqrt2)
    gB = []
    for v in BE:
        w = []
        for i in range(8):
            a = b = F(0)
            for k in range(8):
                ca, cb = Mcols[k][i]
                a += v[k] * ca; b += v[k] * cb
            w.append((a / S, b / S))
        gB.append(w)
    # coordinates of gB vectors in basis BE (over Q(sqrt2)): solve BE^T x = w for rational and sqrt2 parts
    Bt = [list(r) for r in zip(*BE)]   # columns = basis vectors
    # invert Bt over Q
    n = 8
    aug = [Bt[i][:] + [F(1 if i == j else 0) for j in range(n)] for i in range(n)]
    for c in range(n):
        p = next(r for r in range(c, n) if aug[r][c] != 0)
        aug[c], aug[p] = aug[p], aug[c]
        pv = aug[c][c]; aug[c] = [x / pv for x in aug[c]]
        for r in range(n):
            if r != c and aug[r][c] != 0:
                f = aug[r][c]; aug[r] = [x - f*y for x, y in zip(aug[r], aug[c])]
    Binv = [row[n:] for row in aug]
    # Z-module generated by gB and sqrt2*gB, in coordinates (Z-basis of E_O = BE and sqrt2*BE)
    rows = []
    for w in gB:
        for mult in (0, 1):
            # value w * (sqrt2)^mult
            ww = [(a, b) if mult == 0 else (2*b, a) for a, b in w]
            ra = [sum(Binv[i][k] * ww[k][0] for k in range(n)) for i in range(n)]
            rb = [sum(Binv[i][k] * ww[k][1] for k in range(n)) for i in range(n)]
            rows.append(ra + rb)
    den = 1
    for r in rows:
        for x in r: den = den * x.denominator // __import__("math").gcd(den, x.denominator)
    IM = [[int(x * den) for x in r] for r in rows]
    divs = smith_divisors(IM)
    # each divisor d = 2^e / den
    import math
    out = []
    for d in divs:
        e = 0
        while d % 2 == 0: d //= 2; e += 1
        assert d == 1, d
        out.append(F(2**e, den))
    return sorted(out)

