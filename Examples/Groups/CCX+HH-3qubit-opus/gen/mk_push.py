def rn(ws):
    """Right-nested product of word expressions."""
    if len(ws) == 1:
        return ws[0]
    return ws[0] + ' • ' + ('(' + rn(ws[1:]) + ')' if len(ws) > 2 else rn(ws[1:]))


def wexp(w):
    if len(w) == 0:
        return 'ε'
    return rn([WORD[x] for x in w])


def par(e):
    return e if ' ' not in e else '(' + e + ')'


def pname(g):
    return 'p' + g


def chkname(g):
    return 'h' + g


