def ikappa(L, ax):
    r, rhs = defrule[L]
    toks = rhs.split(' • ')
    parts = ['ικ-' + t if t in defrule else 'PB.refl' for t in toks]
    if all(p == 'PB.refl' for p in parts):
        return '%s (P.fig4 P.%s)' % (ax, r)
    acc = parts[-1]
    for p in reversed(parts[:-1]):
        acc = 'PB.cong %s (%s)' % (p, acc) if ' ' in acc else 'PB.cong %s %s' % (p, acc)
    return 'PB.trans (%s (P.fig4 P.%s)) (%s)' % (ax, r, acc)

