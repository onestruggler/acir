S7 = 'suc (suc (suc (suc (suc (suc (suc %s))))))'


def gen_fields(level, rel, wrap):
    """The three fields, at the given level (0 or 1)."""
    k = '{%d}' % level
    out = []
    out.append('order%s : ∀ i → i ≤ 6 → T %s i • T i ≈ ε' % (level, k))
    for i in range(7):
        out.append('order%s %d _ = %s' % (level, i, wrap('to≈ %s {w = T %d • T %d} {v = ε} Eq.refl Eq.refl' % (names[('ord', i)], i, i))))
    out.append('order%s (%s) (%s)' % (level, S7 % 'i', absurd_le(7, 6)))
    out.append('')
    out.append('braid%s : ∀ i → i ≤ 5 → T %s i • T (suc i) • T i ≈ T (suc i) • T i • T (suc i)' % (level, k))
    for i in range(6):
        out.append('braid%s %d _ = %s' % (level, i, wrap('to≈ %s {w = T %d • T %d • T %d} {v = T %d • T %d • T %d} Eq.refl Eq.refl'
                                                    % (names[('br', i)], i, i + 1, i, i + 1, i, i + 1))))
    out.append('braid%s (suc (suc (suc (suc (suc (suc i)))))) (%s)' % (level, absurd_le(6, 5)))
    out.append('')
    out.append('far%s : ∀ i j → 2 + i ≤ j → j ≤ 6 → T %s i • T j ≈ T j • T i' % (level, k))
    for i in range(7):
        for j in range(7):
            if j >= i + 2:
                out.append('far%s %d %d _ _ = %s' % (level, i, j, wrap('to≈ %s {w = T %d • T %d} {v = T %d • T %d} Eq.refl Eq.refl'
                                                                 % (names[('far', i, j)], i, j, j, i))))
            else:
                out.append('far%s %d %d (%s) _' % (level, i, j, absurd_le(2 + i, j)))
        out.append('far%s %d (%s) _ (%s)' % (level, i, S7 % 'j', absurd_le(7, 6)))
    out.append('far%s (%s) j lo hi = absurd (Data.Nat.Properties.≤-trans lo hi)' % (level, S7 % 'i'))
    out.append('  where')
    out.append('  import Data.Nat.Properties')
    out.append('  absurd : ∀ {A : Set} {i} → 9 ℕ.+ i ≤ 6 → A')
    out.append('  absurd (%s)' % absurd_le(7, 6))
    return out


